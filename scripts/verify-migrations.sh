#!/usr/bin/env bash
# Proof, against a real PostgreSQL, that the generated schema keeps the data across renames, drops what the journal
# says to drop, and changes nothing when it runs a second time.
#
#   scripts/verify-migrations.sh            (needs docker and a built `sb`: cargo build -p sb-app --bin sb)
#
# The "old" project is the stock sample with the column `total`, a text column `qty`, a `legacy_flag` column, a table `order_drafts`,
# a table `order_notes` and a nullable `note` column. The "new" one records, in its journal, that `total` became `amount`,
# `qty` became an int32, `legacy_flag` and `order_drafts` are gone, `order_notes` became `order_comments`, and `note` is required.
# Both are generated by the real generator; the statements of schema.rs are replayed in one transaction, as the service
# does at start-up (eda_runtime::db::apply_schema).
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
sb="${SB:-$root/target/debug/sb}"
port="${PGPORT_VERIFY:-55432}"
name="sb-migr-verify"
work="$(mktemp -d)"
trap 'docker rm -f "$name" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT

"$sb" sample >"$work/base.json"

python3 -I - "$work" <<'PY'
import json, sys
w = sys.argv[1]
base = json.load(open(f"{w}/base.json"))

def col(name, ty, **kw):
    c = {"name": name, "type": ty, "nullable": False, "primaryKey": False, "default": None}
    c.update(kw)
    return c

def project(new):
    p = json.loads(json.dumps(base))
    svc = p["services"][0]
    orders = svc["tables"][0]
    amount = next(c for c in orders["columns"] if c["name"] == "amount")
    if new:
        amount["renamedFrom"] = ["total"]
        orders["columns"].append(col("qty", "int32", default="1", retypedFrom="string"))
        orders["droppedColumns"] = ["legacy_flag"]
        orders["columns"].append(col("note", "string", default="''", nullableFrom=True))
        svc["droppedTables"] = ["order_drafts"]
        svc["tables"].append({"name": "order_comments", "renamedFrom": ["order_notes"],
                              "columns": [col("id", "int32", primaryKey=True), col("body", "string")]})
        orders["indexes"] = [{"name": "orders_amount_idx", "columns": ["amount"], "unique": False}]
    else:
        # The old design called the column `total`: so do the SQL steps (their paths still read `input.amount`).
        def walk(v, in_sql=False):
            if isinstance(v, dict):
                in_sql = in_sql or v.get("type") == "sql"
                return {k: walk(x, in_sql) for k, x in v.items()}
            if isinstance(v, list):
                return [walk(x, in_sql) for x in v]
            return "total" if in_sql and v == "amount" else v
        p = walk(p)
        svc = p["services"][0]
        orders = svc["tables"][0]
        total = next(c for c in orders["columns"] if c["name"] == "amount")
        total["name"] = "total"
        orders["columns"] += [col("legacy_flag", "bool", default="false"), col("note", "string", nullable=True),
                              col("qty", "string", default="'1'")]
        orders["indexes"] = [{"name": "orders_amount_idx", "columns": ["total"], "unique": False}]
        svc["tables"] += [
            {"name": "order_drafts", "columns": [col("id", "int32", primaryKey=True)]},
            {"name": "order_notes", "columns": [col("id", "int32", primaryKey=True), col("body", "string")]},
        ]
    return p

for new, file in ((False, "old"), (True, "new")):
    json.dump(project(new), open(f"{w}/{file}.json", "w"))
PY

for v in old new; do
  "$sb" validate "$work/$v.json" | grep -v '^$' || true
  "$sb" generate "$work/$v.json" "$work/gen-$v" >/dev/null
  # schema.rs holds one Rust string literal per line, which json.loads reads back as is.
  python3 -I - "$work/gen-$v/services/orders/src/app/schema.rs" "$work/$v.sql" <<'PY'
import json, re, sys
out = []
for line in open(sys.argv[1]):
    m = re.fullmatch(r'\s*(".*"),\s*', line.rstrip("\n"))
    if m:
        out.append(json.loads(m.group(1)))
open(sys.argv[2], "w").write("BEGIN;\n" + ";\n".join(out) + ";\nCOMMIT;\n")
PY
done

docker rm -f "$name" >/dev/null 2>&1 || true
docker run -d --name "$name" -e POSTGRES_PASSWORD=x -p "127.0.0.1:$port:5432" postgres:16-alpine >/dev/null
psql() { docker exec -i -e PGOPTIONS='-c client_min_messages=warning' "$name" psql -U postgres -v ON_ERROR_STOP=1 -qAt "$@"; }
for _ in $(seq 60); do docker exec "$name" pg_isready -U postgres >/dev/null 2>&1 && break; sleep 1; done
sleep 2

fail=0
check() { # description, expected, query
  local got; got="$(psql -c "$3")"
  if [ "$got" = "$2" ]; then echo "ok   $1"; else echo "FAIL $1: expected [$2], got [$got]"; fail=1; fi
}

echo "-- the old schema, with data"
psql <"$work/old.sql"
psql -c "INSERT INTO orders (order_id, total, note) VALUES ('a', 7, NULL), ('b', 123456, 'hi');
         UPDATE orders SET qty = '5' WHERE order_id = 'a';
         INSERT INTO order_drafts VALUES (1); INSERT INTO order_notes VALUES (1, 'kept');"

echo "-- the new schema, twice"
psql <"$work/new.sql"
snapshot() { psql -c "SELECT table_name, column_name, data_type, is_nullable FROM information_schema.columns WHERE table_schema='public' ORDER BY 1,2" ; psql -c "SELECT indexdef FROM pg_indexes WHERE schemaname='public' ORDER BY 1"; psql -c "SELECT conname FROM pg_constraint WHERE connamespace='public'::regnamespace ORDER BY 1"; }
first="$(snapshot)"
psql <"$work/new.sql"
second="$(snapshot)"

check "rename column keeps the data" "7|123456" "SELECT string_agg(amount::text,'|' ORDER BY order_id) FROM orders"
check "old column name is gone" "0" "SELECT count(*) FROM information_schema.columns WHERE table_name='orders' AND column_name='total'"
check "type converted, values kept" "integer|5|1" "SELECT (SELECT data_type FROM information_schema.columns WHERE table_name='orders' AND column_name='qty')||'|'||string_agg(qty::text,'|' ORDER BY order_id) FROM orders"
check "dropped column is gone" "0" "SELECT count(*) FROM information_schema.columns WHERE table_name='orders' AND column_name='legacy_flag'"
check "dropped table is gone" "0" "SELECT count(*) FROM information_schema.tables WHERE table_name='order_drafts'"
check "renamed table keeps its rows" "kept" "SELECT body FROM order_comments"
check "old table name is gone" "0" "SELECT count(*) FROM information_schema.tables WHERE table_name='order_notes'"
check "required column filled with its default" "|hi" "SELECT string_agg(note,'|' ORDER BY order_id) FROM orders"
check "the column is now NOT NULL" "NO" "SELECT is_nullable FROM information_schema.columns WHERE table_name='orders' AND column_name='note'"
check "the index follows the rename" "1" "SELECT count(*) FROM pg_indexes WHERE indexname='orders_amount_idx' AND indexdef LIKE '%(amount)%'"
if [ "$first" = "$second" ]; then echo "ok   a second run changes nothing"; else echo "FAIL second run changed the schema"; fail=1; fi

echo "-- a fresh database straight to the new schema"
psql -c "DROP SCHEMA public CASCADE; CREATE SCHEMA public;"
psql <"$work/new.sql"
check "fresh database: columns" "amount|bigint" "SELECT column_name||'|'||data_type FROM information_schema.columns WHERE table_name='orders' AND column_name='amount'"
check "fresh database: no dropped table" "order_comments" "SELECT string_agg(table_name,',' ORDER BY table_name) FROM information_schema.tables WHERE table_schema='public' AND table_name IN ('order_comments','order_drafts','order_notes')"

exit $fail
