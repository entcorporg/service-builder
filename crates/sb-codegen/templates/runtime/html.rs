//! What the expression `sanitizeHtml` calls: the HTML of a user, made safe to store and to show again.
//!
//! An allow-list, not a list of what is forbidden (Ammonia, with its default rules): what is not known to be harmless goes.
//! Scripts, styles, frames, forms, objects and `svg` are removed with what is inside them (or, for a tag that only wraps
//! text, only the tag); every attribute that runs code (`onclick`, `onerror`, ...) and every one that is not on the list;
//! links and images only keep an address that goes to `http`, `https`, `mailto`, `tel`, `ftp` or similar, never
//! `javascript:` or `data:`; and every link gets `rel="noopener noreferrer"` (and loses its `target`). What stays is the
//! formatting a text editor produces: paragraphs, emphasis, lists, headings, quotes, code, tables, links and images.
//!
//! What it makes safe is **HTML text**: put in an attribute, a script or a style of another page it is not. Output to a mail or a
//! page as the content of an element, not as anything else.
//!
//! Needs the cargo feature `html`; the generator turns it on for the services that use the expression.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

/// `html`, cleaned. The same text twice gives the same text (cleaning what is clean changes nothing).
pub fn sanitize(html: &str) -> String {
    ammonia::clean(html)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scripts_and_event_attributes_go_and_the_formatting_stays() {
        assert_eq!(
            sanitize("<p onclick=\"x()\">Hi <b>there</b><script>alert(1)</script></p>"),
            "<p>Hi <b>there</b></p>"
        );
        assert_eq!(sanitize("<style>p{color:red}</style><h1>Title</h1>"), "<h1>Title</h1>");
        assert_eq!(sanitize("<iframe src=\"//evil\"></iframe>text"), "text");
        assert_eq!(sanitize("<svg onload=alert(1)>"), "");
        assert_eq!(sanitize("<ul><li>one</li><li><em>two</em></li></ul>"), "<ul><li>one</li><li><em>two</em></li></ul>");
    }

    #[test]
    fn a_link_that_runs_code_loses_its_address_and_the_others_get_a_safe_rel() {
        assert_eq!(sanitize("<a href=\"javascript:alert(1)\">x</a>"), "<a rel=\"noopener noreferrer\">x</a>");
        assert_eq!(
            sanitize("<a href=\"https://example.com\" target=\"_blank\">ok</a>"),
            "<a href=\"https://example.com\" rel=\"noopener noreferrer\">ok</a>"
        );
        assert!(!sanitize("<a href=\"  JaVaScRiPt:alert(1)\">x</a>").contains("script"));
        assert!(!sanitize("<img src=\"data:text/html;base64,PHNjcmlwdD4=\">").contains("data:"));
        assert!(sanitize("<a href=\"mailto:a@b.c\">m</a>").contains("mailto:a@b.c"));
    }

    #[test]
    fn what_is_broken_is_repaired_and_plain_text_is_escaped() {
        // Unclosed tags are closed, and text that looks like markup but is text stays text.
        assert_eq!(sanitize("<b>bold"), "<b>bold</b>");
        assert_eq!(sanitize("1 < 2 & 3 > 2"), "1 &lt; 2 &amp; 3 &gt; 2");
        assert_eq!(sanitize(""), "");
        assert_eq!(sanitize("just text"), "just text");
        // Nested and mis-nested tricks that rely on how a browser repairs HTML.
        let nasty = "<<script>alert(1)//<</script>";
        let cleaned = sanitize(nasty);
        assert!(!cleaned.contains("<script") && !cleaned.contains("alert(1)</"), "{cleaned}");
    }

    #[test]
    fn cleaning_clean_html_changes_nothing() {
        for html in [
            "<p>Hello <b>world</b></p>",
            "<a href=\"https://example.com\" rel=\"noopener noreferrer\">x</a>",
            "<blockquote>q</blockquote><pre><code>let a = 1;</code></pre>",
        ] {
            let once = sanitize(html);
            assert_eq!(sanitize(&once), once, "{html}");
        }
    }
}
