//! Transactional outbox on PostgreSQL.
//!
//! A flow never talks to Kafka directly: [`enqueue`] writes the event into the `outbox` table inside
//! the same transaction as the rest of the flow, so state and events commit (or roll back) together.
//! A [`Relay`] then moves rows to Kafka:
//!
//! - an `AFTER INSERT` trigger sends `NOTIFY outbox`, and the relay `LISTEN`s, so a new event is
//!   published right away; a timer is the fallback for retries and lost notifications;
//! - a failed publish is retried with an exponential backoff;
//! - after [`Settings::max_attempts`] failures the record is parked on `<topic>.dlq` and flagged
//!   `dead_at` in the table. If the DLQ itself is unreachable it is retried: nothing is dropped;
//! - published rows are deleted, parked ones are kept for inspection.
//!
//! Delivery is at-least-once (a crash between the Kafka ack and the commit republishes the row), and
//! events with the same key stay ordered: a key with an event waiting for its retry blocks the
//! later events of that key. Only one relay works at a time across the replicas of a service.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::collections::HashSet;
use std::sync::Arc;
use std::time::Duration;

use anyhow::{Context, Result};
use sqlx::postgres::{PgConnectOptions, PgListener, PgPoolOptions};
use sqlx::{Connection, PgConnection, PgPool, Postgres, Row, Transaction};
use tokio::sync::Notify;

use crate::Producer;

/// Channel the insert trigger notifies and the relay listens to.
pub const CHANNEL: &str = "outbox";

const LOCK_MIGRATE: i64 = 0x6f62_786d;
const LOCK_RELAY: i64 = 0x6f62_7872;

const SCHEMA: &str = r#"
CREATE TABLE IF NOT EXISTS outbox (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    topic           TEXT        NOT NULL,
    message_key     TEXT,
    payload         BYTEA       NOT NULL,
    attempts        INT         NOT NULL DEFAULT 0,
    last_error      TEXT,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    dead_at         TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS outbox_pending_idx ON outbox (id) WHERE dead_at IS NULL;

CREATE OR REPLACE FUNCTION outbox_notify() RETURNS trigger AS $$
BEGIN
    PERFORM pg_notify('outbox', '');
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS outbox_notify ON outbox;
CREATE TRIGGER outbox_notify AFTER INSERT ON outbox
    FOR EACH ROW EXECUTE FUNCTION outbox_notify();
"#;

/// Rows to publish now, oldest first. A row waits while an older row with the same key is itself
/// waiting for its retry, so a retry never lets a newer event overtake it.
const SELECT_DUE: &str = r#"
SELECT o.id, o.topic, o.message_key, o.payload, o.attempts
FROM outbox o
WHERE o.dead_at IS NULL
  AND o.next_attempt_at <= now()
  AND NOT EXISTS (
        SELECT 1 FROM outbox e
        WHERE e.id < o.id
          AND e.dead_at IS NULL
          AND e.next_attempt_at > now()
          AND e.topic = o.topic
          AND e.message_key IS NOT NULL
          AND e.message_key = o.message_key)
ORDER BY o.id
LIMIT $1
"#;

/// Connects to PostgreSQL, waiting for the server to start and creating the database if it does
/// not exist yet.
pub async fn connect(url: &str) -> Result<PgPool> {
    let options: PgConnectOptions = url.parse().context("invalid database URL")?;
    let mut attempt = 0;
    let mut created = false;
    loop {
        attempt += 1;
        let pool = PgPoolOptions::new()
            .max_connections(10)
            .acquire_timeout(Duration::from_secs(5))
            .connect_with(options.clone())
            .await;
        match pool {
            Ok(pool) => return Ok(pool),
            // 3D000: invalid_catalog_name, the database is missing.
            Err(sqlx::Error::Database(e)) if e.code().as_deref() == Some("3D000") && !created => {
                create_database(&options).await?;
                created = true;
            }
            Err(e) if attempt < 10 => {
                tracing::warn!("database not ready ({e}), retrying");
                tokio::time::sleep(Duration::from_secs(2)).await;
            }
            Err(e) => return Err(e).context("database unreachable"),
        }
    }
}

async fn create_database(options: &PgConnectOptions) -> Result<()> {
    let name = options.get_database().unwrap_or("postgres").to_string();
    let mut admin = PgConnection::connect_with(&options.clone().database("postgres"))
        .await
        .with_context(|| format!("database `{name}` does not exist and `postgres` is unreachable"))?;
    let sql = format!("CREATE DATABASE \"{}\"", name.replace('"', "\"\""));
    match sqlx::query(&sql).execute(&mut admin).await {
        Ok(_) => tracing::info!("created database {name}"),
        // 42P04: duplicate_database, another replica was faster.
        Err(sqlx::Error::Database(e)) if e.code().as_deref() == Some("42P04") => {}
        Err(e) => return Err(e).with_context(|| format!("cannot create database `{name}`")),
    }
    Ok(())
}

/// Creates the outbox table and its notify trigger. Safe to run on every start-up, from several
/// replicas at once.
pub async fn migrate(pool: &PgPool) -> Result<()> {
    let mut tx = pool.begin().await?;
    sqlx::query("SELECT pg_advisory_xact_lock($1)")
        .bind(LOCK_MIGRATE)
        .execute(&mut *tx)
        .await?;
    sqlx::raw_sql(SCHEMA)
        .execute(&mut *tx)
        .await
        .context("cannot create the outbox table")?;
    tx.commit().await?;
    Ok(())
}

/// Queues `message` for `topic`. It is published after `tx` commits, and never if `tx` rolls back.
pub async fn enqueue<M: prost::Message>(
    tx: &mut Transaction<'_, Postgres>,
    topic: &str,
    key: Option<&str>,
    message: &M,
) -> Result<()> {
    sqlx::query("INSERT INTO outbox (topic, message_key, payload) VALUES ($1, $2, $3)")
        .bind(topic)
        .bind(key)
        .bind(message.encode_to_vec())
        .execute(&mut **tx)
        .await
        .with_context(|| format!("cannot queue an event for {topic}"))?;
    Ok(())
}

#[derive(Clone, Debug)]
pub struct Settings {
    /// Publish attempts before a record is parked on its dead-letter topic.
    pub max_attempts: u32,
    /// Rows handled per transaction.
    pub batch_size: i64,
    /// Wait after the first failure; doubles on each following one.
    pub base_backoff: Duration,
    pub max_backoff: Duration,
    /// Longest sleep without a notification (retries come due, notifications get lost).
    pub poll_interval: Duration,
}

impl Settings {
    pub fn new(max_attempts: u32) -> Self {
        Self {
            max_attempts: max_attempts.max(1),
            batch_size: 50,
            base_backoff: Duration::from_secs(1),
            max_backoff: Duration::from_secs(60),
            poll_interval: Duration::from_secs(10),
        }
    }

    fn backoff(&self, attempts: u32) -> Duration {
        let factor = 2u32.saturating_pow(attempts.saturating_sub(1).min(16));
        self.base_backoff.saturating_mul(factor).min(self.max_backoff)
    }
}

pub struct Relay {
    pool: PgPool,
    producer: Producer,
    settings: Settings,
}

impl Relay {
    pub fn new(pool: PgPool, brokers: &str, settings: Settings) -> Result<Self> {
        Ok(Self {
            pool,
            producer: Producer::new(brokers)?,
            settings,
        })
    }

    /// Publishes the outbox forever. Meant to run in its own task.
    pub async fn run(self) {
        let wake = Arc::new(Notify::new());
        tokio::spawn(listen(self.pool.clone(), wake.clone()));
        tracing::info!(
            "outbox relay started (max {} attempts per event)",
            self.settings.max_attempts
        );
        loop {
            let wait = match self.drain().await {
                Ok(wait) => wait,
                Err(e) => {
                    tracing::error!("outbox relay: {e:#}");
                    Duration::from_secs(2)
                }
            };
            // A notification stored while we were busy wakes the next wait immediately.
            let _ = tokio::time::timeout(wait, wake.notified()).await;
        }
    }

    /// Relays everything that is due, then says how long to sleep before the next retry comes due.
    async fn drain(&self) -> Result<Duration> {
        while self.relay_batch().await? > 0 {}
        let next: Option<f64> = sqlx::query_scalar(
            "SELECT EXTRACT(EPOCH FROM (min(next_attempt_at) - now()))::float8 FROM outbox WHERE dead_at IS NULL",
        )
        .fetch_one(&self.pool)
        .await?;
        let poll = self.settings.poll_interval;
        Ok(next
            .map(|s| Duration::from_secs_f64(s.max(0.05)).min(poll))
            .unwrap_or(poll))
    }

    /// One transaction: publish a batch of due rows. Returns how many rows it looked at.
    async fn relay_batch(&self) -> Result<usize> {
        let mut tx = self.pool.begin().await?;
        let locked: bool = sqlx::query_scalar("SELECT pg_try_advisory_xact_lock($1)")
            .bind(LOCK_RELAY)
            .fetch_one(&mut *tx)
            .await?;
        if !locked {
            return Ok(0); // another replica is relaying
        }
        let rows = sqlx::query(SELECT_DUE)
            .bind(self.settings.batch_size)
            .fetch_all(&mut *tx)
            .await?;

        // Keys that failed in this pass: their later events wait, to keep the order.
        let mut blocked: HashSet<(String, String)> = HashSet::new();
        for row in &rows {
            let id: i64 = row.get("id");
            let topic: String = row.get("topic");
            let key: Option<String> = row.get("message_key");
            let payload: Vec<u8> = row.get("payload");
            let attempts: i32 = row.get("attempts");
            if let Some(k) = &key
                && blocked.contains(&(topic.clone(), k.clone()))
            {
                continue;
            }

            let published = self
                .producer
                .publish_bytes(&topic, key.as_deref().map(str::as_bytes), &payload)
                .await;
            let Err(error) = published else {
                sqlx::query("DELETE FROM outbox WHERE id = $1")
                    .bind(id)
                    .execute(&mut *tx)
                    .await?;
                continue;
            };

            let attempts = attempts as u32 + 1;
            let error = format!("{error:#}");
            let parked = attempts >= self.settings.max_attempts
                && self.park(&topic, key.as_deref(), &payload, attempts, &error).await;
            if parked {
                tracing::error!(
                    "outbox: {topic} event #{id} failed {attempts} times ({error}); parked on {topic}.dlq"
                );
                sqlx::query(
                    "UPDATE outbox SET attempts = $2, last_error = $3, dead_at = now() WHERE id = $1",
                )
                .bind(id)
                .bind(attempts as i32)
                .bind(&error)
                .execute(&mut *tx)
                .await?;
                continue; // the poison event is out of the way: later ones may go
            }

            let wait = self.settings.backoff(attempts);
            tracing::warn!(
                "outbox: {topic} event #{id} failed (attempt {attempts}/{}): {error}; retrying in {wait:?}",
                self.settings.max_attempts
            );
            sqlx::query(
                "UPDATE outbox SET attempts = $2, last_error = $3, \
                 next_attempt_at = now() + make_interval(secs => $4) WHERE id = $1",
            )
            .bind(id)
            .bind(attempts as i32)
            .bind(&error)
            .bind(wait.as_secs_f64())
            .execute(&mut *tx)
            .await?;
            if let Some(k) = key {
                blocked.insert((topic, k));
            }
        }
        tx.commit().await?;
        Ok(rows.len())
    }

    /// Writes the record to `<topic>.dlq`. When that fails the row stays in the outbox and is
    /// retried later, so an event is never lost.
    async fn park(
        &self,
        topic: &str,
        key: Option<&str>,
        payload: &[u8],
        attempts: u32,
        error: &str,
    ) -> bool {
        let attempts = attempts.to_string();
        let result = self
            .producer
            .publish_bytes_with_headers(
                &format!("{topic}.dlq"),
                key.map(str::as_bytes),
                payload,
                &[
                    ("x-origin", "outbox"),
                    ("x-attempts", &attempts),
                    ("x-error", error),
                ],
            )
            .await;
        if let Err(e) = &result {
            tracing::error!("outbox: cannot publish to {topic}.dlq: {e:#}; will retry");
        }
        result.is_ok()
    }
}

/// Turns `NOTIFY outbox` into wake-ups of the relay. The connection is re-established on its own.
async fn listen(pool: PgPool, wake: Arc<Notify>) {
    loop {
        let mut listener = match PgListener::connect_with(&pool).await {
            Ok(l) => l,
            Err(e) => {
                tracing::warn!("outbox listener: cannot connect ({e}), retrying");
                tokio::time::sleep(Duration::from_secs(2)).await;
                continue;
            }
        };
        if let Err(e) = listener.listen(CHANNEL).await {
            tracing::warn!("outbox listener: cannot LISTEN ({e}), retrying");
            tokio::time::sleep(Duration::from_secs(2)).await;
            continue;
        }
        // Events queued while we were not listening.
        wake.notify_one();
        loop {
            match listener.recv().await {
                Ok(_) => wake.notify_one(),
                Err(e) => {
                    tracing::warn!("outbox listener: connection lost ({e}), reconnecting");
                    break;
                }
            }
        }
    }
}
