//! What the `rateLimit` step calls: a sliding window per key.
//!
//! By default the counts live in the memory of the process and are not shared between instances of a service: with several
//! replicas, the real limit is `max` times the number of replicas.
//!
//! With `shared` (cargo feature `shared-limit`, turned on by the generator for the services that have such a step) the counts
//! live in the key-value server of the project, DragonflyDB, Valkey or Redis (`DRAGONFLY_URL`, the one of `publishLive`), and the
//! limit is the same whatever the number of replicas. The window is the same one, counted by one Lua script that the server
//! runs without interruption: it forgets the attempts that left the window, refuses (without counting) when `max` are in it,
//! and counts this one otherwise. The clock is the server's, so the replicas cannot disagree on it. It needs Redis 5 or later
//! (a script that reads the time then writes), or DragonflyDB.
//!
//! The store is a convenience, not a dependency: when it cannot be reached (or does not answer within a quarter of a second)
//! the step counts in memory, as it would without the option, logs it, and does not ask the store again for a few seconds.
//! A request is never refused because the store is down.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::collections::{HashMap, VecDeque};
use std::sync::{LazyLock, Mutex};
use std::time::{Duration, Instant};

use anyhow::Result;

use crate::http::HttpError;

/// How often the keys that went quiet are forgotten, so that the memory does not grow with every key seen.
const SWEEP_EVERY: Duration = Duration::from_secs(60);

struct Entry {
    window: Duration,
    hits: VecDeque<Instant>,
}

pub struct Limiter {
    entries: HashMap<String, Entry>,
    last_sweep: Instant,
}

impl Limiter {
    pub fn new(now: Instant) -> Self {
        Self {
            entries: HashMap::new(),
            last_sweep: now,
        }
    }

    /// Counts an attempt. `Err(wait)`: how long until the oldest attempt of the window expires.
    pub fn check(
        &mut self,
        key: &str,
        max: usize,
        window: Duration,
        now: Instant,
    ) -> Result<(), Duration> {
        if now.duration_since(self.last_sweep) >= SWEEP_EVERY {
            self.entries.retain(|_, e| {
                e.hits
                    .back()
                    .is_some_and(|&t| now.duration_since(t) < e.window)
            });
            self.last_sweep = now;
        }
        let entry = self.entries.entry(key.to_owned()).or_insert_with(|| Entry {
            window,
            hits: VecDeque::new(),
        });
        entry.window = window;
        while entry
            .hits
            .front()
            .is_some_and(|&t| now.duration_since(t) >= window)
        {
            entry.hits.pop_front();
        }
        if entry.hits.len() >= max {
            let oldest = entry.hits.front().copied().unwrap_or(now);
            return Err(window.saturating_sub(now.duration_since(oldest)));
        }
        entry.hits.push_back(now);
        Ok(())
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }
}

static LIMITER: LazyLock<Mutex<Limiter>> = LazyLock::new(|| Mutex::new(Limiter::new(Instant::now())));

/// The key a step counts under: the step, then what it counts by.
fn counter_key(scope: &str, key: &str) -> String {
    format!("{scope}\u{1f}{key}")
}

/// The answer of a step past its limit: a 429 with the seconds to wait in `Retry-After`.
fn too_many(wait: Duration) -> anyhow::Error {
    HttpError::new(429, "too many attempts, try again later")
        .with_retry_after(wait.as_secs().max(1))
        .into()
}

/// The step: `scope` is the step, `key` what it counts by (an e-mail, an address). Past `max` attempts in
/// `window_secs`, the answer is a 429 with the seconds to wait in `Retry-After`.
pub fn check(scope: &str, key: &str, max: u32, window_secs: u32) -> Result<()> {
    let key = counter_key(scope, key);
    let outcome = LIMITER
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
        .check(
            &key,
            max as usize,
            Duration::from_secs(u64::from(window_secs)),
            Instant::now(),
        );
    outcome.map_err(too_many)
}

/// The step with `shared`: the same rule, counted in the key-value server so that every instance sees the same attempts. When
/// the server cannot be reached, it counts in memory (see the top of this file).
#[cfg(feature = "shared-limit")]
pub async fn check_shared(scope: &str, key: &str, max: u32, window_secs: u32) -> Result<()> {
    let counter = counter_key(scope, key);
    match store::hit(&counter, max, window_secs).await {
        Ok(None) => Ok(()),
        Ok(Some(wait)) => Err(too_many(wait)),
        Err(unreachable) => {
            store::note_failure(&unreachable);
            check(scope, key, max, window_secs)
        }
    }
}

/// A service that has a shared `rateLimit` does not start when the server is not named in production, or is not a Redis URL.
#[cfg(feature = "shared-limit")]
pub fn check_config() -> Result<()> {
    store::check_config()
}

#[cfg(feature = "shared-limit")]
mod store {
    use super::*;
    use redis::aio::ConnectionManager;
    use tokio::sync::OnceCell;

    /// How long the store has to answer: a rate limit must not make a request wait for a server that is gone.
    const ANSWER_WITHIN: Duration = Duration::from_millis(250);
    /// How long the store is left alone after it failed to answer, counting in memory meanwhile.
    const LEAVE_ALONE: Duration = Duration::from_secs(5);

    /// What the server runs, atomically. `KEYS[1]` the counter, `ARGV[1]` the most attempts, `ARGV[2]` the window in
    /// milliseconds, `ARGV[3]` a name for this attempt that no other has. It answers `{ 0, 0 }` when the attempt is counted, or
    /// `{ 1, milliseconds to wait }` when the window is full: the wait is the time until the oldest attempt leaves it.
    const SCRIPT: &str = r#"
local t = redis.call('TIME')
local now = t[1] * 1000 + math.floor(t[2] / 1000)
local window = tonumber(ARGV[2])
redis.call('ZREMRANGEBYSCORE', KEYS[1], '-inf', now - window)
if redis.call('ZCARD', KEYS[1]) >= tonumber(ARGV[1]) then
  local oldest = redis.call('ZRANGE', KEYS[1], 0, 0, 'WITHSCORES')
  return { 1, window - (now - tonumber(oldest[2])) }
end
redis.call('ZADD', KEYS[1], now, ARGV[3])
redis.call('PEXPIRE', KEYS[1], window)
return { 0, 0 }
"#;

    static CONNECTION: OnceCell<ConnectionManager> = OnceCell::const_new();
    static SCRIPT_HANDLE: LazyLock<redis::Script> = LazyLock::new(|| redis::Script::new(SCRIPT));
    /// Until when the store is left alone, after a failure.
    static LEFT_ALONE_UNTIL: Mutex<Option<Instant>> = Mutex::new(None);
    /// Makes the name of each attempt unique in the process; the random part makes it unique between processes.
    static SEQUENCE: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    static PROCESS: LazyLock<u64> = LazyLock::new(rand::random::<u64>);

    pub(super) fn url() -> Result<String> {
        match std::env::var("DRAGONFLY_URL") {
            Ok(url) if !url.trim().is_empty() => Ok(url.trim().to_string()),
            _ if std::env::var("APP_ENV").is_ok_and(|e| e == "production") => {
                anyhow::bail!("DRAGONFLY_URL is required in production")
            }
            _ => Ok("redis://localhost:6379".into()),
        }
    }

    pub(super) fn check_config() -> Result<()> {
        let url = url()?;
        if !(url.starts_with("redis://") || url.starts_with("rediss://") || url.starts_with("redis+unix://")) {
            anyhow::bail!("DRAGONFLY_URL must be a redis:// or rediss:// URL");
        }
        Ok(())
    }

    fn lock<T>(m: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
        m.lock().unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Counts an attempt in the store. `Ok(None)`: counted. `Ok(Some(wait))`: the window is full. `Err`: the store did not
    /// answer, and the caller counts in memory.
    pub(super) async fn hit(counter: &str, max: u32, window_secs: u32) -> Result<Option<Duration>, anyhow::Error> {
        if lock(&LEFT_ALONE_UNTIL).is_some_and(|until| Instant::now() < until) {
            anyhow::bail!("the store failed a moment ago");
        }
        let attempt = format!(
            "{:016x}{:016x}",
            *PROCESS,
            SEQUENCE.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
        );
        let call = async {
            let mut connection = CONNECTION
                .get_or_try_init(|| async {
                    ConnectionManager::new(redis::Client::open(url()?)?)
                        .await
                        .map_err(anyhow::Error::from)
                })
                .await?
                .clone();
            let (full, wait_ms): (i64, i64) = SCRIPT_HANDLE
                .key(format!("rl:{counter}"))
                .arg(max)
                .arg(u64::from(window_secs) * 1000)
                .arg(attempt)
                .invoke_async(&mut connection)
                .await?;
            Ok::<_, anyhow::Error>((full != 0).then(|| Duration::from_millis(wait_ms.max(0) as u64)))
        };
        match tokio::time::timeout(ANSWER_WITHIN, call).await {
            Ok(outcome) => outcome,
            Err(_) => anyhow::bail!("the store did not answer within {ANSWER_WITHIN:?}"),
        }
    }

    /// Leaves the store alone for a while, and says so once for the whole while.
    pub(super) fn note_failure(error: &anyhow::Error) {
        let mut until = lock(&LEFT_ALONE_UNTIL);
        let now = Instant::now();
        if until.is_none_or(|u| now >= u) {
            tracing::warn!(%error, "shared rate limit: the store is out of reach, counting in memory");
            *until = Some(now + LEAVE_ALONE);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const MINUTE: Duration = Duration::from_secs(60);

    #[test]
    fn blocks_after_max_then_reopens() {
        let t0 = Instant::now();
        let mut limiter = Limiter::new(t0);
        for i in 0..3 {
            assert!(limiter.check("a", 3, MINUTE, t0 + Duration::from_secs(i)).is_ok());
        }
        let wait = limiter
            .check("a", 3, MINUTE, t0 + Duration::from_secs(10))
            .unwrap_err();
        assert_eq!(wait, Duration::from_secs(50));
        assert!(limiter.check("a", 3, MINUTE, t0 + Duration::from_secs(61)).is_ok());
    }

    #[test]
    fn keys_are_independent() {
        let t0 = Instant::now();
        let mut limiter = Limiter::new(t0);
        assert!(limiter.check("a", 1, MINUTE, t0).is_ok());
        assert!(limiter.check("b", 1, MINUTE, t0).is_ok());
        assert!(limiter.check("a", 1, MINUTE, t0).is_err());
    }

    #[test]
    fn a_refused_attempt_is_not_counted() {
        // Otherwise a client that keeps trying would never get out of the window.
        let t0 = Instant::now();
        let mut limiter = Limiter::new(t0);
        assert!(limiter.check("a", 1, MINUTE, t0).is_ok());
        for i in 1..30 {
            assert!(limiter.check("a", 1, MINUTE, t0 + Duration::from_secs(i)).is_err());
        }
        assert!(limiter.check("a", 1, MINUTE, t0 + Duration::from_secs(61)).is_ok());
    }

    #[test]
    fn quiet_keys_are_forgotten() {
        let t0 = Instant::now();
        let mut limiter = Limiter::new(t0);
        for i in 0..100 {
            limiter.check(&format!("k{i}"), 1, MINUTE, t0).unwrap();
        }
        assert_eq!(limiter.len(), 100);
        // Two minutes later a new key arrives: the sweep drops the 100 that expired.
        limiter.check("fresh", 1, MINUTE, t0 + Duration::from_secs(120)).unwrap();
        assert_eq!(limiter.len(), 1);
        assert!(!limiter.is_empty());
    }

    #[test]
    fn the_step_answers_a_429_with_retry_after() {
        let scope = "test-step";
        for _ in 0..2 {
            check(scope, "someone", 2, 900).unwrap();
        }
        let error = check(scope, "someone", 2, 900).unwrap_err();
        let http = error.downcast_ref::<HttpError>().unwrap();
        assert_eq!(http.status, 429);
        let wait = http.retry_after.unwrap();
        assert!((1..=900).contains(&wait), "{wait}");
        // Another key, and another step, are not affected.
        check(scope, "someone else", 2, 900).unwrap();
        check("another-step", "someone", 2, 900).unwrap();
    }

    /// A key no other run of the tests has used, so that a server that keeps its counters does not make them depend on each other.
    #[cfg(feature = "shared-limit")]
    fn unique(prefix: &str) -> String {
        format!("{prefix}-{:016x}", rand::random::<u64>())
    }

    #[cfg(feature = "shared-limit")]
    #[tokio::test]
    async fn the_shared_step_answers_a_429_without_a_server() {
        // With a server named, the test against it (below) is the one that runs: the connection of the store is made once for
        // the process, in the runtime of whichever test asks first, and the tests each have a runtime of their own.
        if std::env::var_os("DRAGONFLY_URL").is_some() {
            return;
        }
        // Nothing to count in: the step counts in memory, and the third attempt of two is refused, with the same answer as the
        // step without the option.
        let (scope, key) = (unique("shared-step"), unique("someone"));
        for _ in 0..2 {
            check_shared(&scope, &key, 2, 900).await.unwrap();
        }
        let error = check_shared(&scope, &key, 2, 900).await.unwrap_err();
        let http = error.downcast_ref::<HttpError>().unwrap();
        assert_eq!(http.status, 429);
        assert!((1..=900).contains(&http.retry_after.unwrap()));
        check_shared(&scope, &unique("someone else"), 2, 900).await.unwrap();
    }

    #[cfg(feature = "shared-limit")]
    #[test]
    fn the_store_is_a_redis_url() {
        // Not production: a missing variable is the local server, and a wrong one is refused.
        if std::env::var_os("DRAGONFLY_URL").is_none() && std::env::var_os("APP_ENV").is_none() {
            assert!(check_config().is_ok());
        }
    }

    /// Against a real server: `DRAGONFLY_URL=redis://localhost:6379 cargo test -p eda-runtime --features shared-limit --lib
    /// rate_limit -- --ignored`. The attempts must be in the server (not in this process), the window must reopen by itself, and
    /// a refused attempt must not be counted.
    #[cfg(feature = "shared-limit")]
    #[tokio::test]
    #[ignore = "needs DRAGONFLY_URL"]
    async fn the_store_counts_the_window_for_every_instance() {
        let url = std::env::var("DRAGONFLY_URL").expect("DRAGONFLY_URL");
        let mut server = redis::Client::open(url).unwrap().get_multiplexed_async_connection().await.unwrap();
        let (scope, key) = (unique("store"), unique("someone"));
        let counter = format!("rl:{}", counter_key(&scope, &key));
        for _ in 0..3 {
            check_shared(&scope, &key, 3, 1).await.unwrap();
        }
        let counted: i64 = redis::cmd("ZCARD").arg(&counter).query_async(&mut server).await.unwrap();
        assert_eq!(counted, 3, "the attempts are in the server");
        for _ in 0..5 {
            assert!(check_shared(&scope, &key, 3, 1).await.is_err());
        }
        let counted: i64 = redis::cmd("ZCARD").arg(&counter).query_async(&mut server).await.unwrap();
        assert_eq!(counted, 3, "a refused attempt is not counted");
        // Nothing in this process's memory: the in-memory limiter never saw the key.
        assert!(LIMITER.lock().unwrap().entries.is_empty() || !LIMITER.lock().unwrap().entries.contains_key(&counter_key(&scope, &key)));
        // The window reopens by itself, and the counter does not outlive it.
        tokio::time::sleep(Duration::from_millis(1100)).await;
        check_shared(&scope, &key, 3, 1).await.unwrap();
        let ttl: i64 = redis::cmd("PTTL").arg(&counter).query_async(&mut server).await.unwrap();
        assert!((1..=1000).contains(&ttl), "{ttl}");
    }
}
