    fn a_token_signed_by_another_key_is_refused() {
        let forged = signed(&JwtKeys::from_seed(&[2; 32]), claims(), 300);
        assert!(verifier(&JwtKeys::from_seed(&[1; 32])).verify(&forged, "issuer").is_none());
    }

    #[test]
    fn expired_wrong_issuer_and_tampered_tokens_are_refused() {
        let keys = JwtKeys::from_seed(&[1; 32]);
        let verifier = verifier(&keys);
        // Expired a minute ago (the tolerance is 5 seconds), and just expired (within it).
        assert!(verifier.verify(&signed(&keys, claims(), -60), "issuer").is_none());
        assert!(verifier.verify(&signed(&keys, claims(), -2), "issuer").is_some(), "within the tolerance");
        let token = signed(&keys, claims(), 300);
        assert!(verifier.verify(&token, "another").is_none(), "wrong issuer");
        // Another payload, with the original signature.
        let mut parts: Vec<String> = token.split('.').map(str::to_owned).collect();
        let mut other = claims();
        other.insert("tid".into(), "tenant-2".into());
        other.extend([("iss".into(), "issuer".into()), ("exp".into(), (now() + 300).into())]);
        parts[1] = URL_SAFE_NO_PAD.encode(serde_json::to_vec(&other).unwrap());
        assert!(verifier.verify(&parts.join("."), "issuer").is_none());
        // No `sub`: not an access token.
        let mut nameless = claims();
        nameless.remove("sub");
        assert!(verifier.verify(&signed(&keys, nameless, 300), "issuer").is_none());
    }

    #[test]
    fn none_and_hmac_algorithms_are_refused() {
        let keys = JwtKeys::from_seed(&[1; 32]);
        let verifier = verifier(&keys);
        let header = URL_SAFE_NO_PAD.encode(br#"{"alg":"none","typ":"JWT","kid":"x"}"#);
        let payload = URL_SAFE_NO_PAD.encode(serde_json::to_vec(&claims()).unwrap());
        assert!(verifier.verify(&format!("{header}.{payload}."), "issuer").is_none());
        // HS256 signed with the public key as the secret (the classic attack), with the right `kid` to get as far as the check.
        let mut hs_header = Header::new(Algorithm::HS256);
        hs_header.kid = Some(keys.jwk().kid);
        let mut payload = claims();
        payload.extend([("iss".into(), "issuer".into()), ("exp".into(), (now() + 300).into())]);
        let hs = encode(&hs_header, &payload, &Hs::from_secret(&keys.public)).unwrap();
        assert!(verifier.verify(&hs, "issuer").is_none());
    }

