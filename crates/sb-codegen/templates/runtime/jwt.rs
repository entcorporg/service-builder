    /// A one-shot HTTP server answering the same JWKS to each connection, for the remote tests.
    async fn serve(jwks: std::sync::Arc<Mutex<String>>) -> (String, std::sync::Arc<std::sync::atomic::AtomicU32>) {
        use std::sync::atomic::{AtomicU32, Ordering};
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let url = format!("http://{}/.well-known/jwks.json", listener.local_addr().unwrap());
        let hits = std::sync::Arc::new(AtomicU32::new(0));
        let counter = hits.clone();
        tokio::spawn(async move {
            loop {
                let (mut stream, _) = listener.accept().await.unwrap();
                counter.fetch_add(1, Ordering::SeqCst);
                // Read the request first: closing a socket that has unread data resets the connection, answer lost.
                let mut request = [0u8; 2048];
                let _ = stream.read(&mut request).await;
                let body = jwks.lock().unwrap().clone();
                let reply = format!("HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}", body.len());
                let _ = stream.write_all(reply.as_bytes()).await;
            }
        });
        (url, hits)
    }

    #[tokio::test]
    async fn a_remote_jwks_is_fetched_once_and_again_when_a_rotation_brings_a_new_key() {
        use std::sync::atomic::Ordering;
        let (old, new) = (JwtKeys::from_seed(&[3; 32]), JwtKeys::from_seed(&[4; 32]));
        let jwks = std::sync::Arc::new(Mutex::new(jwks_json(&[old.jwk()]).to_string()));
        let (url, hits) = serve(jwks.clone()).await;
        // SAFETY: only this test touches this variable.
        unsafe { std::env::set_var("EDA_TEST_JWKS_URL", &url) };
        let old_token = signed(&old, claims(), 300);
        assert!(verify(Source::Url("EDA_TEST_JWKS_URL"), "issuer", &old_token).await.is_ok());
        assert!(verify(Source::Url("EDA_TEST_JWKS_URL"), "issuer", &old_token).await.is_ok());
        assert_eq!(hits.load(Ordering::SeqCst), 1, "kept in memory");
        // The issuer rotates: a token of the new key names a key we do not know. Within the refetch delay, no
        // new fetch, so that a stream of forged `kid`s cannot make the service fetch on every request.
        *jwks.lock().unwrap() = jwks_json(&[new.jwk(), old.jwk()]).to_string();
        let new_token = signed(&new, claims(), 300);
        assert!(verify(Source::Url("EDA_TEST_JWKS_URL"), "issuer", &new_token).await.is_err());
        assert_eq!(hits.load(Ordering::SeqCst), 1, "not before the delay");
        // After the delay, the unknown key triggers the fetch, and the token is accepted.
        remote::CACHE.lock().unwrap().get_mut(&url).unwrap().fetched = Instant::now() - Duration::from_secs(11);
        assert!(verify(Source::Url("EDA_TEST_JWKS_URL"), "issuer", &new_token).await.is_ok());
        assert_eq!(hits.load(Ordering::SeqCst), 2);
        assert!(verify(Source::Url("EDA_TEST_JWKS_URL"), "issuer", &old_token).await.is_ok(), "still published");
    }

    #[test]
    fn a_bearer_header_gives_its_token() {
        assert_eq!(bearer("Bearer abc.def.ghi"), "abc.def.ghi");
        assert_eq!(bearer("  bearer   abc  "), "abc");
        assert_eq!(bearer("BEARER x"), "x");
        // Not a bearer header: nothing, which no token matches.
        for other in ["", "abc.def.ghi", "Basic dXNlcjpwYXNz", "Bearer", "Bearertoken"] {
            assert_eq!(bearer(other), "", "{other:?}");
        }
    }

    #[test]
    fn claims_become_the_schema_the_flow_reads() {
        #[derive(serde::Deserialize, Default, Debug, PartialEq)]
        #[serde(default)]
        struct Claims {
            sub: String,
            roles: Vec<String>,
            tid: String,
        }
        let mut c = claims();
        // The standard claims the schema does not name are ignored; the ones the token lacks take their default.
        c.insert("iat".into(), 1.into());
        c.remove("tid");
        let got: Claims = claims_into(c).unwrap();
        assert_eq!(got, Claims { sub: "account-1".into(), roles: vec!["staff".into()], tid: String::new() });
        // A claim of another type than the schema says: a 401, not a 500.
        let mut wrong = Map::new();
        wrong.insert("roles".into(), "staff".into());
        let error = claims_into::<Claims>(wrong).unwrap_err();
        assert_eq!(error.downcast_ref::<HttpError>().unwrap().status, 401);
    }

