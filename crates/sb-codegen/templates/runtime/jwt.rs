    #[test]
    fn a_rotation_keeps_the_old_tokens_valid_until_the_old_key_is_removed() {
        let (old, new) = (JwtKeys::from_seed(&[1; 32]), JwtKeys::from_seed(&[2; 32]));
        let (old_token, new_token) = (signed(&old, claims(), 300), signed(&new, claims(), 300));
        let during = JwksVerifier::from_jwks(&jwks_json(&[new.jwk(), old.jwk()])).unwrap();
        assert!(during.verify(&old_token, "issuer").is_some() && during.verify(&new_token, "issuer").is_some());
        // The tokens of the old key have all expired: it is taken out.
        let after = JwksVerifier::from_jwks(&jwks_json(&[new.jwk()])).unwrap();
        assert!(after.verify(&old_token, "issuer").is_none() && after.verify(&new_token, "issuer").is_some());
        // A JWKS with no usable key is an error, not a verifier that refuses everything.
        assert!(JwksVerifier::from_jwks(&serde_json::json!({ "keys": [] })).is_err());
        assert!(JwksVerifier::from_jwks(&serde_json::json!({ "keys": [{ "kty": "RSA", "kid": "a", "n": "x" }] })).is_err());
    }

