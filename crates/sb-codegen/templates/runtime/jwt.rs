//! What the JWT steps call: access tokens signed with Ed25519 (EdDSA), verifiable without a database, and the
//! JWKS that publishes the public keys to the services that check them on their own.
//!
//! The algorithm is imposed (EdDSA): `none`, and HS256 signed with the public key as a secret, are refused.
//! Issuer, `exp` (5 seconds of tolerance) and the `sub` claim are checked. The key id (`kid`, derived from the
//! public key) picks the verification key, which is what makes a rotation possible: the old key stays published
//! while the tokens it signed can still circulate.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::collections::HashMap;
use std::sync::{LazyLock, Mutex};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use anyhow::{Result, anyhow};
use base64::Engine;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use ed25519_dalek::SigningKey;
use jsonwebtoken::{Algorithm, DecodingKey, EncodingKey, Header, Validation, decode, decode_header, encode};
pub use serde_json::json;
use serde_json::{Map, Value};
use sha2::{Digest, Sha256};

use crate::http::HttpError;

/// Tolerance on `exp` for clocks that are slightly off.
const LEEWAY_SECS: u64 = 5;

/// The PKCS#8 prefix of an Ed25519 private key (RFC 8410), followed by the 32 bytes of the seed.
const PKCS8_ED25519_PREFIX: [u8; 16] = [
    0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x04, 0x22, 0x04, 0x20,
];

/// A key id derived from the public key: the same key always has the same one, on every instance.
fn kid_of(public: &[u8; 32]) -> String {
    URL_SAFE_NO_PAD.encode(&Sha256::digest(public)[..8])
}

/// The public half of a signing key, as a JWK (RFC 7517). Nothing private is ever in it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Jwk {
    pub kty: String,
    pub crv: String,
    pub alg: String,
    pub kid: String,
    pub x: String,
}

/// The signing side: holds the private seed.
pub struct JwtKeys {
    encoding: EncodingKey,
    public: [u8; 32],
    kid: String,
}

impl JwtKeys {
    pub fn from_seed(seed: &[u8; 32]) -> Self {
        let public = SigningKey::from_bytes(seed).verifying_key().to_bytes();
        let mut pkcs8 = PKCS8_ED25519_PREFIX.to_vec();
        pkcs8.extend_from_slice(seed);
        Self {
            encoding: EncodingKey::from_ed_der(&pkcs8),
            kid: kid_of(&public),
            public,
        }
    }

    /// The seed of an environment variable: 32 bytes as 64 hexadecimal characters. A service that has a JWT step
    /// fails at start-up when it is missing or malformed.
    pub fn from_env(env_name: &str) -> Result<Self> {
        Ok(Self::from_seed(&crate::crypto::key(env_name)?))
    }

    pub fn jwk(&self) -> Jwk {
        Jwk {
            kty: "OKP".into(),
            crv: "Ed25519".into(),
            alg: "EdDSA".into(),
            kid: self.kid.clone(),
            x: URL_SAFE_NO_PAD.encode(self.public),
        }
    }

    fn sign(&self, claims: &Map<String, Value>) -> Result<String> {
        let mut header = Header::new(Algorithm::EdDSA);
        header.kid = Some(self.kid.clone());
        encode(&header, claims, &self.encoding).map_err(|e| anyhow!("cannot sign the token: {e}"))
    }
}

fn now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.as_secs() as i64)
}

/// The step `signJwt`: the claims of the author plus `iss`, `iat` and `exp`, which the author cannot override.
pub fn sign(key_env: &str, issuer: &str, ttl_secs: u32, mut claims: Map<String, Value>) -> Result<String> {
    let issued = now();
    claims.insert("iss".into(), issuer.into());
    claims.insert("iat".into(), issued.into());
    claims.insert("exp".into(), (issued + i64::from(ttl_secs)).into());
    JwtKeys::from_env(key_env)?.sign(&claims)
}

/// The step `jwks`: the public keys of these seeds, the first being the one that signs. A rotation puts the new
/// seed first and keeps the old one listed until its tokens have expired.
pub fn public_keys(key_envs: &[&str]) -> Result<Vec<Jwk>> {
    key_envs
        .iter()
        .map(|env| Ok(JwtKeys::from_env(env)?.jwk()))
        .collect()
}

/// A JWKS (RFC 7517), as JSON.
pub fn jwks_json(keys: &[Jwk]) -> Value {
    serde_json::json!({ "keys": keys.iter().map(|k| serde_json::json!({
        "kty": k.kty, "crv": k.crv, "use": "sig", "alg": k.alg, "kid": k.kid, "x": k.x,
    })).collect::<Vec<_>>() })
}

/// The verifying side: knows the public keys of a JWKS, never a seed.
#[derive(Clone)]
pub struct JwksVerifier {
    keys: HashMap<String, DecodingKey>,
}

impl JwksVerifier {
    /// Reads a JWKS; ignores the keys that are not `OKP`/`Ed25519`.
    pub fn from_jwks(jwks: &Value) -> Result<Self> {
        let mut keys = HashMap::new();
        for jwk in jwks["keys"].as_array().into_iter().flatten() {
            if jwk["kty"] != "OKP" || jwk["crv"] != "Ed25519" {
                continue;
            }
            let (Some(kid), Some(x)) = (jwk["kid"].as_str(), jwk["x"].as_str()) else {
                continue;
            };
            let public = URL_SAFE_NO_PAD
                .decode(x)
                .map_err(|_| anyhow!("the `x` of a key of the JWKS is not readable"))?;
            keys.insert(kid.to_owned(), DecodingKey::from_ed_der(&public));
        }
        if keys.is_empty() {
            anyhow::bail!("the JWKS has no usable Ed25519 key");
        }
        Ok(Self { keys })
    }

    fn knows(&self, token: &str) -> bool {
        decode_header(token)
            .ok()
            .and_then(|h| h.kid)
            .is_some_and(|kid| self.keys.contains_key(&kid))
    }

    /// Checks the signature, the algorithm (EdDSA only), the issuer and the expiry. Whatever the reason of a
    /// refusal, `None`: the client is told nothing more than "invalid token".
    pub fn verify(&self, token: &str, issuer: &str) -> Option<Map<String, Value>> {
        let header = decode_header(token).ok()?;
        let key = self.keys.get(header.kid.as_deref()?)?;
        let mut validation = Validation::new(Algorithm::EdDSA);
        validation.leeway = LEEWAY_SECS;
        validation.set_issuer(&[issuer]);
        validation.set_required_spec_claims(&["exp", "iss", "sub"]);
        match decode::<Value>(token, key, &validation).ok()?.claims {
            Value::Object(claims) => Some(claims),
            _ => None,
        }
    }
}

/// The token of an `Authorization: Bearer <token>` header: what follows the word (any case), or nothing, which no
/// token matches.
pub fn bearer(header: &str) -> &str {
    let header = header.trim();
    match header.split_once(char::is_whitespace) {
        Some((scheme, token)) if scheme.eq_ignore_ascii_case("bearer") => token.trim(),
        _ => "",
    }
}

/// The claims of a verified token as the API schema the flow reads. A claim the token lacks has the default of its
/// field; one of another type than the schema says is a 401, like any token this service does not understand.
pub fn claims_into<T: serde::de::DeserializeOwned>(claims: Map<String, Value>) -> Result<T> {
    serde_json::from_value(Value::Object(claims)).map_err(|e| {
        tracing::warn!(error = %e, "a verified token does not fit the claims schema");
        HttpError::unauthorized("invalid token").into()
    })
}

/// The URL of the JWKS of the service that signs, from the environment variable `env_name`. A service that
/// verifies with it fails at start-up when it is missing or is not `http://`.
pub fn jwks_url(env_name: &str) -> Result<String> {
    let url = std::env::var(env_name).map_err(|_| anyhow!("{env_name} is not set: the JWKS cannot be fetched"))?;
    if !url.starts_with("http://") {
        anyhow::bail!("{env_name} must start with http:// (services talk inside their network)");
    }
    Ok(url)
}

/// Where the public keys of a `verifyJwt` step come from.
pub enum Source<'a> {
    /// The seeds of this service, in the environment: it verifies what it signs.
    Keys(&'a [&'a str]),
    /// The environment variable that holds the URL (`http://host:port/path`) of the JWKS of the service that signs.
    Url(&'a str),
}

/// The step `verifyJwt`: the claims of a valid token, or a 401 that says nothing about why.
pub async fn verify(source: Source<'_>, issuer: &str, token: &str) -> Result<Map<String, Value>> {
    let claims = match source {
        Source::Keys(envs) => {
            let jwks = jwks_json(&public_keys(envs)?);
            JwksVerifier::from_jwks(&jwks)?.verify(token, issuer)
        }
        Source::Url(env) => remote::verify(env, issuer, token).await?,
    };
    claims.ok_or_else(|| HttpError::unauthorized("invalid token").into())
}

/// A JWKS fetched over plain HTTP from the service that signs (they talk inside the same network), kept in memory
/// and fetched again when a token names a key that is not in it: that is how a rotation reaches the services that
/// verify, without a restart.
mod remote {
    use super::*;
    use tokio::io::{AsyncReadExt, AsyncWriteExt};

    /// A JWKS is a few hundred bytes: anything bigger is not one.
    const MAX_BODY: usize = 64 * 1024;
    const TIMEOUT: Duration = Duration::from_secs(5);
    /// A token with an unknown key id cannot make the service fetch more often than this.
    const REFETCH_AFTER: Duration = Duration::from_secs(10);

    pub(super) struct Cached {
        verifier: JwksVerifier,
        pub(super) fetched: Instant,
    }

    pub(super) static CACHE: LazyLock<Mutex<HashMap<String, Cached>>> = LazyLock::new(|| Mutex::new(HashMap::new()));

    pub(super) async fn verify(url_env: &str, issuer: &str, token: &str) -> Result<Option<Map<String, Value>>> {
        let url = jwks_url(url_env)?;
        let cached = CACHE
            .lock()
            .unwrap_or_else(|p| p.into_inner())
            .get(&url)
            .map(|c| (c.verifier.clone(), c.fetched));
        let verifier = match cached {
            Some((v, fetched)) if v.knows(token) || fetched.elapsed() < REFETCH_AFTER => v,
            _ => {
                let jwks = fetch(&url).await?;
                let verifier = JwksVerifier::from_jwks(&jwks)?;
                CACHE.lock().unwrap_or_else(|p| p.into_inner()).insert(
                    url,
                    Cached {
                        verifier: verifier.clone(),
                        fetched: Instant::now(),
                    },
                );
                verifier
            }
        };
        Ok(verifier.verify(token, issuer))
    }

    /// `GET` of a JWKS, `http://host[:port]/path` only.
    pub(super) async fn fetch(url: &str) -> Result<Value> {
        let rest = url
            .strip_prefix("http://")
            .ok_or_else(|| anyhow!("the JWKS URL must start with http:// (services talk inside their network)"))?;
        let (authority, path) = rest.split_once('/').map_or((rest, "/".to_string()), |(a, p)| (a, format!("/{p}")));
        let address = if authority.contains(':') { authority.to_string() } else { format!("{authority}:80") };
        let exchange = async {
            let mut stream = tokio::net::TcpStream::connect(&address).await?;
            let request = format!("GET {path} HTTP/1.1\r\nHost: {authority}\r\nAccept: application/json\r\nConnection: close\r\n\r\n");
            stream.write_all(request.as_bytes()).await?;
            let mut response = Vec::new();
            stream.take(MAX_BODY as u64 + 4096).read_to_end(&mut response).await?;
            anyhow::Ok(response)
        };
        let response = tokio::time::timeout(TIMEOUT, exchange)
            .await
            .map_err(|_| anyhow!("the JWKS at {url} did not answer in time"))??;
        let text = String::from_utf8_lossy(&response);
        let (head, body) = text.split_once("\r\n\r\n").ok_or_else(|| anyhow!("the JWKS at {url} sent no HTTP answer"))?;
        let status = head.split_whitespace().nth(1).unwrap_or_default();
        if status != "200" {
            anyhow::bail!("the JWKS at {url} answered {status}");
        }
        if head.to_ascii_lowercase().contains("transfer-encoding: chunked") {
            anyhow::bail!("the JWKS at {url} is chunked: it has to be sent with a Content-Length");
        }
        if body.len() > MAX_BODY {
            anyhow::bail!("the JWKS at {url} is too big");
        }
        Ok(serde_json::from_str(body)?)
    }
}

