//! What the steps `meter` and `checkQuota` call: the uses of a service counted per tenant and per period, in its database.
//!
//! Every use is a row of `usage_events` (the meter, the tenant, how many units, when), written in the transaction of the handler
//! that makes the use: the use and what it pays for commit together, or not at all. A view, `usage_daily`, adds them up per
//! meter, tenant and day, for a dashboard or an invoice; the rows themselves are kept, they are the record a bill is checked
//! against. A use can carry an idempotency key: the same key a second time is ignored, so that a retried request or a
//! redelivered event is counted once.
//!
//! A quota is checked against the rows, not against a counter kept next to them, so the two can never disagree. The calendar
//! periods (`hour`, `day`, `month`, `year`) are in UTC. To keep two requests of one tenant from both taking the last unit, the
//! check takes a lock on the meter and the tenant that lasts until the transaction ends (`pg_advisory_xact_lock`): the next
//! check of the same pair waits for this run to commit, then sees its use.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::Result;

use crate::http::HttpError;

/// The table of the uses, created with the schema of the service. `amount` is signed: a negative amount gives units back (a seat
/// released, a file deleted).
pub const CREATE_EVENTS_TABLE: &str = "CREATE TABLE IF NOT EXISTS usage_events (id BIGSERIAL PRIMARY KEY, meter TEXT NOT NULL, tenant TEXT NOT NULL, amount BIGINT NOT NULL, idempotency_key TEXT, occurred_at TIMESTAMPTZ NOT NULL DEFAULT now())";

/// What a check reads: the uses of one tenant of one meter, from a date.
pub const CREATE_EVENTS_INDEX: &str = "CREATE INDEX IF NOT EXISTS usage_events_by_tenant ON usage_events (meter, tenant, occurred_at)";

/// A use with the same idempotency key is the same use. Rows without a key are all distinct (NULLs are, in a unique index).
pub const CREATE_EVENTS_UNIQUE: &str = "CREATE UNIQUE INDEX IF NOT EXISTS usage_events_idempotency ON usage_events (meter, tenant, idempotency_key)";

/// The uses added up per meter, tenant and day (UTC).
pub const CREATE_DAILY_VIEW: &str = "CREATE OR REPLACE VIEW usage_daily AS SELECT meter, tenant, date_trunc('day', occurred_at AT TIME ZONE 'UTC') AS day, SUM(amount)::BIGINT AS total, COUNT(*)::BIGINT AS events FROM usage_events GROUP BY meter, tenant, date_trunc('day', occurred_at AT TIME ZONE 'UTC')";

/// What a quota adds the uses up over.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Period {
    Hour,
    Day,
    Month,
    Year,
    /// Everything since the first use.
    Forever,
}

impl Period {
    /// The unit `date_trunc` cuts the calendar at.
    fn unit(self) -> Option<&'static str> {
        match self {
            Period::Hour => Some("hour"),
            Period::Day => Some("day"),
            Period::Month => Some("month"),
            Period::Year => Some("year"),
            Period::Forever => None,
        }
    }
}

/// Records a use: `amount` units of `meter` for `tenant`. `false`: `idempotency_key` was already used for this meter and tenant,
/// the use was counted before and this one is ignored.
///
/// Call it inside the transaction of the handler: if the handler fails, the use is rolled back with the rest.
pub async fn meter(
    tx: &mut sqlx::PgConnection,
    meter: &str,
    tenant: &str,
    amount: i64,
    idempotency_key: Option<&str>,
) -> Result<bool> {
    let inserted = sqlx::query(
        "INSERT INTO usage_events (meter, tenant, amount, idempotency_key) VALUES ($1, $2, $3, $4) ON CONFLICT DO NOTHING",
    )
    .bind(meter)
    .bind(tenant)
    .bind(amount)
    .bind(idempotency_key)
    .execute(tx)
    .await?
    .rows_affected();
    Ok(inserted == 1)
}

/// What a tenant used of a meter over a period, and when the period ends.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Usage {
    pub used: i64,
    /// Seconds until the period ends (`None` for `forever`).
    pub resets_in: Option<u64>,
}

/// The uses of `tenant` of `meter` over the current period. Read-only and lock-free: a dashboard can call it.
pub async fn usage(tx: &mut sqlx::PgConnection, meter: &str, tenant: &str, period: Period) -> Result<Usage> {
    match period.unit() {
        None => {
            let used: i64 = sqlx::query_scalar(
                "SELECT COALESCE(SUM(amount), 0)::BIGINT FROM usage_events WHERE meter = $1 AND tenant = $2",
            )
            .bind(meter)
            .bind(tenant)
            .fetch_one(tx)
            .await?;
            Ok(Usage { used, resets_in: None })
        }
        Some(unit) => {
            // The period starts at the last cut of the calendar in UTC, and ends one unit later. `unit` is one of four words
            // of this file, never text from outside, and it is a parameter anyway.
            let (used, resets_in): (i64, i64) = sqlx::query_as(
                "WITH w AS (SELECT date_trunc($3, now() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC' AS since) \
                 SELECT COALESCE((SELECT SUM(amount) FROM usage_events WHERE meter = $1 AND tenant = $2 AND occurred_at >= w.since), 0)::BIGINT, \
                        CEIL(EXTRACT(EPOCH FROM ((w.since AT TIME ZONE 'UTC' + ('1 ' || $3)::interval) AT TIME ZONE 'UTC' - now())))::BIGINT \
                 FROM w",
            )
            .bind(meter)
            .bind(tenant)
            .bind(unit)
            .fetch_one(tx)
            .await?;
            Ok(Usage { used, resets_in: Some(resets_in.max(1) as u64) })
        }
    }
}

/// What is left when `wanted` more units are taken: `None` when it would pass `limit`.
fn left_after(used: i64, wanted: i64, limit: i64) -> Option<i64> {
    let total = used.checked_add(wanted)?;
    (total <= limit).then_some(limit - total)
}

/// The step: refuses with a 429 (and the seconds until the period ends in `Retry-After`) when `wanted` more units would take the
/// uses of `tenant` over `limit`; otherwise answers what is left after them. Takes the lock described at the top of this file.
pub async fn check(
    tx: &mut sqlx::PgConnection,
    meter: &str,
    tenant: &str,
    limit: i64,
    wanted: i64,
    period: Period,
) -> Result<i64> {
    sqlx::query("SELECT pg_advisory_xact_lock(hashtextextended($1, 0))")
        .bind(format!("usage\u{1f}{meter}\u{1f}{tenant}"))
        .execute(&mut *tx)
        .await?;
    let now = usage(tx, meter, tenant, period).await?;
    match left_after(now.used, wanted, limit) {
        Some(left) => Ok(left),
        None => {
            let mut error = HttpError::new(429, format!("quota exceeded for {meter}"));
            if let Some(seconds) = now.resets_in {
                error = error.with_retry_after(seconds);
            }
            Err(error.into())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlx::PgPool;

    #[test]
    fn the_last_unit_can_be_taken_and_the_next_cannot() {
        assert_eq!(left_after(0, 1, 5), Some(4));
        assert_eq!(left_after(4, 1, 5), Some(0));
        assert_eq!(left_after(5, 1, 5), None);
        assert_eq!(left_after(3, 3, 5), None);
        // Giving units back is never refused while the use stays under the limit.
        assert_eq!(left_after(5, -2, 5), Some(2));
        // An overflow is a refusal, not a panic.
        assert_eq!(left_after(i64::MAX, 1, i64::MAX), None);
    }

    #[test]
    fn only_the_calendar_periods_have_an_end() {
        assert_eq!(Period::Month.unit(), Some("month"));
        assert_eq!(Period::Hour.unit(), Some("hour"));
        assert_eq!(Period::Forever.unit(), None);
    }

    static SCHEMA: tokio::sync::OnceCell<()> = tokio::sync::OnceCell::const_new();

    /// Needs a database: `EDA_TEST_DATABASE_URL=postgres://... cargo test -p eda-runtime -- --ignored`.
    async fn database() -> PgPool {
        let url = std::env::var("EDA_TEST_DATABASE_URL").expect("EDA_TEST_DATABASE_URL");
        let db = PgPool::connect(&url).await.unwrap();
        // Created once: two `CREATE TABLE IF NOT EXISTS` at the same time can still collide.
        SCHEMA
            .get_or_init(|| async {
                for statement in [CREATE_EVENTS_TABLE, CREATE_EVENTS_INDEX, CREATE_EVENTS_UNIQUE, CREATE_DAILY_VIEW] {
                    sqlx::query(statement).execute(&db).await.unwrap();
                }
            })
            .await;
        db
    }

    /// A tenant no other test (or earlier run) has used.
    fn tenant(prefix: &str) -> String {
        format!("{prefix}-{:016x}", rand::random::<u64>())
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn uses_are_added_up_per_tenant_and_a_quota_refuses_past_its_limit() {
        let db = database().await;
        let (a, b) = (tenant("a"), tenant("b"));
        let mut tx = db.begin().await.unwrap();
        for _ in 0..3 {
            assert!(check(&mut tx, "calls", &a, 3, 1, Period::Month).await.is_ok());
            assert!(meter(&mut tx, "calls", &a, 1, None).await.unwrap());
        }
        // The fourth is refused, with the seconds until the end of the month; the tenant, and the meter, are not the same.
        let error = check(&mut tx, "calls", &a, 3, 1, Period::Month).await.unwrap_err();
        let http = error.downcast_ref::<HttpError>().unwrap();
        assert_eq!(http.status, 429);
        assert!(http.retry_after.unwrap() >= 1);
        assert_eq!(check(&mut tx, "calls", &b, 3, 1, Period::Month).await.unwrap(), 2);
        assert_eq!(check(&mut tx, "other", &a, 3, 1, Period::Month).await.unwrap(), 2);
        // A bigger request is refused as a whole, even when part of it would fit.
        assert!(check(&mut tx, "other", &a, 3, 4, Period::Day).await.is_err());
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn the_same_key_counts_once_and_units_can_be_given_back() {
        let db = database().await;
        let t = tenant("once");
        let mut tx = db.begin().await.unwrap();
        assert!(meter(&mut tx, "seats", &t, 2, Some("invite-1")).await.unwrap());
        assert!(!meter(&mut tx, "seats", &t, 2, Some("invite-1")).await.unwrap());
        assert!(meter(&mut tx, "seats", &t, 1, Some("invite-2")).await.unwrap());
        assert_eq!(usage(&mut tx, "seats", &t, Period::Forever).await.unwrap(), Usage { used: 3, resets_in: None });
        assert!(meter(&mut tx, "seats", &t, -1, None).await.unwrap());
        assert!(meter(&mut tx, "seats", &t, 0, None).await.unwrap());
        assert_eq!(usage(&mut tx, "seats", &t, Period::Forever).await.unwrap().used, 2);
        // The same key for another meter, or another tenant, is another use.
        assert!(meter(&mut tx, "storage", &t, 5, Some("invite-1")).await.unwrap());
        assert!(meter(&mut tx, "seats", &tenant("other"), 1, Some("invite-1")).await.unwrap());
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn a_period_only_counts_its_own_uses_and_the_view_adds_the_days_up() {
        let db = database().await;
        let t = tenant("period");
        let mut tx = db.begin().await.unwrap();
        // One use last year, one two days ago, one now.
        for when in ["now() - interval '400 days'", "now() - interval '2 days'", "now()"] {
            sqlx::query(&format!(
                "INSERT INTO usage_events (meter, tenant, amount, occurred_at) VALUES ('calls', $1, 10, {when})"
            ))
            .bind(&t)
            .execute(&mut *tx)
            .await
            .unwrap();
        }
        assert_eq!(usage(&mut tx, "calls", &t, Period::Forever).await.unwrap().used, 30);
        // This year holds the use of now, and the one of two days ago unless the year began in between.
        assert!((10..=20).contains(&usage(&mut tx, "calls", &t, Period::Year).await.unwrap().used));
        let hour = usage(&mut tx, "calls", &t, Period::Hour).await.unwrap();
        assert_eq!(hour.used, 10);
        assert!((1..=3600).contains(&hour.resets_in.unwrap()), "{hour:?}");
        let days: Vec<(i64, i64)> = sqlx::query_as("SELECT total, events FROM usage_daily WHERE tenant = $1 ORDER BY day")
            .bind(&t)
            .fetch_all(&mut *tx)
            .await
            .unwrap();
        assert_eq!(days, vec![(10, 1), (10, 1), (10, 1)]);
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn two_requests_of_a_tenant_cannot_both_take_the_last_unit() {
        let db = database().await;
        let t = tenant("race");
        let mut first = db.begin().await.unwrap();
        assert_eq!(check(&mut first, "calls", &t, 1, 1, Period::Month).await.unwrap(), 0);
        // The second request checks while the first has not used its unit yet: it must wait for the first run, not read an
        // empty meter and pass.
        let second = tokio::spawn({
            let (db, t) = (db.clone(), t.clone());
            async move {
                let mut tx = db.begin().await.unwrap();
                let refused = check(&mut tx, "calls", &t, 1, 1, Period::Month).await.is_err();
                tx.rollback().await.unwrap();
                refused
            }
        });
        tokio::time::sleep(std::time::Duration::from_millis(300)).await;
        assert!(!second.is_finished(), "the second check waits for the first run");
        assert!(meter(&mut first, "calls", &t, 1, None).await.unwrap());
        first.commit().await.unwrap();
        assert!(second.await.unwrap(), "once the first run has committed, the second sees its use and is refused");
        sqlx::query("DELETE FROM usage_events WHERE tenant = $1").bind(&t).execute(&db).await.unwrap();
    }
}

