//! What the `verifyChallenge` step and the challenge route call: a proof of work in the manner of ALTCHA, against the robots that
//! fill in a form. No third-party service, no cookie, nothing that follows the visitor.
//!
//! The service hands out a challenge (`GET <path>`): a random `salt`, and `challenge`, the SHA-256 of the salt followed by a
//! secret number drawn in `0..=maxnumber`, signed with an HMAC-SHA256 under a key only the services know. The widget does not
//! have the number: it tries them all until the hash is the challenge. That costs a visitor a moment of computing, and costs a
//! robot the same moment for every form it sends. The form comes back with the solution (`algorithm`, `challenge`, `number`,
//! `salt`, `signature`, as base64 of a JSON, which is what the ALTCHA widget sends), and the step checks, in this order:
//!
//! 1. the algorithm is `SHA-256`, and the number is in the range that was asked;
//! 2. the signature is the HMAC of the challenge: the challenge is one this service made (any replica: the key is shared);
//! 3. the SHA-256 of the salt and the number is the challenge: the work was done;
//! 4. the salt carries an expiry (`?expires=<unix seconds>&`, covered by the hash, so it cannot be moved) that has not passed;
//! 5. the solution has not been used: its signature is recorded in `challenge_uses`, in the transaction of the handler, with
//!    the other replicas looking at the same table. A solution is worth one form; if the handler fails after it, the record is
//!    rolled back with the rest and the visitor can send the same solution again.
//!
//! The comparisons take the same time whatever the input. Everything the step refuses is one answer to the client (400, "the
//! challenge is missing, wrong, expired or already used"): which of these it was stays in the logs.
//!
//! The format is the ALTCHA v1 one (`SHA-256`), so the widget, and any ALTCHA library, can talk to this service.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::time::{SystemTime, UNIX_EPOCH};

use anyhow::Result;
use base64::Engine as _;
use hmac::{Hmac, KeyInit, Mac};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::http::HttpError;

type HmacSha256 = Hmac<Sha256>;

/// The table of the solutions already accepted, created with the schema of the service. A row is forgotten once its challenge
/// has expired (it could not be accepted again anyway).
pub const CREATE_USES_TABLE: &str = "CREATE TABLE IF NOT EXISTS challenge_uses (signature TEXT PRIMARY KEY, expires_at TIMESTAMPTZ NOT NULL)";

/// What the widget reads.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Challenge {
    pub algorithm: String,
    pub challenge: String,
    pub maxnumber: u32,
    pub salt: String,
    pub signature: String,
}

/// What the widget sends back, as base64 of this JSON (`took` and other fields are ignored).
#[derive(Debug, Deserialize)]
struct Solution {
    algorithm: String,
    challenge: String,
    number: u64,
    salt: String,
    signature: String,
}

/// The development key, used only when `APP_ENV` is not `production` and the variable is not set: it lets a service start for a
/// try without any setting, and means anyone can make a challenge.
const DEVELOPMENT_KEY: &str = "development-only-challenge-key";
const MIN_KEY_LEN: usize = 16;

/// The key of the environment variable `env_name`. In production a service that has a challenge does not start without it.
fn key(env_name: &str) -> Result<Vec<u8>> {
    match std::env::var(env_name) {
        Ok(key) if key.trim().len() >= MIN_KEY_LEN => Ok(key.trim().as_bytes().to_vec()),
        Ok(key) if !key.trim().is_empty() => {
            anyhow::bail!("{env_name} is too short: at least {MIN_KEY_LEN} characters")
        }
        _ if std::env::var("APP_ENV").is_ok_and(|e| e == "production") => {
            anyhow::bail!("{env_name} is required in production: the key the challenges are signed with")
        }
        _ => Ok(DEVELOPMENT_KEY.as_bytes().to_vec()),
    }
}

/// A service that hands out challenges does not start without a usable key. Outside production a missing one is the
/// development key, which the log says once.
pub fn check_config(env_name: &str) -> Result<()> {
    let key = key(env_name)?;
    if key == DEVELOPMENT_KEY.as_bytes() {
        tracing::warn!("{env_name} is not set: challenges are signed with the development key, which anyone can use");
    }
    Ok(())
}

fn now() -> u64 {
    SystemTime::now().duration_since(UNIX_EPOCH).map_or(0, |d| d.as_secs())
}

fn hash(salt: &str, number: u64) -> String {
    hex::encode(Sha256::digest(format!("{salt}{number}").as_bytes()))
}

fn sign(key: &[u8], challenge: &str) -> HmacSha256 {
    // An HMAC key can have any length.
    let mut mac = HmacSha256::new_from_slice(key).expect("an HMAC key of any size");
    mac.update(challenge.as_bytes());
    mac
}

/// The seconds since 1970 at which a salt of this service stops being valid: `<hex>?expires=<seconds>&`.
fn expires_of(salt: &str) -> Option<u64> {
    let params = salt.split_once('?')?.1;
    params.split('&').find_map(|p| p.strip_prefix("expires=")?.parse().ok())
}

/// A new challenge: the secret number is in `0..=max_number`, and the solution is accepted for `ttl_secs`.
pub fn issue(env_name: &str, max_number: u32, ttl_secs: u32) -> Result<Challenge> {
    Ok(make(&key(env_name)?, max_number, ttl_secs, now(), rand::random(), rand::random()))
}

/// The challenge made of what is drawn: separate from [`issue`] so that the tests can fix the draw and the clock.
fn make(key: &[u8], max_number: u32, ttl_secs: u32, at: u64, random: [u8; 12], draw: u64) -> Challenge {
    let number = draw % (u64::from(max_number) + 1);
    // The trailing `&` keeps the number, which comes right after the salt in the hash, from running into the expiry.
    let salt = format!("{}?expires={}&", hex::encode(random), at + u64::from(ttl_secs));
    let challenge = hash(&salt, number);
    let signature = hex::encode(sign(key, &challenge).finalize().into_bytes());
    Challenge {
        algorithm: "SHA-256".into(),
        challenge,
        maxnumber: max_number,
        salt,
        signature,
    }
}

/// Why a solution was refused. The client is only told it was not accepted: which of these it was stays in the logs.
#[derive(Debug, PartialEq, Eq)]
pub enum Refused {
    Missing,
    Malformed,
    /// Not `SHA-256`, or a number beyond what was asked.
    NotAsked,
    /// Not signed by this service: forged, or from another key.
    NotOurs,
    /// The signed challenge is not the hash of the number: the work was not done.
    NotSolved,
    Expired,
    AlreadyUsed,
}

impl std::fmt::Display for Refused {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Refused::Missing => "no solution",
            Refused::Malformed => "malformed solution",
            Refused::NotAsked => "not the algorithm or the range that was asked",
            Refused::NotOurs => "the challenge was not signed by this service",
            Refused::NotSolved => "the number is not the solution of the challenge",
            Refused::Expired => "the challenge has expired",
            Refused::AlreadyUsed => "the solution was already used",
        })
    }
}

/// What the solution says, once it is known to be a solution of a challenge of this service that has not expired: the
/// signature (what is recorded as used) and when the challenge expires.
#[derive(Debug, PartialEq, Eq)]
pub struct Accepted {
    pub signature: String,
    pub expires: u64,
}

/// Checks a solution (steps 1 to 4 of the top of this file), at the time `at`. Nothing is recorded.
pub fn check(key: &[u8], max_number: u32, payload: &str, at: u64) -> Result<Accepted, Refused> {
    let payload = payload.trim();
    if payload.is_empty() {
        return Err(Refused::Missing);
    }
    let json = base64::engine::general_purpose::STANDARD
        .decode(payload)
        .or_else(|_| base64::engine::general_purpose::URL_SAFE_NO_PAD.decode(payload))
        .map_err(|_| Refused::Malformed)?;
    let solution: Solution = serde_json::from_slice(&json).map_err(|_| Refused::Malformed)?;
    if solution.algorithm != "SHA-256" || solution.number > u64::from(max_number) {
        return Err(Refused::NotAsked);
    }
    // The signature, compared by the HMAC itself in the time it takes whatever the signature is.
    let signed = hex::decode(&solution.signature).map_err(|_| Refused::Malformed)?;
    if sign(key, &solution.challenge).verify_slice(&signed).is_err() {
        return Err(Refused::NotOurs);
    }
    // The hash: both are public values, but a comparison that stops at the first difference is not one to leave around.
    let expected = hash(&solution.salt, solution.number);
    if !same(expected.as_bytes(), solution.challenge.as_bytes()) {
        return Err(Refused::NotSolved);
    }
    match expires_of(&solution.salt) {
        Some(expires) if expires > at => Ok(Accepted { signature: solution.signature, expires }),
        _ => Err(Refused::Expired),
    }
}

/// Equal, in the time it takes for equal lengths whatever they hold.
fn same(a: &[u8], b: &[u8]) -> bool {
    a.len() == b.len() && a.iter().zip(b).fold(0u8, |diff, (x, y)| diff | (x ^ y)) == 0
}

/// The step: the solution in `payload` is one of a challenge of this service, not expired, not used. Otherwise the route ends
/// with a 400. Call it inside the transaction of the handler, first, before anything that costs: if the handler fails, the use
/// is rolled back with the rest.
pub async fn verify(
    tx: &mut sqlx::PgConnection,
    key_env: &str,
    max_number: u32,
    payload: &str,
) -> Result<()> {
    let refuse = |why: Refused| {
        tracing::info!(%why, "challenge refused");
        anyhow::Error::from(HttpError::new(400, "the challenge is missing, wrong, expired or already used"))
    };
    let accepted = check(&key(key_env)?, max_number, payload, now()).map_err(refuse)?;
    let inserted = sqlx::query(
        "INSERT INTO challenge_uses (signature, expires_at) VALUES ($1, to_timestamp($2)) ON CONFLICT DO NOTHING",
    )
    .bind(&accepted.signature)
    .bind(accepted.expires as f64)
    .execute(&mut *tx)
    .await?
    .rows_affected();
    if inserted == 0 {
        return Err(refuse(Refused::AlreadyUsed));
    }
    // The rows of challenges that expired are of no use: a few requests in a hundred sweep them, so that no schedule is needed.
    if rand::random::<u8>() < 3 {
        sqlx::query("DELETE FROM challenge_uses WHERE expires_at < now()").execute(tx).await?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const KEY: &[u8] = b"a-key-of-more-than-sixteen-bytes";
    const AT: u64 = 1_800_000_000;

    /// What the widget does: tries the numbers until the hash is the challenge, then answers.
    fn solve(c: &Challenge) -> String {
        let number = (0..=u64::from(c.maxnumber)).find(|n| hash(&c.salt, *n) == c.challenge).expect("a solution");
        answer(c, number)
    }

    fn answer(c: &Challenge, number: u64) -> String {
        let json = serde_json::json!({
            "algorithm": c.algorithm, "challenge": c.challenge, "number": number, "salt": c.salt,
            "signature": c.signature, "took": 12,
        });
        base64::engine::general_purpose::STANDARD.encode(json.to_string())
    }

    fn challenge() -> Challenge {
        make(KEY, 2_000, 300, AT, [7; 12], 1_234)
    }

    #[test]
    fn a_challenge_has_the_shape_the_widget_reads() {
        let c = challenge();
        assert_eq!(c.algorithm, "SHA-256");
        assert_eq!(c.maxnumber, 2_000);
        assert_eq!(c.challenge.len(), 64);
        assert_eq!(c.signature.len(), 64);
        assert_eq!(c.salt, format!("{}?expires={}&", "07".repeat(12), AT + 300));
        // The challenge is the hash of the salt and the secret number, which is nowhere in it.
        assert_eq!(c.challenge, hash(&c.salt, 1_234));
        assert!(!serde_json::to_string(&c).unwrap().contains("1234"));
        // Known answer: the first test vector of the SHA-256 of "abc" fixes the hash function itself.
        assert_eq!(
            hex::encode(Sha256::digest(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn the_number_is_always_in_the_range_asked() {
        for draw in [0, 1, 999, 1_000, 1_001, u64::MAX] {
            let c = make(KEY, 1_000, 60, AT, [0; 12], draw);
            assert!((0..=1_000).any(|n| hash(&c.salt, n) == c.challenge), "{draw}");
        }
        // A range of one number: the number is 0.
        let c = make(KEY, 0, 60, AT, [0; 12], u64::MAX);
        assert_eq!(c.challenge, hash(&c.salt, 0));
    }

    #[test]
    fn a_solved_challenge_is_accepted() {
        let c = challenge();
        let accepted = check(KEY, 2_000, &solve(&c), AT + 10).unwrap();
        assert_eq!(accepted, Accepted { signature: c.signature, expires: AT + 300 });
    }

    #[test]
    fn what_is_not_a_solution_is_refused_for_the_right_reason() {
        let c = challenge();
        let good = solve(&c);
        let at = AT + 10;
        assert_eq!(check(KEY, 2_000, "", at), Err(Refused::Missing));
        assert_eq!(check(KEY, 2_000, "   ", at), Err(Refused::Missing));
        assert_eq!(check(KEY, 2_000, "not base64 !", at), Err(Refused::Malformed));
        let not_json = base64::engine::general_purpose::STANDARD.encode("{");
        assert_eq!(check(KEY, 2_000, &not_json, at), Err(Refused::Malformed));
        // The wrong number.
        assert_eq!(check(KEY, 2_000, &answer(&c, 1_235), at), Err(Refused::NotSolved));
        // Past the range that was asked (even the right hash would not do: here it is simply wrong too).
        assert_eq!(check(KEY, 2_000, &answer(&c, 2_001), at), Err(Refused::NotAsked));
        assert_eq!(check(KEY, 1_000, &good, at), Err(Refused::NotAsked), "the range is the service's, not the client's");
        // Another key: the challenge was not made here. A challenge made up by the client, with a good hash, is no better.
        assert_eq!(check(b"another-key-of-sixteen-bytes+", 2_000, &good, at), Err(Refused::NotOurs));
        let mut forged = make(KEY, 2_000, 300, AT, [9; 12], 5);
        forged.signature = c.signature.clone();
        assert_eq!(check(KEY, 2_000, &answer(&forged, 5), at), Err(Refused::NotOurs));
        // Not `SHA-256`.
        let mut other = c.clone();
        other.algorithm = "SHA-512".into();
        assert_eq!(check(KEY, 2_000, &answer(&other, 1_234), at), Err(Refused::NotAsked));
        // Expired, to the second.
        assert!(check(KEY, 2_000, &good, AT + 299).is_ok());
        assert_eq!(check(KEY, 2_000, &good, AT + 300), Err(Refused::Expired));
        assert_eq!(check(KEY, 2_000, &good, AT + 10_000), Err(Refused::Expired));
    }

    #[test]
    fn the_expiry_cannot_be_moved_without_breaking_the_hash() {
        // A client that adds time to the salt changes the hash, and the signature was made for the old one.
        let c = challenge();
        let mut later = c.clone();
        later.salt = later.salt.replace(&format!("{}", AT + 300), &format!("{}", AT + 3_000_000));
        assert_eq!(check(KEY, 2_000, &answer(&later, 1_234), AT + 10), Err(Refused::NotSolved));
        // Nor can a salt without an expiry get through: one of ours always has it.
        assert_eq!(expires_of("abcdef"), None);
        assert_eq!(expires_of("abcdef?expires=12&"), Some(12));
        assert_eq!(expires_of("abcdef?a=1&expires=12&"), Some(12));
        assert_eq!(expires_of("abcdef?expires=soon&"), None);
    }

    #[test]
    fn the_url_safe_form_of_base64_is_read_too() {
        let c = challenge();
        let number = 1_234;
        let json = serde_json::json!({
            "algorithm": c.algorithm, "challenge": c.challenge, "number": number, "salt": c.salt, "signature": c.signature,
        });
        let url_safe = base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(json.to_string());
        assert!(check(KEY, 2_000, &url_safe, AT + 10).is_ok());
    }

    #[test]
    fn comparisons_see_every_byte() {
        assert!(same(b"abc", b"abc"));
        assert!(!same(b"abc", b"abd"));
        assert!(!same(b"abc", b"ab"));
        assert!(same(b"", b""));
    }

    #[test]
    fn a_short_key_is_refused() {
        // Its own variable: tests run side by side and share the environment.
        let env = "CHALLENGE_TEST_SHORT_KEY";
        // SAFETY: nothing else reads or writes this variable.
        unsafe { std::env::set_var(env, "short") };
        assert!(check_config(env).is_err());
        unsafe { std::env::set_var(env, "a-key-of-more-than-sixteen-bytes") };
        assert!(check_config(env).is_ok());
    }

    static SCHEMA: tokio::sync::OnceCell<()> = tokio::sync::OnceCell::const_new();

    /// Needs a database: `EDA_TEST_DATABASE_URL=postgres://... cargo test -p eda-runtime -- --ignored`.
    async fn database() -> sqlx::PgPool {
        let url = std::env::var("EDA_TEST_DATABASE_URL").expect("EDA_TEST_DATABASE_URL");
        let db = sqlx::PgPool::connect(&url).await.unwrap();
        SCHEMA
            .get_or_init(|| async {
                sqlx::query(CREATE_USES_TABLE).execute(&db).await.unwrap();
            })
            .await;
        db
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn a_solution_is_worth_one_form_for_every_replica_and_a_failed_form_gives_it_back() {
        let db = database().await;
        // A fresh challenge (real clock and key): the key is the development one, set for the test process.
        let env = "CHALLENGE_TEST_KEY";
        // SAFETY: only these tests of this file read it, and they all set it to the same value before reading.
        unsafe { std::env::set_var(env, "a-key-of-more-than-sixteen-bytes") };
        let c = issue(env, 500, 60).unwrap();
        let payload = solve(&c);
        let refused = |e: anyhow::Error| e.downcast_ref::<HttpError>().map(|h| h.status);

        // The first form is accepted, but it fails afterwards: its transaction rolls back, and the solution with it.
        let mut tx = db.begin().await.unwrap();
        verify(&mut tx, env, 500, &payload).await.unwrap();
        tx.rollback().await.unwrap();

        // The visitor sends the same solution again: accepted, and this time the form goes through.
        let mut tx = db.begin().await.unwrap();
        verify(&mut tx, env, 500, &payload).await.unwrap();
        tx.commit().await.unwrap();

        // A second form with the same solution, from another connection (another replica), is refused.
        let mut tx = db.begin().await.unwrap();
        let error = verify(&mut tx, env, 500, &payload).await.unwrap_err();
        assert_eq!(refused(error), Some(400));
        tx.rollback().await.unwrap();

        // Two forms at the same moment with one solution: one of them wins, the other waits for it, then loses.
        let c = issue(env, 500, 60).unwrap();
        let payload = solve(&c);
        let (a, b) = (db.clone(), db.clone());
        let (p1, p2) = (payload.clone(), payload);
        let (first, second) = tokio::join!(
            async move {
                let mut tx = a.begin().await.unwrap();
                let outcome = verify(&mut tx, env, 500, &p1).await;
                tx.commit().await.unwrap();
                outcome.is_ok()
            },
            async move {
                let mut tx = b.begin().await.unwrap();
                let outcome = verify(&mut tx, env, 500, &p2).await;
                tx.commit().await.unwrap();
                outcome.is_ok()
            }
        );
        assert!(first ^ second, "exactly one of two simultaneous uses wins: {first} {second}");

        // A solution that is not one is refused before the database is asked anything.
        let mut tx = db.begin().await.unwrap();
        assert_eq!(refused(verify(&mut tx, env, 500, "").await.unwrap_err()), Some(400));
        tx.rollback().await.unwrap();
    }
}
