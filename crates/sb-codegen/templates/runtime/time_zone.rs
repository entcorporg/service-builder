//! What the expressions `nowSeconds`, `localDate`, `localTime`, `startOfDay`, `addDays`, `addMonths` and `parseLocal` call:
//! calendar arithmetic in a time zone, correct across the changes of time (Jiff, with the IANA database bundled: the service does
//! not depend on the tzdata of the machine it runs on).
//!
//! An instant is whole **seconds since 1970** (an `int64`); a zone is its IANA name (`Europe/Paris`, `America/New_York`, `UTC`).
//! What is calendar, not clock, follows the calendar:
//!
//! * a **day** is not 86 400 seconds: it is 82 800 the day the clocks go forward and 90 000 the day they go back, and
//!   `startOfDay` is where the day of the zone began, not a multiple of 86 400;
//! * `addDays` and `addMonths` keep **the time on the clock**: 09:00 plus a day is 09:00 the next day, 23 or 25 hours later across
//!   a change of time; the 31st plus a month is the last day of the next month;
//! * a local time that **does not exist** (the hour skipped when the clocks go forward) is moved forward by the gap, and one
//!   that **happens twice** (the hour repeated when they go back) is the first of the two.
//!
//! A zone that is not in the database, or an instant outside the years Jiff counts, is a `400` that names it.
//!
//! Needs the cargo feature `time-zones`; the generator turns it on for the services that use the expressions.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::Result;
use jiff::civil::DateTime;
use jiff::{Span, Timestamp, Zoned};

use crate::http::HttpError;

fn bad(what: impl std::fmt::Display) -> anyhow::Error {
    HttpError::bad_request(what.to_string()).into()
}

/// The instant `seconds` in `zone`.
fn zoned(seconds: i64, zone: &str) -> Result<Zoned> {
    let instant = Timestamp::from_second(seconds).map_err(|_| bad(format!("{seconds} is not an instant this service can read")))?;
    instant.in_tz(zone).map_err(|_| bad(format!("`{zone}` is not a time zone of the IANA database")))
}

/// The current instant, in seconds.
pub fn now_seconds() -> i64 {
    Timestamp::now().as_second()
}

/// The day of the instant in the zone: `2026-03-29`.
pub fn local_date(seconds: i64, zone: &str) -> Result<String> {
    Ok(zoned(seconds, zone)?.date().to_string())
}

/// The instant as the date and time on the clock of the zone, with its offset then: `2026-03-29T03:30:00+02:00`.
pub fn local_time(seconds: i64, zone: &str) -> Result<String> {
    Ok(zoned(seconds, zone)?.strftime("%Y-%m-%dT%H:%M:%S%:z").to_string())
}

/// The instant at which the day of `seconds` began in the zone.
pub fn start_of_day(seconds: i64, zone: &str) -> Result<i64> {
    let start = zoned(seconds, zone)?.start_of_day().map_err(|e| bad(format!("cannot find the start of the day: {e}")))?;
    Ok(start.timestamp().as_second())
}

/// The same time on the clock `days` calendar days later (earlier, if negative).
pub fn add_days(seconds: i64, days: i64, zone: &str) -> Result<i64> {
    let span = Span::new().try_days(days).map_err(|_| bad(format!("{days} days is too many")))?;
    shifted(seconds, span, zone)
}

/// The same time on the clock `months` calendar months later; the end of a month is kept in the month.
pub fn add_months(seconds: i64, months: i64, zone: &str) -> Result<i64> {
    let span = Span::new().try_months(months).map_err(|_| bad(format!("{months} months is too many")))?;
    shifted(seconds, span, zone)
}

fn shifted(seconds: i64, span: Span, zone: &str) -> Result<i64> {
    let moved = zoned(seconds, zone)?.checked_add(span).map_err(|_| bad("the result is outside the years this service can read"))?;
    Ok(moved.timestamp().as_second())
}

/// The instant of a date and time written without offset, read in the zone: `Ok(None)` when the text is not a date and time.
/// An unknown zone is an error even when the text is not a date: it is the flow that is wrong, not the data.
pub fn parse_local(text: &str, zone: &str) -> Result<Option<i64>> {
    let tz = jiff::tz::TimeZone::get(zone).map_err(|_| bad(format!("`{zone}` is not a time zone of the IANA database")))?;
    let text = text.trim();
    // A text that says its own offset or zone is not a time on the clock: reading it as one would drop what it says (the parser
    // accepts `10:00:00+02:00` and forgets the `+02:00`), and the instant would be the wrong one.
    let (_, time) = text.split_once(['T', 't', ' ']).unwrap_or((text, ""));
    if time.contains(['+', '-', 'Z', 'z', '[']) {
        return Ok(None);
    }
    let Ok(local) = text.parse::<DateTime>() else {
        return Ok(None);
    };
    Ok(local.to_zoned(tz).ok().map(|z| z.timestamp().as_second()))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 2026-03-29 is the day the clocks go forward in Europe (02:00 becomes 03:00), 2026-10-25 the day they go back.
    const PARIS: &str = "Europe/Paris";

    fn at(local: &str, zone: &str) -> i64 {
        parse_local(local, zone).unwrap().unwrap()
    }

    #[test]
    fn the_day_and_the_clock_depend_on_the_zone() {
        // 2026-03-29T22:30:00Z: late evening in Paris (+02:00), already the next day in Tokyo, still the day in New York.
        let t = at("2026-03-29T22:30:00", "UTC");
        assert_eq!(local_date(t, PARIS).unwrap(), "2026-03-30");
        assert_eq!(local_date(t, "Asia/Tokyo").unwrap(), "2026-03-30");
        assert_eq!(local_date(t, "America/New_York").unwrap(), "2026-03-29");
        assert_eq!(local_time(t, PARIS).unwrap(), "2026-03-30T00:30:00+02:00");
        assert_eq!(local_time(t, "Asia/Kolkata").unwrap(), "2026-03-30T04:00:00+05:30");
        assert_eq!(local_time(t, "UTC").unwrap(), "2026-03-29T22:30:00+00:00");
        assert_eq!(local_date(0, "UTC").unwrap(), "1970-01-01");
        assert_eq!(local_date(-1, "UTC").unwrap(), "1969-12-31");
    }

    #[test]
    fn a_day_is_23_hours_when_the_clocks_go_forward_and_25_when_they_go_back() {
        let day = |local: &str| start_of_day(at(local, PARIS), PARIS).unwrap();
        let (a, b, c, d) = (day("2026-03-28T12:00:00"), day("2026-03-29T12:00:00"), day("2026-03-30T12:00:00"), day("2026-10-25T12:00:00"));
        assert_eq!(b - a, 86_400);
        assert_eq!(c - b, 82_800, "the 29th of March has 23 hours");
        assert_eq!(day("2026-10-26T12:00:00") - d, 90_000, "the 25th of October has 25 hours");
        // The start of the day is the midnight of the zone, whatever the time of the instant.
        assert_eq!(local_time(b, PARIS).unwrap(), "2026-03-29T00:00:00+01:00");
        assert_eq!(start_of_day(at("2026-03-29T00:00:00", PARIS), PARIS).unwrap(), b);
        assert_eq!(start_of_day(at("2026-03-29T23:59:59", PARIS), PARIS).unwrap(), b);
    }

    #[test]
    fn adding_days_keeps_the_clock_and_not_the_number_of_seconds() {
        let nine = at("2026-03-28T09:00:00", PARIS);
        let next = add_days(nine, 1, PARIS).unwrap();
        assert_eq!(local_time(next, PARIS).unwrap(), "2026-03-29T09:00:00+02:00");
        assert_eq!(next - nine, 82_800, "23 hours later: the clocks went forward in between");
        // 86 400 seconds is not a day: it is 10:00 here.
        assert_eq!(local_time(nine + 86_400, PARIS).unwrap(), "2026-03-29T10:00:00+02:00");
        // Back across the other change, and into the past.
        let back = add_days(at("2026-10-26T09:00:00", PARIS), -1, PARIS).unwrap();
        assert_eq!(local_time(back, PARIS).unwrap(), "2026-10-25T09:00:00+01:00");
        assert_eq!(add_days(nine, 0, PARIS).unwrap(), nine);
        assert_eq!(add_days(nine, 7, "UTC").unwrap() - nine, 7 * 86_400);
    }

    #[test]
    fn adding_months_keeps_the_clock_and_the_end_of_a_month_stays_in_its_month() {
        let month = |local: &str, n: i64, zone: &str| local_time(add_months(at(local, zone), n, zone).unwrap(), zone).unwrap();
        assert_eq!(month("2026-01-31T10:00:00", 1, "UTC"), "2026-02-28T10:00:00+00:00");
        assert_eq!(month("2028-01-31T10:00:00", 1, "UTC"), "2028-02-29T10:00:00+00:00", "a leap year");
        assert_eq!(month("2026-03-31T10:00:00", 1, PARIS), "2026-04-30T10:00:00+02:00");
        assert_eq!(month("2026-11-15T10:00:00", 3, PARIS), "2027-02-15T10:00:00+01:00");
        assert_eq!(month("2026-03-15T10:00:00", -2, PARIS), "2026-01-15T10:00:00+01:00");
        assert_eq!(month("2026-05-01T08:30:00", 12, PARIS), "2027-05-01T08:30:00+02:00");
    }

    #[test]
    fn a_time_that_does_not_exist_is_moved_forward_and_one_that_happens_twice_is_the_first() {
        // 02:30 on the 29th of March 2026 in Paris does not exist (02:00 is 03:00): it is 03:30.
        assert_eq!(local_time(at("2026-03-29T02:30:00", PARIS), PARIS).unwrap(), "2026-03-29T03:30:00+02:00");
        // 02:30 on the 25th of October happens twice (+02:00, then +01:00): the first.
        assert_eq!(local_time(at("2026-10-25T02:30:00", PARIS), PARIS).unwrap(), "2026-10-25T02:30:00+02:00");
    }

    #[test]
    fn a_text_is_read_as_a_date_and_time_or_it_is_nothing() {
        let t = at("2026-03-29T10:00:00", "UTC");
        assert_eq!(parse_local("2026-03-29 10:00", "UTC").unwrap(), Some(t));
        assert_eq!(parse_local("  2026-03-29T10:00:00  ", "UTC").unwrap(), Some(t));
        assert_eq!(parse_local("2026-03-29", "UTC").unwrap(), Some(t - 10 * 3600), "a date alone is its midnight");
        for not in [
            "",
            "nonsense",
            "29/03/2026",
            "2026-13-01T00:00:00",
            "2026-02-30",
            // What says its own offset or zone is not a time on the clock.
            "2026-03-29T10:00:00Z",
            "2026-03-29T10:00:00z",
            "2026-03-29T10:00:00+02:00",
            "2026-03-29 10:00:00-05:00",
            "2026-03-29T10:00:00+02:00[Europe/Paris]",
            "2026-03-29T10:00[Europe/Paris]",
        ] {
            assert_eq!(parse_local(not, "UTC").unwrap(), None, "{not:?}");
        }
    }

    fn status(error: anyhow::Error) -> u16 {
        error.downcast_ref::<HttpError>().expect("an HTTP error").status
    }

    #[test]
    fn a_zone_that_does_not_exist_and_an_instant_out_of_range_are_a_400_that_says_so() {
        for result in [
            local_date(0, "Europe/Pariss"),
            local_time(0, ""),
            local_time(0, "paris"),
        ] {
            let error = result.unwrap_err();
            assert_eq!(status(error), 400);
        }
        assert_eq!(status(start_of_day(0, "Mars/Olympus").unwrap_err()), 400);
        assert_eq!(status(add_days(0, 1, "Nowhere").unwrap_err()), 400);
        assert_eq!(status(parse_local("2026-03-29", "Nowhere").unwrap_err()), 400, "the zone is the flow's, even for a text that is not a date");
        assert_eq!(status(local_date(i64::MAX, "UTC").unwrap_err()), 400);
        assert_eq!(status(add_days(0, i64::MAX, "UTC").unwrap_err()), 400);
        assert_eq!(status(add_months(0, i64::MAX, "UTC").unwrap_err()), 400);
        assert_eq!(status(add_months(253_402_300_799, 1, "UTC").unwrap_err()), 400);
        let message = local_date(0, "Europe/Pariss").unwrap_err().downcast::<HttpError>().unwrap().message;
        assert!(message.contains("Europe/Pariss"), "{message}");
    }

    #[test]
    fn the_clock_is_now() {
        let before = Timestamp::now().as_second();
        let now = now_seconds();
        assert!(now >= before && now - before < 5);
        assert!(local_date(now, "UTC").unwrap().starts_with("20"));
    }
}
