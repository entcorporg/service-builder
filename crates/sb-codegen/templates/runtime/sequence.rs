//! What the step `nextNumber` calls: numbers one after the other **without gaps**, for what has to be numbered by law (invoices,
//! credit notes).
//!
//! A database sequence (`SERIAL`, `nextval`) is never what is wanted for that: it does not give a number back when the transaction
//! that took it fails, so a failed run leaves a hole in the numbering. Here a sequence is a row of `number_sequences`, taken and
//! increased by one statement **in the transaction of the handler**: the row is locked until that transaction ends, so
//!
//! * two runs cannot get the same number (the second waits for the first to commit, then takes the next one);
//! * a run that fails (or whose later step fails) rolls the increase back, and the next run gets the number it would have had.
//!
//! The price is that runs which number **the same sequence and scope** wait for one another, one after the other: take the number
//! at the end of the run, right before what is written with it, and keep what comes after it short. A scope (a company, a year)
//! has its own count and its own row, so the runs of two companies do not wait for each other.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::Result;

/// The table of the sequences, created with the schema of the service: the last number given of each sequence and scope.
pub const CREATE_TABLE: &str = "CREATE TABLE IF NOT EXISTS number_sequences (sequence TEXT NOT NULL, scope TEXT NOT NULL DEFAULT '', last_value BIGINT NOT NULL, PRIMARY KEY (sequence, scope))";

/// The next number of `sequence` in `scope` (`""` when there is none): `start` for the first one, then one more each time. Call it
/// inside the transaction of the handler (see the top of this file).
pub async fn next(tx: &mut sqlx::PgConnection, sequence: &str, scope: &str, start: i64) -> Result<i64> {
    // One statement does both: the first call of a sequence inserts `start`, the others add one. A race on the first insert is
    // settled by the primary key: the second insert waits for the first transaction, then takes the `DO UPDATE` branch.
    let number: i64 = sqlx::query_scalar(
        "INSERT INTO number_sequences (sequence, scope, last_value) VALUES ($1, $2, $3) \
         ON CONFLICT (sequence, scope) DO UPDATE SET last_value = number_sequences.last_value + 1 \
         RETURNING last_value",
    )
    .bind(sequence)
    .bind(scope)
    .bind(start)
    .fetch_one(tx)
    .await?;
    Ok(number)
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlx::PgPool;

    static SCHEMA: tokio::sync::OnceCell<()> = tokio::sync::OnceCell::const_new();

    /// Needs a database: `EDA_TEST_DATABASE_URL=postgres://... cargo test -p eda-runtime -- --ignored`.
    async fn database() -> PgPool {
        let url = std::env::var("EDA_TEST_DATABASE_URL").expect("EDA_TEST_DATABASE_URL");
        let db = PgPool::connect(&url).await.unwrap();
        SCHEMA
            .get_or_init(|| async {
                sqlx::query(CREATE_TABLE).execute(&db).await.unwrap();
            })
            .await;
        db
    }

    /// A sequence no other test (or earlier run) has used.
    fn unique(prefix: &str) -> String {
        format!("{prefix}-{:016x}", rand::random::<u64>())
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn numbers_follow_one_another_from_the_start_and_a_scope_counts_apart() {
        let db = database().await;
        let (sequence, other) = (unique("invoices"), unique("credit"));
        let mut tx = db.begin().await.unwrap();
        for expected in 1..=3 {
            assert_eq!(next(&mut tx, &sequence, "", 1).await.unwrap(), expected);
        }
        // Another scope, another sequence, and another start are their own counts.
        assert_eq!(next(&mut tx, &sequence, "2026", 1).await.unwrap(), 1);
        assert_eq!(next(&mut tx, &sequence, "2026", 1).await.unwrap(), 2);
        assert_eq!(next(&mut tx, &other, "", 1000).await.unwrap(), 1000);
        assert_eq!(next(&mut tx, &other, "", 1000).await.unwrap(), 1001);
        // The start only counts for the first number: a different one given later changes nothing.
        assert_eq!(next(&mut tx, &other, "", 5).await.unwrap(), 1002);
        assert_eq!(next(&mut tx, &sequence, "", 1).await.unwrap(), 4);
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn a_run_that_fails_gives_its_number_back_so_there_is_no_gap() {
        let db = database().await;
        let sequence = unique("invoices");
        let mut tx = db.begin().await.unwrap();
        assert_eq!(next(&mut tx, &sequence, "", 1).await.unwrap(), 1);
        tx.commit().await.unwrap();
        // The second run takes 2, then fails: nothing of it is kept.
        let mut tx = db.begin().await.unwrap();
        assert_eq!(next(&mut tx, &sequence, "", 1).await.unwrap(), 2);
        tx.rollback().await.unwrap();
        // The third gets the number the second did not use.
        let mut tx = db.begin().await.unwrap();
        assert_eq!(next(&mut tx, &sequence, "", 1).await.unwrap(), 2);
        tx.commit().await.unwrap();
        // A sequence of the database, for comparison, would have skipped it.
        sqlx::query("DELETE FROM number_sequences WHERE sequence = $1").bind(&sequence).execute(&db).await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn runs_at_the_same_time_get_different_numbers_and_all_of_them() {
        let db = database().await;
        let sequence = unique("invoices");
        // Twenty runs together, the first of them on a sequence that does not exist yet (the race on the first insert); half
        // of them fail after taking their number.
        let mut tasks = vec![];
        for i in 0..20 {
            let (db, sequence) = (db.clone(), sequence.clone());
            tasks.push(tokio::spawn(async move {
                let mut tx = db.begin().await.unwrap();
                let number = next(&mut tx, &sequence, "", 1).await.unwrap();
                if i % 2 == 0 {
                    tx.commit().await.unwrap();
                    Some(number)
                } else {
                    tx.rollback().await.unwrap();
                    None
                }
            }));
        }
        let mut kept = vec![];
        for task in tasks {
            kept.extend(task.await.unwrap());
        }
        kept.sort_unstable();
        // The ten that committed hold ten different numbers, and the numbering has no hole: 1 to 10.
        assert_eq!(kept, (1..=10).collect::<Vec<i64>>());
        let last: i64 = sqlx::query_scalar("SELECT last_value FROM number_sequences WHERE sequence = $1 AND scope = ''")
            .bind(&sequence)
            .fetch_one(&db)
            .await
            .unwrap();
        assert_eq!(last, 10);
        sqlx::query("DELETE FROM number_sequences WHERE sequence = $1").bind(&sequence).execute(&db).await.unwrap();
    }
}
