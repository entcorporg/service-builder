//! What the step `refreshRotate` calls: refresh tokens that work once, in families.
//!
//! A login starts a **family** with a first token. Each refresh spends the token it is given and issues the next one of the same
//! family: a token is never valid twice. A token that is presented **again** after it was spent was copied or stolen (the thief or
//! the owner is holding an old one): the whole family is revoked, so that the newest token, which the other party holds, stops
//! working too, and the person has to sign in again. The step commits that revocation before it answers, because a plain refusal
//! drops the transaction.
//!
//! A token is 256 random bits (64 hexadecimal characters). Only its SHA-256 is stored, in `refresh_tokens` of the service's
//! database, in the transaction of the handler. Whatever is wrong with a token that was not spent (unknown, expired, of a revoked
//! family) is the same `401 invalid refresh token`; which it was stays in the log.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::Result;
use sqlx::Row;

use crate::http::HttpError;

/// The table of the tokens, created with the schema of the service.
pub const CREATE_TABLE: &str = "CREATE TABLE IF NOT EXISTS refresh_tokens (token_hash TEXT PRIMARY KEY, family_id TEXT NOT NULL, subject TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), expires_at TIMESTAMPTZ NOT NULL, used_at TIMESTAMPTZ, revoked_at TIMESTAMPTZ)";

/// What the revocation of a family looks for.
pub const CREATE_FAMILY_INDEX: &str = "CREATE INDEX IF NOT EXISTS refresh_tokens_by_family ON refresh_tokens (family_id)";

const REFUSED: &str = "invalid refresh token";

/// What a rotation gives.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Rotation {
    /// The token was good and is spent: the next one, and whom the family is for.
    Rotated(Rotated),
    /// The token had already been spent: the family is revoked (not committed yet: the caller commits, then answers).
    Replayed(Replayed),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rotated {
    pub token: String,
    pub subject: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Replayed {
    pub subject: String,
}

fn hash(token: &str) -> String {
    crate::crypto::sha256_hex(token.trim())
}

/// The answer to a token that cannot be used.
pub fn refused() -> anyhow::Error {
    HttpError::unauthorized(REFUSED).into()
}

fn refuse(why: &str) -> anyhow::Error {
    tracing::info!(%why, "refresh token refused");
    refused()
}

async fn insert(tx: &mut sqlx::PgConnection, family: &str, subject: &str, ttl_secs: u32) -> Result<String> {
    let token = crate::crypto::random_token();
    sqlx::query(
        "INSERT INTO refresh_tokens (token_hash, family_id, subject, expires_at) \
         VALUES ($1, $2, $3, now() + make_interval(secs => $4::BIGINT))",
    )
    .bind(hash(&token))
    .bind(family)
    .bind(subject)
    .bind(i64::from(ttl_secs))
    .execute(tx)
    .await?;
    Ok(token)
}

/// The step without a token: starts a family for `subject` and returns its first token, to be handed to the client.
pub async fn start(tx: &mut sqlx::PgConnection, subject: &str, ttl_secs: u32) -> Result<String> {
    if ttl_secs == 0 {
        return Err(HttpError::bad_request("a refresh token is valid for a positive number of seconds").into());
    }
    let family = hex::encode(rand::random::<[u8; 16]>());
    insert(tx, &family, subject, ttl_secs).await
}

/// The step with a token: spends it and issues the next one of its family. A spent token revokes the family.
pub async fn rotate(tx: &mut sqlx::PgConnection, presented: &str, ttl_secs: u32) -> Result<Rotation> {
    if presented.trim().is_empty() {
        return Err(refuse("no token"));
    }
    // The row is locked: two requests with the same token cannot both be the first.
    let row = sqlx::query(
        "SELECT family_id, subject, (used_at IS NOT NULL) AS used, (revoked_at IS NOT NULL) AS revoked, \
         (expires_at <= now()) AS expired FROM refresh_tokens WHERE token_hash = $1 FOR UPDATE",
    )
    .bind(hash(presented))
    .fetch_optional(&mut *tx)
    .await?;
    let Some(row) = row else {
        return Err(refuse("unknown token"));
    };
    let family: String = row.get("family_id");
    let subject: String = row.get("subject");
    if row.get::<bool, _>("revoked") {
        return Err(refuse("family revoked"));
    }
    if row.get::<bool, _>("used") {
        tracing::warn!(family, "refresh token presented again: the family is revoked");
        sqlx::query("UPDATE refresh_tokens SET revoked_at = now() WHERE family_id = $1 AND revoked_at IS NULL")
            .bind(&family)
            .execute(tx)
            .await?;
        return Ok(Rotation::Replayed(Replayed { subject }));
    }
    if row.get::<bool, _>("expired") {
        return Err(refuse("expired"));
    }
    sqlx::query("UPDATE refresh_tokens SET used_at = now() WHERE token_hash = $1")
        .bind(hash(presented))
        .execute(&mut *tx)
        .await?;
    let token = insert(tx, &family, &subject, ttl_secs).await?;
    Ok(Rotation::Rotated(Rotated { token, subject }))
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlx::PgPool;

    #[test]
    fn a_token_is_stored_as_its_hash_and_spaces_around_it_do_not_matter() {
        let token = crate::crypto::random_token();
        assert_eq!(token.len(), 64);
        assert_eq!(hash(&token), hash(&format!("  {token}\n")));
        assert_ne!(hash(&token), token);
    }

    #[test]
    fn the_refusal_is_a_plain_401() {
        let error = refused();
        let http = error.downcast_ref::<HttpError>().expect("an HTTP error");
        assert_eq!(http.status, 401);
    }

    static SCHEMA: tokio::sync::OnceCell<()> = tokio::sync::OnceCell::const_new();

    /// Needs a database: `EDA_TEST_DATABASE_URL=postgres://... cargo test -p eda-runtime -- --ignored`.
    async fn database() -> PgPool {
        let url = std::env::var("EDA_TEST_DATABASE_URL").expect("EDA_TEST_DATABASE_URL");
        let db = PgPool::connect(&url).await.unwrap();
        SCHEMA
            .get_or_init(|| async {
                for statement in [CREATE_TABLE, CREATE_FAMILY_INDEX] {
                    sqlx::query(statement).execute(&db).await.unwrap();
                }
            })
            .await;
        db
    }

    fn status(error: anyhow::Error) -> u16 {
        error.downcast_ref::<HttpError>().expect("an HTTP error").status
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn a_token_works_once_and_only_its_hash_is_stored() {
        let db = database().await;
        let subject = format!("account-{:08x}", rand::random::<u32>());
        let mut tx = db.begin().await.unwrap();
        let first = start(&mut tx, &subject, 3600).await.unwrap();
        let stored: Vec<String> = sqlx::query_scalar("SELECT token_hash FROM refresh_tokens WHERE subject = $1")
            .bind(&subject)
            .fetch_all(&mut *tx)
            .await
            .unwrap();
        assert_eq!(stored, vec![hash(&first)]);
        let Rotation::Rotated(second) = rotate(&mut tx, &first, 3600).await.unwrap() else { panic!("rotated") };
        assert_eq!(second.subject, subject);
        assert_ne!(second.token, first);
        let Rotation::Rotated(third) = rotate(&mut tx, &second.token, 3600).await.unwrap() else { panic!("rotated") };
        assert_eq!(third.subject, subject);
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn a_spent_token_revokes_the_whole_family() {
        let db = database().await;
        let subject = format!("account-{:08x}", rand::random::<u32>());
        let mut tx = db.begin().await.unwrap();
        let first = start(&mut tx, &subject, 3600).await.unwrap();
        let Rotation::Rotated(second) = rotate(&mut tx, &first, 3600).await.unwrap() else { panic!("rotated") };
        // The old token again: a replay, and the newest token of the family stops working.
        let Rotation::Replayed(replayed) = rotate(&mut tx, &first, 3600).await.unwrap() else { panic!("replayed") };
        assert_eq!(replayed.subject, subject);
        assert_eq!(status(rotate(&mut tx, &second.token, 3600).await.unwrap_err()), 401);
        // Another family of the same subject is not touched.
        let other = start(&mut tx, &subject, 3600).await.unwrap();
        assert!(matches!(rotate(&mut tx, &other, 3600).await.unwrap(), Rotation::Rotated(_)));
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn unknown_empty_and_expired_tokens_are_the_same_401() {
        let db = database().await;
        let subject = format!("account-{:08x}", rand::random::<u32>());
        let mut tx = db.begin().await.unwrap();
        let token = start(&mut tx, &subject, 3600).await.unwrap();
        sqlx::query("UPDATE refresh_tokens SET expires_at = now() - interval '1 second' WHERE subject = $1")
            .bind(&subject)
            .execute(&mut *tx)
            .await
            .unwrap();
        for bad in ["", "garbage", token.as_str()] {
            assert_eq!(status(rotate(&mut tx, bad, 3600).await.unwrap_err()), 401, "{bad:?}");
        }
        assert_eq!(status(start(&mut tx, &subject, 0).await.unwrap_err()), 400);
        tx.rollback().await.unwrap();
    }
}
