//! What the steps `audit` and `auditRead` call: the audit journal, who did what to what, and when.
//!
//! Every entry is a row of `audit_events` of the service's database, written **in the transaction of the handler** that makes the
//! change: the change and its trace commit together or not at all, so the journal never tells of something that did not happen and
//! never misses something that did. The table is **append-only**: a trigger refuses an update and a delete (it protects the journal
//! from the application, flows included, not from the owner of the database, who can disable a trigger).
//!
//! An entry says *who* (`actor`), *what* (`action`, `invoice.issued`), *to what* (`target_type` and `target_id`), *for which company*
//! (`tenant`, empty when it is not any company's), *when* (the clock of the database), and the values *before* and *after* the change
//! as JSON objects; `changed` lists the names whose value is not the same in both, so that a screen can show what moved without
//! comparing.
//!
//! Reading is by company, **newest first**, a page at a time with a cursor (the `id` of the last entry read): no offset, so a page
//! does not shift when entries are written meanwhile. A company reads its own entries and no one else's: the tenant is an
//! argument of every read, not an option.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::Result;
use serde::Serialize;
use serde_json::{Map, Value};
use sqlx::Row;

use crate::http::HttpError;

/// The table of the journal, created with the schema of the service.
pub const CREATE_TABLE: &str = "CREATE TABLE IF NOT EXISTS audit_events (id BIGSERIAL PRIMARY KEY, occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(), tenant TEXT NOT NULL DEFAULT '', actor TEXT NOT NULL, action TEXT NOT NULL, target_type TEXT NOT NULL, target_id TEXT NOT NULL, before JSONB, after JSONB, changed TEXT[] NOT NULL DEFAULT '{}')";

/// What a company reads: its entries, newest first.
pub const CREATE_TENANT_INDEX: &str = "CREATE INDEX IF NOT EXISTS audit_events_by_tenant ON audit_events (tenant, id DESC)";

/// What is read of one thing: its history.
pub const CREATE_TARGET_INDEX: &str = "CREATE INDEX IF NOT EXISTS audit_events_by_target ON audit_events (tenant, target_type, target_id, id DESC)";

/// The function the trigger calls: an update or a delete of an entry is refused.
pub const CREATE_GUARD_FUNCTION: &str = "CREATE OR REPLACE FUNCTION audit_events_append_only() RETURNS trigger AS $$ BEGIN RAISE EXCEPTION 'audit_events is append-only: % is refused', TG_OP USING ERRCODE = 'integrity_constraint_violation'; END; $$ LANGUAGE plpgsql";

/// Refuses to change or remove an entry, once the journal exists.
pub const CREATE_GUARD_TRIGGER: &str = "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_events_append_only' AND tgrelid = 'audit_events'::regclass) THEN CREATE TRIGGER audit_events_append_only BEFORE UPDATE OR DELETE ON audit_events FOR EACH ROW EXECUTE FUNCTION audit_events_append_only(); END IF; END $$";

/// What an entry may hold of values, in bytes of JSON: a journal is not where a document is kept.
const MAX_VALUES_BYTES: usize = 64 * 1024;

/// Named values, written as a JSON object: `Values::new().set("status", "draft").set("total", 1200)`.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct Values(Map<String, Value>);

impl Values {
    pub fn new() -> Self {
        Self::default()
    }

    /// A value is any plain value; one that is absent (`None`) is `null`.
    pub fn set(mut self, name: &str, value: impl Serialize) -> Self {
        self.0.insert(name.to_owned(), serde_json::to_value(value).unwrap_or(Value::Null));
        self
    }
}

/// What the step `audit` writes.
#[derive(Debug)]
pub struct Event<'a> {
    pub action: &'a str,
    pub target_type: &'a str,
    pub target: &'a str,
    pub actor: &'a str,
    pub tenant: Option<&'a str>,
    pub before: Option<Values>,
    pub after: Option<Values>,
}

/// The names whose value is not the same in both, in order: a name in only one of them has changed too.
fn changed(before: &Option<Values>, after: &Option<Values>) -> Vec<String> {
    let (empty_b, empty_a) = (Map::new(), Map::new());
    let b = before.as_ref().map_or(&empty_b, |v| &v.0);
    let a = after.as_ref().map_or(&empty_a, |v| &v.0);
    let mut names: Vec<&String> = b.keys().chain(a.keys()).collect();
    names.sort();
    names.dedup();
    names.into_iter().filter(|n| b.get(*n) != a.get(*n)).cloned().collect()
}

/// Writes the entry. Call it inside the transaction of the handler.
pub async fn record(tx: &mut sqlx::PgConnection, event: Event<'_>) -> Result<()> {
    let changed = changed(&event.before, &event.after);
    let (before, after) = (event.before.map(|v| Value::Object(v.0)), event.after.map(|v| Value::Object(v.0)));
    for values in [&before, &after].into_iter().flatten() {
        if values.to_string().len() > MAX_VALUES_BYTES {
            return Err(HttpError::new(413, "the values of an audit entry are too large").into());
        }
    }
    sqlx::query(
        "INSERT INTO audit_events (tenant, actor, action, target_type, target_id, before, after, changed) \
         VALUES ($1, $2, $3, $4, $5, $6::TEXT::JSONB, $7::TEXT::JSONB, $8)",
    )
    .bind(event.tenant.unwrap_or(""))
    .bind(event.actor)
    .bind(event.action)
    .bind(event.target_type)
    .bind(event.target)
    // As text, cast by the database: the same as the other JSON columns of the generated services (no `json` feature of sqlx).
    .bind(before.map(|v| v.to_string()))
    .bind(after.map(|v| v.to_string()))
    .bind(&changed)
    .execute(tx)
    .await?;
    Ok(())
}

/// What `auditRead` asks for. `tenant` is not optional.
#[derive(Debug, Default)]
pub struct Filter<'a> {
    pub tenant: &'a str,
    pub target_type: Option<&'a str>,
    pub target: Option<&'a str>,
    pub action: Option<&'a str>,
    /// The `id` of the last entry already read: only older ones are read.
    pub cursor: Option<i64>,
    pub limit: u32,
}

/// One entry, as the schema `AuditEntry` holds it: the time is RFC 3339 in UTC, `before` and `after` are JSON text (empty when the
/// entry has no such values).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    pub id: i64,
    pub at: String,
    pub actor: String,
    pub action: String,
    pub target_type: String,
    pub target_id: String,
    pub before: String,
    pub after: String,
    pub changed: Vec<String>,
}

/// A page of entries and, when there are more, the cursor of the next one.
#[derive(Debug, Default)]
pub struct Page {
    pub entries: Vec<Entry>,
    pub next: Option<i64>,
}

/// Reads a page of the journal of a company, newest first.
pub async fn read(tx: &mut sqlx::PgConnection, filter: Filter<'_>) -> Result<Page> {
    let limit = i64::from(filter.limit.clamp(1, 200));
    // One more than asked: that is how to know whether there is a next page, without counting.
    let rows = sqlx::query(
        "SELECT id, to_char(occurred_at AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"') AS at, actor, action, target_type, target_id, \
                COALESCE(before::TEXT, '') AS before, COALESCE(after::TEXT, '') AS after, changed \
         FROM audit_events \
         WHERE tenant = $1 \
           AND ($2::TEXT IS NULL OR target_type = $2) \
           AND ($3::TEXT IS NULL OR target_id = $3) \
           AND ($4::TEXT IS NULL OR action = $4) \
           AND ($5::BIGINT IS NULL OR id < $5) \
         ORDER BY id DESC LIMIT $6",
    )
    .bind(filter.tenant)
    .bind(filter.target_type)
    .bind(filter.target)
    .bind(filter.action)
    .bind(filter.cursor)
    .bind(limit + 1)
    .fetch_all(tx)
    .await?;
    let mut entries: Vec<Entry> = rows
        .iter()
        .map(|r| Entry {
            id: r.get("id"),
            at: r.get("at"),
            actor: r.get("actor"),
            action: r.get("action"),
            target_type: r.get("target_type"),
            target_id: r.get("target_id"),
            before: r.get("before"),
            after: r.get("after"),
            changed: r.get("changed"),
        })
        .collect();
    let more = entries.len() as i64 > limit;
    entries.truncate(limit as usize);
    let next = if more { entries.last().map(|e| e.id) } else { None };
    Ok(Page { entries, next })
}

#[cfg(test)]
mod tests {
    use super::*;
    use sqlx::PgPool;

    #[test]
    fn what_changed_is_what_is_not_the_same_before_and_after() {
        let before = Some(Values::new().set("status", "draft").set("total", 1200).set("gone", true));
        let after = Some(Values::new().set("status", "sent").set("total", 1200).set("added", "x"));
        assert_eq!(changed(&before, &after), vec!["added", "gone", "status"]);
        // No values before (a creation): everything given after is new. None at all: nothing changed.
        assert_eq!(changed(&None, &after), vec!["added", "status", "total"]);
        assert_eq!(changed(&before, &None), vec!["gone", "status", "total"]);
        assert!(changed(&None, &None).is_empty());
        // The same values, in another order, are the same.
        let reordered = Some(Values::new().set("total", 1200).set("status", "draft").set("gone", true));
        assert!(changed(&before, &reordered).is_empty());
        // A number is not its text, and an absent value is `null`, not nothing.
        assert_eq!(changed(&Some(Values::new().set("n", 1)), &Some(Values::new().set("n", "1"))), vec!["n"]);
        let absent = Values::new().set("v", None::<String>);
        assert_eq!(absent.0["v"], Value::Null);
    }

    static SCHEMA: tokio::sync::OnceCell<()> = tokio::sync::OnceCell::const_new();

    /// Needs a database: `EDA_TEST_DATABASE_URL=postgres://... cargo test -p eda-runtime -- --ignored`.
    async fn database() -> PgPool {
        let url = std::env::var("EDA_TEST_DATABASE_URL").expect("EDA_TEST_DATABASE_URL");
        let db = PgPool::connect(&url).await.unwrap();
        SCHEMA
            .get_or_init(|| async {
                for statement in [CREATE_TABLE, CREATE_TENANT_INDEX, CREATE_TARGET_INDEX, CREATE_GUARD_FUNCTION, CREATE_GUARD_TRIGGER] {
                    sqlx::query(statement).execute(&db).await.unwrap();
                }
                // The schema is applied at every start: a second time changes nothing and breaks nothing.
                for statement in [CREATE_TABLE, CREATE_GUARD_FUNCTION, CREATE_GUARD_TRIGGER] {
                    sqlx::query(statement).execute(&db).await.unwrap();
                }
            })
            .await;
        db
    }

    /// A company no other test (or earlier run) has used.
    fn tenant(prefix: &str) -> String {
        format!("{prefix}-{:016x}", rand::random::<u64>())
    }

    fn event<'a>(tenant: &'a str, action: &'a str, target: &'a str) -> Event<'a> {
        Event {
            action,
            target_type: "invoice",
            target,
            actor: "alice",
            tenant: Some(tenant),
            before: Some(Values::new().set("status", "draft")),
            after: Some(Values::new().set("status", "sent")),
        }
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn an_entry_is_written_with_its_values_and_read_back_by_its_company_only() {
        let db = database().await;
        let (acme, other) = (tenant("acme"), tenant("other"));
        let mut tx = db.begin().await.unwrap();
        record(&mut tx, event(&acme, "invoice.sent", "inv-1")).await.unwrap();
        record(&mut tx, Event { before: None, after: Some(Values::new().set("total", 500)), ..event(&other, "invoice.created", "inv-9") }).await.unwrap();
        record(&mut tx, Event { tenant: None, ..event(&acme, "job.ran", "x") }).await.unwrap();
        let page = read(&mut tx, Filter { tenant: &acme, limit: 10, ..Default::default() }).await.unwrap();
        // Its own, and only its own: the other company's entry and the one with no company are not in it.
        assert_eq!(page.entries.len(), 1);
        let e = &page.entries[0];
        assert_eq!((e.actor.as_str(), e.action.as_str(), e.target_type.as_str(), e.target_id.as_str()), ("alice", "invoice.sent", "invoice", "inv-1"));
        assert_eq!(serde_json::from_str::<Value>(&e.before).unwrap(), serde_json::json!({"status": "draft"}));
        assert_eq!(serde_json::from_str::<Value>(&e.after).unwrap(), serde_json::json!({"status": "sent"}));
        assert_eq!(e.changed, vec!["status"]);
        assert!(e.at.len() == 20 && e.at.ends_with('Z') && e.at.contains('T'), "{}", e.at);
        assert_eq!(page.next, None);
        // The other company has its own, with no `before`.
        let theirs = read(&mut tx, Filter { tenant: &other, limit: 10, ..Default::default() }).await.unwrap();
        assert_eq!((theirs.entries.len(), theirs.entries[0].before.as_str()), (1, ""));
        assert_eq!(theirs.entries[0].changed, vec!["total"]);
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn the_journal_is_read_newest_first_a_page_at_a_time_without_shifting_and_can_be_filtered() {
        let db = database().await;
        let acme = tenant("acme");
        let mut tx = db.begin().await.unwrap();
        for i in 0..7 {
            let action = if i % 2 == 0 { "invoice.sent" } else { "invoice.paid" };
            record(&mut tx, event(&acme, action, &format!("inv-{}", i % 3))).await.unwrap();
        }
        let first = read(&mut tx, Filter { tenant: &acme, limit: 3, ..Default::default() }).await.unwrap();
        assert_eq!(first.entries.len(), 3);
        assert!(first.entries.windows(2).all(|w| w[0].id > w[1].id), "newest first");
        let cursor = first.next.expect("more entries follow");
        assert_eq!(cursor, first.entries[2].id);
        // An entry written between two pages does not shift the next one (a cursor, not an offset).
        record(&mut tx, event(&acme, "invoice.sent", "inv-new")).await.unwrap();
        let second = read(&mut tx, Filter { tenant: &acme, limit: 3, cursor: Some(cursor), ..Default::default() }).await.unwrap();
        assert_eq!(second.entries.len(), 3);
        assert!(second.entries[0].id < cursor);
        let third = read(&mut tx, Filter { tenant: &acme, limit: 3, cursor: second.next, ..Default::default() }).await.unwrap();
        assert_eq!((third.entries.len(), third.next), (1, None), "the last page has the rest and no cursor");
        // 7 written before the first page, one after: the three pages hold exactly the 7 (not the late one, and none twice).
        let mut ids: Vec<i64> = [&first, &second, &third].iter().flat_map(|p| p.entries.iter().map(|e| e.id)).collect();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(ids.len(), 7);
        // Filtered by what it was done to, by what was done.
        let by_target = read(&mut tx, Filter { tenant: &acme, target_type: Some("invoice"), target: Some("inv-0"), limit: 50, ..Default::default() }).await.unwrap();
        assert!(by_target.entries.len() == 3 && by_target.entries.iter().all(|e| e.target_id == "inv-0"));
        let by_action = read(&mut tx, Filter { tenant: &acme, action: Some("invoice.paid"), limit: 50, ..Default::default() }).await.unwrap();
        assert_eq!(by_action.entries.len(), 3);
        let none = read(&mut tx, Filter { tenant: &acme, action: Some("nothing"), limit: 50, ..Default::default() }).await.unwrap();
        assert!(none.entries.is_empty() && none.next.is_none());
        tx.rollback().await.unwrap();
    }

    #[tokio::test]
    #[ignore = "needs EDA_TEST_DATABASE_URL"]
    async fn the_journal_is_append_only_and_an_entry_follows_the_fate_of_its_transaction() {
        let db = database().await;
        let acme = tenant("acme");
        // Committed with its transaction, rolled back with it: the change and its trace go together.
        let mut tx = db.begin().await.unwrap();
        record(&mut tx, event(&acme, "invoice.sent", "kept")).await.unwrap();
        tx.commit().await.unwrap();
        let mut tx = db.begin().await.unwrap();
        record(&mut tx, event(&acme, "invoice.sent", "lost")).await.unwrap();
        tx.rollback().await.unwrap();
        let mut tx = db.begin().await.unwrap();
        let page = read(&mut tx, Filter { tenant: &acme, limit: 10, ..Default::default() }).await.unwrap();
        assert_eq!(page.entries.iter().map(|e| e.target_id.as_str()).collect::<Vec<_>>(), vec!["kept"]);
        tx.rollback().await.unwrap();
        // Nothing can change or remove it, even a statement that matches it.
        let update = sqlx::query("UPDATE audit_events SET actor = 'mallory' WHERE tenant = $1").bind(&acme).execute(&db).await.unwrap_err();
        assert!(update.to_string().contains("append-only"), "{update}");
        let delete = sqlx::query("DELETE FROM audit_events WHERE tenant = $1").bind(&acme).execute(&db).await.unwrap_err();
        assert!(delete.to_string().contains("append-only"), "{delete}");
        // The values are bounded.
        let big = Values::new().set("blob", "x".repeat(MAX_VALUES_BYTES));
        let mut tx = db.begin().await.unwrap();
        let error = record(&mut tx, Event { after: Some(big), ..event(&acme, "invoice.sent", "big") }).await.unwrap_err();
        assert_eq!(error.downcast_ref::<HttpError>().unwrap().status, 413);
        tx.rollback().await.unwrap();
    }
}
