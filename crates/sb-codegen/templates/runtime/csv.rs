//! CSV for the HTTP routes (RFC 4180): the answer of a route that lists, and the body of a route that imports.
//!
//! **Writing**: one header line with the keys, then one line per item, lines ended by CRLF. A cell that holds a comma, a quote or a
//! line break is quoted, a quote inside it is doubled. A value that is `null` or missing is an empty cell. A text that starts with
//! `=`, `+`, `-` or `@` is written as it is: a spreadsheet may read it as a formula, so an export of text that people typed is
//! opened with the care owed to any file from the outside.
//!
//! **Reading**: the first line names the columns (any order, extra columns ignored, a leading byte-order mark is skipped), each
//! following line is one item. Every cell is read as the type of its column; **all the lines that are refused are reported at once**
//! (the line number, the column and why), not only the first. `items_partial` keeps the valid lines and reports the refused ones.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use serde_json::{Map, Number, Value};

/// The type of a column, which says how its text is read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// Text, `uuid`, `timestamp` and `bytes`: kept as it is (the schema reads it after).
    Text,
    Int32,
    Int64,
    Float,
    Bool,
}

/// One column of the item: its JSON key, its type, and whether an empty cell is refused.
#[derive(Debug, Clone, Copy)]
pub struct Column {
    pub key: &'static str,
    pub kind: Kind,
    pub required: bool,
}

/// The most lines reported at once, so that a file of a million wrong lines does not answer with a million messages.
const MAX_REPORTED: usize = 50;

/// The CSV of the items found in `list` (a JSON array of objects), with the columns `keys` in this order.
pub fn write(list: &Value, keys: &[&str]) -> String {
    let mut out = String::new();
    push_line(&mut out, keys.iter().map(|k| (*k).to_string()));
    for item in list.as_array().into_iter().flatten() {
        push_line(
            &mut out,
            keys.iter().map(|k| match item.get(*k) {
                None | Some(Value::Null) => String::new(),
                Some(Value::String(s)) => s.clone(),
                Some(other) => other.to_string(),
            }),
        );
    }
    out
}

fn push_line(out: &mut String, cells: impl Iterator<Item = String>) {
    for (i, cell) in cells.enumerate() {
        if i > 0 {
            out.push(',');
        }
        if cell.contains([',', '"', '\r', '\n']) {
            out.push('"');
            out.push_str(&cell.replace('"', "\"\""));
            out.push('"');
        } else {
            out.push_str(&cell);
        }
    }
    out.push_str("\r\n");
}

/// The records of a CSV text, each with the number of the line it starts on (the first line is 1). Lines with no cell are skipped.
pub fn records(text: &str) -> Result<Vec<(usize, Vec<String>)>, String> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut records = Vec::new();
    let mut record: Vec<String> = Vec::new();
    let mut cell = String::new();
    let mut quoted = false;
    let mut was_quoted = false;
    let mut line = 1usize;
    let mut start = 1usize;
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        if quoted {
            match c {
                '"' if chars.peek() == Some(&'"') => {
                    chars.next();
                    cell.push('"');
                }
                '"' => quoted = false,
                _ => {
                    if c == '\n' {
                        line += 1;
                    }
                    cell.push(c);
                }
            }
            continue;
        }
        match c {
            '"' if cell.is_empty() && !was_quoted => {
                quoted = true;
                was_quoted = true;
            }
            '"' => {
                return Err(format!(
                    "line {line}: a quote inside a cell that is not quoted"
                ));
            }
            ',' => {
                record.push(std::mem::take(&mut cell));
                was_quoted = false;
            }
            '\r' if chars.peek() == Some(&'\n') => {}
            '\n' | '\r' => {
                record.push(std::mem::take(&mut cell));
                was_quoted = false;
                let empty = record.len() == 1 && record[0].is_empty();
                if !empty {
                    records.push((start, std::mem::take(&mut record)));
                } else {
                    record.clear();
                }
                line += 1;
                start = line;
            }
            _ => {
                if was_quoted {
                    return Err(format!(
                        "line {line}: text after the closing quote of a cell"
                    ));
                }
                cell.push(c);
            }
        }
    }
    if quoted {
        return Err(format!("line {start}: a quote that is never closed"));
    }
    if !cell.is_empty() || !record.is_empty() || was_quoted {
        record.push(cell);
        records.push((start, record));
    }
    Ok(records)
}

/// A line that is refused: its number, the column (empty when the whole line is wrong) and why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rejected {
    pub line: usize,
    pub column: String,
    pub message: String,
}

impl Rejected {
    fn text(&self) -> String {
        if self.column.is_empty() {
            format!("line {}: {}", self.line, self.message)
        } else {
            format!("line {}: {} : {}", self.line, self.column, self.message)
        }
    }

    /// The refusal as the JSON object `{ line, column, message }` of a report.
    pub fn json(&self) -> Value {
        serde_json::json!({ "line": self.line, "column": self.column, "message": self.message })
    }
}

/// The items of a CSV body, as JSON objects keyed by the columns, or the lines that are refused (at most 50).
pub fn items(text: &str, columns: &[Column]) -> Result<Vec<Value>, Vec<String>> {
    let (items, rejected) = read(text, columns, false)?;
    if rejected.is_empty() {
        Ok(items)
    } else {
        Err(rejected.iter().map(Rejected::text).collect())
    }
}

/// Like [`items`], but a refused line does not refuse the file: the valid lines are returned with the refused ones (at most 50
/// reported). A file whose header is wrong, or that is not CSV at all, is still refused as a whole.
pub fn items_partial(
    text: &str,
    columns: &[Column],
) -> Result<(Vec<Value>, Vec<Rejected>), Vec<String>> {
    read(text, columns, true)
}

fn read(
    text: &str,
    columns: &[Column],
    partial: bool,
) -> Result<(Vec<Value>, Vec<Rejected>), Vec<String>> {
    let records = records(text).map_err(|e| vec![e])?;
    let Some(((_, header), body)) = records.split_first() else {
        return Err(vec!["line 1: the header line is missing".to_string()]);
    };
    let header: Vec<&str> = header.iter().map(|h| h.trim()).collect();
    // A column that is optional may be left out of the file; a required one may not.
    let missing: Vec<String> = columns
        .iter()
        .filter(|c| c.required && !header.contains(&c.key))
        .map(|c| format!("line 1: the column `{}` is missing", c.key))
        .collect();
    if !missing.is_empty() {
        return Err(missing);
    }

    let mut items = Vec::with_capacity(body.len());
    let mut errors: Vec<Rejected> = Vec::new();
    for (line, cells) in body {
        let mut refused = |column: &str, message: String| {
            if errors.len() < MAX_REPORTED {
                errors.push(Rejected {
                    line: *line,
                    column: column.to_string(),
                    message,
                });
            }
        };
        if cells.len() != header.len() {
            refused(
                "",
                format!("{} cells, the header has {}", cells.len(), header.len()),
            );
        } else {
            let mut object = Map::new();
            let mut ok = true;
            for column in columns {
                let Some(at) = header.iter().position(|h| *h == column.key) else {
                    continue;
                };
                match cell(&cells[at], column) {
                    Ok(Some(value)) => {
                        object.insert(column.key.to_string(), value);
                    }
                    Ok(None) => {}
                    Err(why) => {
                        refused(column.key, why.to_string());
                        ok = false;
                    }
                }
            }
            if ok {
                items.push(Value::Object(object));
            }
        }
        if !partial && errors.len() >= MAX_REPORTED {
            break;
        }
    }
    Ok((items, errors))
}

/// One cell as the JSON value of its column; `None` leaves the key out, which an optional field accepts.
fn cell(text: &str, column: &Column) -> Result<Option<Value>, &'static str> {
    if column.kind == Kind::Text {
        // A required text that is empty is present (the rules of the schema refuse it when it must not be); an
        // optional one that is empty is not sent.
        return Ok(if text.is_empty() && !column.required {
            None
        } else {
            Some(Value::String(text.to_string()))
        });
    }
    let text = text.trim();
    if text.is_empty() {
        return if column.required {
            Err("is required")
        } else {
            Ok(None)
        };
    }
    match column.kind {
        Kind::Text => unreachable!("handled above"),
        Kind::Int32 => text
            .parse::<i32>()
            .map(|n| Some(Value::from(n)))
            .map_err(|_| "not a whole number that fits in 32 bits"),
        Kind::Int64 => text
            .parse::<i64>()
            .map(|n| Some(Value::from(n)))
            .map_err(|_| "not a whole number"),
        Kind::Float => text
            .parse::<f64>()
            .ok()
            .and_then(Number::from_f64)
            .map(|n| Some(Value::Number(n)))
            .ok_or("not a number"),
        Kind::Bool => match text.to_ascii_lowercase().as_str() {
            "true" | "1" => Ok(Some(Value::Bool(true))),
            "false" | "0" => Ok(Some(Value::Bool(false))),
            _ => Err("not true or false"),
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    const COLS: [Column; 3] = [
        Column {
            key: "reference",
            kind: Kind::Text,
            required: true,
        },
        Column {
            key: "seuil",
            kind: Kind::Int32,
            required: true,
        },
        Column {
            key: "actif",
            kind: Kind::Bool,
            required: false,
        },
    ];

    #[test]
    fn writes_a_header_then_one_line_per_item_and_quotes_what_needs_it() {
        let list = json!([
            { "reference": "A-1", "nom": "Vis, 4 mm", "seuil": 5 },
            { "reference": "B\"2", "nom": "ligne\nsuivante", "seuil": null }
        ]);
        assert_eq!(
            write(&list, &["reference", "nom", "seuil"]),
            "reference,nom,seuil\r\nA-1,\"Vis, 4 mm\",5\r\n\"B\"\"2\",\"ligne\nsuivante\",\r\n"
        );
        assert_eq!(write(&json!([]), &["a", "b"]), "a,b\r\n");
    }

    #[test]
    fn what_is_written_is_read_back() {
        let list = json!([{ "reference": "x,\"y\"\nz", "seuil": 3 }]);
        let text = write(&list, &["reference", "seuil"]);
        let rows = records(&text).unwrap();
        assert_eq!(rows[1].1, vec!["x,\"y\"\nz".to_string(), "3".to_string()]);
    }

    #[test]
    fn reads_lf_and_crlf_a_bom_and_skips_blank_lines() {
        let rows = records("\u{feff}a,b\r\n1,2\n\n3,4").unwrap();
        assert_eq!(
            rows,
            vec![
                (1, vec!["a".into(), "b".into()]),
                (2, vec!["1".into(), "2".into()]),
                (4, vec!["3".into(), "4".into()]),
            ]
        );
    }

    #[test]
    fn a_broken_quote_is_refused() {
        assert!(records("a\n\"open").is_err());
        assert!(records("a\nab\"c").is_err());
        assert!(records("a\n\"ab\"c").is_err());
    }

    #[test]
    fn items_are_typed_by_their_column_in_any_order_and_extra_columns_are_ignored() {
        let got = items("seuil,extra,reference,actif\n4,zz,R1,true\n,,R2,\n", &COLS);
        // The second line has no seuil, which is required.
        assert_eq!(got.unwrap_err(), vec!["line 3: seuil : is required"]);
        let got = items("seuil,extra,reference,actif\n4,zz,R1,true\n7,,R2,\n", &COLS).unwrap();
        assert_eq!(
            got[0],
            json!({ "reference": "R1", "seuil": 4, "actif": true })
        );
        assert_eq!(got[1], json!({ "reference": "R2", "seuil": 7 }));
    }

    #[test]
    fn every_refused_line_is_reported_with_its_number() {
        let err = items("reference,seuil\nA,x\nB,2\nC,99999999999\nD\n", &COLS).unwrap_err();
        assert_eq!(
            err,
            vec![
                "line 2: seuil : not a whole number that fits in 32 bits",
                "line 4: seuil : not a whole number that fits in 32 bits",
                "line 5: 1 cells, the header has 2",
            ]
        );
    }

    #[test]
    fn a_partial_read_keeps_the_valid_lines_and_reports_the_others() {
        let (items, rejected) =
            items_partial("reference,seuil\nA,x\nB,2\nC,99999999999\nD\n", &COLS).unwrap();
        assert_eq!(items, vec![json!({ "reference": "B", "seuil": 2 })]);
        assert_eq!(
            rejected.iter().map(Rejected::json).collect::<Vec<_>>(),
            vec![
                json!({ "line": 2, "column": "seuil", "message": "not a whole number that fits in 32 bits" }),
                json!({ "line": 4, "column": "seuil", "message": "not a whole number that fits in 32 bits" }),
                json!({ "line": 5, "column": "", "message": "1 cells, the header has 2" }),
            ]
        );
        // A wrong header is still the whole file's problem.
        assert!(items_partial("reference\nA\n", &COLS).is_err());
        // The valid lines after the cap are kept, only the report is capped.
        let body = format!("reference,seuil\n{}B,2\n", "A,x\n".repeat(500));
        let (items, rejected) = items_partial(&body, &COLS).unwrap();
        assert_eq!((items.len(), rejected.len()), (1, MAX_REPORTED));
    }

    #[test]
    fn a_missing_required_column_is_named_once() {
        assert_eq!(
            items("reference\nA\n", &COLS).unwrap_err(),
            vec!["line 1: the column `seuil` is missing"]
        );
        assert!(items("", &COLS).is_err());
    }

    #[test]
    fn the_report_is_capped() {
        let body = format!("reference,seuil\n{}", "A,x\n".repeat(500));
        assert_eq!(items(&body, &COLS).unwrap_err().len(), MAX_REPORTED);
    }
}
