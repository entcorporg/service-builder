//! Private object storage (S3: Garage or MinIO in development, AWS in production) for the `image*` and `object*` steps.
//!
//! What crosses a step is text: an object body is **base64** (the standard alphabet), which is how a client sends a file
//! in a JSON request and how the answer carries it back. The type of an image is recognised by its **first bytes**: the
//! `Content-Type` a client sends is never believed, since it decides what is served later, and there is no SVG (it can
//! carry a script).
//!
//! Settings come from the environment, never from the project: the bucket from the variable a step names, an optional
//! `S3_ENDPOINT` (set: a compatible store, addressed by path; unset: AWS), and the credentials from the standard chain of
//! the SDK (`AWS_ACCESS_KEY_ID`, `AWS_SECRET_ACCESS_KEY`, `AWS_REGION`). Nothing is requested when the client is built.
//!
//! Needs the cargo feature `s3`; the generator turns it on for the services that use it.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::{Result, anyhow};
use aws_sdk_s3::{Client, error::DisplayErrorContext, primitives::ByteStream};
use base64::Engine as _;
use base64::engine::general_purpose::STANDARD;

use crate::http::HttpError;

/// No object goes through a step above this, whatever the step says: 10 MiB.
pub const HARD_LIMIT_BYTES: usize = 10 * 1024 * 1024;

const PNG_MAGIC: &[u8] = &[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A];
const JPEG_MAGIC: &[u8] = &[0xFF, 0xD8, 0xFF];

/// The type of an image from its first bytes, if it is one of `allow` (`"png"`, `"jpeg"`).
pub fn sniff(bytes: &[u8], allow: &[&str]) -> Option<&'static str> {
    let kind = if bytes.starts_with(PNG_MAGIC) {
        ("png", "image/png")
    } else if bytes.starts_with(JPEG_MAGIC) {
        ("jpeg", "image/jpeg")
    } else {
        return None;
    };
    allow.contains(&kind.0).then_some(kind.1)
}

/// The step `imageSniff`: `input` is the image in base64. It must not be empty or above `max_bytes`, and must be one of
/// `allow`; the result is its media type. Anything else is a `400`.
pub fn sniff_image(input: &str, allow: &[&str], max_bytes: usize) -> Result<&'static str> {
    let bad = |message: &str| anyhow::Error::from(HttpError::bad_request(message));
    // Before decoding, so that a huge text is not decoded just to be refused.
    if input.len() > max_bytes.div_ceil(3) * 4 + 4 {
        return Err(bad("the image is too large"));
    }
    let bytes = STANDARD.decode(input.trim()).map_err(|_| bad("the image is not valid base64"))?;
    if bytes.is_empty() {
        return Err(bad("the image is empty"));
    }
    if bytes.len() > max_bytes {
        return Err(bad("the image is too large"));
    }
    sniff(&bytes, allow).ok_or_else(|| bad("the image must be one of the accepted types"))
}

/// The object store: a client, which is cheap to share.
pub struct Store {
    client: Client,
}

impl Store {
    pub fn new(client: Client) -> Self {
        Self { client }
    }

    /// The real AWS client, or a compatible store when `endpoint` is given (addressed by path, as Garage expects). The
    /// region defaults to `us-east-1` when the environment has none, which such stores ignore.
    pub async fn connect(endpoint: Option<&str>) -> Self {
        let region = aws_config::meta::region::RegionProviderChain::default_provider().or_else("us-east-1");
        let mut loader = aws_config::defaults(aws_config::BehaviorVersion::latest()).region(region);
        if let Some(endpoint) = endpoint {
            loader = loader.endpoint_url(endpoint);
        }
        let sdk = loader.load().await;
        let mut config = aws_sdk_s3::config::Builder::from(&sdk);
        if endpoint.is_some() {
            config = config.force_path_style(true);
        }
        Self::new(Client::from_conf(config.build()))
    }

    pub async fn put(&self, bucket: &str, key: &str, bytes: Vec<u8>, content_type: &str) -> Result<()> {
        self.client
            .put_object()
            .bucket(bucket)
            .key(key)
            .body(ByteStream::from(bytes))
            .content_type(content_type)
            .send()
            .await
            .map_err(|e| unavailable(DisplayErrorContext(&e)))?;
        Ok(())
    }

    /// `None` for an object that does not exist: that is an answer, not a failure.
    pub async fn get(&self, bucket: &str, key: &str) -> Result<Option<Vec<u8>>> {
        match self.client.get_object().bucket(bucket).key(key).send().await {
            Ok(output) => {
                let bytes = output.body.collect().await.map_err(unavailable)?;
                Ok(Some(bytes.into_bytes().to_vec()))
            }
            Err(e) if e.as_service_error().is_some_and(|s| s.is_no_such_key()) => Ok(None),
            Err(e) => Err(unavailable(DisplayErrorContext(&e))),
        }
    }

    pub async fn delete(&self, bucket: &str, key: &str) -> Result<()> {
        self.client
            .delete_object()
            .bucket(bucket)
            .key(key)
            .send()
            .await
            .map_err(|e| unavailable(DisplayErrorContext(&e)))?;
        Ok(())
    }
}

/// A store that cannot be reached is a `503`, not a `500`: the service is fine, what it depends on is not. The detail
/// stays in the logs.
fn unavailable(detail: impl std::fmt::Display) -> anyhow::Error {
    tracing::warn!(error = %detail, "object storage failed");
    HttpError::new(503, "storage unavailable").into()
}

static STORE: tokio::sync::OnceCell<Store> = tokio::sync::OnceCell::const_new();

fn endpoint() -> Option<String> {
    std::env::var("S3_ENDPOINT").ok().filter(|e| !e.trim().is_empty())
}

async fn store() -> &'static Store {
    STORE.get_or_init(|| async { Store::connect(endpoint().as_deref()).await }).await
}

/// A service that has an object step fails at start-up when its bucket is not named, or the endpoint is not a URL.
pub fn check_config(bucket_envs: &[&str]) -> Result<()> {
    for env in bucket_envs {
        bucket(env)?;
    }
    if let Some(endpoint) = endpoint()
        && !(endpoint.starts_with("http://") || endpoint.starts_with("https://"))
    {
        anyhow::bail!("S3_ENDPOINT must be an http(s) URL");
    }
    Ok(())
}

fn bucket(env: &str) -> Result<String> {
    match std::env::var(env) {
        Ok(name) if !name.trim().is_empty() => Ok(name.trim().to_string()),
        _ => Err(anyhow!("{env} is not set: the name of the bucket is needed")),
    }
}

/// An object key a flow built from its data: not empty, not huge, no control character.
fn key_ok(key: &str) -> Result<&str> {
    if key.is_empty() || key.len() > 1024 || key.chars().any(char::is_control) {
        return Err(HttpError::bad_request("invalid object key").into());
    }
    Ok(key)
}

/// A media type as `type/subtype`, so that nothing else can reach a header.
fn media_type_ok(media_type: &str) -> Result<&str> {
    let part = |s: &str| !s.is_empty() && s.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'+' | b'-'));
    match media_type.split_once('/') {
        Some((a, b)) if media_type.len() <= 100 && part(a) && part(b) => Ok(media_type),
        _ => Err(HttpError::bad_request("invalid content type").into()),
    }
}

/// The step `objectPut`: stores `body` (base64) under `key` in the bucket named by the variable `bucket_env`.
pub async fn put(bucket_env: &str, key: &str, body: &str, content_type: &str) -> Result<()> {
    let (key, content_type) = (key_ok(key)?, media_type_ok(content_type)?);
    if body.len() > HARD_LIMIT_BYTES.div_ceil(3) * 4 + 4 {
        return Err(HttpError::bad_request("the object is too large").into());
    }
    let bytes = STANDARD.decode(body.trim()).map_err(|_| HttpError::bad_request("the object is not valid base64"))?;
    if bytes.len() > HARD_LIMIT_BYTES {
        return Err(HttpError::bad_request("the object is too large").into());
    }
    store().await.put(&bucket(bucket_env)?, key, bytes, content_type).await
}

/// The step `objectGet`: the object in base64, or `None` when there is none.
pub async fn get(bucket_env: &str, key: &str) -> Result<Option<String>> {
    let key = key_ok(key)?;
    Ok(store().await.get(&bucket(bucket_env)?, key).await?.map(|bytes| STANDARD.encode(bytes)))
}

/// The step `objectDelete`. Deleting what is not there is not an error.
pub async fn delete(bucket_env: &str, key: &str) -> Result<()> {
    let key = key_ok(key)?;
    store().await.delete(&bucket(bucket_env)?, key).await
}

#[cfg(all(test, feature = "s3-tests"))]
mod tests {
    use super::*;
    use std::collections::HashMap;
    use std::sync::{Arc, Mutex};

    use aws_sdk_s3::config::retry::RetryConfig;
    use aws_sdk_s3::config::{BehaviorVersion, Credentials, Region};
    use axum::Router;
    use axum::body::Bytes;
    use axum::extract::{Path, State};
    use axum::http::{HeaderMap, StatusCode, header};
    use axum::response::IntoResponse;
    use axum::routing::put as put_route;

    const PNG_BYTES: &[u8] = &[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A, 1, 2, 3];
    const JPEG_BYTES: &[u8] = &[0xFF, 0xD8, 0xFF, 0xE0, 1, 2, 3];
    const BOTH: &[&str] = &["png", "jpeg"];

    type Objects = Arc<Mutex<HashMap<String, (Vec<u8>, String)>>>;

    /// A fake S3 on a local port: it keeps what it is sent, answers `NoSuchKey` (404 and XML) for a missing object, and
    /// notes whether each request was signed.
    #[derive(Clone, Default)]
    struct FakeS3 {
        objects: Objects,
        signed: Arc<Mutex<Vec<bool>>>,
    }

    async fn s3_put(State(s): State<FakeS3>, Path((bucket, key)): Path<(String, String)>, headers: HeaderMap, body: Bytes) -> StatusCode {
        s.signed.lock().unwrap().push(headers.contains_key(header::AUTHORIZATION));
        let content_type = headers.get(header::CONTENT_TYPE).and_then(|v| v.to_str().ok()).unwrap_or("").to_owned();
        s.objects.lock().unwrap().insert(format!("{bucket}/{key}"), (body.to_vec(), content_type));
        StatusCode::OK
    }

    async fn s3_get(State(s): State<FakeS3>, Path((bucket, key)): Path<(String, String)>) -> axum::response::Response {
        match s.objects.lock().unwrap().get(&format!("{bucket}/{key}")) {
            Some((bytes, content_type)) => ([(header::CONTENT_TYPE, content_type.clone())], bytes.clone()).into_response(),
            None => (
                StatusCode::NOT_FOUND,
                [(header::CONTENT_TYPE, "application/xml")],
                "<?xml version=\"1.0\"?><Error><Code>NoSuchKey</Code><Message>absent</Message></Error>",
            )
                .into_response(),
        }
    }

    async fn s3_delete(State(s): State<FakeS3>, Path((bucket, key)): Path<(String, String)>) -> StatusCode {
        s.objects.lock().unwrap().remove(&format!("{bucket}/{key}"));
        StatusCode::NO_CONTENT
    }

    async fn spawn_fake() -> (FakeS3, String) {
        let fake = FakeS3::default();
        let app = Router::new().route("/{bucket}/{key}", put_route(s3_put).get(s3_get).delete(s3_delete)).with_state(fake.clone());
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let url = format!("http://{}", listener.local_addr().unwrap());
        tokio::spawn(async move { axum::serve(listener, app).await });
        (fake, url)
    }

    /// A client set like `Store::connect` with an endpoint (path addressing), explicit credentials, and no retry so that
    /// the tests stay fast.
    fn store_for(endpoint: &str) -> Store {
        let config = aws_sdk_s3::Config::builder()
            .behavior_version(BehaviorVersion::latest())
            .region(Region::new("garage"))
            .endpoint_url(endpoint)
            .force_path_style(true)
            .credentials_provider(Credentials::new("AKTEST", "secret", None, None, "test"))
            .retry_config(RetryConfig::disabled())
            .build();
        Store::new(Client::from_conf(config))
    }

    fn status_of<T>(result: Result<T>) -> Option<u16> {
        result.err().and_then(|e| e.downcast::<HttpError>().ok()).map(|e| e.status)
    }

    #[test]
    fn an_image_is_what_its_first_bytes_say_not_what_it_is_called() {
        assert_eq!(sniff(PNG_BYTES, BOTH), Some("image/png"));
        assert_eq!(sniff(JPEG_BYTES, BOTH), Some("image/jpeg"));
        assert_eq!(sniff(b"<svg onload=alert(1)>", BOTH), None, "no SVG");
        assert_eq!(sniff(b"<?xml version=\"1.0\"?><svg/>", BOTH), None);
        assert_eq!(sniff(b"GIF89a", BOTH), None);
        assert_eq!(sniff(b"", BOTH), None);
        // Only the types the step allows.
        assert_eq!(sniff(PNG_BYTES, &["jpeg"]), None);
        assert_eq!(sniff(JPEG_BYTES, &["png"]), None);
        // A PNG signature that is cut short is not one.
        assert_eq!(sniff(&PNG_BYTES[..7], BOTH), None);
    }

    #[test]
    fn the_step_refuses_what_is_empty_oversized_or_unknown_with_a_400() {
        let encode = |bytes: &[u8]| STANDARD.encode(bytes);
        assert_eq!(sniff_image(&encode(PNG_BYTES), BOTH, 1024).unwrap(), "image/png");
        assert_eq!(sniff_image(&format!("  {}\n", encode(JPEG_BYTES)), BOTH, 1024).unwrap(), "image/jpeg");
        for (what, input) in [
            ("empty", String::new()),
            ("not base64", "not base64!!".to_string()),
            ("text", encode(b"hello")),
            ("svg", encode(b"<svg onload=alert(1)>")),
            // A data URL is not base64: the prefix is the client's to remove.
            ("data url", format!("data:image/png;base64,{}", encode(PNG_BYTES))),
        ] {
            assert_eq!(status_of(sniff_image(&input, BOTH, 1024)), Some(400), "{what}");
        }
        // The limit counts the decoded bytes, and includes itself.
        let mut at_limit = PNG_BYTES.to_vec();
        at_limit.resize(1024, 0);
        assert!(sniff_image(&encode(&at_limit), BOTH, 1024).is_ok());
        at_limit.push(0);
        assert_eq!(status_of(sniff_image(&encode(&at_limit), BOTH, 1024)), Some(400));
        // A text far above the limit is refused without being decoded.
        assert_eq!(status_of(sniff_image(&"A".repeat(10_000), BOTH, 1024)), Some(400));
    }

    #[test]
    fn keys_and_types_cannot_carry_more_than_they_name() {
        assert!(key_ok("avatars/7d9f0c1e").is_ok());
        for key in ["", "a\nb", "a\u{0}b", &"k".repeat(1025)] {
            assert_eq!(status_of(key_ok(key).map(|_| ())), Some(400), "{key:?}");
        }
        assert!(media_type_ok("image/png").is_ok());
        assert!(media_type_ok("application/vnd.api+json").is_ok());
        for wrong in ["", "png", "image/", "/png", "image/png\r\nX-Evil: 1", "image/png; charset=x", "a/b/c"] {
            assert_eq!(status_of(media_type_ok(wrong).map(|_| ())), Some(400), "{wrong:?}");
        }
    }

    #[test]
    fn the_bucket_and_the_endpoint_are_checked_at_start_up() {
        unsafe {
            std::env::set_var("EDA_TEST_BUCKET", "avatars");
            std::env::remove_var("EDA_TEST_NO_BUCKET");
            std::env::set_var("EDA_TEST_EMPTY_BUCKET", "  ");
            std::env::remove_var("S3_ENDPOINT");
        }
        assert_eq!(bucket("EDA_TEST_BUCKET").unwrap(), "avatars");
        assert!(check_config(&["EDA_TEST_BUCKET"]).is_ok());
        assert!(check_config(&["EDA_TEST_NO_BUCKET"]).is_err());
        assert!(check_config(&["EDA_TEST_EMPTY_BUCKET"]).is_err());
    }

    #[tokio::test]
    async fn the_store_puts_gets_and_deletes_over_http_with_signed_requests() {
        let (fake, url) = spawn_fake().await;
        let store = store_for(&url);
        let key = "7d9f0c1e";

        store.put("avatars", key, PNG_BYTES.to_vec(), "image/png").await.unwrap();
        let (stored, content_type) = fake.objects.lock().unwrap().get("avatars/7d9f0c1e").cloned().unwrap();
        assert_eq!(stored, PNG_BYTES);
        assert_eq!(content_type, "image/png");
        assert_eq!(fake.signed.lock().unwrap().as_slice(), [true], "the request is signed (SigV4)");

        assert_eq!(store.get("avatars", key).await.unwrap().as_deref(), Some(PNG_BYTES));
        store.delete("avatars", key).await.unwrap();
        assert_eq!(store.get("avatars", key).await.unwrap(), None, "NoSuchKey is None, not an error");
        // Deleting again is fine.
        store.delete("avatars", key).await.unwrap();
    }

    #[tokio::test]
    async fn a_missing_object_is_none_but_an_unreachable_store_is_a_503() {
        let (_fake, url) = spawn_fake().await;
        assert_eq!(store_for(&url).get("avatars", "unknown").await.unwrap(), None);

        // A closed port: the store is down.
        let closed = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let dead_url = format!("http://{}", closed.local_addr().unwrap());
        drop(closed);
        let dead = store_for(&dead_url);
        assert_eq!(status_of(dead.put("avatars", "k", PNG_BYTES.to_vec(), "image/png").await), Some(503));
        assert_eq!(status_of(dead.get("avatars", "k").await), Some(503));
        assert_eq!(status_of(dead.delete("avatars", "k").await), Some(503));
    }
}
