        let (parts, body) = request.into_parts();
        let body = to_bytes(body, 1 << 20).await.unwrap_or_default();
        let target = parts.uri.path_and_query().map(|p| p.as_str().to_string()).unwrap_or_default();
        fake.seen.lock().unwrap().push(Seen {
            method: parts.method.to_string(),
            target: target.clone(),
            headers: parts.headers.iter().map(|(n, v)| (n.to_string(), v.to_str().unwrap_or("").to_string())).collect(),
            body: String::from_utf8_lossy(&body).into_owned(),
        });
        let path = parts.uri.path();
