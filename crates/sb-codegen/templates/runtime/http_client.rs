//! Outbound HTTP calls (Stripe, Twilio, any REST service) for the `httpCall` step.
//!
//! What keeps a call safe, whatever the flow feeds it:
//! * the **base address** comes from the environment (a variable the step names), never from a value of the flow, and a
//!   service that cannot use it does not start; a flow cannot send a request where a client chose. Redirects are not
//!   followed (they would move the request, and the secret with it, to another host);
//! * a **path** is fixed text plus values that go through [`segment`], each one a single encoded segment (it cannot add a
//!   segment, a query or a fragment, nor be `.` or `..`); the query and a form body are encoded here, a header value
//!   that is not a valid one is a `400`;
//! * the **secrets** (token, password, key) are read from the environment on each call and never logged; nor is any URL,
//!   header or body, only the status. A secret is never sent in clear over `http://` to anything but this machine;
//! * a call has a **time limit** per attempt, an answer a **size limit** (5 MiB), and a retry only follows a failure that
//!   means "try again" (no answer in time, host unreachable, 429, 502, 503, 504), with a growing wait.
//!
//! Needs the cargo feature `http-client`; the generator turns it on for the services that use it.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::sync::OnceLock;
use std::time::Duration;

use anyhow::{Result, anyhow};
use reqwest::header::{HeaderName, HeaderValue};
use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::Value;

use crate::http::HttpError;

/// The largest answer read: 5 MiB. A service that returns more is not what the flow expects.
const MAX_ANSWER_BYTES: usize = 5 * 1024 * 1024;
const FIRST_WAIT: Duration = Duration::from_millis(200);
const LONGEST_WAIT: Duration = Duration::from_secs(5);

/// How a call authenticates. The strings are the names of environment variables, except the header of an API key.
pub enum Auth<'a> {
    None,
    /// `Authorization: Bearer <token>`.
    Bearer(&'a str),
    /// `Authorization: Basic`, from the variables of the user name and of the password.
    Basic(&'a str, &'a str),
    /// The key, from the variable, in this header.
    ApiKey(&'a str, &'a str),
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum BodyFormat {
    Json,
    Form,
}

/// `name = value` pairs of a query, of headers or of a body. A value is anything that becomes JSON; in a query, a header
/// or a form a text is itself, a number or a boolean is written, and an absent value is left out.
#[derive(Default, Debug, Clone)]
pub struct Fields(Vec<(String, Value)>);

impl Fields {
    pub fn set(&mut self, name: &str, value: impl Serialize) {
        self.0.push((name.to_string(), serde_json::to_value(value).unwrap_or(Value::Null)));
    }

    /// An optional value: nothing is sent when it is absent.
    pub fn set_opt(&mut self, name: &str, value: Option<impl Serialize>) {
        if let Some(value) = value {
            self.set(name, value);
        }
    }

    fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    /// The pairs as text, for a query, a header or a form. Null and structures have no text form: they are left out.
    fn texts(&self) -> Vec<(&str, String)> {
        self.0
            .iter()
            .filter_map(|(name, value)| {
                let text = match value {
                    Value::String(s) => s.clone(),
                    Value::Number(n) => n.to_string(),
                    Value::Bool(b) => b.to_string(),
                    _ => return None,
                };
                Some((name.as_str(), text))
            })
            .collect()
    }

    fn json(&self) -> Value {
        Value::Object(self.0.iter().map(|(k, v)| (k.clone(), v.clone())).collect())
    }
}

/// What the step asks for. The path is already built with [`segment`].
pub struct Call<'a> {
    /// The id of the step, for the logs.
    pub id: &'a str,
    pub method: &'a str,
    pub base_url_env: &'a str,
    pub path: &'a str,
    pub query: Fields,
    pub headers: Fields,
    pub auth: Auth<'a>,
    pub body: Fields,
    pub format: BodyFormat,
    pub timeout_secs: u64,
    pub retries: u32,
    pub idempotency_key: Option<String>,
    /// The circuit breaker and the bulkhead of the step (see `resilience`): none by default.
    pub resilience: crate::resilience::Policy,
}

/// What came back. `status` is `0` when nobody answered (timeout, host unreachable, an answer that is too large).
#[derive(Debug)]
pub struct Answer {
    pub status: u16,
    body: Vec<u8>,
}

impl Answer {
    pub fn ok(&self) -> bool {
        (200..300).contains(&self.status)
    }

    /// Stops the flow with `status` and `message` unless the call succeeded (a 2xx). A 5xx answers a generic text.
    pub fn require_success(self, status: u16, message: &str) -> Result<Self> {
        if self.ok() {
            Ok(self)
        } else {
            Err(HttpError::new(status, message).into())
        }
    }

    /// The JSON answer read into `T` (fields it does not name are ignored, fields it lacks take their default). A
    /// success that is not what `T` expects is a `502`; after a failure, what cannot be read is just the default, since the
    /// status says what happened.
    pub fn parse<T: DeserializeOwned + Default>(&self) -> Result<T> {
        if self.body.iter().all(u8::is_ascii_whitespace) {
            return Ok(T::default());
        }
        match serde_json::from_slice(&self.body) {
            Ok(value) => Ok(value),
            Err(_) if !self.ok() => Ok(T::default()),
            Err(_) => Err(HttpError::new(502, "the external service sent an answer that is not what was expected").into()),
        }
    }
}

/// A value of the flow as one segment of a path: percent-encoded, so it cannot add a segment, a query or a fragment.
/// Empty, `.` and `..` are a `400` (a client could otherwise climb out of the path).
pub fn segment(value: &str) -> Result<String> {
    if value.is_empty() || value == "." || value == ".." {
        return Err(HttpError::bad_request("invalid value in a path").into());
    }
    Ok(encode(value, false))
}

/// Percent-encoding. `form`: the `application/x-www-form-urlencoded` flavour (a space is `+`); otherwise a space is `%20`.
fn encode(text: &str, form: bool) -> String {
    let mut out = String::with_capacity(text.len());
    for b in text.bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => out.push(b as char),
            b' ' if form => out.push('+'),
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

fn form_encode(pairs: &[(&str, String)]) -> String {
    pairs.iter().map(|(k, v)| format!("{}={}", encode(k, true), encode(v, true))).collect::<Vec<_>>().join("&")
}

fn is_loopback(host: &str) -> bool {
    host == "localhost" || host.ends_with(".localhost") || host == "[::1]" || host.starts_with("127.")
}

/// The base address, checked: `http(s)://host[:port][/prefix]`, no credentials, query or fragment.
fn parse_base(value: &str) -> Result<reqwest::Url> {
    let url = reqwest::Url::parse(value.trim()).map_err(|e| anyhow!("not a URL: {e}"))?;
    if !matches!(url.scheme(), "http" | "https") {
        anyhow::bail!("the scheme must be http or https");
    }
    if url.host_str().is_none() {
        anyhow::bail!("it has no host");
    }
    if !url.username().is_empty() || url.password().is_some() {
        anyhow::bail!("it must not carry credentials (they go in the authentication of the step)");
    }
    if url.query().is_some() || url.fragment().is_some() {
        anyhow::bail!("it must have no query or fragment");
    }
    Ok(url)
}

fn base_url(env: &str) -> Result<reqwest::Url> {
    let value = std::env::var(env).map_err(|_| anyhow!("{env} is not set: the address of the external service is needed"))?;
    parse_base(&value).map_err(|e| anyhow!("{env}: {e}"))
}

fn secret(env: &str) -> Result<String> {
    match std::env::var(env) {
        Ok(value) if !value.trim().is_empty() => Ok(value.trim().to_string()),
        _ => Err(anyhow!("{env} is not set: the secret of an external service is needed")),
    }
}

/// A service that calls an external API fails at start-up when its address is not a usable URL or a secret is missing, and
/// when a secret would travel in clear over `http://` to another machine. `targets` are `(base URL variable, secret
/// variables)`. Nothing is requested here.
pub fn check_config(targets: &[(&str, &[&str])]) -> Result<()> {
    for (env, secrets) in targets {
        let url = base_url(env)?;
        for s in *secrets {
            secret(s)?;
        }
        if !secrets.is_empty() && url.scheme() == "http" && !url.host_str().is_some_and(is_loopback) {
            anyhow::bail!("{env} is http:// and the call carries a secret: use https://");
        }
    }
    Ok(())
}

fn client() -> &'static reqwest::Client {
    static CLIENT: OnceLock<reqwest::Client> = OnceLock::new();
    CLIENT.get_or_init(|| {
        reqwest::Client::builder()
            // A redirect would send the request, and the secret, to a host the environment did not name.
            .redirect(reqwest::redirect::Policy::none())
            .user_agent("eda-service")
            .build()
            .expect("an HTTP client")
    })
}

/// The step `httpCall`: the answer of the external service, or an error for what is wrong with the call itself (a `400`
/// for a value that cannot be sent, a `500` for a configuration that is missing). What the service did (a status, no
/// answer) is the [`Answer`].
pub async fn send(call: Call<'_>) -> Result<Answer> {
    let base = base_url(call.base_url_env)?;
    send_guarded(base, call).await
}

/// The call, through the circuit and the bulkhead of its step. A call they refuse is not made: it is answered like a call nobody
/// answered (status `0`), so that `on_error` decides what the flow does. Whether the dependency is unwell is judged on the whole
/// call, retries included: a timeout, no answer, a 429 or a 5xx; a 4xx is the caller's doing, and so is a call that was wrong in
/// itself (a value that cannot be sent, a setting that is missing), which says nothing of the dependency.
async fn send_guarded(base: reqwest::Url, call: Call<'_>) -> Result<Answer> {
    let guard = match crate::resilience::enter(call.resilience, call.base_url_env, call.id) {
        Ok(guard) => guard,
        Err(rejected) => {
            tracing::warn!(step = call.id, reason = rejected.reason, retry_after = rejected.retry_after, "outbound call not made");
            return Ok(Answer { status: 0, body: vec![] });
        }
    };
    let answer = send_to(base, call).await;
    match &answer {
        Ok(a) => guard.finish(!(a.status == 0 || a.status == 429 || a.status >= 500)),
        Err(_) => drop(guard),
    }
    answer
}

async fn send_to(base: reqwest::Url, call: Call<'_>) -> Result<Answer> {
    let method = reqwest::Method::from_bytes(call.method.as_bytes()).map_err(|_| anyhow!("unknown method {}", call.method))?;
    let mut url = base.as_str().trim_end_matches('/').to_string();
    url.push_str(call.path);
    let query = call.query.texts();
    if !query.is_empty() {
        url.push('?');
        url.push_str(&form_encode(&query));
    }
    let url = reqwest::Url::parse(&url).map_err(|_| HttpError::bad_request("invalid address for the external service"))?;
    // The path built from values must not have changed host, whatever it held.
    if url.host_str() != base.host_str() || url.port() != base.port() || url.scheme() != base.scheme() {
        return Err(HttpError::bad_request("invalid address for the external service").into());
    }
    let mut headers = reqwest::header::HeaderMap::new();
    let mut put = |name: &str, value: &str| -> Result<()> {
        let name = HeaderName::from_bytes(name.as_bytes()).map_err(|_| HttpError::bad_request("invalid header name"))?;
        let value = HeaderValue::from_str(value).map_err(|_| HttpError::bad_request("invalid header value"))?;
        headers.insert(name, value);
        Ok(())
    };
    for (name, value) in call.headers.texts() {
        put(name, &value)?;
    }
    if let Some(key) = &call.idempotency_key {
        put("Idempotency-Key", key)?;
    }
    match &call.auth {
        Auth::None => {}
        Auth::Bearer(env) => put("Authorization", &format!("Bearer {}", secret(env)?))?,
        Auth::ApiKey(header, env) => put(header, &secret(env)?)?,
        Auth::Basic(..) => {}
    }
    let basic = match &call.auth {
        Auth::Basic(user, password) => Some((secret(user)?, secret(password)?)),
        _ => None,
    };
    let (content_type, payload) = if call.body.is_empty() {
        (None, None)
    } else {
        match call.format {
            BodyFormat::Json => (Some("application/json"), Some(call.body.json().to_string().into_bytes())),
            BodyFormat::Form => (Some("application/x-www-form-urlencoded"), Some(form_encode(&call.body.texts()).into_bytes())),
        }
    };
    let timeout = Duration::from_secs(call.timeout_secs.max(1));
    let mut wait = FIRST_WAIT;
    for attempt in 0..=call.retries {
        let mut request = client().request(method.clone(), url.clone()).headers(headers.clone()).timeout(timeout);
        if let Some((user, password)) = &basic {
            request = request.basic_auth(user, Some(password));
        }
        if let Some(content_type) = content_type {
            request = request.header("Content-Type", content_type);
        }
        if let Some(payload) = &payload {
            request = request.body(payload.clone());
        }
        let (answer, reason) = match request.send().await {
            Ok(response) => {
                let status = response.status().as_u16();
                match read_limited(response).await {
                    Ok(body) => (Answer { status, body }, None),
                    Err(reason) => (Answer { status: 0, body: vec![] }, Some(reason)),
                }
            }
            Err(e) if e.is_timeout() => (Answer { status: 0, body: vec![] }, Some("timeout")),
            Err(_) => (Answer { status: 0, body: vec![] }, Some("unreachable")),
        };
        let retry = answer.status == 0 || matches!(answer.status, 429 | 502 | 503 | 504);
        if answer.ok() || !retry || attempt == call.retries {
            if !answer.ok() {
                tracing::warn!(step = call.id, status = answer.status, reason, attempt, "outbound call did not succeed");
            }
            return Ok(answer);
        }
        tracing::warn!(step = call.id, status = answer.status, reason, attempt, "outbound call will be retried");
        tokio::time::sleep(wait).await;
        wait = (wait * 2).min(LONGEST_WAIT);
    }
    unreachable!("the last attempt returns")
}

/// The body of an answer, at most [`MAX_ANSWER_BYTES`].
async fn read_limited(mut response: reqwest::Response) -> std::result::Result<Vec<u8>, &'static str> {
    let mut body = Vec::new();
    while let Some(chunk) = response.chunk().await.map_err(|e| if e.is_timeout() { "timeout" } else { "unreachable" })? {
        if body.len() + chunk.len() > MAX_ANSWER_BYTES {
            return Err("answer too large");
        }
        body.extend_from_slice(&chunk);
    }
    Ok(body)
}

