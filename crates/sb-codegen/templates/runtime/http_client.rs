    #[tokio::test]
    async fn retries_follow_a_503_with_the_same_idempotency_key_and_stop_on_a_refusal() {
        let (fake, base) = spawn().await;
        fake.failures.store(2, Ordering::SeqCst);
        let mut c = call("POST", "/flaky");
        c.retries = 3;
        c.idempotency_key = Some("k-1".into());
        let answer = send_to(base.clone(), c).await.unwrap();
        assert_eq!(answer.status, 200);
        {
            let seen = fake.seen.lock().unwrap();
            assert_eq!(seen.len(), 3);
            assert!(seen.iter().all(|s| s.header("idempotency-key") == Some("k-1")));
        }
        // Not enough retries: the last answer is given.
        fake.seen.lock().unwrap().clear();
        fake.failures.store(5, Ordering::SeqCst);
        let mut c = call("GET", "/flaky");
        c.retries = 1;
        assert_eq!(send_to(base.clone(), c).await.unwrap().status, 503);
        assert_eq!(fake.seen.lock().unwrap().len(), 2);
        // A 402 is a decision, not a hiccup: no retry.
        fake.seen.lock().unwrap().clear();
        let mut c = call("GET", "/status/402");
        c.retries = 3;
        assert_eq!(send_to(base, c).await.unwrap().status, 402);
        assert_eq!(fake.seen.lock().unwrap().len(), 1);
    }

