//! Events for the browsers: the step `publishLive`.
//!
//! A flow does not talk to the browsers. It leaves a JSON message on a channel of DragonflyDB (or Valkey, or Redis) and the
//! real-time service of the project, which listens to that channel, hands it to the open streams it is for. The shape of the
//! message is the one that service reads (`events.rs` of its template); the editor checks the same rules, so what reaches
//! this module is already valid.
//!
//! The events are **kept until the flow has committed** and sent then, never before: a run that fails sends nothing, and the
//! browser is never told about a change the database does not have. Sending is best effort. The database is the truth and the
//! browser reads its state again (`resync` after a cut, a fetch after an event), so an event that cannot be published is
//! logged and the request still succeeds.
//!
//! The server is named by `DRAGONFLY_URL` (required when `APP_ENV=production`, `redis://localhost:6379` otherwise). Nothing is
//! requested when the service starts, only checked; the connection is made at the first event and kept.
//!
//! Needs the cargo feature `live`; the generator turns it on for the services that use it.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use anyhow::Result;
use redis::aio::ConnectionManager;
use serde_json::{Map, Value, json};
use tokio::sync::OnceCell;

/// What an event is for and what it says. `kind` is `domain.action`; the audience is an account, or a permission and/or a
/// list of accounts (in a company when `tenant_id` is given).
#[derive(Debug, Default, Clone)]
pub struct Event<'a> {
    pub kind: &'a str,
    pub account_id: Option<String>,
    pub tenant_id: Option<String>,
    pub permission: Option<&'a str>,
    pub account_ids: Vec<String>,
    /// The tab that made the change: it already has the answer to its write, so it does not get the event.
    pub origin: Option<String>,
    /// A few identifiers, never content.
    pub data: Vec<(&'a str, String)>,
}

impl Event<'_> {
    /// The message as the real-time service reads it.
    fn message(&self) -> Value {
        let mut m = Map::new();
        m.insert("type".into(), json!(self.kind));
        if let Some(v) = &self.account_id {
            m.insert("accountId".into(), json!(v));
        }
        if let Some(v) = &self.tenant_id {
            m.insert("tenantId".into(), json!(v));
        }
        if let Some(v) = self.permission {
            m.insert("permission".into(), json!(v));
        }
        if !self.account_ids.is_empty() {
            m.insert("accountIds".into(), json!(self.account_ids));
        }
        if let Some(v) = &self.origin {
            m.insert("origin".into(), json!(v));
        }
        let data: Map<String, Value> = self.data.iter().map(|(k, v)| ((*k).to_string(), json!(v))).collect();
        m.insert("data".into(), Value::Object(data));
        Value::Object(m)
    }

    /// What the real-time service would refuse, seen before the event is sent. It cannot be a flow's fault at design time
    /// (the editor checks the same things): a value that comes from the data is what can break a rule.
    fn problem(&self) -> Option<String> {
        if let Some((key, _)) = self.data.iter().find(|(_, v)| v.len() > 64 || v.chars().any(char::is_control)) {
            return Some(format!("the value of `{key}` is over 64 characters or holds a control character"));
        }
        if self.account_id.is_none() && self.permission.is_none() && self.account_ids.is_empty() {
            return Some("no audience: the list of accounts is empty and there is no account or permission".into());
        }
        None
    }
}

/// The events of one run, waiting for its commit.
#[derive(Debug, Default)]
pub struct Live {
    pending: Vec<(&'static str, String)>,
}

impl Live {
    /// Keeps `event` for `channel` until [`Live::flush`].
    pub fn push(&mut self, channel: &'static str, event: Event<'_>) {
        if let Some(problem) = event.problem() {
            tracing::error!(event = event.kind, %problem, "live event dropped");
            return;
        }
        self.pending.push((channel, event.message().to_string()));
    }

    /// Sends what was kept. To be called after the commit; it never fails the flow.
    pub async fn flush(&mut self) {
        if self.pending.is_empty() {
            return;
        }
        let pending = std::mem::take(&mut self.pending);
        if let Err(e) = publish_all(&pending).await {
            tracing::warn!(error = %e, events = pending.len(), "live events not published");
        }
    }
}

static CONNECTION: OnceCell<ConnectionManager> = OnceCell::const_new();

fn url() -> Result<String> {
    match std::env::var("DRAGONFLY_URL") {
        Ok(url) if !url.trim().is_empty() => Ok(url.trim().to_string()),
        _ if std::env::var("APP_ENV").is_ok_and(|e| e == "production") => {
            anyhow::bail!("DRAGONFLY_URL is required in production")
        }
        _ => Ok("redis://localhost:6379".into()),
    }
}

async fn publish_all(pending: &[(&'static str, String)]) -> Result<()> {
    let mut connection = CONNECTION
        .get_or_try_init(|| async { ConnectionManager::new(redis::Client::open(url()?)?).await.map_err(anyhow::Error::from) })
        .await?
        .clone();
    // One round trip for the whole run.
    let mut pipe = redis::pipe();
    for (channel, payload) in pending {
        pipe.cmd("PUBLISH").arg(*channel).arg(payload).ignore();
    }
    pipe.query_async::<()>(&mut connection).await?;
    Ok(())
}

/// A service that has a `publishLive` step does not start when the server is not named in production, or is not a Redis URL.
pub fn check_config() -> Result<()> {
    let url = url()?;
    if !(url.starts_with("redis://") || url.starts_with("rediss://") || url.starts_with("redis+unix://")) {
        anyhow::bail!("DRAGONFLY_URL must be a redis:// or rediss:// URL");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_message_is_the_one_the_real_time_service_reads() {
        let event = Event {
            kind: "contact.updated",
            tenant_id: Some("t".into()),
            permission: Some("contacts.view"),
            origin: Some("o".into()),
            data: vec![("id", "42".into())],
            ..Default::default()
        };
        assert_eq!(
            event.message(),
            json!({"type": "contact.updated", "tenantId": "t", "permission": "contacts.view", "origin": "o", "data": {"id": "42"}})
        );
    }

    #[test]
    fn what_is_not_set_is_left_out() {
        let event = Event { kind: "a.b", account_id: Some("a".into()), ..Default::default() };
        assert_eq!(event.message(), json!({"type": "a.b", "accountId": "a", "data": {}}));
    }

    #[test]
    fn an_event_the_service_would_refuse_is_not_kept() {
        let mut live = Live::default();
        live.push("c", Event { kind: "a.b", ..Default::default() });
        live.push("c", Event { kind: "a.b", account_id: Some("a".into()), data: vec![("k", "x".repeat(65))], ..Default::default() });
        live.push("c", Event { kind: "a.b", account_id: Some("a".into()), data: vec![("k", "line\nbreak".into())], ..Default::default() });
        assert!(live.pending.is_empty());
        live.push("c", Event { kind: "a.b", account_ids: vec!["a".into()], ..Default::default() });
        assert_eq!(live.pending.len(), 1);
    }
}
