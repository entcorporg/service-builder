//! What the expressions `shortId` and `fromShortId` call: a whole number as a short text for an address, and back.
//!
//! [Sqids](https://sqids.org): `UkLWZg` for 1, `pndklV` for 1000, at least six characters, letters and digits, the same text for
//! the same number every time. A person can read it out, and paste it in a message.
//!
//! **It is not a secret.** Sqids mixes the alphabet so that consecutive numbers do not look consecutive, which hides the order from
//! the eye, not from a person who wants to find it: with a few ids, anyone can work out the number of any other. It protects
//! nothing: the right to read what an id names has to be checked as for any other id, and a number that must not be guessed
//! (a token, a secret) must not be one.
//!
//! Only **the exact text a number makes** is read back: a text that decodes to a number but is not the one that number makes
//! (Sqids reads many texts as numbers) is nothing, so that two different addresses never name the same thing.
//!
//! Needs the cargo feature `short-id`; the generator turns it on for the services that use the expressions.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::sync::LazyLock;

use anyhow::{Result, anyhow};
use sqids::Sqids;

/// The shortest text: six characters, so that the first numbers do not give away how few there are.
const MIN_LENGTH: u8 = 6;

static SQIDS: LazyLock<Sqids> =
    LazyLock::new(|| Sqids::builder().min_length(MIN_LENGTH).build().expect("a valid Sqids configuration"));

/// The short text of `number` (zero or more).
pub fn encode(number: i64) -> Result<String> {
    let number = u64::try_from(number).map_err(|_| anyhow!("a short id is made from a number of zero or more, not {number}"))?;
    SQIDS.encode(&[number]).map_err(|e| anyhow!("cannot make a short id: {e}"))
}

/// The number `text` stands for: absent unless it is exactly what [`encode`] makes of one number.
pub fn decode(text: &str) -> Option<i64> {
    let numbers = SQIDS.decode(text);
    let [number] = numbers.as_slice() else {
        return None;
    };
    let number = i64::try_from(*number).ok()?;
    (encode(number).ok()? == text).then_some(number)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_number_is_a_short_text_of_six_characters_or_more_and_comes_back() {
        assert_eq!(encode(1).unwrap(), "UkLWZg");
        assert_eq!(encode(1_000).unwrap(), "pndklV");
        for n in [0, 1, 2, 9, 10, 99, 12_345, 123_456_789, i64::MAX] {
            let text = encode(n).unwrap();
            assert!(text.len() >= 6, "{text}");
            assert!(text.chars().all(|c| c.is_ascii_alphanumeric()), "{text}");
            assert_eq!(decode(&text), Some(n), "{n} -> {text}");
        }
        // The same number is the same text, and consecutive ones do not look consecutive.
        assert_eq!(encode(7).unwrap(), encode(7).unwrap());
        assert_ne!(encode(7).unwrap(), encode(8).unwrap());
    }

    #[test]
    fn a_negative_number_is_an_error_and_what_is_not_the_exact_text_is_nothing() {
        assert!(encode(-1).is_err());
        assert_eq!(decode(""), None);
        assert_eq!(decode("!!"), None);
        assert_eq!(decode("not a short id"), None);
        // Sqids reads this as a number, but it is not the text that number makes: two addresses must not name one thing.
        assert!(SQIDS.decode("zzzzzzzzzz").len() == 1);
        assert_eq!(decode("zzzzzzzzzz"), None);
        // A text of the right shape for a number that does not fit an int64.
        let huge = SQIDS.encode(&[u64::MAX]).unwrap();
        assert_eq!(decode(&huge), None);
        // The text of one number is not that of two.
        let two = SQIDS.encode(&[1, 2]).unwrap();
        assert_eq!(decode(&two), None);
    }
}
