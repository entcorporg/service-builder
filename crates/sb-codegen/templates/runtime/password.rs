//! What the `passwordStrength` step calls: a judgment on a password before it is hashed.
//!
//! * **How easy it is to guess** (zxcvbn): dictionaries and common passwords, names, keyboard walks, dates, repeats and
//!   sequences, l33t substitutions, and the `inputs` of the account (the e-mail address, the name: a password made of them is no
//!   better for being long). The score is 0 (too guessable) to 4 (very unguessable); under the minimum the route answers a 400
//!   that says why, in the words of the library. Only the first 100 characters are judged: the estimator is quadratic, and what
//!   comes after 100 characters does not change the verdict of a password that already has them.
//! * **Whether it is in a known breach**, when asked (Pwned Passwords, by range): the SHA-1 of the password is computed here,
//!   only its first five hexadecimal characters leave the process, the server answers every suffix that starts the same
//!   (padded, so that the size says nothing), and the comparison is made here. The password, nor its hash, is never sent. The
//!   address of the API is `PWNED_PASSWORDS_URL` (`https://api.pwnedpasswords.com` by default: a mirror can be named).
//!   The check **lets the password through** when the API does not answer within three seconds or answers something else than
//!   a list, and says so in the log: signing people up must not depend on another service being up.
//!
//! The estimator runs on the blocking pool, like the hash of a password: it can take a few tens of milliseconds, the first time
//! more (its dictionaries are built then).
//!
//! Needs the cargo feature `password-strength`; the generator turns it on for the services that use it.
//!
//! @generated by service-builder. Do not edit: changes are overwritten on the next export.

use std::time::Duration;

use anyhow::Result;
use sha1::{Digest, Sha1};

use crate::http::HttpError;

/// How much of a password is judged.
const JUDGED_CHARS: usize = 100;
/// The code of a refusal on length when the step names none.
const DEFAULT_LENGTH_CODE: &str = "MOT_DE_PASSE_INVALIDE";
const DEFAULT_RANGE_API: &str = "https://api.pwnedpasswords.com";
const RANGE_TIMEOUT: Duration = Duration::from_secs(3);

/// The score of `password` (0 to 4) and, under 3, the reason in the library's words.
pub struct Judgment {
    pub score: u8,
    pub reason: Option<String>,
}

/// Judges the password. `inputs` are the texts of the account it must not be made of.
pub fn judge(password: &str, inputs: &[&str]) -> Judgment {
    let judged: String = password.chars().take(JUDGED_CHARS).collect();
    // The estimator finds a text of the account only as a whole word: an address is no use as it is, its parts are (the name
    // before the `@`, the words of the domain). So each text counts, and so does each word of three characters or more in it.
    let mut words: Vec<&str> = vec![];
    for input in inputs.iter().copied().filter(|i| !i.is_empty()) {
        words.push(input);
        words.extend(
            input
                .split(|c: char| !c.is_alphanumeric())
                .filter(|w| w.chars().count() >= 3),
        );
    }
    let entropy = zxcvbn::zxcvbn(&judged, &words);
    let score = u8::from(entropy.score());
    let reason = entropy.feedback().and_then(|f| {
        f.warning()
            .map(|w| w.to_string())
            .or_else(|| f.suggestions().first().map(|s| s.to_string()))
    });
    Judgment { score, reason }
}

/// The step. `Ok(score)` when the password is at least `min_score` (and, with `breached`, not in a known breach); otherwise a
/// 400 that tells the visitor what to change. The password is not kept, logged or sent anywhere but as the five characters
/// described at the top of this file.
pub async fn check(
    password: &str,
    inputs: &[&str],
    min_score: u8,
    breached: bool,
    lengths: (Option<u32>, Option<u32>),
    code: Option<&str>,
) -> Result<u8> {
    // The length is counted in characters, as typed (no trim), and comes first: a refusal that costs nothing.
    let chars = password.chars().count();
    let (min_length, max_length) = lengths;
    let refuse = |message: String, default_code: Option<&str>| -> anyhow::Error {
        let error = HttpError::new(400, message);
        match code.or(default_code) {
            Some(code) => error.with_code(code).into(),
            None => error.into(),
        }
    };
    if let Some(min) = min_length.filter(|min| chars < *min as usize) {
        return Err(refuse(
            format!("password: at least {min} characters"),
            Some(DEFAULT_LENGTH_CODE),
        ));
    }
    if let Some(max) = max_length.filter(|max| chars > *max as usize) {
        return Err(refuse(
            format!("password: at most {max} characters"),
            Some(DEFAULT_LENGTH_CODE),
        ));
    }
    let (password_owned, inputs_owned): (String, Vec<String>) =
        (password.to_owned(), inputs.iter().map(|i| (*i).to_owned()).collect());
    let judgment = tokio::task::spawn_blocking(move || {
        let refs: Vec<&str> = inputs_owned.iter().map(String::as_str).collect();
        judge(&password_owned, &refs)
    })
    .await?;
    if judgment.score < min_score {
        let message = match judgment.reason {
            Some(reason) => format!("password: too easy to guess ({reason})"),
            None => "password: too easy to guess".to_string(),
        };
        return Err(refuse(message, None));
    }
    if breached {
        let base = std::env::var("PWNED_PASSWORDS_URL").unwrap_or_else(|_| DEFAULT_RANGE_API.to_string());
        match breach_count(base.trim_end_matches('/'), password).await {
            Ok(0) => {}
            Ok(_) => {
                return Err(refuse(
                    "password: found in a known data breach, choose another one".to_string(),
                    None,
                ));
            }
            Err(error) => tracing::warn!(%error, "breached passwords: the range API did not answer, the password is let through"),
        }
    }
    Ok(judgment.score)
}

/// The SHA-1 of the password in upper-case hexadecimal, split into what is sent (five characters) and what stays.
fn split_hash(password: &str) -> (String, String) {
    let hash = hex::encode_upper(Sha1::digest(password.as_bytes()));
    (hash[..5].to_string(), hash[5..].to_string())
}

/// How many times the password is in a known breach, by range: `0` when it is not.
async fn breach_count(base: &str, password: &str) -> Result<u64> {
    let (prefix, suffix) = split_hash(password);
    let client = reqwest::Client::builder()
        .timeout(RANGE_TIMEOUT)
        // The padding hides how many suffixes there are; no redirect moves the question to another host.
        .redirect(reqwest::redirect::Policy::none())
        .build()?;
    let answer = client
        .get(format!("{base}/range/{prefix}"))
        .header("Add-Padding", "true")
        .send()
        .await?;
    if !answer.status().is_success() {
        anyhow::bail!("the range API answered {}", answer.status());
    }
    // A list of a few hundred lines: nothing like the limit of an outbound call, but not unbounded either.
    let body = answer.bytes().await?;
    if body.len() > 1024 * 1024 {
        anyhow::bail!("the range API answered more than 1 MiB");
    }
    Ok(count_in(&String::from_utf8_lossy(&body), &suffix))
}

/// The count that goes with `suffix` in a list of `SUFFIX:COUNT` lines. A padding line has a count of 0.
fn count_in(list: &str, suffix: &str) -> u64 {
    list.lines()
        .filter_map(|line| line.trim().split_once(':'))
        .find(|(candidate, _)| candidate.eq_ignore_ascii_case(suffix))
        .and_then(|(_, count)| count.trim().parse().ok())
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_known_hash_is_split_after_five_characters() {
        // The example of the Pwned Passwords documentation: SHA-1("password") = 5BAA6 1E4C9B93F3F0682250B6CF8331B7EE68FD8.
        assert_eq!(
            split_hash("password"),
            ("5BAA6".to_string(), "1E4C9B93F3F0682250B6CF8331B7EE68FD8".to_string())
        );
    }

    #[test]
    fn a_list_is_read_by_suffix_and_padding_counts_for_nothing() {
        let list = "0018A45C4D1DEF81644B54AB7F969B88D65:1\r\n00D4F6E8FA6EECAD2A3AA415EEC418D38EC:2\r\n1E4C9B93F3F0682250B6CF8331B7EE68FD8:9545824\r\n011053FD0102E94D6AE2F8B83D76FAF94F6:0\r\n";
        assert_eq!(count_in(list, "1E4C9B93F3F0682250B6CF8331B7EE68FD8"), 9_545_824);
        assert_eq!(count_in(list, "1e4c9b93f3f0682250b6cf8331b7ee68fd8"), 9_545_824);
        assert_eq!(count_in(list, "011053FD0102E94D6AE2F8B83D76FAF94F6"), 0, "padding");
        assert_eq!(count_in(list, "FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF"), 0);
        assert_eq!(count_in("", "ABC"), 0);
        assert_eq!(count_in("garbage without a colon", "ABC"), 0);
    }

    #[test]
    fn the_score_goes_with_how_guessable_the_password_is() {
        assert!(judge("password", &[]).score <= 1);
        assert!(judge("123456789", &[]).score <= 1);
        assert!(judge("azertyuiop", &[]).score <= 1);
        assert!(judge("correct horse battery staple wonderful", &[]).score >= 3);
        let strong = judge("q7#Vf!z9Lm2@xT4w", &[]);
        assert_eq!(strong.score, 4);
        assert!(strong.reason.is_none());
    }

    #[test]
    fn the_texts_of_the_account_make_a_password_worse() {
        // The name and the surname of the address, run together: a dictionary has neither, the account has both.
        let alone = judge("jeannedurand", &[]);
        let with = judge("jeannedurand", &["jeanne.durand@example.com"]);
        assert!(with.score <= alone.score);
        assert!(with.score <= 1, "{} (alone: {})", with.score, alone.score);
        // The same with the name given whole.
        assert!(judge("jeannedurand", &["Jeanne", "Durand"]).score <= 1);
        // Empty inputs are left out, not read as "the empty string is in the password".
        assert_eq!(judge("q7#Vf!z9Lm2@xT4w", &[""]).score, 4);
        assert_eq!(judge("q7#Vf!z9Lm2@xT4w", &["a@b.c"]).score, 4, "words of under three characters are left out");
    }

    #[test]
    fn a_long_password_is_judged_on_its_first_characters_only() {
        let long = "q7#Vf!z9Lm2@xT4w".repeat(400);
        let started = std::time::Instant::now();
        assert_eq!(judge(&long, &[]).score, 4);
        assert!(started.elapsed() < Duration::from_secs(5), "{:?}", started.elapsed());
    }

    fn refused(error: anyhow::Error) -> (u16, String) {
        let http = error.downcast_ref::<HttpError>().expect("an HTTP error");
        (http.status, http.message.clone())
    }

    #[tokio::test]
    async fn a_weak_password_is_a_400_that_says_why_and_a_good_one_has_its_score_back() {
        let (status, message) = refused(check("password", &[], 3, false, (None, None), None).await.unwrap_err());
        assert_eq!(status, 400);
        assert!(message.starts_with("password: too easy to guess"), "{message}");
        assert_eq!(check("q7#Vf!z9Lm2@xT4w", &[], 3, false, (None, None), None).await.unwrap(), 4);
        // The minimum is the service's: a score of 1 is enough for a minimum of 1, and not for 4.
        assert!(check("password1", &[], 0, false, (None, None), None).await.is_ok());
    }

    #[tokio::test]
    async fn the_length_is_refused_first_with_a_stable_code() {
        let strong = "q7#Vf!z9Lm2@xT4w";
        let bounds = (Some(20), Some(24));
        let code = |e: anyhow::Error| e.downcast_ref::<HttpError>().unwrap().code.clone();
        let short = check(strong, &[], 3, false, bounds, None).await.unwrap_err();
        assert_eq!(refused_status(&short), 400);
        assert_eq!(code(short), Some("MOT_DE_PASSE_INVALIDE".to_string()));
        let long = check(&"a".repeat(25), &[], 0, false, bounds, Some("TROP_LONG")).await.unwrap_err();
        assert_eq!(code(long), Some("TROP_LONG".to_string()));
        // Characters, not bytes: 20 accents are 20.
        assert!(check(&"é".repeat(20), &[], 0, false, bounds, None).await.is_ok());
        // A weakness refusal carries a code only when the step names one.
        let weak = check("password", &[], 3, false, (None, None), None).await.unwrap_err();
        assert_eq!(code(weak), None);
        let weak = check("password", &[], 3, false, (None, None), Some("FAIBLE")).await.unwrap_err();
        assert_eq!(code(weak), Some("FAIBLE".to_string()));
    }

    fn refused_status(error: &anyhow::Error) -> u16 {
        error.downcast_ref::<HttpError>().expect("an HTTP error").status
    }

    /// A server that answers one request with the given body, on a local port. Returns its address.
    async fn range_api(status: &'static str, body: &'static str) -> String {
        use tokio::io::{AsyncReadExt, AsyncWriteExt};
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = format!("http://{}", listener.local_addr().unwrap());
        tokio::spawn(async move {
            // Two questions at most: the test asks once, or twice.
            for _ in 0..2 {
                let Ok((mut socket, _)) = listener.accept().await else { return };
                let mut request = vec![0u8; 4096];
                let read = socket.read(&mut request).await.unwrap_or(0);
                let request = String::from_utf8_lossy(&request[..read]).to_string();
                // The question carries the five characters, never more, and asks for padding.
                assert!(request.starts_with("GET /range/5BAA6 "), "{request}");
                assert!(request.to_ascii_lowercase().contains("add-padding: true"), "{request}");
                let answer = format!(
                    "HTTP/1.1 {status}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}",
                    body.len()
                );
                let _ = socket.write_all(answer.as_bytes()).await;
            }
        });
        address
    }

    #[tokio::test]
    async fn a_breached_password_is_found_by_its_range_and_the_password_never_leaves() {
        let api = range_api("200 OK", "0018A45C4D1DEF81644B54AB7F969B88D65:1\r\n1E4C9B93F3F0682250B6CF8331B7EE68FD8:9545824\r\n").await;
        assert_eq!(breach_count(&api, "password").await.unwrap(), 9_545_824);
    }

    #[tokio::test]
    async fn a_password_that_is_not_in_the_list_is_not_breached_and_an_unwell_api_is_an_error() {
        let api = range_api("200 OK", "0018A45C4D1DEF81644B54AB7F969B88D65:1\r\n").await;
        assert_eq!(breach_count(&api, "password").await.unwrap(), 0);
        let down = range_api("503 Service Unavailable", "").await;
        assert!(breach_count(&down, "password").await.is_err());
        // Nothing listens: an error too (the step lets the password through, and logs it).
        assert!(breach_count("http://127.0.0.1:1", "password").await.is_err());
    }
}
