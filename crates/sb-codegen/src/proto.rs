//! `.proto` generation.

use sb_model::names::snake;
use sb_model::{FieldType, MessageKind, Project};

use crate::writer::Code;

pub fn package_name(project: &Project) -> String {
    snake(&project.name)
}

pub fn proto_file_name(project: &Project) -> String {
    format!("{}.proto", package_name(project))
}

fn proto_type(ty: &FieldType) -> String {
    match ty {
        FieldType::String => "string".into(),
        FieldType::Bool => "bool".into(),
        FieldType::Int32 => "int32".into(),
        FieldType::Int64 => "int64".into(),
        FieldType::Float => "float".into(),
        FieldType::Double => "double".into(),
        FieldType::Bytes => "bytes".into(),
        FieldType::Timestamp => "google.protobuf.Timestamp".into(),
        FieldType::Message { name } => name.clone(),
    }
}

pub fn generate(project: &Project) -> String {
    let mut c = Code::new();
    c.line("// @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line("syntax = \"proto3\";");
    c.blank();
    c.line(format!("package {};", package_name(project)));
    let uses_timestamp = project
        .messages
        .iter()
        .flat_map(|m| &m.fields)
        .any(|f| f.ty == FieldType::Timestamp);
    if uses_timestamp {
        c.blank();
        c.line("import \"google/protobuf/timestamp.proto\";");
    }

    let sections = [
        (MessageKind::Proto, "gRPC schemas and shared types"),
        (MessageKind::Event, "Events (Kafka payloads)"),
        (
            MessageKind::Api,
            "HTTP API schemas (also read and written as JSON)",
        ),
    ];
    for (kind, title) in sections {
        let mut messages = project
            .messages
            .iter()
            .filter(|m| m.kind == kind)
            .peekable();
        if messages.peek().is_none() {
            continue;
        }
        c.blank();
        c.line(format!("// ---- {title} ----"));
        for m in messages {
            c.blank();
            c.open(format!("message {}", m.name));
            for (f, n) in m.fields.iter().zip(m.field_numbers()) {
                let label = if f.repeated {
                    "repeated "
                } else if f.optional && !f.ty.is_message() {
                    "optional "
                } else {
                    ""
                };
                c.line(format!("{label}{} {} = {n};", proto_type(&f.ty), f.name));
            }
            c.close();
        }
    }

    for s in project.services.iter().filter(|s| !s.rpcs.is_empty()) {
        c.blank();
        c.line("// ---- gRPC services ----");
        c.blank();
        c.open(format!("service {}", s.name));
        for r in &s.rpcs {
            c.line(format!(
                "rpc {}({}) returns ({});",
                r.name, r.request, r.response
            ));
        }
        c.close();
    }
    c.finish()
}

#[cfg(test)]
mod tests {
    use super::*;
    use sb_model::{Field, Message, sample};

    #[test]
    fn sample_proto() {
        let proto = generate(&sample::orders());
        assert!(proto.contains("package orders_demo;"));
        assert!(proto.contains("message CreateOrderRequest {\n    Customer customer = 1;\n    int64 amount = 2;\n    repeated string items = 3;\n}"));
        assert!(proto.contains("optional string note = 3;"));
        assert!(proto.contains("service Orders {\n    rpc CreateOrder(CreateOrderRequest) returns (CreateOrderResponse);"));
        // Services without RPC are not emitted.
        assert!(!proto.contains("service Payments"));
        assert!(!proto.contains("timestamp.proto"));
    }

    #[test]
    fn api_schemas_get_their_own_section() {
        let proto = generate(&sb_model::sample::orders());
        assert!(proto.contains("// ---- HTTP API schemas (also read and written as JSON) ----"));
        assert!(
            proto.contains(
                "message OrderView {\n    string order_id = 1;\n    string status = 2;\n}"
            )
        );
        // Proto schemas first, then events, then the HTTP API.
        let at = |needle: &str| proto.find(needle).unwrap();
        assert!(at("message CreateOrderRequest") < at("message OrderCreated"));
        assert!(at("message OrderCreated") < at("message OrderView"));
        assert!(proto.contains("// ---- Events (Kafka payloads) ----"));
    }

    #[test]
    fn explicit_tags_are_kept_and_never_reused() {
        let mut m = Message {
            kind: Default::default(),
            name: "M".into(),
            fields: vec![
                Field::new("a", FieldType::String),
                Field::new("b", FieldType::String),
                Field::new("c", FieldType::Timestamp),
            ],
        };
        m.fields[0].tag = Some(2);
        m.fields[2].tag = Some(7);
        assert_eq!(m.field_numbers(), vec![2, 1, 7]);

        let mut p = Project::new("p");
        p.messages.push(m);
        assert!(generate(&p).contains("import \"google/protobuf/timestamp.proto\";"));
    }
}
