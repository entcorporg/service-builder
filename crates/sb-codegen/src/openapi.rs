//! The OpenAPI 3.1 document of the HTTP routes of a service: what a front-end developer (or a client generator) reads
//! instead of the project. It is derived from the same model as the handlers, so the two cannot drift apart: the
//! parameters are the path, the query string, the headers and the cookies the handler reads; the schemas are the API
//! schemas, with the rules of their fields as constraints; the statuses are the success status and the ones a flow can
//! answer with (`fail`, a rate limit, a signature...).

use std::collections::BTreeMap;

use sb_model::names::route_params;
use sb_model::{Field, FieldType, Project, RequestSource, Route, Rule, Service, Step};
use serde_json::{Map, Value, json};

/// The document of a service, or `None` when it has no route.
pub fn openapi(project: &Project, service: &Service) -> Option<Value> {
    if service.routes.is_empty() {
        return None;
    }
    let mut schemas = Schemas::default();
    let error_name = schemas.error_name(project);
    let mut paths: Map<String, Value> = Map::new();
    for route in &service.routes {
        let operation = operation(project, service, route, &error_name, &mut schemas);
        let item = paths
            .entry(route.path.clone())
            .or_insert_with(|| Value::Object(Map::new()));
        item[route.method.as_str().to_lowercase()] = operation;
    }
    let mut components = Map::new();
    let mut all = schemas.used(project);
    all.insert(
        error_name,
        json!({
            "type": "object",
            "description": "Every error is answered as `{ \"error\": \"...\" }`.",
            "properties": { "error": { "type": "string" } },
            "required": ["error"],
        }),
    );
    components.insert("schemas".into(), Value::Object(all.into_iter().collect()));
    let mut doc = json!({
        "openapi": "3.1.0",
        "info": {
            "title": format!("{} - {}", project.name, service.name),
            "version": "1.0.0",
            "description": format!(
                "HTTP API of the `{}` service, generated by Service Builder. JSON, with the field names of the schemas.",
                service.name
            ),
        },
        "paths": paths,
        "components": components,
    });
    if let Some(port) = service.http_port {
        doc["servers"] =
            json!([{ "url": format!("http://localhost:{port}"), "description": "Local" }]);
    }
    Some(doc)
}

/// The document as the file written with the export.
pub fn openapi_json(project: &Project, service: &Service) -> Option<String> {
    openapi(project, service)
        .map(|doc| serde_json::to_string_pretty(&doc).expect("a document is JSON") + "\n")
}

/// The schemas the operations refer to, collected as they are met.
#[derive(Default)]
struct Schemas {
    names: Vec<String>,
}

impl Schemas {
    /// A name for the error schema that no message of the project already has.
    fn error_name(&self, project: &Project) -> String {
        let mut name = "ErrorBody".to_string();
        while project.message(&name).is_some() {
            name.push('_');
        }
        name
    }

    fn reference(&mut self, message: &str) -> Value {
        if !self.names.iter().any(|n| n == message) {
            self.names.push(message.to_string());
        }
        json!({ "$ref": format!("#/components/schemas/{message}") })
    }

    /// The schema of every message met, and the ones nested in them.
    fn used(&mut self, project: &Project) -> BTreeMap<String, Value> {
        let mut out = BTreeMap::new();
        let mut i = 0;
        while i < self.names.len() {
            let name = self.names[i].clone();
            i += 1;
            if let Some(m) = project.message(&name) {
                let fields: Vec<&Field> = m.fields.iter().collect();
                out.insert(name, self.object(&fields));
            }
        }
        out
    }

    /// An object schema of fields. A field is required when a client has to send it.
    fn object(&mut self, fields: &[&Field]) -> Value {
        let mut properties = Map::new();
        let mut required = vec![];
        for f in fields {
            properties.insert(f.name.clone(), self.field(f));
            if !f.optional && !f.lenient {
                required.push(Value::String(f.name.clone()));
            }
        }
        let mut object = json!({ "type": "object", "properties": properties });
        if !required.is_empty() {
            object["required"] = Value::Array(required);
        }
        object
    }

    /// The schema of one field: its type, the rules as constraints, a list, and `null` when it may be left out.
    fn field(&mut self, f: &Field) -> Value {
        let mut item = self.scalar(&f.ty);
        for rule in &f.rules {
            match rule {
                Rule::Length { min, max } => {
                    item["minLength"] = json!(min);
                    item["maxLength"] = json!(max);
                    item["description"] = "Length in characters, once trimmed.".into();
                }
                Rule::Email => {
                    item["format"] = "email".into();
                }
                Rule::Siren => {
                    item["pattern"] = "^[0-9]{9}$".into();
                    item["description"] =
                        "A French company number: 9 digits with a valid Luhn check digit.".into();
                }
            }
        }
        let mut schema = if f.repeated {
            json!({ "type": "array", "items": item })
        } else {
            item
        };
        if f.optional {
            schema = nullable(schema);
        }
        schema
    }

    fn scalar(&mut self, ty: &FieldType) -> Value {
        match ty {
            FieldType::String => json!({ "type": "string" }),
            FieldType::Uuid => json!({ "type": "string", "format": "uuid" }),
            FieldType::Bool => json!({ "type": "boolean" }),
            FieldType::Int32 => json!({ "type": "integer", "format": "int32" }),
            FieldType::Int64 => json!({ "type": "integer", "format": "int64" }),
            FieldType::Float => json!({ "type": "number", "format": "float" }),
            FieldType::Double => json!({ "type": "number", "format": "double" }),
            FieldType::Bytes => json!({ "type": "string", "contentEncoding": "base64" }),
            FieldType::Timestamp => json!({ "type": "string", "format": "date-time" }),
            FieldType::Message { name } => self.reference(name),
        }
    }
}

/// `null` is also accepted (OpenAPI 3.1 is plain JSON Schema: no `nullable` keyword).
fn nullable(schema: Value) -> Value {
    match schema
        .get("type")
        .and_then(Value::as_str)
        .map(str::to_owned)
    {
        Some(ty) if schema.get("$ref").is_none() => {
            let mut schema = schema;
            schema["type"] = json!([ty, "null"]);
            schema
        }
        _ => json!({ "anyOf": [schema, { "type": "null" }] }),
    }
}

/// What a step can make a route answer with, besides the success: status and what it means.
fn step_statuses(route: &Route) -> Vec<(u16, String, bool)> {
    let mut out: Vec<(u16, String, bool)> = vec![];
    for step in &route.steps {
        step.walk(&mut |s| {
            let found: Option<(u16, String, bool)> = match s {
                Step::Fail {
                    status,
                    message,
                    retry_after,
                    ..
                } => Some((*status, message.clone(), retry_after.is_some())),
                Step::RateLimit { .. } => Some((429, "Too many attempts".into(), true)),
                Step::VerifyHmac { .. } => {
                    Some((401, "The signature is missing or wrong".into(), false))
                }
                Step::VerifyJwt { .. } => Some((
                    401,
                    "The token is missing, invalid or expired".into(),
                    false,
                )),
                Step::TotpVerify { .. } => Some((401, "The code is wrong".into(), false)),
                Step::HashPassword { .. } => Some((400, "The password is too long".into(), false)),
                Step::PasskeyLoginStart { .. } | Step::PasskeyLoginFinish { .. } => {
                    Some((401, "The passkey is refused".into(), false))
                }
                Step::PasskeyRegisterStart { .. } | Step::PasskeyRegisterFinish { .. } => {
                    Some((400, "The passkey is refused".into(), false))
                }
                // An outbound call that fails ends the route with its own status; one that goes on answers nothing.
                Step::HttpCall {
                    on_error: sb_model::HttpOnError::Fail,
                    error_status,
                    error_message,
                    ..
                } => Some(if *error_status >= 500 {
                    (
                        *error_status,
                        "The call to another service failed".into(),
                        false,
                    )
                } else {
                    (*error_status, error_message.clone(), false)
                }),
                Step::Sql {
                    op: sb_model::SqlOp::Select,
                    many: false,
                    bind: Some(_),
                    missing,
                    ..
                } => Some(match missing {
                    Some(m) => (m.status, m.message.clone(), false),
                    None => (404, "No row matches".into(), false),
                }),
                _ => None,
            };
            if let Some((status, message, retry)) = found {
                match out.iter_mut().find(|(st, _, _)| *st == status) {
                    Some((_, text, r)) => {
                        if !text.split("; ").any(|t| t == message) {
                            text.push_str("; ");
                            text.push_str(&message);
                        }
                        *r |= retry;
                    }
                    None => out.push((status, message, retry)),
                }
            }
        });
    }
    out.sort_by_key(|(status, _, _)| *status);
    out
}

fn operation(
    project: &Project,
    service: &Service,
    route: &Route,
    error: &str,
    schemas: &mut Schemas,
) -> Value {
    let params = route_params(&route.path).unwrap_or_default();
    let request = project.message(&route.request);
    let mut parameters = vec![];
    let mut body_fields: Vec<&Field> = vec![];
    for f in request.iter().flat_map(|m| &m.fields) {
        let (place, name) = if params.contains(&f.name) {
            ("path", f.name.clone())
        } else {
            match &f.source {
                Some(RequestSource::Header { name }) => ("header", name.clone()),
                Some(RequestSource::Cookie { name }) => ("cookie", name.clone()),
                None if route.method.has_body() => {
                    body_fields.push(f);
                    continue;
                }
                None => ("query", f.name.clone()),
            }
        };
        let mut schema = schemas.field(f);
        // The place of a parameter says whether it is optional: `null` has no form there.
        if f.optional {
            schema = schemas.scalar(&f.ty);
        }
        let mut parameter = json!({
            "name": name,
            "in": place,
            "required": place == "path" || (!f.optional && !f.lenient),
            "schema": schema,
        });
        if place == "header" || place == "cookie" {
            parameter["description"] =
                format!("Fills the field `{}` of the request.", f.name).into();
        }
        parameters.push(parameter);
    }

    let mut op = Map::new();
    op.insert("operationId".into(), route.name.clone().into());
    op.insert(
        "summary".into(),
        format!("{} {}", route.method.as_str(), route.path).into(),
    );
    let mut notes = vec![];
    if let Some(Step::VerifyHmac { header, .. }) = route.steps.first() {
        notes.push(format!(
            "The body is authenticated by the signature in the `{header}` header (HMAC-SHA256 of `timestamp.body`, `t=<seconds>,v1=<hex>`)."
        ));
        parameters.push(json!({
            "name": header, "in": "header", "required": true,
            "description": "The signature of the raw body.",
            "schema": { "type": "string" },
        }));
    }
    if !notes.is_empty() {
        op.insert("description".into(), notes.join(" ").into());
    }
    if !parameters.is_empty() {
        op.insert("parameters".into(), Value::Array(parameters));
    }
    if route.method.has_body() {
        let body = schemas.object(&body_fields);
        let required = body.get("required").is_some();
        op.insert(
            "requestBody".into(),
            json!({
                "required": required,
                "content": { "application/json": { "schema": body } },
            }),
        );
    }

    // Success: the status of the route, and the ones a `respond` step picks instead.
    let mut statuses = vec![route.status];
    let mut headers: BTreeMap<String, Value> = BTreeMap::new();
    for step in &route.steps {
        step.walk(&mut |s| {
            if let Step::Respond {
                status,
                cookies,
                headers: hs,
                ..
            } = s
            {
                if let Some(status) = status
                    && !statuses.contains(status)
                {
                    statuses.push(*status);
                }
                if !cookies.is_empty() {
                    let names: Vec<String> = cookies.iter().map(|c| format!("`{}`", c.name)).collect();
                    headers.insert(
                        "Set-Cookie".into(),
                        json!({
                            "description": format!("Sets the cookie(s) {}.", names.join(", ")),
                            "schema": { "type": "string" },
                        }),
                    );
                }
                for h in hs {
                    headers.insert(
                        h.name.clone(),
                        json!({ "description": "Set by the flow.", "schema": { "type": "string" } }),
                    );
                }
            }
        });
    }
    statuses.sort();
    let mut responses = Map::new();
    for status in statuses {
        let mut response = json!({
            "description": "Success",
            "content": { "application/json": { "schema": schemas.reference(&route.response) } },
        });
        if !headers.is_empty() {
            response["headers"] = Value::Object(headers.clone().into_iter().collect());
        }
        responses.insert(status.to_string(), response);
    }

    // Errors: the ones every route can answer, then the ones its steps choose.
    let error_body = json!({ "application/json": { "schema": { "$ref": format!("#/components/schemas/{error}") } } });
    let mut errors: Vec<(u16, String, bool)> = vec![(
        400,
        "The request is refused: a required field is missing, a rule fails, or a value has the wrong type".into(),
        false,
    )];
    if route.method.has_body() {
        errors.push((
            422,
            "The JSON body cannot be read as the schema".into(),
            false,
        ));
    }
    for (status, text, retry) in step_statuses(route) {
        match errors.iter_mut().find(|(s, _, _)| *s == status) {
            Some((_, t, r)) => {
                t.push_str("; ");
                t.push_str(&text);
                *r |= retry;
            }
            None => errors.push((status, text, retry)),
        }
    }
    errors.push((
        500,
        "Internal error (the details are in the logs)".into(),
        false,
    ));
    errors.sort_by_key(|(s, _, _)| *s);
    for (status, text, retry) in errors {
        let mut response = json!({ "description": text, "content": error_body });
        if retry {
            response["headers"] = json!({
                "Retry-After": {
                    "description": "Seconds to wait before trying again.",
                    "schema": { "type": "integer" },
                }
            });
        }
        // A step may answer a status that is also a success of the route: the success text stays.
        responses.entry(status.to_string()).or_insert(response);
    }
    op.insert("responses".into(), Value::Object(responses));
    op.insert("tags".into(), json!([service.name]));
    Value::Object(op)
}

#[cfg(test)]
mod tests {
    use super::*;
    use sb_model::sample;

    fn orders_doc() -> Value {
        let p = sample::showcase();
        openapi(&p, &p.services[0]).expect("the first service has routes")
    }

    #[test]
    fn a_service_without_routes_has_no_document() {
        let p = sample::showcase();
        let silent = p.services.iter().find(|s| s.routes.is_empty()).unwrap();
        assert!(openapi(&p, silent).is_none());
    }

    #[test]
    fn paths_methods_and_parameters_follow_the_routes() {
        let doc = orders_doc();
        assert_eq!(doc["openapi"], "3.1.0");
        let get = &doc["paths"]["/orders/{order_id}"]["get"];
        assert_eq!(get["operationId"], "get_order");
        assert_eq!(get["parameters"][0]["in"], "path");
        assert_eq!(get["parameters"][0]["required"], true);
        assert!(get.get("requestBody").is_none());
        let post = &doc["paths"]["/orders"]["post"];
        assert!(
            post["requestBody"]["content"]["application/json"]["schema"]["properties"]["amount"]
                .is_object()
        );
        // A path parameter is not repeated in the body.
        let put = &doc["paths"]["/orders/{order_id}/receipt"]["put"];
        let body = &put["requestBody"]["content"]["application/json"]["schema"];
        assert!(body["properties"].get("order_id").is_none());
        assert_eq!(body["required"], json!(["issued_at", "stamp"]));
    }

    #[test]
    fn headers_and_cookies_sources_become_parameters() {
        let doc = orders_doc();
        let found = doc["paths"]
            .as_object()
            .unwrap()
            .values()
            .flat_map(|item| item.as_object().unwrap().values())
            .flat_map(|op| op["parameters"].as_array().into_iter().flatten())
            .any(|p| p["in"] == "header" || p["in"] == "cookie");
        assert!(found, "the showcase reads a header or a cookie somewhere");
    }

    #[test]
    fn bytes_timestamps_and_rules_have_their_json_form() {
        let doc = orders_doc();
        let receipt = &doc["paths"]["/orders/{order_id}/receipt"]["put"]["requestBody"]["content"]
            ["application/json"]["schema"]["properties"];
        assert_eq!(receipt["issued_at"]["format"], "date-time");
        assert_eq!(receipt["stamp"]["contentEncoding"], "base64");
        assert_eq!(receipt["note"]["maxLength"], 200);
        let signup = &doc["paths"]["/signup"]["post"]["requestBody"]["content"]["application/json"]
            ["schema"]["properties"];
        assert_eq!(signup["email"]["format"], "email");
        assert_eq!(signup["email"]["type"], "string");
    }

    #[test]
    fn statuses_come_from_the_flow() {
        let doc = orders_doc();
        let responses = &doc["paths"]["/orders"]["post"]["responses"];
        // The route's success, its `fail` (400, shared with the invalid requests), its rate limit.
        assert!(responses["201"]["headers"]["Set-Cookie"].is_object());
        assert!(
            responses["400"]["description"]
                .as_str()
                .unwrap()
                .contains("the amount must be positive")
        );
        assert!(responses["429"]["headers"]["Retry-After"].is_object());
        assert!(responses["500"].is_object());
        let receipt = &doc["paths"]["/orders/{order_id}/receipt"]["put"]["responses"]["200"];
        assert!(receipt["headers"]["Cache-Control"].is_object());
        assert!(receipt["headers"]["X-Order-Id"].is_object());
        assert_eq!(
            doc["paths"]["/orders/{order_id}"]["get"]["responses"]["404"]["description"],
            "No row matches"
        );
    }

    #[test]
    fn the_routes_of_sql_logic_and_http_calls_are_described() {
        let doc = orders_doc();
        // An outbound call that fails ends the route with its own status.
        let intent = &doc["paths"]["/payments/intents"]["post"]["responses"];
        assert!(intent["502"].is_object(), "{intent}");
        // A paged read: its inputs are query parameters, its answer a list with the page cursor.
        let posts = &doc["paths"]["/tenant/posts"]["get"];
        let names: Vec<&str> = posts["parameters"]
            .as_array()
            .unwrap()
            .iter()
            .map(|p| p["name"].as_str().unwrap())
            .collect();
        for wanted in ["search", "page_size", "after_title", "after_id"] {
            assert!(names.contains(&wanted), "{wanted} in {names:?}");
        }
        let page = &doc["components"]["schemas"]["PostsPage"]["properties"];
        assert_eq!(page["items"]["type"], "array");
        assert_eq!(page["total"]["type"], "integer");
        // A route that loops over a list: the list is an array of the line schema.
        let lines = &doc["paths"]["/orders/{order_id}/lines"]["post"];
        let body = &lines["requestBody"]["content"]["application/json"]["schema"];
        assert_eq!(body["properties"]["lines"]["type"], "array");
        // `fail` inside the loop is a status of the route.
        assert!(lines["responses"]["400"].is_object());
        // `lenient` fields are left out of `required`.
        let required = body["required"].as_array().cloned().unwrap_or_default();
        assert!(!required.contains(&json!("lines")));
    }

    #[test]
    fn every_reference_resolves() {
        let p = sample::showcase();
        for s in p.services.iter().filter(|s| !s.routes.is_empty()) {
            let doc = openapi(&p, s).unwrap();
            let text = doc.to_string();
            for part in text.split("\"$ref\":\"#/components/schemas/").skip(1) {
                let name = part.split('"').next().unwrap();
                assert!(
                    doc["components"]["schemas"][name].is_object(),
                    "{name} is not defined"
                );
            }
        }
    }
}
