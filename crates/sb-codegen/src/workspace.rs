/// Compiles the proto with `protox` (pure Rust), so no `protoc` is needed on the machine.
/// API schemas also derive serde: they travel as JSON on the HTTP routes.
fn contracts_build(project: &Project, proto_name: &str) -> String {
    let package = proto::package_name(project);
    let mut c = Code::new();
    c.line("// @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.open("fn main() -> Result<(), Box<dyn std::error::Error>>");
    c.line(format!(
        "let descriptors = protox::compile([\"{proto_name}\"], [\"proto\"])?;"
    ));
    let api: Vec<_> = project
        .messages
        .iter()
        .filter(|m| m.kind == MessageKind::Api)
        .collect();
    if api.is_empty() {
        c.line("tonic_prost_build::configure().compile_fds(descriptors)?;");
    } else {
        c.line("let mut builder = tonic_prost_build::configure();");
        c.line("// Missing JSON fields take their default, like protobuf fields do.");
        let names: Vec<String> = api.iter().map(|m| format!("{:?}", m.name)).collect();
        c.open(format!("for message in [{}]", names.join(", ")));
        c.line(format!("let path = format!(\".{package}.{{message}}\");"));
        c.line("builder = builder");
        c.line("    .type_attribute(&path, \"#[derive(serde::Serialize, serde::Deserialize)]\")");
        c.line("    .type_attribute(&path, \"#[serde(default)]\");");
        c.close();
        c.line("builder.compile_fds(descriptors)?;");
    }
    c.line("println!(\"cargo:rerun-if-changed=proto\");");
    c.line("Ok(())");
    c.close();
    c.finish()
}

fn contracts_lib(project: &Project) -> String {
    let mut c = Code::new();
    c.line("// @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line("//! Messages and gRPC stubs generated from the project schemas, plus topic names.");
    c.blank();
    c.open("pub mod pb");
    c.line(format!(
        "tonic::include_proto!(\"{}\");",
        proto::package_name(project)
    ));
    c.close();
    c.blank();
    c.line("/// Kafka topic names.");
    c.open("pub mod topics");
    for t in &project.topics {
        let producers = if t.producers.is_empty() {
            String::new()
        } else {
            format!(" Produced by {}.", t.producers.join(", "))
        };
        c.line(format!(
            "/// Carries `pb::{}`.{producers}\npub const {}: &str = {:?};",
            t.message,
            topic_const(&t.name),
            t.name
        ));
        c.line(format!(
            "/// Where records of `{}` that could not be handled or published are parked.\npub const {}_DLQ: &str = \"{}.dlq\";",
            t.name,
            topic_const(&t.name),
            t.name
        ));
    }
    c.close();
    c.finish()
}

