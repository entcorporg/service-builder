fn readme(project: &Project) -> String {
    let mut s = format!(
        "# {}\n\nGenerated by Service Builder. Event-driven Rust services: gRPC for RPC, Kafka for events.\n\n\
         ## Run\n\n```sh\ndocker compose up -d      # Kafka on localhost:9092, PostgreSQL on localhost:5432\n",
        project.name
    );
    for svc in &project.services {
        s.push_str(&format!("cargo run -p {}\n", service::crate_name(svc)));
    }
    s.push_str(
        "```\n\nEach service runs in its own terminal. Topics are created on startup.\n\n\
         Build requirements: a C/C++ toolchain, `cmake`, `pkg-config` and OpenSSL headers \
         (Debian/Ubuntu: `sudo apt install build-essential cmake pkg-config libssl-dev`). \
         `protoc` is not needed.\n\n",
    );
    s.push_str("## Services\n\n");
    for svc in &project.services {
        s.push_str(&service_doc(project, svc));
    }
    s.push_str(
        "\n## Notes\n\n\
         - Events are protobuf messages (see `contracts/proto`). Field numbers are stable across regenerations.\n\
         - Consumers are at-least-once: a record that keeps failing is parked on `<topic>.dlq`. Make handlers idempotent.\n\
         - Every service owns a PostgreSQL database (created on start-up). A flow runs in one transaction, `tx`: the events it \
         publishes are written to the service's `outbox` table in that transaction, then relayed to Kafka (woken by `LISTEN/NOTIFY`). \
         An event that still cannot be published after `OUTBOX_MAX_ATTEMPTS` attempts is parked on `<topic>.dlq` and kept in the table \
         with `dead_at` set. Delivery is at-least-once.\n\
         - In a *Code Rust* step use `tx` for your own queries, and call `tx.commit().await?` before an early `return`: \
         otherwise the transaction, and the events queued in it, are rolled back.\n\
         - HTTP routes (for the front) speak JSON with the field names of the API schema. `{param}` of the path fills the field of the same \
         name; the other fields come from the JSON body (POST, PUT, PATCH) or the query string (GET, DELETE). Errors are `{ \"error\": \"...\" }`: \
         a flow picks the status with `return Err(eda_runtime::http::HttpError::not_found(\"...\").into());`, any other error is a 500 \
         whose details only go to the logs. Browsers may call the API from the origins of `CORS_ORIGINS` (`*` by default, set it in production).\n\
         - Environment: `KAFKA_BROKERS`, `<SERVICE>_PORT` (gRPC), `<SERVICE>_HTTP_PORT`, `CORS_ORIGINS`, `<SERVICE>_URL` (address used to call \
         another service), `<SERVICE>_DATABASE_URL`, `OUTBOX_MAX_ATTEMPTS`.\n\
         - Everything here is regenerated on export: edit the project in Service Builder, not these files.\n",
    );
    s
}

fn service_doc(project: &Project, svc: &Service) -> String {
    let mut s = format!("### {} (gRPC port {})\n\n", svc.name, svc.port);
    if let Some(port) = svc.http_port.filter(|_| !svc.routes.is_empty()) {
        s.push_str(&format!("HTTP API on port {port}:\n\n"));
    }
    for r in &svc.routes {
        s.push_str(&format!(
            "- `{} {}` -> `{}` ({}, {})\n",
            r.method.as_str(),
            r.path,
            r.name,
            r.request,
            r.response
        ));
    }
    for r in &svc.rpcs {
        s.push_str(&format!(
            "- RPC `{}({}) -> {}`\n",
            r.name, r.request, r.response
        ));
    }
    for c in &svc.consumers {
        s.push_str(&format!("- consumes `{}` with `{}`\n", c.topic, c.name));
    }
    for t in project
        .topics
        .iter()
        .filter(|t| t.producers.contains(&svc.name))
    {
        s.push_str(&format!("- produces `{}`\n", t.name));
    }
    s.push('\n');
    s
}
