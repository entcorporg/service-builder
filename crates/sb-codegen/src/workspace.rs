/// Compiles the proto with `protox` (pure Rust), so no `protoc` is needed on the machine.
fn contracts_build(proto_name: &str) -> String {
    format!(
        r#"// @generated by service-builder. Do not edit: changes are overwritten on export.
fn main() -> Result<(), Box<dyn std::error::Error>> {{
    let descriptors = protox::compile(["{proto_name}"], ["proto"])?;
    tonic_prost_build::configure().compile_fds(descriptors)?;
    println!("cargo:rerun-if-changed=proto");
    Ok(())
}}
"#
    )
}

fn contracts_lib(project: &Project) -> String {
    let mut c = Code::new();
    c.line("// @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line("//! Messages and gRPC stubs generated from the project schemas, plus topic names.");
    c.blank();
    c.open("pub mod pb");
    c.line(format!(
        "tonic::include_proto!(\"{}\");",
        proto::package_name(project)
    ));
    c.close();
    c.blank();
    c.line("/// Kafka topic names.");
    c.open("pub mod topics");
    for t in &project.topics {
        c.line(format!(
            "/// Carries `pb::{}`.\npub const {}: &str = {:?};",
            t.message,
            topic_const(&t.name),
            t.name
        ));
    }
    c.close();
    c.finish()
}

