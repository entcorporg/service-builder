//! Files shared by every service of the generated workspace.

use sb_model::names::topic_const;
use sb_model::{Project, Service};

use crate::GeneratedFile;
use crate::proto;
use crate::service;
use crate::writer::Code;

const RUNTIME_LIB: &str = include_str!("../templates/runtime/lib.rs");
const RUNTIME_CARGO: &str = include_str!("../templates/runtime/Cargo.toml");

pub fn files(project: &Project) -> Vec<GeneratedFile> {
    let proto_name = proto::proto_file_name(project);
    vec![
        GeneratedFile::new("Cargo.toml", root_cargo(project)),
        GeneratedFile::new(".gitignore", "/target\n"),
        GeneratedFile::new("README.md", readme(project)),
        GeneratedFile::new("docker-compose.yml", docker_compose()),
        GeneratedFile::new("contracts/Cargo.toml", CONTRACTS_CARGO),
        GeneratedFile::new("contracts/build.rs", contracts_build(&proto_name)),
        GeneratedFile::new("contracts/src/lib.rs", contracts_lib(project)),
        GeneratedFile::new(
            format!("contracts/proto/{proto_name}"),
            proto::generate(project),
        ),
        GeneratedFile::new("runtime/Cargo.toml", RUNTIME_CARGO),
        GeneratedFile::new("runtime/src/lib.rs", RUNTIME_LIB),
    ]
}

fn root_cargo(project: &Project) -> String {
    let mut members = vec!["\"contracts\"".to_string(), "\"runtime\"".to_string()];
    members.extend(
        project
            .services
            .iter()
            .map(|s| format!("\"{}\"", service::dir(s))),
    );
    format!(
        r#"# @generated by service-builder. Do not edit: changes are overwritten on export.
[workspace]
resolver = "3"
members = [{}]

[workspace.package]
version = "0.1.0"
edition = "2024"

[workspace.dependencies]
anyhow = "1"
prost = "0.14"
prost-types = "0.14"
protox = "0.10"
# `curl` works around librdkafka 2.12 including <curl/curl.h> even when curl is disabled.
rdkafka = {{ version = "0.39", features = ["cmake-build", "tokio", "curl"] }}
tokio = {{ version = "1", features = ["macros", "rt-multi-thread", "signal", "time"] }}
tonic = "0.14"
tonic-prost = "0.14"
tonic-prost-build = "0.14"
tracing = "0.1"
tracing-subscriber = {{ version = "0.3", features = ["env-filter"] }}
uuid = {{ version = "1", features = ["v4"] }}
"#,
        members.join(", ")
    )
}

