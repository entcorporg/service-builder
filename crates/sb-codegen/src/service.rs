fn rules_fn(message: &str) -> String {
    format!("check_{}", snake(message))
}

/// One function per schema the routes of the service receive and that has rules, its own or inside it.
fn rules_rs(c: &mut Code, project: &Project, service: &Service) {
    let received: BTreeSet<&str> = service
        .routes
        .iter()
        .flat_map(|r| {
            // The request, and the schemas nested in it.
            let mut names = vec![r.request.as_str()];
            let mut i = 0;
            while i < names.len() {
                if let Some(m) = project.message(names[i]) {
                    for f in &m.fields {
                        if let FieldType::Message { name } = &f.ty
                            && !names.contains(&name.as_str())
                        {
                            names.push(name);
                        }
                    }
                }
                i += 1;
            }
            names
        })
        .filter(|n| project.has_rules(n))
        .collect();
    if received.is_empty() {
        return;
    }
    c.blank();
    c.open("fn invalid(message: String) -> ApiError");
    c.line("ApiError::new(StatusCode::BAD_REQUEST, message)");
    c.close();
    for name in received {
        let Some(m) = project.message(name) else {
            continue;
        };
        c.blank();
        c.line(format!(
            "/// The rules of `{name}`: the first that fails is a 400."
        ));
        c.open(format!(
            "fn {}(m: &pb::{name}) -> Result<(), String>",
            rules_fn(name)
        ));
        for f in &m.fields {
            let field = &f.name;
            if let FieldType::Message { name: inner } = &f.ty {
                if project.has_rules(inner) {
                    let check = rules_fn(inner);
                    // The path of the field travels with the message: `company.name`, `contacts[2].email`.
                    if f.repeated {
                        c.line(format!(
                            "for (i, item) in m.{field}.iter().enumerate() {{ {check}(item).map_err(|e| format!(\"{field}[{{i}}].{{e}}\"))?; }}"
                        ));
                    } else {
                        c.line(format!(
                            "if let Some(item) = &m.{field} {{ {check}(item).map_err(|e| format!(\"{field}.{{e}}\"))?; }}"
                        ));
                    }
                }
                continue;
            }
            if f.rules.is_empty() {
                continue;
            }
            let calls: Vec<String> = f
                .rules
                .iter()
                .map(|rule| {
                    let call = match rule {
                        Rule::Length { min, max } => {
                            format!("eda_runtime::validation::length({field:?}, v, {min}, {max})")
                        }
                        Rule::Email => format!("eda_runtime::validation::email({field:?}, v)"),
                        Rule::Siren => format!("eda_runtime::validation::siren({field:?}, v)"),
                    };
                    format!("{call}?;")
                })
                .collect();
            let body = calls.join(" ");
            if f.repeated {
                c.line(format!("for v in &m.{field} {{ {body} }}"));
            } else if f.optional {
                c.line(format!("if let Some(v) = &m.{field} {{ {body} }}"));
            } else {
                c.line(format!("{{ let v = &m.{field}; {body} }}"));
            }
        }
        c.line("Ok(())");
        c.close();
    }
}

/// The signature check of a route, if it has one: the header, the environment variable of the secret, the tolerance.
fn hmac_of(route: &sb_model::Route) -> Option<(&str, &str, u32)> {
    match route.steps.first() {
        Some(Step::VerifyHmac {
            header,
            secret_env,
            tolerance_secs,
            ..
        }) => Some((header, secret_env, *tolerance_secs)),
        _ => None,
    }
}

/// A claim as a JSON value: a path keeps its type (a list stays a list, an absent optional is `null`), a literal is
/// its JSON, and raw Rust is anything that serializes.
fn claim_json(project: &Project, scope: &Scope, value: &Expr) -> Result<String, CodegenError> {
    Ok(match value {
        Expr::Path { path } => {
            let rp = sb_model::typing::resolve_path(project, scope, path)
                .map_err(CodegenError::Internal)?;
            format!("eda_runtime::jwt::json!({})", crate::expr::path_code(&rp))
        }
        Expr::Literal { value } => format!("eda_runtime::jwt::json!({value})"),
        Expr::Raw { code } => format!("eda_runtime::jwt::json!({})", code.trim()),
        Expr::Now => {
            return Err(CodegenError::Internal(
                "`now()` only exists in an SQL step".into(),
            ));
        }
    })
}

/// The seeds and the JWKS URLs the JWT steps of a service read from the environment, once each.
fn jwt_settings(service: &Service) -> (BTreeSet<&str>, BTreeSet<&str>) {
    let (mut seeds, mut urls) = (BTreeSet::new(), BTreeSet::new());
    for step in service.handler_steps() {
        step.walk(&mut |s| match s {
            Step::SignJwt { key_env, .. } => {
                seeds.insert(key_env.as_str());
            }
            Step::Jwks { key_envs, .. } => seeds.extend(key_envs.iter().map(String::as_str)),
            Step::VerifyJwt { source, .. } => match source {
                sb_model::JwksSource::Keys { key_envs } => {
                    seeds.extend(key_envs.iter().map(String::as_str))
                }
                sb_model::JwksSource::Url { url_env } => {
                    urls.insert(url_env.as_str());
                }
            },
            _ => {}
        });
    }
    (seeds, urls)
}

/// The environment variables of the encryption keys a service uses, once each.
fn encryption_keys(service: &Service) -> BTreeSet<&str> {
    let mut keys = BTreeSet::new();
    for step in service.handler_steps() {
        step.walk(&mut |s| {
            if let Step::Encrypt { key_env, .. } | Step::Decrypt { key_env, .. } = s {
                keys.insert(key_env.as_str());
            }
        });
    }
    keys
}

/// The environment variables of the secrets of the signed webhooks of a service, once each.
fn webhook_secrets(service: &Service) -> BTreeSet<&str> {
    service
        .routes
        .iter()
        .filter_map(hmac_of)
        .map(|(_, env, _)| env)
        .collect()
}

/// Whether a route answers with a status or cookies of its own: its flow then returns a `Reply`.
fn needs_reply(route: &sb_model::Route) -> bool {
    let mut extras = false;
    for step in &route.steps {
        step.walk(&mut |s| {
            extras |= matches!(s, Step::Respond { status, cookies, .. } if status.is_some() || !cookies.is_empty())
        });
    }
    extras
}

fn api_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c =
        flows_header("One function per HTTP route, built from the steps drawn in the editor.");
    for r in &service.routes {
        c.blank();
        c.line(format!("/// `{} {}`", r.method.as_str(), r.path));
        let reply = needs_reply(r);
        let returns = if reply {
            format!("eda_runtime::http::Reply<pb::{}>", r.response)
        } else {
            format!("pb::{}", r.response)
        };
        c.open(format!(
            "pub async fn {}(ctx: &Ctx, input: pb::{}) -> anyhow::Result<{returns}>",
            r.name, r.request
        ));
        begin(&mut c);
        let mut scope = Scope::with_input(&r.request);
        steps(
            &mut c,
            project,
            service,
            &mut scope,
            &r.steps,
            Some(&r.response),
            reply,
        )?;
        c.line("tx.commit().await?;");
        c.line(if reply {
            format!(
                "Ok(eda_runtime::http::Reply::new(pb::{}::default()))",
                r.response
            )
        } else {
            format!("Ok(pb::{}::default())", r.response)
        });
        c.close();
    }
    Ok(c.finish())
}

fn consumer_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c =
        flows_header("One function per consumer, built from the steps drawn in the editor.");
    for cons in &service.consumers {
        let topic = project
            .topic(&cons.topic)
            .ok_or_else(|| CodegenError::Internal(format!("unknown topic `{}`", cons.topic)))?;
        c.blank();
        c.line(format!(
            "/// Consumes `{}` ({}).",
            topic.name, topic.message
        ));
        c.open(format!(
            "pub async fn {}(ctx: &Ctx, input: pb::{}) -> anyhow::Result<()>",
            cons.name, topic.message
        ));
        begin(&mut c);
        if let Some(field) = &cons.idempotent_on {
            // Recorded in this transaction: a handling that fails leaves no trace, and the retry does the work.
            c.open(format!(
                "if !eda_runtime::dedup::first_time(&mut tx, {:?}, &input.{field}.to_string()).await?",
                cons.name
            ));
            c.line(format!(
                "tracing::info!(consumer = {:?}, event = %input.{field}, \"duplicate event skipped\");",
                cons.name
            ));
            c.line("tx.commit().await?;");
            c.line("return Ok(());");
            c.close();
        }
        let mut scope = Scope::with_input(&topic.message);
        steps(
            &mut c,
            project,
            service,
            &mut scope,
            &cons.steps,
            None,
            false,
        )?;
        c.line("tx.commit().await?;");
        c.line("Ok(())");
        c.close();
    }
    Ok(c.finish())
}

fn job_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c = flows_header("One function per job, built from the steps drawn in the editor.");
    for job in &service.jobs {
        c.blank();
        c.line(format!("/// Every {} s.", job.every_secs));
        c.open(format!(
            "pub async fn {}(ctx: &Ctx) -> anyhow::Result<()>",
            job.name
        ));
        begin(&mut c);
        // No request, no event: there is no `input`.
        let mut scope = Scope::default();
        steps(
            &mut c, project, service, &mut scope, &job.steps, None, false,
        )?;
        c.line("tx.commit().await?;");
        c.line("Ok(())");
        c.close();
    }
    Ok(c.finish())
}

/// Starts every job of the service on its schedule, and stops them when the service ends.
fn scheduler_rs(service: &Service) -> String {
    let mut c = Code::new();
    c.line(HEADER);
    c.line("//! Runs the jobs of this service on their schedule (see `eda_runtime::jobs`).");
    c.blank();
    c.line("use std::time::Duration;");
    c.blank();
    c.line("use tokio::{sync::watch, task::JoinHandle};");
    c.blank();
    c.line("use crate::{app::ctx::Ctx, flows};");
    c.blank();
    c.line("/// The running jobs. Every instance of the service runs them: their steps must be safe to repeat.");
    c.open("pub struct Scheduler");
    c.line("stop: watch::Sender<bool>,");
    c.line("handles: Vec<JoinHandle<()>>,");
    c.close();
    c.blank();
    c.open("impl Scheduler");
    c.open("pub fn spawn(ctx: &Ctx) -> Self");
    c.line("let (stop, shutdown) = watch::channel(false);");
    c.line("let mut handles = Vec::new();");
    for job in &service.jobs {
        c.line(format!(
            "// `{}` every {} s -> flows::jobs::{}",
            job.name, job.every_secs, job.name
        ));
        c.block();
        c.line("let ctx = ctx.clone();");
        c.line(format!(
            "handles.push(eda_runtime::jobs::spawn_periodic({:?}, Duration::from_secs({}), shutdown.clone(), move || {{",
            job.name, job.every_secs
        ));
        c.line("    let ctx = ctx.clone();");
        c.line(format!(
            "    async move {{ flows::jobs::{}(&ctx).await }}",
            job.name
        ));
        c.line("}));");
        c.close();
    }
    c.line("Self { stop, handles }");
    c.close();
    c.blank();
    c.line("/// Asks the jobs to stop and waits for the runs in progress to finish.");
    c.open("pub async fn stop(self)");
    c.line("let _ = self.stop.send(true);");
    c.open("for handle in self.handles");
    c.line("let _ = handle.await;");
    c.close();
    c.close();
    c.close();
    c.finish()
}

fn steps(
    c: &mut Code,
    project: &Project,
    service: &Service,
    scope: &mut Scope,
    list: &[Step],
    response: Option<&str>,
    reply: bool,
) -> Result<(), CodegenError> {
    for step in list {
        c.line(format!("// {}", describe(step)));
        match step {
            Step::Log { level, message, .. } => {
                c.line(log_code(project, scope, *level, message)?);
            }
            Step::Let {
                name,
                value_type,
                optional,
                repeated,
                value,
                ..
            } => {
                let ty = TypeRef {
                    ty: value_type.clone(),
                    repeated: *repeated,
                    optional: *optional && !*repeated,
                };
                let value = lower(project, scope, value, &ty)?;
                c.line(format!(
                    "let {name}: {} = {value};",
                    rust_let_type(value_type, ty.optional, ty.repeated)
                ));
                scope.bind(name.clone(), ty);
            }
            Step::Publish { topic, payload, .. } => {
                let t = project
                    .topic(topic)
                    .ok_or_else(|| CodegenError::Internal(format!("unknown topic `{topic}`")))?;
                let literal = struct_literal(project, scope, &t.message, payload)?;
                c.block();
                c.line(format!("let event = {literal};"));
                let key = match &t.key_field {
                    Some(key) => {
                        c.line(format!("let key = event.{key}.to_string();"));
                        "Some(&key)"
                    }
                    None => "None",
                };
                c.line(format!(
                    "eda_runtime::outbox::enqueue(&mut tx, topics::{}, {key}, &event).await?;",
                    topic_const(topic)
                ));
                c.close();
            }
            Step::CallRpc {
                service,
                method,
                request,
                bind,
                ..
            } => {
                let target = project.service(service).ok_or_else(|| {
                    CodegenError::Internal(format!("unknown service `{service}`"))
                })?;
                let rpc = target
                    .rpc(method)
                    .ok_or_else(|| CodegenError::Internal(format!("unknown RPC `{method}`")))?;
                let literal = struct_literal(project, scope, &rpc.request, request)?;
                let call = format!(
                    "ctx.{}.clone().{}({literal}).await?.into_inner()",
                    snake(service),
                    snake(method)
                );
                match bind {
                    Some(var) => {
                        c.line(format!("let {var} = {call};"));
                        scope.bind(var.clone(), TypeRef::message(&rpc.response));
                    }
                    None => {
                        c.line(format!("let _ = {call};"));
                    }
                }
            }
            Step::Branch {
                condition,
                then,
                otherwise,
                ..
            } => {
                c.open(format!("if {}", condition_code(project, scope, condition)?));
                steps(
                    c,
                    project,
                    service,
                    &mut scope.clone(),
                    then,
                    response,
                    reply,
                )?;
                if !otherwise.is_empty() {
                    c.close_open("else");
                    steps(
                        c,
                        project,
                        service,
                        &mut scope.clone(),
                        otherwise,
                        response,
                        reply,
                    )?;
                }
                c.close();
            }
            Step::Respond {
                fields,
                status,
                cookies,
                ..
            } => {
                let response = response.ok_or_else(|| {
                    CodegenError::Internal("Respond used outside of an RPC handler".into())
                })?;
                let literal = struct_literal(project, scope, response, fields)?;
                c.line(format!("let reply = {literal};"));
                c.line("tx.commit().await?;");
                if reply {
                    let mut out = "eda_runtime::http::Reply::new(reply)".to_string();
                    if let Some(status) = status {
                        out.push_str(&format!(".status({status})"));
                    }
                    for cookie in cookies {
                        out.push_str(&format!(
                            ".cookie({})",
                            cookie_code(project, scope, cookie)?
                        ));
                    }
                    c.line(format!("return Ok({out});"));
                } else {
                    c.line("return Ok(reply);");
                }
            }
            // Checked by the HTTP handler on the raw body, before it is read as JSON (`transport/http.rs`).
            Step::VerifyHmac { header, .. } => {
                c.line(format!("// signature in `{header}` already verified"));
            }
            Step::RateLimit {
                id,
                key,
                max,
                window_secs,
                ..
            } => {
                let key = lower(project, scope, key, &TypeRef::scalar(FieldType::String))?;
                c.line(format!(
                    "eda_runtime::rate_limit::check({id:?}, &({key}), {max}, {window_secs})?;"
                ));
            }
            Step::Sql { .. } => sql_step(c, project, service, scope, step)?,
            Step::HashPassword { input, bind, .. } => {
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::hash_password({input}).await?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::VerifyPassword {
                password,
                stored,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let maybe = TypeRef {
                    optional: true,
                    ..text.clone()
                };
                let password = lower(project, scope, password, &text)?;
                let stored = lower(project, scope, stored, &maybe)?;
                c.line(format!(
                    "let {bind}: bool = eda_runtime::crypto::verify_password({password}, {stored}).await;"
                ));
                scope.bind(bind.clone(), TypeRef::scalar(FieldType::Bool));
            }
            Step::Encrypt {
                key_env,
                input,
                bind,
                ..
            }
            | Step::Decrypt {
                key_env,
                input,
                bind,
                ..
            } => {
                let function = if matches!(step, Step::Encrypt { .. }) {
                    "encrypt"
                } else {
                    "decrypt"
                };
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::{function}({key_env:?}, &{input})?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::SignJwt {
                key_env,
                issuer,
                ttl_secs,
                claims,
                bind,
                ..
            } => {
                c.open(format!("let {bind}: String ="));
                c.line("let mut claims = eda_runtime::jwt::Map::new();");
                for claim in claims {
                    let value = claim_json(project, scope, &claim.value)?;
                    c.line(format!(
                        "claims.insert({:?}.to_string(), {value});",
                        claim.field
                    ));
                }
                c.line(format!(
                    "eda_runtime::jwt::sign({key_env:?}, {issuer:?}, {ttl_secs}, claims)?"
                ));
                c.close_with(";");
                scope.bind(bind.clone(), TypeRef::scalar(FieldType::String));
            }
            Step::VerifyJwt {
                token,
                bearer,
                source,
                issuer,
                schema,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let token = lower(project, scope, token, &text)?;
                let source = match source {
                    sb_model::JwksSource::Keys { key_envs } => {
                        let list: Vec<String> = key_envs.iter().map(|k| format!("{k:?}")).collect();
                        format!("eda_runtime::jwt::Source::Keys(&[{}])", list.join(", "))
                    }
                    sb_model::JwksSource::Url { url_env } => {
                        format!("eda_runtime::jwt::Source::Url({url_env:?})")
                    }
                };
                c.open(format!("let {bind}: pb::{schema} ="));
                c.line(format!("let token = {token};"));
                if *bearer {
                    c.line("let token = eda_runtime::jwt::bearer(&token);");
                }
                c.line(format!(
                    "eda_runtime::jwt::claims_into(eda_runtime::jwt::verify({source}, {issuer:?}, {}).await?)?",
                    if *bearer { "token" } else { "&token" }
                ));
                c.close_with(";");
                scope.bind(bind.clone(), TypeRef::message(schema));
            }
            Step::Jwks { key_envs, bind, .. } => {
                let list: Vec<String> = key_envs.iter().map(|k| format!("{k:?}")).collect();
                c.line(format!("let {bind} = pb::Jwks {{"));
                c.line(format!(
                    "    keys: eda_runtime::jwt::public_keys(&[{}])?",
                    list.join(", ")
                ));
                c.line("        .into_iter()");
                c.line("        .map(|k| pb::Jwk { kty: k.kty, crv: k.crv, alg: k.alg, kid: k.kid, x: k.x, ..Default::default() })");
                c.line("        .collect(),");
                c.line("    ..Default::default()");
                c.line("};");
                scope.bind(bind.clone(), TypeRef::message("Jwks"));
            }
            Step::RandomToken { bind, .. } => {
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::random_token();"
                ));
                scope.bind(bind.clone(), TypeRef::scalar(FieldType::String));
            }
            Step::Sha256 { input, bind, .. } => {
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::sha256_hex(&{input});"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::Fail {
                status,
                message,
                retry_after,
                ..
            } => {
                // The transaction is dropped with the early return: nothing the flow wrote is kept.
                c.line(format!(
                    "let error = eda_runtime::http::HttpError::new({status}, {message:?});"
                ));
                if let Some(wait) = retry_after {
                    let seconds = lower(project, scope, wait, &TypeRef::scalar(FieldType::Int64))?;
                    c.line(format!(
                        "let error = error.with_retry_after(u64::try_from({seconds}).unwrap_or(0));"
                    ));
                }
                c.line("return Err(error.into());");
            }
            Step::Code { code, .. } => {
                c.line(code.trim_end());
            }
        }
    }
    Ok(())
}

/// `Cookie::new(name, value)` with the attributes that differ from the safe defaults.
fn cookie_code(
    project: &Project,
    scope: &Scope,
    cookie: &sb_model::Cookie,
) -> Result<String, CodegenError> {
    let value = lower(
        project,
        scope,
        &cookie.value,
        &TypeRef::scalar(FieldType::String),
    )?;
    let mut out = format!("eda_runtime::http::Cookie::new({:?}, {value})", cookie.name);
    if let Some(seconds) = cookie.max_age_secs {
        out.push_str(&format!(".max_age({seconds})"));
    }
    if let Some(path) = &cookie.path {
        out.push_str(&format!(".path({path:?})"));
    }
    if !cookie.http_only {
        out.push_str(".http_only(false)");
    }
    if !cookie.secure {
        out.push_str(".secure(false)");
    }
    match cookie.same_site {
        sb_model::SameSite::Lax => {}
        sb_model::SameSite::Strict => {
            out.push_str(".same_site(eda_runtime::http::SameSite::Strict)")
        }
        sb_model::SameSite::None => out.push_str(".same_site(eda_runtime::http::SameSite::None)"),
    }
    Ok(out)
}

// ---- SQL step --------------------------------------------------------------------------

fn quoted(ident: &str) -> String {
    format!("\"{ident}\"")
}

/// Rust type of a column value, as read by `Row::try_get`.
fn column_rust(col: &Column) -> String {
    let base = match col.ty.field_type() {
        FieldType::Bool => "bool",
        FieldType::Int32 => "i32",
        FieldType::Int64 => "i64",
        FieldType::Float => "f32",
        FieldType::Double => "f64",
        _ => "String",
    };
    if col.nullable {
        format!("Option<{base}>")
    } else {
        base.to_string()
    }
}

/// What a flow sees for a column (nullable columns are optional).
fn column_type_ref(col: &Column) -> TypeRef {
    let mut t = TypeRef::scalar(col.ty.field_type());
    t.optional = col.nullable;
    t
}

/// The placeholder of the n-th parameter, cast back to the database type of a text-cast column.
fn placeholder(n: usize, col: &Column) -> String {
    if col.ty.is_text_cast() {
        format!("${n}::{}", col.ty.sql().to_lowercase())
    } else {
        format!("${n}")
    }
}

fn sql_step(
    c: &mut Code,
    project: &Project,
    service: &Service,
    scope: &mut Scope,
    step: &Step,
) -> Result<(), CodegenError> {
    let Step::Sql {
        id,
        op,
        table,
        bind,
        columns,
        many,
        into,
        conditions,
        values,
        order_by,
        descending,
        limit,
        missing,
    } = step
    else {
        return Ok(());
    };
    let t = service
        .table(table)
        .ok_or_else(|| CodegenError::Internal(format!("unknown table `{table}`")))?;
    let col = |name: &str| {
        t.column(name).ok_or_else(|| {
            CodegenError::Internal(format!("table `{table}` has no column `{name}`"))
        })
    };

    // Parameters, in the order of the placeholders: the values written, then the WHERE. The database clock
    // (`now()`) is part of the statement itself and takes no parameter.
    let mut binds: Vec<String> = Vec::new();
    let mut set_sql = Vec::new();
    for a in values {
        let column = col(&a.field)?;
        if matches!(a.value, Expr::Now) {
            set_sql.push((quoted(&column.name), "now()".to_string()));
            continue;
        }
        binds.push(lower(project, scope, &a.value, &column_type_ref(column))?);
        set_sql.push((quoted(&column.name), placeholder(binds.len(), column)));
    }
    let mut where_sql = Vec::new();
    for cond in conditions {
        let column = col(&cond.column)?;
        let right = if matches!(cond.value, Expr::Now) {
            "now()".to_string()
        } else {
            binds.push(lower(
                project,
                scope,
                &cond.value,
                &column_type_ref(column),
            )?);
            placeholder(binds.len(), column)
        };
        where_sql.push(format!(
            "{} {} {right}",
            quoted(&column.name),
            cond.sql_op()
        ));
    }
    let where_clause = if where_sql.is_empty() {
        String::new()
    } else {
        format!(" WHERE {}", where_sql.join(" AND "))
    };

    let query = |sql: &str| -> String {
        let mut q = format!("sqlx::query({sql:?})");
        for b in &binds {
            q.push_str(&format!(".bind({b})"));
        }
        q
    };

    // The columns a select reads, or that an insert, update or delete gives back (`RETURNING`).
    let selected: Vec<&Column> = columns.iter().map(|n| col(n)).collect::<Result<_, _>>()?;
    let exprs: Vec<String> = selected
        .iter()
        .map(|cl| {
            let name = quoted(&cl.name);
            match cl.ty {
                // ISO 8601 / RFC 3339, in UTC, whatever the session time zone.
                ColumnType::Timestamp => format!(
                    "to_char({name} AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') AS {name}"
                ),
                ColumnType::Uuid | ColumnType::Jsonb => format!("{name}::text AS {name}"),
                _ => name,
            }
        })
        .collect();

    let mut sql = match op {
        SqlOp::Insert => {
            let names: Vec<_> = set_sql.iter().map(|(n, _)| n.as_str()).collect();
            let params: Vec<_> = set_sql.iter().map(|(_, p)| p.as_str()).collect();
            format!(
                "INSERT INTO {} ({}) VALUES ({})",
                quoted(table),
                names.join(", "),
                params.join(", ")
            )
        }
        SqlOp::Update => {
            let sets: Vec<_> = set_sql.iter().map(|(n, p)| format!("{n} = {p}")).collect();
            format!(
                "UPDATE {} SET {}{where_clause}",
                quoted(table),
                sets.join(", ")
            )
        }
        SqlOp::Delete => format!("DELETE FROM {}{where_clause}", quoted(table)),
        SqlOp::Select => {
            let mut sql = format!(
                "SELECT {} FROM {}{where_clause}",
                exprs.join(", "),
                quoted(table)
            );
            if let Some(o) = order_by {
                sql.push_str(&format!(
                    " ORDER BY {}{}",
                    quoted(&col(o)?.name),
                    if *descending { " DESC" } else { "" }
                ));
            }
            match (many, limit) {
                (true, Some(n)) => sql.push_str(&format!(" LIMIT {n}")),
                (false, _) => sql.push_str(" LIMIT 1"),
                _ => {}
            }
            sql
        }
    };

    // Nothing to read back: run it.
    if *op != SqlOp::Select && columns.is_empty() {
        c.line(format!("{}.execute(&mut *tx).await?;", query(&sql)));
        return Ok(());
    }
    if *op != SqlOp::Select {
        sql.push_str(&format!(" RETURNING {}", exprs.join(", ")));
    }
    let var = bind.as_deref().ok_or_else(|| {
        CodegenError::Internal("a SQL step that reads rows needs a variable".into())
    })?;
    // What the route answers when one row was expected and none came back.
    let missing_error = match missing {
        Some(m) => format!(
            "eda_runtime::http::HttpError::new({}, {:?})",
            m.status, m.message
        ),
        None => format!("eda_runtime::http::HttpError::not_found(\"{table}: no row matches\")"),
    };
    let fill = |target: &str, fields: Vec<&str>| {
        let mut lit = format!("{target} {{\n");
        for f in fields {
            lit.push_str(&format!("    {f}: row.try_get({f:?})?,\n"));
        }
        lit
    };
    match (into, many) {
        (Some(schema), true) => {
            let ty = format!("pb::{schema}");
            let msg = project
                .message(schema)
                .ok_or_else(|| CodegenError::Internal(format!("unknown message `{schema}`")))?;
            let lit = fill(&ty, msg.fields.iter().map(|f| f.name.as_str()).collect());
            c.line(format!("let {var}: Vec<{ty}> = {}", query(&sql)));
            c.line("    .fetch_all(&mut *tx)");
            c.line("    .await?");
            c.line("    .iter()");
            c.line(format!("    .map(|row| -> anyhow::Result<{ty}> {{"));
            c.line(format!(
                "        Ok({lit}        ..Default::default()\n    }})"
            ));
            c.line("    })");
            c.line("    .collect::<anyhow::Result<Vec<_>>>()?;");
            scope.bind(
                var,
                TypeRef {
                    repeated: true,
                    ..TypeRef::message(schema)
                },
            );
        }
        (_, true) => {
            return Err(CodegenError::Internal(
                "a list of rows needs a schema to convert them into".into(),
            ));
        }
        (found, false) => {
            let (ty, lit, bound) = match found {
                Some(schema) => {
                    let msg = project.message(schema).ok_or_else(|| {
                        CodegenError::Internal(format!("unknown message `{schema}`"))
                    })?;
                    let ty = format!("pb::{schema}");
                    let lit = fill(&ty, msg.fields.iter().map(|f| f.name.as_str()).collect());
                    (
                        ty,
                        format!("{lit}    ..Default::default()\n}}"),
                        TypeRef::message(schema),
                    )
                }
                None => {
                    let name = sql_row_name(table, id);
                    let lit = fill(&name, selected.iter().map(|cl| cl.name.as_str()).collect());
                    (
                        name,
                        format!("{lit}}}"),
                        TypeRef::message(sql_row_name(table, id)),
                    )
                }
            };
            c.open(format!("let {var} = "));
            if into.is_none() {
                // The row is a struct of its own, local to the step.
                c.line(format!("struct {ty} {{"));
                for cl in &selected {
                    c.line(format!("    {}: {},", cl.name, column_rust(cl)));
                }
                c.line("}");
            }
            c.line(format!("let row = {}", query(&sql)));
            c.line("    .fetch_optional(&mut *tx)");
            c.line("    .await?");
            c.line(format!("    .ok_or_else(|| {missing_error})?;"));
            c.line(lit);
            c.close_with(";");
            scope.bind(var, bound);
        }
    }
    Ok(())
}

fn describe(step: &Step) -> String {
    match step {
        Step::Log { .. } => "log".into(),
        Step::Let { name, .. } => format!("let {name}"),
        Step::Publish { topic, .. } => format!("publish to {topic}"),
        Step::CallRpc {
            service, method, ..
        } => format!("call {service}.{method}"),
        Step::Branch { .. } => "branch".into(),
        Step::Respond { .. } => "respond".into(),
        Step::Fail { status, .. } => format!("fail {status}"),
        Step::VerifyHmac { header, .. } => format!("verify the signature in {header}"),
        Step::RateLimit {
            max, window_secs, ..
        } => format!("rate limit {max} per {window_secs}s"),
        Step::HashPassword { bind, .. } => format!("hash password into {bind}"),
        Step::VerifyPassword { bind, .. } => format!("verify password into {bind}"),
        Step::RandomToken { bind, .. } => format!("random token into {bind}"),
        Step::Sha256 { bind, .. } => format!("sha256 into {bind}"),
        Step::Encrypt { bind, .. } => format!("encrypt into {bind}"),
        Step::SignJwt { bind, .. } => format!("sign a token into {bind}"),
        Step::VerifyJwt { bind, .. } => format!("verify a token into {bind}"),
        Step::Jwks { bind, .. } => format!("publish the public keys into {bind}"),
        Step::Decrypt { bind, .. } => format!("decrypt into {bind}"),
        Step::Sql { op, table, .. } => format!(
            "sql {} {table}",
            match op {
                SqlOp::Select => "select from",
                SqlOp::Insert => "insert into",
                SqlOp::Update => "update",
                SqlOp::Delete => "delete from",
            }
        ),
        Step::Code { .. } => "custom code".into(),
    }
}
