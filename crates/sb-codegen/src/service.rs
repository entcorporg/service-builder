/// The HTTP API for the front: one handler per route, translating the request into the
/// schema of the route and the answer (or the error) into JSON, then delegating to `flows::api`.
fn http_rs(project: &Project, service: &Service) -> String {
    // Routes sharing a path are served by one `MethodRouter`, in order of appearance.
    let mut paths: Vec<(&str, Vec<&sb_model::Route>)> = vec![];
    for r in &service.routes {
        match paths.iter_mut().find(|(p, _)| *p == r.path) {
            Some((_, list)) => list.push(r),
            None => paths.push((&r.path, vec![r])),
        }
    }
    let verb = |m: HttpMethod| m.as_str().to_lowercase();
    // Only the first method of a path is a free function; the others chain on the `MethodRouter`.
    let mut verbs: Vec<String> = paths.iter().map(|(_, rs)| verb(rs[0].method)).collect();
    let serves_openapi = project.openapi.serve;
    if serves_openapi || service.challenge.is_some() {
        verbs.push("get".into());
    }
    verbs.sort();
    verbs.dedup();
    let any_params = service
        .routes
        .iter()
        .any(|r| route_params(&r.path).is_ok_and(|p| !p.is_empty()));

    let mut c = Code::new();
    c.line(HEADER);
    c.line("//! HTTP API of the service, for the front (JSON). Each handler translates and delegates to `flows::api`.");
    c.blank();
    c.line("use std::collections::HashMap;");
    c.blank();
    c.line("use axum::{");
    if service.routes.iter().any(|r| hmac_of(r).is_some()) {
        c.line("    body::Bytes,");
    }
    c.line("    Json, Router,");
    let any_image = service.routes.iter().any(|r| {
        let mut found = false;
        for step in &r.steps {
            step.walk(&mut |s| found |= matches!(s, Step::ImageSniff { .. }));
        }
        found
    });
    c.line(format!(
        "    extract::{{{}{}{}State}},",
        if any_image { "DefaultBodyLimit, " } else { "" },
        if service.routes.iter().any(|r| !r.method.has_body()
            && !required_fields(project, r, &route_params(&r.path).unwrap_or_default()).is_empty())
        {
            "RawQuery, "
        } else {
            ""
        },
        if any_params { "Path, " } else { "" }.to_owned()
            + if service.routes.iter().any(|r| !r.method.has_body()) {
                "Query, "
            } else {
                ""
            }
    ));
    c.line(
        if service
            .routes
            .iter()
            .any(|r| hmac_of(r).is_some() || !sourced_fields(project, r).is_empty())
        {
            "    http::{HeaderMap, HeaderValue, StatusCode},"
        } else {
            "    http::{HeaderValue, StatusCode},"
        },
    );
    c.line("    response::{IntoResponse, Response},");
    c.line(format!("    routing::{{{}}},", verbs.join(", ")));
    c.line("};");
    c.line("use contracts::pb;");
    c.line("use tower_http::cors::{Any, CorsLayer};");
    c.blank();
    c.line("use crate::{");
    c.line("    app::{config::Config, ctx::Ctx},");
    c.line("    flows,");
    c.line("};");
    c.blank();

    c.line("/// Serves the HTTP API until the process stops.");
    c.open("pub async fn serve(config: &Config, ctx: Ctx) -> anyhow::Result<()>");
    c.line("let app = Router::new()");
    for (path, routes) in &paths {
        let mut chain = String::new();
        for (i, r) in routes.iter().enumerate() {
            if i == 0 {
                chain.push_str(&format!("{}(handle_{})", verb(r.method), r.name));
            } else {
                chain.push_str(&format!(".{}(handle_{})", verb(r.method), r.name));
            }
        }
        // An image travels in base64 inside the JSON: the default limit of the body (2 MB) would refuse a 2 MB image.
        let mut limit = 0usize;
        for r in routes {
            for step in &r.steps {
                step.walk(&mut |s| {
                    if let Step::ImageSniff { max_bytes, .. } = s {
                        limit = limit.max((*max_bytes as usize).div_ceil(3) * 4 + 16 * 1024);
                    }
                });
            }
        }
        if limit > 0 {
            chain.push_str(&format!(".layer(DefaultBodyLimit::max({limit}))"));
        }
        c.line(format!("    .route({path:?}, {chain})"));
    }
    if serves_openapi {
        c.line(format!(
            "    .route({:?}, get(openapi_document))",
            project.openapi.path
        ));
    }
    if let Some(cfg) = &service.challenge {
        c.line(format!(
            "    .route({:?}, get(challenge_document))",
            cfg.path
        ));
    }
    c.line("    .layer(cors(config))");
    c.line("    .with_state(ctx);");
    c.line("let listener = tokio::net::TcpListener::bind((\"0.0.0.0\", config.http_port)).await?;");
    c.line(format!(
        "tracing::info!(\"{} HTTP API listening on {{}}\", listener.local_addr()?);",
        service.name
    ));
    c.line("axum::serve(listener, app).await?;");
    c.line("Ok(())");
    c.close();
    c.blank();

    c.open("fn cors(config: &Config) -> CorsLayer");
    c.line("let layer = CorsLayer::new().allow_methods(Any).allow_headers(Any);");
    c.open("if config.cors_origins.trim() == \"*\"");
    c.line("layer.allow_origin(Any)");
    c.close_open("else");
    c.line("let origins: Vec<HeaderValue> = config");
    c.line("    .cors_origins");
    c.line("    .split(',')");
    c.line("    .filter_map(|origin| origin.trim().parse().ok())");
    c.line("    .collect();");
    c.line("layer.allow_origin(origins)");
    c.close();
    c.close();

    if serves_openapi {
        c.blank();
        c.line("/// The OpenAPI 3.1 document of these routes, written next to the crate when the code is generated.");
        c.line("const OPENAPI: &str = include_str!(\"../../openapi.json\");");
        c.blank();
        c.open("async fn openapi_document() -> impl IntoResponse");
        c.line("([(axum::http::header::CONTENT_TYPE, \"application/json\")], OPENAPI)");
        c.close();
    }

    if let Some(cfg) = &service.challenge {
        c.blank();
        c.line("/// A new proof-of-work challenge for the form that comes next (see `eda_runtime::challenge`). Never cached: each visitor gets");
        c.line("/// their own, and one is accepted once.");
        c.open("async fn challenge_document() -> Response");
        c.line(format!(
            "match eda_runtime::challenge::issue({:?}, {}, {}) {{",
            cfg.key_env, cfg.max_number, cfg.ttl_secs
        ));
        c.line("    Ok(challenge) => ([(axum::http::header::CACHE_CONTROL, \"no-store\")], Json(challenge)).into_response(),");
        c.line("    Err(error) => {");
        c.line("        tracing::error!(%error, \"cannot make a challenge\");");
        c.line("        StatusCode::INTERNAL_SERVER_ERROR.into_response()");
        c.line("    }");
        c.line("}");
        c.close();
    }

    for r in &service.routes {
        let params = route_params(&r.path).unwrap_or_default();
        let status = match r.status {
            201 => "StatusCode::CREATED",
            202 => "StatusCode::ACCEPTED",
            _ => "StatusCode::OK",
        };
        let sourced = sourced_fields(project, r);
        let required = required_fields(project, r, &params);
        let needs = needs_presence_check(project, r, &params);
        // A body is read as a `Value` first when some of its fields must be there: presence cannot be seen on the struct.
        let checked = r.method.has_body() && needs && hmac_of(r).is_none();
        let query_checked = !r.method.has_body() && !required.is_empty();
        let m = if params.is_empty() && sourced.is_empty() {
            ""
        } else {
            "mut "
        };
        c.blank();
        c.line(format!("/// `{} {}`", r.method.as_str(), r.path));
        c.line(format!("async fn handle_{}(", r.name));
        c.indent();
        c.line("State(ctx): State<Ctx>,");
        if !params.is_empty() {
            c.line("Path(path): Path<HashMap<String, String>>,");
        }
        let signed = hmac_of(r);
        if signed.is_some() {
            // The signature covers the exact bytes: they are read as JSON only once it checks out.
            c.line("headers: HeaderMap,");
            c.line("body: Bytes,");
        } else {
            if !sourced.is_empty() {
                c.line("headers: HeaderMap,");
            }
            if query_checked {
                c.line("RawQuery(raw_query): RawQuery,");
            }
            c.line(if checked {
                "Json(body): Json<serde_json::Value>,".to_string()
            } else if r.method.has_body() {
                format!("Json({m}input): Json<pb::{}>,", r.request)
            } else {
                format!("Query({m}input): Query<pb::{}>,", r.request)
            });
        }
        c.dedent();
        let reply = needs_reply(r);
        c.open(if reply {
            ") -> Result<Response, ApiError>".to_string()
        } else {
            format!(
                ") -> Result<(StatusCode, Json<pb::{}>), ApiError>",
                r.response
            )
        });
        if let Some((header, secret_env, tolerance)) = signed {
            c.line(format!(
                "eda_runtime::webhook::check({secret_env:?}, headers.get({header:?}).and_then(|v| v.to_str().ok()), &body, {tolerance})?;"
            ));
            if needs {
                c.line("let body: serde_json::Value = serde_json::from_slice(&body)");
                c.line("    .map_err(|e| ApiError::new(StatusCode::BAD_REQUEST, e.to_string()))?;");
                c.line(format!(
                    "{}(&body).map_err(invalid)?;",
                    required_fn(&r.name)
                ));
                c.line(format!(
                    "let {m}input: pb::{} = serde_json::from_value(body)",
                    r.request
                ));
                c.line("    .map_err(|e| ApiError::new(StatusCode::BAD_REQUEST, e.to_string()))?;");
            } else {
                c.line(format!(
                    "let {m}input = Json::<pb::{}>::from_bytes(&body)",
                    r.request
                ));
                c.line("    .map_err(|e| ApiError::new(StatusCode::BAD_REQUEST, e.body_text()))?");
                c.line("    .0;");
            }
        } else if checked {
            // What a client left out is refused by name; what it sent is then read as the schema.
            c.line(format!(
                "{}(&body).map_err(invalid)?;",
                required_fn(&r.name)
            ));
            c.line(format!(
                "let {m}input: pb::{} = serde_json::from_value(body).map_err(|e| ApiError::new(StatusCode::UNPROCESSABLE_ENTITY, e.to_string()))?;",
                r.request
            ));
        }
        if query_checked {
            for (field, _) in &required {
                c.line(format!(
                    "if !eda_runtime::http::query_has(raw_query.as_deref(), {field:?}) {{ return Err(invalid(\"{field} : is required\".into())); }}"
                ));
            }
        }
        for param in &params {
            c.line(format!("input.{param} = param(&path, {param:?})?;"));
        }
        for (field, source) in &sourced {
            // Always overwritten, so that nothing a client puts in the body or the query stands for a header.
            let read = match source {
                RequestSource::Header { name } => format!(
                    "headers.get({:?}).and_then(|v| v.to_str().ok()).map(str::to_string)",
                    name.to_ascii_lowercase()
                ),
                RequestSource::Cookie { name } => format!(
                    "eda_runtime::http::cookie(headers.get_all(axum::http::header::COOKIE).iter().filter_map(|v| v.to_str().ok()), {name:?})"
                ),
            };
            let what = match source {
                RequestSource::Header { name } => format!("header `{name}`"),
                RequestSource::Cookie { name } => format!("cookie `{name}`"),
            };
            if project
                .message(&r.request)
                .and_then(|m| m.field(field))
                .is_some_and(|f| f.lenient)
            {
                c.line(format!("input.{field} = {read}.unwrap_or_default();"));
            } else {
                c.line(format!(
                    "input.{field} = {read}.ok_or_else(|| invalid(\"{field} : is required (sent in the {what})\".into()))?;"
                ));
            }
        }
        if project.has_rules(&r.request) {
            // The rules of the schema, before any step: the first that fails is a 400.
            c.line(format!(
                "{}(&input).map_err(invalid)?;",
                rules_fn(&r.request)
            ));
        }
        c.line(format!("flows::api::{}(&ctx, input)", r.name));
        c.line("    .await");
        if reply {
            c.line("    .map_err(ApiError::from)");
            c.line("    .and_then(|reply| {");
            c.line(format!(
                "        let status = reply.status.and_then(|s| StatusCode::from_u16(s).ok()).unwrap_or({status});"
            ));
            c.line("        let mut response = (status, Json(reply.body)).into_response();");
            c.line("        for (name, value) in &reply.headers {");
            c.line("            // A name or value the flow computed that is not a valid header is a flaw of the flow, not of the client.");
            c.line("            let pair = axum::http::HeaderName::try_from(name.as_str()).ok().zip(Some(value).filter(|v| eda_runtime::http::header_value_ok(v)).and_then(|v| HeaderValue::from_str(v).ok()));");
            c.line("            let Some((name, value)) = pair else {");
            c.line("                tracing::error!(header = %name, \"response header refused: its value is not a valid header value\");");
            c.line("                return Err(ApiError::new(StatusCode::INTERNAL_SERVER_ERROR, \"internal error\"));");
            c.line("            };");
            c.line("            response.headers_mut().append(name, value);");
            c.line("        }");
            c.line("        for cookie in &reply.cookies {");
            c.line(
                "            if let Ok(value) = HeaderValue::from_str(&cookie.header_value()) {",
            );
            c.line("                response.headers_mut().append(axum::http::header::SET_COOKIE, value);");
            c.line("            }");
            c.line("        }");
            c.line("        Ok(response)");
            c.line("    })");
        } else {
            c.line(format!("    .map(|body| ({status}, Json(body)))"));
            c.line("    .map_err(ApiError::from)");
        }
        c.close();
    }

    if any_params {
        c.blank();
        c.line("/// Reads a path parameter into the type of the schema field it fills.");
        c.open("fn param<T: std::str::FromStr>(path: &HashMap<String, String>, name: &str) -> Result<T, ApiError>");
        c.line("path.get(name)");
        c.line("    .and_then(|value| value.parse().ok())");
        c.line("    .ok_or_else(|| ApiError::new(StatusCode::BAD_REQUEST, format!(\"invalid path parameter `{name}`\")))");
        c.close();
    }

    let needs_invalid = service.routes.iter().any(|r| {
        let params = route_params(&r.path).unwrap_or_default();
        needs_presence_check(project, r, &params)
            || !required_fields(project, r, &params).is_empty()
            || sourced_fields(project, r).iter().any(|(f, _)| {
                project
                    .message(&r.request)
                    .and_then(|m| m.field(f))
                    .is_some_and(|f| !f.lenient)
            })
    }) || service.routes.iter().any(|r| project.has_rules(&r.request));
    if needs_invalid {
        c.blank();
        c.open("fn invalid(message: String) -> ApiError");
        c.line("ApiError::new(StatusCode::BAD_REQUEST, message)");
        c.close();
    }
    required_rs(&mut c, project, service);
    rules_rs(&mut c, project, service);

    c.blank();
    c.line("/// Errors are answered as `{ \"error\": \"...\" }`. A flow picks the status with `eda_runtime::http::HttpError`;");
    c.line("/// a 5xx, like anything that is not an `HttpError`, answers a generic text and keeps the details in the logs.");
    c.open("struct ApiError");
    c.line("status: StatusCode,");
    c.line("message: String,");
    c.line("retry_after: Option<u64>,");
    c.close();
    c.blank();
    c.open("impl ApiError");
    c.open("fn new(status: StatusCode, message: impl Into<String>) -> Self");
    c.line("Self { status, message: message.into(), retry_after: None }");
    c.close();
    c.close();
    c.blank();
    c.open("impl From<anyhow::Error> for ApiError");
    c.open("fn from(error: anyhow::Error) -> Self");
    c.open("match error.downcast_ref::<eda_runtime::http::HttpError>()");
    c.open("Some(e) =>");
    c.line(
        "let status = StatusCode::from_u16(e.status).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);",
    );
    c.open("if status.is_server_error()");
    c.line("tracing::error!(status = e.status, \"HTTP flow failed: {}\", e.message);");
    c.line("let message = if status == StatusCode::INTERNAL_SERVER_ERROR { \"internal error\".to_string() } else { status.canonical_reason().unwrap_or(\"server error\").to_lowercase() };");
    c.line("return Self { status, message, retry_after: e.retry_after };");
    c.close();
    c.line("Self { status, message: e.message.clone(), retry_after: e.retry_after }");
    c.close();
    c.open("None =>");
    c.line("tracing::error!(\"HTTP handler failed: {error:#}\");");
    c.line("Self::new(StatusCode::INTERNAL_SERVER_ERROR, \"internal error\")");
    c.close();
    c.close();
    c.close();
    c.close();
    c.blank();
    c.open("impl IntoResponse for ApiError");
    c.open("fn into_response(self) -> Response");
    c.line("let mut response = (self.status, Json(HashMap::from([(\"error\", self.message)]))).into_response();");
    c.open("if let Some(seconds) = self.retry_after");
    c.line("response.headers_mut().insert(axum::http::header::RETRY_AFTER, axum::http::HeaderValue::from(seconds));");
    c.close();
    c.line("response");
    c.close();
    c.close();
    c.finish()
}

