fn config_rs(project: &Project, service: &Service, publishes: bool) -> String {
    let has_rpcs = !service.rpcs.is_empty();
    let has_routes = !service.routes.is_empty();
    let mut c = Code::new();
    c.line(HEADER);
    c.line("//! Runtime configuration, read once from the environment.");
    c.blank();
    if has_rpcs || has_routes || publishes {
        c.line("use anyhow::Context;");
        c.blank();
    }
    c.line("#[derive(Clone, Debug)]");
    c.open("pub struct Config");
    c.line("pub brokers: String,");
    c.line("pub database_url: String,");
    if has_rpcs {
        c.line("pub port: u16,");
    }
    if has_routes {
        c.line("pub http_port: u16,");
        c.line("/// Origins allowed to call the HTTP API from a browser: `*` or a comma-separated list.");
        c.line("pub cors_origins: String,");
    }
    if publishes {
        c.line("/// Publish attempts before an event is parked on its dead-letter topic.");
        c.line("pub outbox_max_attempts: u32,");
    }
    c.close();
    c.blank();
    c.open("impl Config");
    c.open("pub fn from_env() -> anyhow::Result<Self>");
    let secrets = webhook_secrets(service);
    if !secrets.is_empty() {
        c.line("// The secrets of the signed webhooks: a service that cannot verify them does not start.");
        for env in &secrets {
            c.line(format!("eda_runtime::webhook::secret({env:?})?;"));
        }
    }
    let (seeds, urls) = jwt_settings(service);
    if !seeds.is_empty() || !urls.is_empty() {
        c.line(
            "// The keys of the tokens: a service that cannot sign or verify them does not start.",
        );
        for env in &seeds {
            c.line(format!("eda_runtime::jwt::JwtKeys::from_env({env:?})?;"));
        }
        for env in &urls {
            c.line(format!("eda_runtime::jwt::jwks_url({env:?})?;"));
        }
    }
    if uses_passkeys(service) {
        c.line("// The relying party of the passkeys is the site: a service that does not know its address does not start.");
        c.line("eda_runtime::webauthn::check_config()?;");
    }
    if uses_live(service) {
        c.line("// The events for the browsers go through DragonflyDB: in production the service must know where it is.");
        c.line("eda_runtime::live::check_config()?;");
    }
    if let Some(cfg) = &service.challenge {
        c.line("// The challenges are signed with a key every replica shares: in production the service must have it.");
        c.line(format!(
            "eda_runtime::challenge::check_config({:?})?;",
            cfg.key_env
        ));
    }
    if service.uses_shared_limit() {
        c.line("// The rate limits counted for all the replicas go through DragonflyDB: in production the service must know where it is.");
        c.line("eda_runtime::rate_limit::check_config()?;");
    }
    let buckets = bucket_envs(service);
    if !buckets.is_empty() {
        c.line("// The buckets are named in the environment, and the endpoint must be a URL: nothing is requested here.");
        let list: Vec<String> = buckets.iter().map(|b| format!("{b:?}")).collect();
        c.line(format!(
            "eda_runtime::s3::check_config(&[{}])?;",
            list.join(", ")
        ));
    }
    let targets = crate::http_call::http_targets(service);
    if !targets.is_empty() {
        c.line("// The external services this one calls: their addresses and secrets are in the environment, and nothing is requested here.");
        let list: Vec<String> = targets
            .iter()
            .map(|(base, secrets)| {
                let secrets: Vec<String> = secrets.iter().map(|s| format!("{s:?}")).collect();
                format!("({base:?}, &[{}][..])", secrets.join(", "))
            })
            .collect();
        c.line(format!(
            "eda_runtime::http_client::check_config(&[{}])?;",
            list.join(", ")
        ));
    }
    let keys = encryption_keys(service);
    if !keys.is_empty() {
        c.line("// The encryption keys: a service that cannot read what it stored does not start.");
        for env in &keys {
            c.line(format!("eda_runtime::crypto::key({env:?})?;"));
        }
    }
    c.open("Ok(Self");
    c.line("brokers: eda_runtime::env_or(\"KAFKA_BROKERS\", \"localhost:9092\"),");
    let db_env = format!("{}_DATABASE_URL", shouty(&service.name));
    c.line(format!(
        "database_url: eda_runtime::env_or({db_env:?}, \"postgres://postgres:postgres@localhost:5432/{}\"),",
        snake(&service.name)
    ));
    if has_rpcs {
        let env = format!("{}_PORT", shouty(&service.name));
        c.line(format!(
            "port: eda_runtime::env_or({env:?}, \"{}\")",
            service.port
        ));
        c.line("    .parse()");
        c.line(format!("    .context(\"{env} must be a port number\")?,"));
    }
    if has_routes {
        let env = format!("{}_HTTP_PORT", shouty(&service.name));
        c.line(format!(
            "http_port: eda_runtime::env_or({env:?}, \"{}\")",
            service.http_port.unwrap_or(DEFAULT_HTTP_PORT)
        ));
        c.line("    .parse()");
        c.line(format!("    .context(\"{env} must be a port number\")?,"));
        c.line("cors_origins: eda_runtime::env_or(\"CORS_ORIGINS\", \"*\"),");
    }
    if publishes {
        c.line(format!(
            "outbox_max_attempts: eda_runtime::env_or(\"OUTBOX_MAX_ATTEMPTS\", \"{}\")",
            project.outbox.max_attempts
        ));
        c.line("    .parse()");
        c.line("    .context(\"OUTBOX_MAX_ATTEMPTS must be a number\")?,");
    }
    c.close_with(")");
    c.close();
    c.close();
    c.finish()
}

fn bootstrap_rs(project: &Project, service: &Service, publishes: bool) -> String {
    let topics = used_topics(project, service);
    let mut c = Code::new();
    c.line(HEADER);
    c.line("//! Start-up steps, kept out of `main` so it only reads as a sequence.");
    c.blank();
    if !topics.is_empty() {
        c.line("use contracts::topics;");
        c.blank();
    }
    c.line("use crate::app::config::Config;");
    if !topics.is_empty() {
        c.blank();
        c.line("/// Creates the topics this service publishes to or consumes, and their dead-letter topics.");
        c.open("pub async fn provision_topics(config: &Config) -> anyhow::Result<()>");
        c.line("eda_runtime::ensure_topics(&config.brokers, &[")
            .indent();
        for t in &topics {
            for suffix in ["", "_DLQ"] {
                c.line(format!(
                    "eda_runtime::TopicSpec {{ name: topics::{}{suffix}.to_string(), partitions: {}, replication: {} }},",
                    topic_const(&t.name),
                    t.partitions,
                    t.replication_factor
                ));
            }
        }
        c.dedent().line("]).await");
        c.close();
    }
    c.blank();
    c.line(match (publishes, !has_schema(service)) {
        (true, false) => {
            "/// Connects to the service's own database, creates its tables and the outbox table."
        }
        (true, true) => "/// Connects to the service's own database and creates the outbox table.",
        (false, false) => "/// Connects to the service's own database and creates its tables.",
        (false, true) => "/// Connects to the service's own database.",
    });
    c.open("pub async fn connect_database(config: &Config) -> anyhow::Result<sqlx::PgPool>");
    c.line("let db = eda_runtime::connect_database(&config.database_url).await?;");
    if publishes {
        c.line("eda_runtime::outbox::migrate(&db).await?;");
    }
    if has_schema(service) {
        c.line("crate::app::schema::apply(&db).await?;");
    }
    c.line("Ok(db)");
    c.close();
    if service.rpcs.is_empty() && service.routes.is_empty() {
        c.blank();
        c.line("/// Keeps the process alive until Ctrl+C: nothing here serves requests.");
        c.open("pub async fn wait_for_shutdown() -> anyhow::Result<()>");
        c.line(format!(
            "tracing::info!(\"{} running{}, press Ctrl+C to stop\");",
            service.name,
            match (service.consumers.is_empty(), service.jobs.is_empty()) {
                (true, true) => "",
                (false, true) => " (consumers only)",
                (true, false) => " (jobs only)",
                (false, false) => " (consumers and jobs only)",
            }
        ));
        c.line("tokio::signal::ctrl_c().await?;");
        c.line("Ok(())");
        c.close();
    }
    c.finish()
}

/// The tables designed in the editor, as idempotent statements, in the order they can apply: every
/// table with its columns, then every column again with `ADD COLUMN IF NOT EXISTS` (so that a column
/// added to the design reaches an existing database), then the unique constraints, the indexes and the
/// foreign keys. Those come last because a foreign key may point at a table that comes after its own.
fn schema_rs(service: &Service) -> String {
    let mut c = Code::new();
    c.line(HEADER);
    c.line("//! The tables of this service, as designed in the editor. Applied at start-up, additive only.");
    c.blank();
    c.line("const STATEMENTS: &[&str] = &[");
    c.indent();
    let definition = |col: &Column| {
        let mut d = format!("{} {}", quoted(&col.name), col.ty.sql());
        if !col.nullable {
            d.push_str(" NOT NULL");
        }
        if let Some(default) = col.default.as_deref().filter(|d| !d.trim().is_empty()) {
            d.push_str(&format!(" DEFAULT {}", default.trim()));
        }
        d
    };
    let mut statements: Vec<String> = Vec::new();
    // The journal first: a renamed table or column must be found under its new name by what follows, or it would be
    // created empty next to the old one.
    for t in &service.tables {
        for (from, to) in rename_steps(&t.renamed_from, &t.name) {
            statements.push(rename_table(from, to));
        }
    }
    for t in &service.tables {
        for c in &t.columns {
            for (from, to) in rename_steps(&c.renamed_from, &c.name) {
                statements.push(rename_column(&t.name, from, to));
            }
        }
    }
    for t in &service.tables {
        let mut parts: Vec<String> = t.columns.iter().map(&definition).collect();
        let pk = column_list(&t.primary_key());
        if !t.primary_key().is_empty() {
            parts.push(format!("PRIMARY KEY ({pk})"));
        }
        statements.push(format!(
            "CREATE TABLE IF NOT EXISTS {} ({})",
            quoted(&t.name),
            parts.join(", ")
        ));
        for col in t.columns.iter().filter(|col| !col.primary_key) {
            statements.push(format!(
                "ALTER TABLE {} ADD COLUMN IF NOT EXISTS {}",
                quoted(&t.name),
                definition(col)
            ));
        }
    }
    // Conversions and drops come before the constraints: a dropped column takes the indexes and constraints on it along,
    // and an index of the same name that the design now defines on other columns must be created afresh, not skipped.
    for t in &service.tables {
        for c in &t.columns {
            if c.retyped_from.is_some_and(|from| from.converts_to(c.ty)) {
                statements.push(retype_column(&t.name, c));
            }
            if c.nullable_from.is_some_and(|was| was != c.nullable) {
                statements.push(set_nullability(&t.name, c));
            }
        }
        for name in &t.dropped_columns {
            statements.push(format!(
                "ALTER TABLE {} DROP COLUMN IF EXISTS {} CASCADE",
                quoted(&t.name),
                quoted(name)
            ));
        }
    }
    for name in &service.dropped_tables {
        statements.push(format!("DROP TABLE IF EXISTS {} CASCADE", quoted(name)));
    }
    for t in &service.tables {
        for u in &t.uniques {
            statements.push(add_constraint(
                &t.name,
                &u.name,
                &format!("UNIQUE ({})", column_list(&u.columns)),
            ));
        }
        for i in &t.indexes {
            statements.push(format!(
                "CREATE {}INDEX IF NOT EXISTS {} ON {} ({})",
                if i.unique { "UNIQUE " } else { "" },
                quoted(&i.name),
                quoted(&t.name),
                column_list(&i.columns)
            ));
        }
    }
    for t in &service.tables {
        for fk in &t.foreign_keys {
            statements.push(add_constraint(
                &t.name,
                &fk.name,
                &format!(
                    "FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE {} ON UPDATE {}",
                    column_list(&fk.columns),
                    quoted(&fk.ref_table),
                    column_list(&fk.ref_columns),
                    fk.on_delete.sql(),
                    fk.on_update.sql()
                ),
            ));
        }
    }
    for statement in statements {
        c.line(format!("{statement:?},"));
    }
    if service.has_idempotent_consumers() {
        c.line("eda_runtime::dedup::CREATE_TABLE,");
    }
    // The tables the two-factor steps keep their state in.
    let (mut replay, mut recovery) = (false, false);
    for step in service.handler_steps() {
        step.walk(&mut |s| match s {
            Step::TotpVerify { .. } => replay = true,
            Step::RecoveryCodes { .. } | Step::RecoveryCodeUse { .. } => recovery = true,
            _ => {}
        });
    }
    if uses_passkeys(service) {
        c.line("eda_runtime::webauthn::CREATE_STATES_TABLE,");
        c.line("eda_runtime::webauthn::ADD_STATES_ORIGIN,");
        c.line("eda_runtime::webauthn::CREATE_CREDENTIALS_TABLE,");
        c.line("eda_runtime::webauthn::CREATE_CREDENTIALS_INDEX,");
    }
    if service.uses_challenge_check() {
        // The solutions already accepted: a solution is worth one form, for every replica.
        c.line("eda_runtime::challenge::CREATE_USES_TABLE,");
    }
    if service.uses_usage() {
        // The uses metered and checked against quotas, and the view that adds them up per day.
        for statement in [
            "CREATE_EVENTS_TABLE",
            "CREATE_EVENTS_INDEX",
            "CREATE_EVENTS_UNIQUE",
            "CREATE_DAILY_VIEW",
        ] {
            c.line(format!("eda_runtime::usage::{statement},"));
        }
    }
    if replay {
        c.line("eda_runtime::totp::CREATE_STEPS_TABLE,");
    }
    if recovery {
        c.line("eda_runtime::totp::CREATE_RECOVERY_TABLE,");
    }
    c.dedent();
    c.line("];");
    c.blank();
    c.open("pub async fn apply(db: &sqlx::PgPool) -> anyhow::Result<()>");
    c.line("eda_runtime::db::apply_schema(db, STATEMENTS).await");
    c.close();
    c.finish()
}

/// The renames to replay, oldest first: the names a thing had, then the one it has: `[a, b]` and `c` give a -> b, b -> c.
/// Each step only runs where its old name exists and its new one does not, so any earlier state reaches the current one.
fn rename_steps<'a>(history: &'a [String], current: &'a str) -> Vec<(&'a str, &'a str)> {
    let names: Vec<&str> = history
        .iter()
        .map(String::as_str)
        .chain([current])
        .collect();
    names.windows(2).map(|w| (w[0], w[1])).collect()
}

fn column_exists(table: &str, column: &str) -> String {
    format!(
        "EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = '{table}' AND column_name = '{column}')"
    )
}

fn rename_table(from: &str, to: &str) -> String {
    let exists = |name: &str| {
        format!(
            "EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = '{name}')"
        )
    };
    format!(
        "DO $$ BEGIN IF {} AND NOT {} THEN ALTER TABLE {} RENAME TO {}; END IF; END $$",
        exists(from),
        exists(to),
        quoted(from),
        quoted(to)
    )
}

fn rename_column(table: &str, from: &str, to: &str) -> String {
    format!(
        "DO $$ BEGIN IF {} AND NOT {} THEN ALTER TABLE {} RENAME COLUMN {} TO {}; END IF; END $$",
        column_exists(table, from),
        column_exists(table, to),
        quoted(table),
        quoted(from),
        quoted(to)
    )
}

/// Converts the column when the database does not hold the current type yet. The default goes first and comes back
/// after: Postgres cannot cast an old default to the new type by itself.
fn retype_column(table: &str, col: &Column) -> String {
    let (t, c, ty) = (quoted(table), quoted(&col.name), col.ty.sql());
    let mut body = format!(
        "ALTER TABLE {t} ALTER COLUMN {c} DROP DEFAULT; ALTER TABLE {t} ALTER COLUMN {c} TYPE {ty} USING {c}::{ty};"
    );
    if let Some(default) = col.default.as_deref().filter(|d| !d.trim().is_empty()) {
        body.push_str(&format!(
            " ALTER TABLE {t} ALTER COLUMN {c} SET DEFAULT {};",
            default.trim()
        ));
    }
    format!(
        "DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = '{t}'::regclass AND attname = '{}' AND NOT attisdropped AND atttypid <> '{ty}'::regtype) THEN {body} END IF; END $$",
        col.name
    )
}

/// Applies a recorded change of nullability when the database is not there yet. Making a column required first gives
/// its nulls the default, if there is one: with none, a null makes `SET NOT NULL` fail and the start-up stops.
fn set_nullability(table: &str, col: &Column) -> String {
    let (t, c) = (quoted(table), quoted(&col.name));
    let body = if col.nullable {
        format!("ALTER TABLE {t} ALTER COLUMN {c} DROP NOT NULL;")
    } else {
        let mut body = String::new();
        if let Some(default) = col.default.as_deref().filter(|d| !d.trim().is_empty()) {
            body.push_str(&format!(
                "UPDATE {t} SET {c} = {} WHERE {c} IS NULL; ",
                default.trim()
            ));
        }
        body.push_str(&format!("ALTER TABLE {t} ALTER COLUMN {c} SET NOT NULL;"));
        body
    };
    format!(
        "DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = '{t}'::regclass AND attname = '{}' AND NOT attisdropped AND attnotnull = {}) THEN {body} END IF; END $$",
        col.name, col.nullable
    )
}

fn column_list(columns: &[impl AsRef<str>]) -> String {
    columns
        .iter()
        .map(|c| quoted(c.as_ref()))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Postgres has no `ADD CONSTRAINT IF NOT EXISTS`: the constraint is added unless the table already has
/// one of that name.
fn add_constraint(table: &str, name: &str, definition: &str) -> String {
    format!(
        "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '{name}' AND conrelid = '{}'::regclass) \
         THEN ALTER TABLE {} ADD CONSTRAINT {} {definition}; END IF; END $$",
        quoted(table),
        quoted(table),
        quoted(name)
    )
}

