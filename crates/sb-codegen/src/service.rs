fn flows_header(doc: &str) -> Code {
    let mut c = Code::new();
    c.line(HEADER);
    c.line(format!("//! {doc}"));
    c.line("#![allow(unused, unreachable_code, clippy::all)]");
    c.blank();
    c.line("use contracts::{pb, topics};");
    c.line("use sqlx::Row as _;");
    c.blank();
    c.line("use crate::app::ctx::Ctx;");
    c
}

/// Every run is one transaction: what a flow writes through `tx` and the events it publishes
/// (queued in the outbox) commit together, or not at all.
fn begin(c: &mut Code, service: &Service) {
    c.line("// One transaction per run: state written through `tx` and the events published below commit together.");
    c.line("let mut tx = ctx.db.begin().await?;");
    if uses_live(service) {
        c.line("// Events for the browsers wait here, and are sent once the transaction has committed (never before, never on failure).");
        c.line("let mut live = eda_runtime::live::Live::default();");
    }
}

/// The commit of a run. The events for the browsers are sent right after it, so that a run that fails sends none, and the
/// browser never hears of a change the database does not have.
fn commit(c: &mut Code, service: &Service) {
    c.line("tx.commit().await?;");
    if uses_live(service) {
        c.line("live.flush().await;");
    }
}

/// Whether a handler of the service pushes an event to the browsers (`publishLive`): it then holds a `live` buffer, and the
/// runtime brings the Redis client in.
fn uses_live(service: &Service) -> bool {
    let mut used = false;
    for step in service.handler_steps() {
        step.walk(&mut |s| used |= matches!(s, Step::PublishLive { .. }));
    }
    used
}

fn rpc_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c = flows_header("One function per RPC, built from the steps drawn in the editor.");
    for r in &service.rpcs {
        c.blank();
        c.open(format!(
            "pub async fn {}(ctx: &Ctx, input: pb::{}) -> anyhow::Result<pb::{}>",
            snake(&r.name),
            r.request,
            r.response
        ));
        begin(&mut c, service);
        let mut scope = Scope::with_input(&r.request);
        steps(
            &mut c,
            project,
            service,
            &mut scope,
            &r.steps,
            Some(&r.response),
            false,
        )?;
        commit(&mut c, service);
        c.line(format!("Ok(pb::{}::default())", r.response));
        c.close();
    }
    Ok(c.finish())
}

fn rules_fn(message: &str) -> String {
    format!("check_{}", snake(message))
}

/// One function per schema the routes of the service receive and that has rules, its own or inside it.
fn rules_rs(c: &mut Code, project: &Project, service: &Service) {
    let received: BTreeSet<&str> = service
        .routes
        .iter()
        .flat_map(|r| {
            // The request, and the schemas nested in it.
            let mut names = vec![r.request.as_str()];
            let mut i = 0;
            while i < names.len() {
                if let Some(m) = project.message(names[i]) {
                    for f in &m.fields {
                        if let FieldType::Message { name } = &f.ty
                            && !names.contains(&name.as_str())
                        {
                            names.push(name);
                        }
                    }
                }
                i += 1;
            }
            names
        })
        .filter(|n| project.has_rules(n))
        .collect();
    if received.is_empty() {
        return;
    }
    for name in received {
        let Some(m) = project.message(name) else {
            continue;
        };
        c.blank();
        c.line(format!(
            "/// The rules of `{name}`: the first that fails is a 400."
        ));
        c.open(format!(
            "fn {}(m: &pb::{name}) -> Result<(), String>",
            rules_fn(name)
        ));
        for f in &m.fields {
            let field = &f.name;
            if let FieldType::Message { name: inner } = &f.ty {
                if project.has_rules(inner) {
                    let check = rules_fn(inner);
                    // The path of the field travels with the message: `company.name`, `contacts[2].email`.
                    if f.repeated {
                        c.line(format!(
                            "for (i, item) in m.{field}.iter().enumerate() {{ {check}(item).map_err(|e| format!(\"{field}[{{i}}].{{e}}\"))?; }}"
                        ));
                    } else {
                        c.line(format!(
                            "if let Some(item) = &m.{field} {{ {check}(item).map_err(|e| format!(\"{field}.{{e}}\"))?; }}"
                        ));
                    }
                }
                continue;
            }
            if f.rules.is_empty() {
                continue;
            }
            let calls: Vec<String> = f
                .rules
                .iter()
                .map(|rule| {
                    let call = match rule {
                        Rule::Length { min, max } => {
                            format!("eda_runtime::validation::length({field:?}, v, {min}, {max})")
                        }
                        Rule::Email => format!("eda_runtime::validation::email({field:?}, v)"),
                        Rule::Siren => format!("eda_runtime::validation::siren({field:?}, v)"),
                    };
                    format!("{call}?;")
                })
                .collect();
            let body = calls.join(" ");
            if f.repeated {
                c.line(format!("for v in &m.{field} {{ {body} }}"));
            } else if f.optional {
                c.line(format!("if let Some(v) = &m.{field} {{ {body} }}"));
            } else {
                c.line(format!("{{ let v = &m.{field}; {body} }}"));
            }
        }
        c.line("Ok(())");
        c.close();
    }
}

/// The signature check of a route, if it has one: the header, the environment variable of the secret, the tolerance.
/// The fields of the request of a route that come from a header or a cookie, with where from.
fn sourced_fields<'a>(
    project: &'a Project,
    route: &sb_model::Route,
) -> Vec<(&'a str, &'a RequestSource)> {
    project.message(&route.request).map_or(vec![], |m| {
        m.fields
            .iter()
            .filter_map(|f| f.source.as_ref().map(|s| (f.name.as_str(), s)))
            .collect()
    })
}

fn required_fn(route: &str) -> String {
    format!("require_{route}")
}

/// The fields of the request a client has to send in the body or the query string: not optional, not lenient, and
/// not filled by the path or by a header or cookie (which are checked where they are read).
fn required_fields<'a>(
    project: &'a Project,
    route: &sb_model::Route,
    params: &[String],
) -> Vec<(&'a str, &'a sb_model::Field)> {
    project.message(&route.request).map_or(vec![], |m| {
        m.fields
            .iter()
            .filter(|f| {
                !f.optional && !f.lenient && f.source.is_none() && !params.contains(&f.name)
            })
            .map(|f| (f.name.as_str(), f))
            .collect()
    })
}

/// Whether a schema, or one nested in it, has a field that must be sent.
fn message_requires(project: &Project, name: &str, seen: &mut Vec<String>) -> bool {
    if seen.iter().any(|n| n == name) {
        return false;
    }
    seen.push(name.to_string());
    project.message(name).is_some_and(|m| {
        m.fields.iter().any(|f| {
            (!f.optional && !f.lenient)
                || matches!(&f.ty, FieldType::Message { name } if message_requires(project, name, seen))
        })
    })
}

/// Whether the body of a route has to be looked at before it is read as the schema: a required field somewhere in it.
fn needs_presence_check(project: &Project, route: &sb_model::Route, params: &[String]) -> bool {
    if !required_fields(project, route, params).is_empty() {
        return true;
    }
    project.message(&route.request).is_some_and(|m| {
        m.fields.iter().any(|f| {
            f.source.is_none()
                && !params.contains(&f.name)
                && matches!(&f.ty, FieldType::Message { name } if message_requires(project, name, &mut vec![]))
        })
    })
}

/// The check of one field of a JSON object: refused when a required one is not sent, then the fields of the nested
/// schema, with their path in the message (`company.name`, `lines[2].sku`).
fn require_field(c: &mut Code, project: &Project, f: &sb_model::Field) {
    let name = &f.name;
    if !f.optional && !f.lenient {
        c.line(format!(
            "if !eda_runtime::http::sent(v, {name:?}) {{ return Err(\"{name} : is required\".into()); }}"
        ));
    }
    if let FieldType::Message { name: inner } = &f.ty
        && message_requires(project, inner, &mut vec![])
    {
        let check = required_fn(&snake(inner));
        if f.repeated {
            c.line(format!(
                "for (i, item) in v.get({name:?}).and_then(|a| a.as_array()).into_iter().flatten().enumerate() {{ {check}_nested(item).map_err(|e| format!(\"{name}[{{i}}].{{e}}\"))?; }}"
            ));
        } else {
            c.line(format!(
                "if let Some(item) = v.get({name:?}).filter(|o| o.is_object()) {{ {check}_nested(item).map_err(|e| format!(\"{name}.{{e}}\"))?; }}"
            ));
        }
    }
}

/// The presence checks of the routes: one function for the fields of a request, one for each schema nested in it.
fn required_rs(c: &mut Code, project: &Project, service: &Service) {
    let mut nested: Vec<String> = vec![];
    // (function, a body that carries everything, the fields a client has to send), for the tests of the checks.
    let mut tested: Vec<(String, String, Vec<&str>)> = vec![];
    for r in &service.routes {
        let params = route_params(&r.path).unwrap_or_default();
        if r.method.has_body() && needs_presence_check(project, r, &params) {
            let m = project.message(&r.request).expect("validated");
            c.blank();
            c.line(format!(
                "/// What the body of `{}` has to carry, by name: a field left out is a 400, not a default value.",
                r.name
            ));
            c.open(format!(
                "fn {}(v: &serde_json::Value) -> Result<(), String>",
                required_fn(&r.name)
            ));
            for f in m
                .fields
                .iter()
                .filter(|f| f.source.is_none() && !params.contains(&f.name))
            {
                require_field(c, project, f);
            }
            c.line("Ok(())");
            c.close();
            let mut full = serde_json::Map::new();
            for f in m
                .fields
                .iter()
                .filter(|f| f.source.is_none() && !params.contains(&f.name))
                .filter(|f| !f.optional && !f.lenient)
            {
                full.insert(f.name.clone(), presence_sample(project, f, &mut vec![]));
            }
            tested.push((
                required_fn(&r.name),
                serde_json::Value::Object(full).to_string(),
                required_fields(project, r, &params)
                    .into_iter()
                    .map(|(n, _)| n)
                    .collect(),
            ));
            // The schemas nested in the request, and the ones nested in them.
            let mut todo: Vec<&str> = m
                .fields
                .iter()
                .filter_map(|f| match &f.ty {
                    FieldType::Message { name } => Some(name.as_str()),
                    _ => None,
                })
                .collect();
            while let Some(name) = todo.pop() {
                if nested.iter().any(|n| n == name) || !message_requires(project, name, &mut vec![])
                {
                    continue;
                }
                nested.push(name.to_string());
                if let Some(inner) = project.message(name) {
                    todo.extend(inner.fields.iter().filter_map(|f| match &f.ty {
                        FieldType::Message { name } => Some(name.as_str()),
                        _ => None,
                    }));
                }
            }
        }
    }
    for name in nested {
        let Some(m) = project.message(&name) else {
            continue;
        };
        c.blank();
        c.open(format!(
            "fn {}_nested(v: &serde_json::Value) -> Result<(), String>",
            required_fn(&snake(&name))
        ));
        for f in &m.fields {
            require_field(c, project, f);
        }
        c.line("Ok(())");
        c.close();
    }
    let tests: Vec<_> = tested
        .iter()
        .filter(|(_, _, fields)| !fields.is_empty())
        .collect();
    if !tests.is_empty() {
        c.blank();
        c.line("#[cfg(test)]");
        c.open("mod tests");
        c.line("use super::*;");
        for (function, full, fields) in tests {
            c.blank();
            c.line("#[test]");
            c.open(format!("fn {function}_names_the_field_left_out()"));
            c.line(format!(
                "let full: serde_json::Value = serde_json::from_str({full:?}).unwrap();"
            ));
            c.line(format!("assert!({function}(&full).is_ok());"));
            c.open(format!("for field in {fields:?}"));
            c.line("let mut left_out = full.clone();");
            c.line("left_out.as_object_mut().unwrap().remove(field);");
            c.line(format!(
                "assert_eq!({function}(&left_out), Err(format!(\"{{field}} : is required\")));"
            ));
            c.line("// `null` is as good as absent; an empty text is a value.");
            c.line("let mut nulled = full.clone();");
            c.line("nulled[field] = serde_json::Value::Null;");
            c.line(format!("assert!({function}(&nulled).is_err());"));
            c.close();
            c.close();
        }
        c.close();
    }
}

/// A JSON value that carries what a client has to send for this field, nested fields included.
fn presence_sample(
    project: &Project,
    f: &sb_model::Field,
    seen: &mut Vec<String>,
) -> serde_json::Value {
    use serde_json::{Value, json};
    let one = match &f.ty {
        FieldType::Message { name } if !seen.contains(name) => {
            seen.push(name.clone());
            let mut object = serde_json::Map::new();
            for inner in project
                .message(name)
                .iter()
                .flat_map(|m| &m.fields)
                .filter(|f| !f.optional && !f.lenient)
            {
                object.insert(inner.name.clone(), presence_sample(project, inner, seen));
            }
            seen.pop();
            Value::Object(object)
        }
        _ => json!(""),
    };
    if f.repeated { json!([]) } else { one }
}

fn hmac_of(route: &sb_model::Route) -> Option<(&str, &str, u32)> {
    match route.steps.first() {
        Some(Step::VerifyHmac {
            header,
            secret_env,
            tolerance_secs,
            ..
        }) => Some((header, secret_env, *tolerance_secs)),
        _ => None,
    }
}

/// A claim as a JSON value: a path keeps its type (a list stays a list, an absent optional is `null`), a literal is
/// its JSON, and raw Rust is anything that serializes.
fn claim_json(project: &Project, scope: &Scope, value: &Expr) -> Result<String, CodegenError> {
    Ok(match value {
        Expr::Path { path } => {
            let rp = sb_model::typing::resolve_path(project, scope, path)
                .map_err(CodegenError::Internal)?;
            format!("eda_runtime::jwt::json!({})", crate::expr::path_code(&rp))
        }
        Expr::Literal { value } => format!("eda_runtime::jwt::json!({value})"),
        Expr::Raw { code } => format!("eda_runtime::jwt::json!({})", code.trim()),
        Expr::Now => {
            return Err(CodegenError::Internal(
                "`now()` only exists in an SQL step".into(),
            ));
        }
        Expr::Template { .. } | Expr::Call { .. } => {
            let ty = sb_model::typing::expr_type(project, scope, value, None)
                .map_err(CodegenError::Internal)?
                .ok_or_else(|| CodegenError::Internal("untyped operation".into()))?;
            format!(
                "eda_runtime::jwt::json!({})",
                crate::expr::lower(project, scope, value, &ty)?
            )
        }
    })
}

/// The seeds and the JWKS URLs the JWT steps of a service read from the environment, once each.
fn jwt_settings(service: &Service) -> (BTreeSet<&str>, BTreeSet<&str>) {
    let (mut seeds, mut urls) = (BTreeSet::new(), BTreeSet::new());
    for step in service.handler_steps() {
        step.walk(&mut |s| match s {
            Step::SignJwt { key_env, .. } => {
                seeds.insert(key_env.as_str());
            }
            Step::Jwks { key_envs, .. } => seeds.extend(key_envs.iter().map(String::as_str)),
            Step::VerifyJwt { source, .. } => match source {
                sb_model::JwksSource::Keys { key_envs } => {
                    seeds.extend(key_envs.iter().map(String::as_str))
                }
                sb_model::JwksSource::Url { url_env } => {
                    urls.insert(url_env.as_str());
                }
            },
            _ => {}
        });
    }
    (seeds, urls)
}

/// The environment variables that name the buckets the object steps of a service use, once each.
fn bucket_envs(service: &Service) -> BTreeSet<&str> {
    service.bucket_envs()
}

/// The `app_url` of a passkey step as the argument of the runtime, an `Option<&str>`: the origin of the request, or
/// `None` for the address of the site (`APP_URL`).
fn lower_app_url(
    project: &Project,
    scope: &Scope,
    app_url: &Option<Expr>,
) -> Result<String, CodegenError> {
    Ok(match app_url {
        Some(app_url) => format!(
            "Some(({}).as_str())",
            lower(project, scope, app_url, &TypeRef::scalar(FieldType::String))?
        ),
        None => "None".to_string(),
    })
}

/// Whether a service has a passkey step: it then needs the address of the site and the `webauthn` feature of the runtime.
fn uses_passkeys(service: &Service) -> bool {
    let mut used = false;
    for step in service.handler_steps() {
        step.walk(&mut |s| {
            used |= matches!(
                s,
                Step::PasskeyRegisterStart { .. }
                    | Step::PasskeyRegisterFinish { .. }
                    | Step::PasskeyLoginStart { .. }
                    | Step::PasskeyLoginFinish { .. }
            )
        });
    }
    used
}

/// The environment variables of the encryption keys a service uses, once each.
fn encryption_keys(service: &Service) -> BTreeSet<&str> {
    let mut keys = BTreeSet::new();
    for step in service.handler_steps() {
        step.walk(&mut |s| {
            if let Step::Encrypt { key_env, .. }
            | Step::Decrypt { key_env, .. }
            | Step::TotpGenerate { key_env, .. }
            | Step::TotpVerify { key_env, .. } = s
            {
                keys.insert(key_env.as_str());
            }
        });
    }
    keys
}

/// The environment variables of the secrets of the signed webhooks of a service, once each.
fn webhook_secrets(service: &Service) -> BTreeSet<&str> {
    service
        .routes
        .iter()
        .filter_map(hmac_of)
        .map(|(_, env, _)| env)
        .collect()
}

/// Whether a route answers with a status or cookies of its own: its flow then returns a `Reply`.
fn needs_reply(route: &sb_model::Route) -> bool {
    let mut extras = false;
    for step in &route.steps {
        step.walk(&mut |s| {
            extras |= matches!(s, Step::Respond { status, cookies, headers, .. } if status.is_some() || !cookies.is_empty() || !headers.is_empty())
        });
    }
    extras
}

fn api_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c =
        flows_header("One function per HTTP route, built from the steps drawn in the editor.");
    for r in &service.routes {
        c.blank();
        c.line(format!("/// `{} {}`", r.method.as_str(), r.path));
        let reply = needs_reply(r);
        let returns = if reply {
            format!("eda_runtime::http::Reply<pb::{}>", r.response)
        } else {
            format!("pb::{}", r.response)
        };
        c.open(format!(
            "pub async fn {}(ctx: &Ctx, input: pb::{}) -> anyhow::Result<{returns}>",
            r.name, r.request
        ));
        begin(&mut c, service);
        let mut scope = Scope::with_input(&r.request);
        steps(
            &mut c,
            project,
            service,
            &mut scope,
            &r.steps,
            Some(&r.response),
            reply,
        )?;
        commit(&mut c, service);
        c.line(if reply {
            format!(
                "Ok(eda_runtime::http::Reply::new(pb::{}::default()))",
                r.response
            )
        } else {
            format!("Ok(pb::{}::default())", r.response)
        });
        c.close();
    }
    Ok(c.finish())
}

fn consumer_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c =
        flows_header("One function per consumer, built from the steps drawn in the editor.");
    for cons in &service.consumers {
        let topic = project
            .topic(&cons.topic)
            .ok_or_else(|| CodegenError::Internal(format!("unknown topic `{}`", cons.topic)))?;
        c.blank();
        c.line(format!(
            "/// Consumes `{}` ({}).",
            topic.name, topic.message
        ));
        c.open(format!(
            "pub async fn {}(ctx: &Ctx, input: pb::{}) -> anyhow::Result<()>",
            cons.name, topic.message
        ));
        begin(&mut c, service);
        if let Some(field) = &cons.idempotent_on {
            // Recorded in this transaction: a handling that fails leaves no trace, and the retry does the work.
            c.open(format!(
                "if !eda_runtime::dedup::first_time(&mut tx, {:?}, &input.{field}.to_string()).await?",
                cons.name
            ));
            c.line(format!(
                "tracing::info!(consumer = {:?}, event = %input.{field}, \"duplicate event skipped\");",
                cons.name
            ));
            commit(&mut c, service);
            c.line("return Ok(());");
            c.close();
        }
        let mut scope = Scope::with_input(&topic.message);
        steps(
            &mut c,
            project,
            service,
            &mut scope,
            &cons.steps,
            None,
            false,
        )?;
        commit(&mut c, service);
        c.line("Ok(())");
        c.close();
    }
    Ok(c.finish())
}

fn job_flows_rs(project: &Project, service: &Service) -> Result<String, CodegenError> {
    let mut c = flows_header("One function per job, built from the steps drawn in the editor.");
    for job in &service.jobs {
        c.blank();
        c.line(format!("/// Every {} s.", job.every_secs));
        c.open(format!(
            "pub async fn {}(ctx: &Ctx) -> anyhow::Result<()>",
            job.name
        ));
        begin(&mut c, service);
        // No request, no event: there is no `input`.
        let mut scope = Scope::default();
        steps(
            &mut c, project, service, &mut scope, &job.steps, None, false,
        )?;
        commit(&mut c, service);
        c.line("Ok(())");
        c.close();
    }
    Ok(c.finish())
}

/// Starts every job of the service on its schedule, and stops them when the service ends.
fn scheduler_rs(service: &Service) -> String {
    let mut c = Code::new();
    c.line(HEADER);
    c.line("//! Runs the jobs of this service on their schedule (see `eda_runtime::jobs`).");
    c.blank();
    c.line("use std::time::Duration;");
    c.blank();
    c.line("use tokio::{sync::watch, task::JoinHandle};");
    c.blank();
    c.line("use crate::{app::ctx::Ctx, flows};");
    c.blank();
    c.line("/// The running jobs. Every instance of the service runs them: their steps must be safe to repeat.");
    c.open("pub struct Scheduler");
    c.line("stop: watch::Sender<bool>,");
    c.line("handles: Vec<JoinHandle<()>>,");
    c.close();
    c.blank();
    c.open("impl Scheduler");
    c.open("pub fn spawn(ctx: &Ctx) -> Self");
    c.line("let (stop, shutdown) = watch::channel(false);");
    c.line("let mut handles = Vec::new();");
    for job in &service.jobs {
        c.line(format!(
            "// `{}` every {} s -> flows::jobs::{}",
            job.name, job.every_secs, job.name
        ));
        c.block();
        c.line("let ctx = ctx.clone();");
        c.line(format!(
            "handles.push(eda_runtime::jobs::spawn_periodic({:?}, Duration::from_secs({}), shutdown.clone(), move || {{",
            job.name, job.every_secs
        ));
        c.line("    let ctx = ctx.clone();");
        c.line(format!(
            "    async move {{ flows::jobs::{}(&ctx).await }}",
            job.name
        ));
        c.line("}));");
        c.close();
    }
    c.line("Self { stop, handles }");
    c.close();
    c.blank();
    c.line("/// Asks the jobs to stop and waits for the runs in progress to finish.");
    c.open("pub async fn stop(self)");
    c.line("let _ = self.stop.send(true);");
    c.open("for handle in self.handles");
    c.line("let _ = handle.await;");
    c.close();
    c.close();
    c.close();
    c.finish()
}

fn steps(
    c: &mut Code,
    project: &Project,
    service: &Service,
    scope: &mut Scope,
    list: &[Step],
    response: Option<&str>,
    reply: bool,
) -> Result<(), CodegenError> {
    for step in list {
        c.line(format!("// {}", describe(step)));
        match step {
            Step::Log { level, message, .. } => {
                c.line(log_code(project, scope, *level, message)?);
            }
            Step::Let {
                name,
                value_type,
                optional,
                repeated,
                value,
                ..
            } => {
                let ty = TypeRef {
                    ty: value_type.clone(),
                    repeated: *repeated,
                    optional: *optional && !*repeated,
                };
                let value = lower(project, scope, value, &ty)?;
                c.line(format!(
                    "let {name}: {} = {value};",
                    rust_let_type(value_type, ty.optional, ty.repeated)
                ));
                scope.bind(name.clone(), ty);
            }
            Step::Publish { topic, payload, .. } => {
                let t = project
                    .topic(topic)
                    .ok_or_else(|| CodegenError::Internal(format!("unknown topic `{topic}`")))?;
                let literal = struct_literal(project, scope, &t.message, payload)?;
                c.block();
                c.line(format!("let event = {literal};"));
                let key = match &t.key_field {
                    Some(key) => {
                        c.line(format!("let key = event.{key}.to_string();"));
                        "Some(&key)"
                    }
                    None => "None",
                };
                c.line(format!(
                    "eda_runtime::outbox::enqueue(&mut tx, topics::{}, {key}, &event).await?;",
                    topic_const(topic)
                ));
                c.close();
            }
            Step::PublishLive {
                service: realtime,
                event,
                account_id,
                tenant_id,
                permission,
                account_ids,
                origin,
                data,
                ..
            } => {
                let target = project
                    .service(realtime)
                    .and_then(|s| s.realtime.as_ref())
                    .ok_or_else(|| {
                        CodegenError::Internal(format!("`{realtime}` is not a real-time service"))
                    })?;
                let id = TypeRef::scalar(FieldType::Uuid);
                // A path or a literal of any text type: the message carries them as text.
                let text = |e: &Expr| -> Result<String, CodegenError> {
                    Ok(format!("({}).to_string()", lower(project, scope, e, &id)?))
                };
                let some = |e: &Option<Expr>| -> Result<String, CodegenError> {
                    Ok(match e {
                        Some(e) => format!("Some({})", text(e)?),
                        None => "None".to_string(),
                    })
                };
                let ids = match account_ids {
                    Some(e) => {
                        let list = TypeRef {
                            repeated: true,
                            ..id.clone()
                        };
                        format!(
                            "({}).iter().map(|id| id.to_string()).collect()",
                            lower(project, scope, e, &list)?
                        )
                    }
                    None => "Vec::new()".to_string(),
                };
                let permission = match permission {
                    Some(p) => format!("Some({p:?})"),
                    None => "None".to_string(),
                };
                let string = TypeRef::scalar(FieldType::String);
                let mut entries = Vec::new();
                for a in data {
                    entries.push(format!(
                        "({:?}, ({}).to_string())",
                        a.field,
                        lower(project, scope, &a.value, &string)?
                    ));
                }
                c.line(format!(
                    "live.push({:?}, eda_runtime::live::Event {{",
                    target.channel
                ));
                c.line(format!("    kind: {event:?},"));
                c.line(format!("    account_id: {},", some(account_id)?));
                c.line(format!("    tenant_id: {},", some(tenant_id)?));
                c.line(format!("    permission: {permission},"));
                c.line(format!("    account_ids: {ids},"));
                c.line(format!("    origin: {},", some(origin)?));
                c.line(format!("    data: vec![{}],", entries.join(", ")));
                c.line("});");
            }
            Step::CallRpc {
                service,
                method,
                request,
                bind,
                ..
            } => {
                let target = project.service(service).ok_or_else(|| {
                    CodegenError::Internal(format!("unknown service `{service}`"))
                })?;
                let rpc = target
                    .rpc(method)
                    .ok_or_else(|| CodegenError::Internal(format!("unknown RPC `{method}`")))?;
                let literal = struct_literal(project, scope, &rpc.request, request)?;
                let call = format!(
                    "ctx.{}.clone().{}({literal}).await?.into_inner()",
                    snake(service),
                    snake(method)
                );
                match bind {
                    Some(var) => {
                        c.line(format!("let {var} = {call};"));
                        scope.bind(var.clone(), TypeRef::message(&rpc.response));
                    }
                    None => {
                        c.line(format!("let _ = {call};"));
                    }
                }
            }
            Step::Branch {
                condition,
                then,
                otherwise,
                ..
            } => {
                c.open(format!("if {}", condition_code(project, scope, condition)?));
                steps(
                    c,
                    project,
                    service,
                    &mut scope.clone(),
                    then,
                    response,
                    reply,
                )?;
                if !otherwise.is_empty() {
                    c.close_open("else");
                    steps(
                        c,
                        project,
                        service,
                        &mut scope.clone(),
                        otherwise,
                        response,
                        reply,
                    )?;
                }
                c.close();
            }
            Step::ForEach {
                item,
                list,
                steps: body,
                ..
            } => {
                let ty = sb_model::typing::expr_type(project, scope, list, None)
                    .map_err(CodegenError::Internal)?
                    .filter(|t| t.repeated)
                    .ok_or_else(|| CodegenError::Internal("a loop needs a list".into()))?;
                c.open(format!(
                    "for {item} in {}",
                    lower(project, scope, list, &ty)?
                ));
                let mut inner = scope.clone();
                inner.bind(
                    item.clone(),
                    TypeRef {
                        repeated: false,
                        ..ty
                    },
                );
                steps(c, project, service, &mut inner, body, response, reply)?;
                c.close();
            }
            Step::Respond {
                fields,
                status,
                cookies,
                headers,
                ..
            } => {
                let response = response.ok_or_else(|| {
                    CodegenError::Internal("Respond used outside of an RPC handler".into())
                })?;
                let literal = struct_literal(project, scope, response, fields)?;
                c.line(format!("let reply = {literal};"));
                commit(c, service);
                if reply {
                    let mut out = "eda_runtime::http::Reply::new(reply)".to_string();
                    if let Some(status) = status {
                        out.push_str(&format!(".status({status})"));
                    }
                    for cookie in cookies {
                        out.push_str(&format!(
                            ".cookie({})",
                            cookie_code(project, scope, cookie)?
                        ));
                    }
                    for header in headers {
                        let value = lower(
                            project,
                            scope,
                            &header.value,
                            &TypeRef::scalar(FieldType::String),
                        )?;
                        out.push_str(&format!(".header({:?}, {value})", header.name));
                    }
                    c.line(format!("return Ok({out});"));
                } else {
                    c.line("return Ok(reply);");
                }
            }
            // Checked by the HTTP handler on the raw body, before it is read as JSON (`transport/http.rs`).
            Step::VerifyHmac { header, .. } => {
                c.line(format!("// signature in `{header}` already verified"));
            }
            Step::RateLimit {
                id,
                key,
                max,
                window_secs,
                shared,
            } => {
                let key = lower(project, scope, key, &TypeRef::scalar(FieldType::String))?;
                if *shared {
                    // Counted in the key-value server, so that every replica sees the same attempts; in memory if it is down.
                    c.line(format!(
                        "eda_runtime::rate_limit::check_shared({id:?}, &({key}), {max}, {window_secs}).await?;"
                    ));
                } else {
                    c.line(format!(
                        "eda_runtime::rate_limit::check({id:?}, &({key}), {max}, {window_secs})?;"
                    ));
                }
            }
            Step::VerifyChallenge { payload, .. } => {
                let cfg = service.challenge.as_ref().ok_or_else(|| {
                    CodegenError::Internal(
                        "`verifyChallenge` in a service with no challenge".into(),
                    )
                })?;
                let payload = lower(project, scope, payload, &TypeRef::scalar(FieldType::String))?;
                c.line(format!(
                    "eda_runtime::challenge::verify(&mut tx, {:?}, {}, &({payload})).await?;",
                    cfg.key_env, cfg.max_number
                ));
            }
            Step::Meter {
                key,
                tenant,
                amount,
                idempotency_key,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let tenant = lower(project, scope, tenant, &text)?;
                let amount = lower(project, scope, amount, &TypeRef::scalar(FieldType::Int64))?;
                let once = match idempotency_key {
                    Some(once) => {
                        format!("Some(({}).as_str())", lower(project, scope, once, &text)?)
                    }
                    None => "None".to_string(),
                };
                c.line(format!(
                    "eda_runtime::usage::meter(&mut tx, {key:?}, &({tenant}), {amount}, {once}).await?;"
                ));
            }
            Step::CheckQuota {
                key,
                tenant,
                limit,
                period,
                wanted,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let units = TypeRef::scalar(FieldType::Int64);
                let tenant = lower(project, scope, tenant, &text)?;
                let limit = lower(project, scope, limit, &units)?;
                let wanted = match wanted {
                    Some(wanted) => lower(project, scope, wanted, &units)?,
                    None => "1_i64".to_string(),
                };
                let period = format!("eda_runtime::usage::Period::{}", period_variant(*period));
                let call = format!(
                    "eda_runtime::usage::check(&mut tx, {key:?}, &({tenant}), {limit}, {wanted}, {period}).await?"
                );
                match bind {
                    Some(bind) => {
                        c.line(format!("let {bind}: i64 = {call};"));
                        scope.bind(bind.clone(), units);
                    }
                    None => {
                        c.line(format!("{call};"));
                    }
                }
            }
            Step::Sql { .. } => sql_step(c, project, service, scope, step)?,
            Step::HttpCall { .. } => crate::http_call::http_call_step(c, project, scope, step)?,
            Step::HashPassword { input, bind, .. } => {
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::hash_password({input}).await?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::VerifyPassword {
                password,
                stored,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let maybe = TypeRef {
                    optional: true,
                    ..text.clone()
                };
                let password = lower(project, scope, password, &text)?;
                let stored = lower(project, scope, stored, &maybe)?;
                c.line(format!(
                    "let {bind}: bool = eda_runtime::crypto::verify_password({password}, {stored}).await;"
                ));
                scope.bind(bind.clone(), TypeRef::scalar(FieldType::Bool));
            }
            Step::Encrypt {
                key_env,
                input,
                bind,
                ..
            }
            | Step::Decrypt {
                key_env,
                input,
                bind,
                ..
            } => {
                let function = if matches!(step, Step::Encrypt { .. }) {
                    "encrypt"
                } else {
                    "decrypt"
                };
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::{function}({key_env:?}, &{input})?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::SignJwt {
                key_env,
                issuer,
                ttl_secs,
                claims,
                bind,
                ..
            } => {
                c.open(format!("let {bind}: String ="));
                c.line("let mut claims = eda_runtime::jwt::Map::new();");
                for claim in claims {
                    let value = claim_json(project, scope, &claim.value)?;
                    c.line(format!(
                        "claims.insert({:?}.to_string(), {value});",
                        claim.field
                    ));
                }
                c.line(format!(
                    "eda_runtime::jwt::sign({key_env:?}, {issuer:?}, {ttl_secs}, claims)?"
                ));
                c.close_with(";");
                scope.bind(bind.clone(), TypeRef::scalar(FieldType::String));
            }
            Step::VerifyJwt {
                token,
                bearer,
                source,
                issuer,
                schema,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let token = lower(project, scope, token, &text)?;
                let source = match source {
                    sb_model::JwksSource::Keys { key_envs } => {
                        let list: Vec<String> = key_envs.iter().map(|k| format!("{k:?}")).collect();
                        format!("eda_runtime::jwt::Source::Keys(&[{}])", list.join(", "))
                    }
                    sb_model::JwksSource::Url { url_env } => {
                        format!("eda_runtime::jwt::Source::Url({url_env:?})")
                    }
                };
                c.open(format!("let {bind}: pb::{schema} ="));
                c.line(format!("let token = {token};"));
                if *bearer {
                    c.line("let token = eda_runtime::jwt::bearer(&token);");
                }
                c.line(format!(
                    "eda_runtime::jwt::claims_into(eda_runtime::jwt::verify({source}, {issuer:?}, {}).await?)?",
                    if *bearer { "token" } else { "&token" }
                ));
                c.close_with(";");
                scope.bind(bind.clone(), TypeRef::message(schema));
            }
            Step::Jwks { key_envs, bind, .. } => {
                let list: Vec<String> = key_envs.iter().map(|k| format!("{k:?}")).collect();
                c.line(format!("let {bind} = pb::Jwks {{"));
                c.line(format!(
                    "    keys: eda_runtime::jwt::public_keys(&[{}])?",
                    list.join(", ")
                ));
                c.line("        .into_iter()");
                c.line("        .map(|k| pb::Jwk { kty: k.kty, crv: k.crv, alg: k.alg, kid: k.kid, x: k.x, ..Default::default() })");
                c.line("        .collect(),");
                c.line("    ..Default::default()");
                c.line("};");
                scope.bind(bind.clone(), TypeRef::message("Jwks"));
            }
            Step::TotpGenerate {
                key_env,
                issuer,
                account,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let account = lower(project, scope, account, &text)?;
                c.line(format!(
                    "let {bind}: pb::TotpSetup = {{ let setup = eda_runtime::totp::generate({key_env:?}, {issuer:?}, &{account})?; pb::TotpSetup {{ sealed: setup.sealed, otpauth_url: setup.otpauth_url, secret: setup.secret, ..Default::default() }} }};"
                ));
                scope.bind(bind.clone(), TypeRef::message("TotpSetup"));
            }
            Step::TotpVerify {
                key_env,
                sealed,
                code,
                account,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let sealed = lower(project, scope, sealed, &text)?;
                let code = lower(project, scope, code, &text)?;
                let account = lower(project, scope, account, &text)?;
                c.line(format!(
                    "eda_runtime::totp::verify(&mut tx, {key_env:?}, &{sealed}, &{code}, &{account}).await?;"
                ));
            }
            Step::RecoveryCodes {
                account,
                count,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let account = lower(project, scope, account, &text)?;
                c.line(format!(
                    "let {bind}: Vec<String> = eda_runtime::totp::issue_recovery_codes(&mut tx, &{account}, {count}).await?;"
                ));
                scope.bind(
                    bind.clone(),
                    TypeRef {
                        repeated: true,
                        ..text
                    },
                );
            }
            Step::RecoveryCodeUse { account, code, .. } => {
                let text = TypeRef::scalar(FieldType::String);
                let account = lower(project, scope, account, &text)?;
                let code = lower(project, scope, code, &text)?;
                c.line(format!(
                    "eda_runtime::totp::use_recovery_code(&mut tx, &{account}, &{code}).await?;"
                ));
            }
            Step::PasskeyRegisterStart {
                account,
                name,
                app_url,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let account = lower(project, scope, account, &text)?;
                let name = lower(project, scope, name, &text)?;
                let app_url = lower_app_url(project, scope, app_url)?;
                c.line(format!(
                    "let {bind}: pb::PasskeyChallenge = {{ let challenge = eda_runtime::webauthn::register_start(&mut tx, &{account}, &{name}, {app_url}).await?; pb::PasskeyChallenge {{ state_id: challenge.state_id, options: challenge.options, ..Default::default() }} }};"
                ));
                scope.bind(bind.clone(), TypeRef::message("PasskeyChallenge"));
            }
            Step::PasskeyRegisterFinish {
                state_id,
                credential,
                account,
                app_url,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let state_id = lower(project, scope, state_id, &text)?;
                let credential = lower(project, scope, credential, &text)?;
                let account = lower(project, scope, account, &text)?;
                let app_url = lower_app_url(project, scope, app_url)?;
                c.line(format!(
                    "eda_runtime::webauthn::register_finish(&mut tx, &{state_id}, &{credential}, &{account}, {app_url}).await?;"
                ));
            }
            Step::PasskeyLoginStart {
                account,
                app_url,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let app_url = lower_app_url(project, scope, app_url)?;
                // Without an account the challenge names nobody (a discoverable login).
                let start = match account {
                    Some(account) => format!(
                        "login_start(&mut tx, &{}, {app_url})",
                        lower(project, scope, account, &text)?
                    ),
                    None => format!("login_discoverable_start(&mut tx, {app_url})"),
                };
                c.line(format!(
                    "let {bind}: pb::PasskeyChallenge = {{ let challenge = eda_runtime::webauthn::{start}.await?; pb::PasskeyChallenge {{ state_id: challenge.state_id, options: challenge.options, ..Default::default() }} }};"
                ));
                scope.bind(bind.clone(), TypeRef::message("PasskeyChallenge"));
            }
            Step::PasskeyLoginFinish {
                state_id,
                credential,
                app_url,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let state_id = lower(project, scope, state_id, &text)?;
                let credential = lower(project, scope, credential, &text)?;
                let app_url = lower_app_url(project, scope, app_url)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::webauthn::login_finish(&mut tx, &{state_id}, &{credential}, {app_url}).await?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::ImageSniff {
                input,
                allow,
                max_bytes,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                let allow: Vec<String> =
                    allow.iter().map(|k| format!("{:?}", k.as_str())).collect();
                c.line(format!(
                    "let {bind}: String = eda_runtime::s3::sniff_image(&{input}, &[{}], {max_bytes})?.to_string();",
                    allow.join(", ")
                ));
                scope.bind(bind.clone(), text);
            }
            Step::ObjectPut {
                bucket_env,
                key,
                body,
                content_type,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let key = lower(project, scope, key, &text)?;
                let body = lower(project, scope, body, &text)?;
                let content_type = lower(project, scope, content_type, &text)?;
                c.line(format!(
                    "eda_runtime::s3::put({bucket_env:?}, &{key}, &{body}, &{content_type}).await?;"
                ));
            }
            Step::ObjectGet {
                bucket_env,
                key,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let key = lower(project, scope, key, &text)?;
                c.line(format!(
                    "let {bind}: Option<String> = eda_runtime::s3::get({bucket_env:?}, &{key}).await?;"
                ));
                scope.bind(
                    bind.clone(),
                    TypeRef {
                        optional: true,
                        ..text
                    },
                );
            }
            Step::ObjectPresignGet {
                bucket_env,
                key,
                expires_secs,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let key = lower(project, scope, key, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::s3::presign_get({bucket_env:?}, &{key}, {expires_secs}).await?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::ObjectPresignPut {
                bucket_env,
                key,
                content_type,
                size,
                max_bytes,
                expires_secs,
                bind,
                ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let int = TypeRef::scalar(FieldType::Int64);
                let key = lower(project, scope, key, &text)?;
                let content_type = lower(project, scope, content_type, &text)?;
                let size = lower(project, scope, size, &int)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::s3::presign_put({bucket_env:?}, &{key}, &{content_type}, {size}, {max_bytes}, {expires_secs}).await?;"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::ObjectDelete {
                bucket_env, key, ..
            } => {
                let text = TypeRef::scalar(FieldType::String);
                let key = lower(project, scope, key, &text)?;
                c.line(format!(
                    "eda_runtime::s3::delete({bucket_env:?}, &{key}).await?;"
                ));
            }
            Step::RandomToken { bind, .. } => {
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::random_token();"
                ));
                scope.bind(bind.clone(), TypeRef::scalar(FieldType::String));
            }
            Step::Sha256 { input, bind, .. } => {
                let text = TypeRef::scalar(FieldType::String);
                let input = lower(project, scope, input, &text)?;
                c.line(format!(
                    "let {bind}: String = eda_runtime::crypto::sha256_hex(&{input});"
                ));
                scope.bind(bind.clone(), text);
            }
            Step::Fail {
                status,
                message,
                retry_after,
                ..
            } => {
                // The transaction is dropped with the early return: nothing the flow wrote is kept.
                c.line(format!(
                    "let error = eda_runtime::http::HttpError::new({status}, {message:?});"
                ));
                if let Some(wait) = retry_after {
                    let seconds = lower(project, scope, wait, &TypeRef::scalar(FieldType::Int64))?;
                    c.line(format!(
                        "let error = error.with_retry_after(u64::try_from({seconds}).unwrap_or(0));"
                    ));
                }
                c.line("return Err(error.into());");
            }
            Step::Code { code, .. } => {
                c.line(code.trim_end());
            }
        }
    }
    Ok(())
}

/// `Cookie::new(name, value)` with the attributes that differ from the safe defaults.
fn cookie_code(
    project: &Project,
    scope: &Scope,
    cookie: &sb_model::Cookie,
) -> Result<String, CodegenError> {
    let value = lower(
        project,
        scope,
        &cookie.value,
        &TypeRef::scalar(FieldType::String),
    )?;
    let mut out = format!("eda_runtime::http::Cookie::new({:?}, {value})", cookie.name);
    if let Some(seconds) = cookie.max_age_secs {
        out.push_str(&format!(".max_age({seconds})"));
    }
    if let Some(path) = &cookie.path {
        out.push_str(&format!(".path({path:?})"));
    }
    if !cookie.http_only {
        out.push_str(".http_only(false)");
    }
    if !cookie.secure {
        out.push_str(".secure(false)");
    }
    match cookie.same_site {
        sb_model::SameSite::Lax => {}
        sb_model::SameSite::Strict => {
            out.push_str(".same_site(eda_runtime::http::SameSite::Strict)")
        }
        sb_model::SameSite::None => out.push_str(".same_site(eda_runtime::http::SameSite::None)"),
    }
    Ok(out)
}

// ---- SQL step --------------------------------------------------------------------------

fn quoted(ident: &str) -> String {
    format!("\"{ident}\"")
}

/// Rust type of a column value, as read by `Row::try_get`.
fn column_rust(col: &Column) -> String {
    let base = match col.ty.field_type() {
        FieldType::Bool => "bool",
        FieldType::Int32 => "i32",
        FieldType::Int64 => "i64",
        FieldType::Float => "f32",
        FieldType::Double => "f64",
        _ => "String",
    };
    if col.nullable {
        format!("Option<{base}>")
    } else {
        base.to_string()
    }
}

/// What a flow sees for a column (nullable columns are optional).
fn column_type_ref(col: &Column) -> TypeRef {
    let mut t = TypeRef::scalar(col.ty.field_type());
    t.optional = col.nullable;
    t
}

/// The placeholder of the n-th parameter, cast back to the database type of a text-cast column.
fn placeholder(n: usize, col: &Column) -> String {
    if col.ty.is_text_cast() {
        format!("${n}::{}", col.ty.sql().to_lowercase())
    } else {
        format!("${n}")
    }
}

/// The variant of `eda_runtime::usage::Period` for a period of the model.
fn period_variant(period: sb_model::UsagePeriod) -> &'static str {
    match period {
        sb_model::UsagePeriod::Hour => "Hour",
        sb_model::UsagePeriod::Day => "Day",
        sb_model::UsagePeriod::Month => "Month",
        sb_model::UsagePeriod::Year => "Year",
        sb_model::UsagePeriod::Forever => "Forever",
    }
}

/// The page size or the offset of a select as an `Option<i64>`: a whole number from the flow (int32 or int64, optional or
/// not), or written in the step.
fn lower_int(project: &Project, scope: &Scope, expr: &Expr) -> Result<String, CodegenError> {
    match expr {
        // A path, a text or an operation: its type comes from the one typing table.
        Expr::Path { .. } | Expr::Template { .. } | Expr::Call { .. } => {
            let ty = sb_model::typing::expr_type(project, scope, expr, None)
                .map_err(CodegenError::Internal)?
                .ok_or_else(|| CodegenError::Internal("untyped page size".into()))?;
            let code = lower(project, scope, expr, &ty)?;
            Ok(if ty.optional {
                format!("{code}.map(|v| v as i64)")
            } else {
                format!("Some({code} as i64)")
            })
        }
        Expr::Literal { value } => match value.as_i64() {
            Some(n) => Ok(format!("Some({n}_i64)")),
            None => Err(CodegenError::Internal(
                "a page size or an offset is a whole number".into(),
            )),
        },
        Expr::Raw { code } => Ok(format!("Some(({}) as i64)", code.trim())),
        Expr::Now => Err(CodegenError::Internal("`now()` is not a page size".into())),
    }
}

fn sql_step(
    c: &mut Code,
    project: &Project,
    service: &Service,
    scope: &mut Scope,
    step: &Step,
) -> Result<(), CodegenError> {
    let Step::Sql {
        id,
        op,
        table,
        bind,
        columns,
        many,
        into,
        conditions,
        values,
        order_by,
        descending,
        limit,
        missing,
        joins,
        then_by,
        limit_from,
        offset,
        cursor,
        total_bind,
        more_bind,
        last_bind,
    } = step
    else {
        return Ok(());
    };
    let t = service
        .table(table)
        .ok_or_else(|| CodegenError::Internal(format!("unknown table `{table}`")))?;
    // What the table adds on its own: the tenant of the rows, and the rows a soft delete keeps out of sight. The author
    // writes neither (the validator refuses it).
    let (mut op, mut conditions, mut values) = (*op, conditions.clone(), values.clone());
    let mut live_only = false;
    if let Some(tenant) = &t.tenant_column {
        let own = Expr::Path {
            path: tenant.clone(),
        };
        if op == SqlOp::Insert {
            values.push(sb_model::Assignment {
                field: tenant.clone(),
                value: own,
            });
        } else {
            conditions.push(sb_model::SqlCondition::new(
                tenant.clone(),
                sb_model::CmpOp::Eq,
                own,
            ));
        }
    }
    if t.soft_delete && op != SqlOp::Insert {
        live_only = true;
        if op == SqlOp::Delete {
            // Nothing is removed: the row is marked, and `RETURNING` still gives it back.
            op = SqlOp::Update;
            values = vec![sb_model::Assignment {
                field: sb_model::DELETED_AT.to_string(),
                value: Expr::Now,
            }];
        }
    }
    let (op, conditions, values) = (&op, &conditions, &values);
    let col = |name: &str| {
        t.column(name).ok_or_else(|| {
            CodegenError::Internal(format!("table `{table}` has no column `{name}`"))
        })
    };
    // With joins every column is written with its table; without, the statement is the one it always was.
    let joined = !joins.is_empty();
    let qual = |owner: &str, column: &Column| {
        if joined {
            format!("{}.{}", quoted(owner), quoted(&column.name))
        } else {
            quoted(&column.name)
        }
    };
    let resolve = |name: &str| {
        service
            .sql_column(table, joins, name)
            .ok_or_else(|| CodegenError::Internal(format!("`{name}` is not a column of the query")))
    };

    // Parameters, in the order of the placeholders: the values written, then the joins, then the WHERE. The database clock
    // (`now()`) is part of the statement itself and takes no parameter.
    let mut binds: Vec<String> = Vec::new();
    let mut set_sql = Vec::new();
    for a in values {
        let column = col(&a.field)?;
        if matches!(a.value, Expr::Now) {
            set_sql.push((quoted(&column.name), "now()".to_string()));
            continue;
        }
        binds.push(lower(project, scope, &a.value, &column_type_ref(column))?);
        set_sql.push((quoted(&column.name), placeholder(binds.len(), column)));
    }
    // The rules of every joined table are in its `ON`, so that a left join stays a left join: a row of the other tenant, or
    // a deleted one, is no match rather than a reason to drop the row.
    let mut from = quoted(table);
    for j in joins {
        let jt = service
            .table(&j.table)
            .ok_or_else(|| CodegenError::Internal(format!("unknown table `{}`", j.table)))?;
        let mut on = Vec::new();
        for pair in &j.on {
            let (lt, lc, _) = resolve(&pair.column)?;
            let rc = jt.column(&pair.ref_column).ok_or_else(|| {
                CodegenError::Internal(format!("`{}` has no column `{}`", j.table, pair.ref_column))
            })?;
            on.push(format!("{} = {}", qual(&lt.name, lc), qual(&jt.name, rc)));
        }
        if let Some(tenant) = &jt.tenant_column {
            let tc = jt.column(tenant).ok_or_else(|| {
                CodegenError::Internal(format!("`{}` has no column `{tenant}`", j.table))
            })?;
            binds.push(lower(
                project,
                scope,
                &Expr::Path {
                    path: tenant.clone(),
                },
                &column_type_ref(tc),
            )?);
            on.push(format!(
                "{} = {}",
                qual(&jt.name, tc),
                placeholder(binds.len(), tc)
            ));
        }
        if jt.soft_delete {
            on.push(format!(
                "{}.{} IS NULL",
                quoted(&jt.name),
                quoted(sb_model::DELETED_AT)
            ));
        }
        from.push_str(&format!(
            " {} {} ON {}",
            match j.kind {
                sb_model::SqlJoinKind::Inner => "INNER JOIN",
                sb_model::SqlJoinKind::Left => "LEFT JOIN",
            },
            quoted(&jt.name),
            on.join(" AND ")
        ));
    }
    let mut where_sql = Vec::new();
    for cond in conditions {
        let (ct, column, _) = resolve(&cond.column)?;
        let lhs = qual(&ct.name, column);
        match cond.test {
            sb_model::SqlTest::Compare => {
                let right = if matches!(cond.value, Expr::Now) {
                    "now()".to_string()
                } else {
                    binds.push(lower(
                        project,
                        scope,
                        &cond.value,
                        &column_type_ref(column),
                    )?);
                    placeholder(binds.len(), column)
                };
                where_sql.push(format!("{lhs} {} {right}", cond.sql_op()));
            }
            sb_model::SqlTest::In => {
                let list = TypeRef {
                    repeated: true,
                    ..TypeRef::scalar(column.ty.field_type())
                };
                binds.push(lower(project, scope, &cond.value, &list)?);
                let cast = if column.ty.is_text_cast() {
                    format!("::{}[]", column.ty.sql().to_lowercase())
                } else {
                    String::new()
                };
                where_sql.push(format!("{lhs} = ANY(${}{cast})", binds.len()));
            }
            sb_model::SqlTest::Contains | sb_model::SqlTest::StartsWith => {
                let text = lower(
                    project,
                    scope,
                    &cond.value,
                    &TypeRef::scalar(sb_model::FieldType::String),
                )?;
                // `%` and `_` of the value are text, not wildcards: the escape character is the backslash.
                let escaped = format!(
                    r#"({text}).replace('\\', "\\\\").replace('%', "\\%").replace('_', "\\_")"#
                );
                binds.push(if cond.test == sb_model::SqlTest::Contains {
                    format!(r#"format!("%{{}}%", {escaped})"#)
                } else {
                    format!(r#"format!("{{}}%", {escaped})"#)
                });
                where_sql.push(format!("{lhs} ILIKE ${} ESCAPE '\\'", binds.len()));
            }
            sb_model::SqlTest::IsNull => where_sql.push(format!("{lhs} IS NULL")),
            sb_model::SqlTest::IsNotNull => where_sql.push(format!("{lhs} IS NOT NULL")),
        }
    }
    if live_only {
        where_sql.push(format!(
            "{} IS NULL",
            qual(table, col(sb_model::DELETED_AT)?)
        ));
    }
    let where_of = |parts: &[String]| {
        if parts.is_empty() {
            String::new()
        } else {
            format!(" WHERE {}", parts.join(" AND "))
        }
    };
    // What a count has to repeat: the statement as it is before the page is cut.
    let counted = (binds.len(), where_of(&where_sql));

    // Keyset pagination: the rows after the one the cursor names, in the order of the sort. Each key is compared once the
    // keys before it are equal, so it works with any mix of directions. An absent first value reads the first page.
    let sort: Vec<(&str, bool)> = order_by
        .iter()
        .map(|o| (o.as_str(), *descending))
        .chain(then_by.iter().map(|k| (k.column.as_str(), k.descending)))
        .collect();
    if *op == SqlOp::Select && !cursor.is_empty() {
        let mut keys = Vec::new();
        for ((name, desc), value) in sort.iter().zip(cursor) {
            let (kt, kc, _) = resolve(name)?;
            let mut want = column_type_ref(kc);
            want.optional = true;
            binds.push(lower(project, scope, value, &want)?);
            let ph = format!("${}::{}", binds.len(), kc.ty.sql().to_lowercase());
            keys.push((qual(&kt.name, kc), *desc, ph));
        }
        let mut any = Vec::new();
        for i in 0..keys.len() {
            let mut all: Vec<String> = keys[..i]
                .iter()
                .map(|(k, _, ph)| format!("{k} = {ph}"))
                .collect();
            let (k, desc, ph) = &keys[i];
            all.push(format!("{k} {} {ph}", if *desc { "<" } else { ">" }));
            any.push(format!("({})", all.join(" AND ")));
        }
        if let Some((_, _, first)) = keys.first() {
            where_sql.push(format!("({first} IS NULL OR {})", any.join(" OR ")));
        }
    }
    let where_clause = where_of(&where_sql);

    let query = |sql: &str, binds: &[String]| -> String {
        let mut q = format!("sqlx::query({sql:?})");
        for b in binds {
            q.push_str(&format!(".bind({b})"));
        }
        q
    };

    // The columns a select reads, or that an insert, update or delete gives back (`RETURNING`).
    let outs = service.sql_out_columns(table, joins, columns);
    let exprs: Vec<String> = outs
        .iter()
        .map(|o| {
            let name = qual(&o.table.name, o.column);
            let alias = quoted(&o.field);
            match o.column.ty {
                // ISO 8601 / RFC 3339, in UTC, whatever the session time zone.
                ColumnType::Timestamp => format!(
                    "to_char({name} AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') AS {alias}"
                ),
                ColumnType::Uuid | ColumnType::Jsonb => format!("{name}::text AS {alias}"),
                _ if joined => format!("{name} AS {alias}"),
                _ => name,
            }
        })
        .collect();

    // The page: a size and an offset asked by the flow, held to the bounds the author gave.
    let var = bind.as_deref();
    let paged_size = limit_from.is_some() || more_bind.is_some();
    let max = limit.unwrap_or(1);
    if *op == SqlOp::Select && *many && (paged_size || offset.is_some()) {
        let v = var.unwrap_or("rows");
        if paged_size {
            let asked = match limit_from {
                Some(e) => lower_int(project, scope, e)?,
                None => "None".to_string(),
            };
            c.line(format!(
                "let {v}_sql_limit: i64 = {asked}.unwrap_or({max}_i64).clamp(1, {max}_i64);"
            ));
        }
        if let Some(e) = offset {
            c.line(format!(
                "let {v}_sql_offset: i64 = {}.unwrap_or(0).clamp(0, 1_000_000_i64);",
                lower_int(project, scope, e)?
            ));
        }
    }

    let mut sql = match op {
        SqlOp::Insert => {
            let names: Vec<_> = set_sql.iter().map(|(n, _)| n.as_str()).collect();
            let params: Vec<_> = set_sql.iter().map(|(_, p)| p.as_str()).collect();
            format!(
                "INSERT INTO {} ({}) VALUES ({})",
                quoted(table),
                names.join(", "),
                params.join(", ")
            )
        }
        SqlOp::Update => {
            let sets: Vec<_> = set_sql.iter().map(|(n, p)| format!("{n} = {p}")).collect();
            format!(
                "UPDATE {} SET {}{where_clause}",
                quoted(table),
                sets.join(", ")
            )
        }
        SqlOp::Delete => format!("DELETE FROM {}{where_clause}", quoted(table)),
        SqlOp::Select => {
            let mut sql = format!("SELECT {} FROM {from}{where_clause}", exprs.join(", "));
            if !sort.is_empty() {
                let keys: Result<Vec<String>, CodegenError> = sort
                    .iter()
                    .map(|(name, desc)| {
                        let (kt, kc, _) = resolve(name)?;
                        Ok(format!(
                            "{}{}",
                            qual(&kt.name, kc),
                            if *desc { " DESC" } else { "" }
                        ))
                    })
                    .collect();
                sql.push_str(&format!(" ORDER BY {}", keys?.join(", ")));
            }
            let v = var.unwrap_or("rows");
            if !*many {
                sql.push_str(" LIMIT 1");
            } else if paged_size {
                binds.push(if more_bind.is_some() {
                    format!("{v}_sql_limit + 1")
                } else {
                    format!("{v}_sql_limit")
                });
                sql.push_str(&format!(" LIMIT ${}", binds.len()));
            } else if let Some(n) = limit {
                sql.push_str(&format!(" LIMIT {n}"));
            }
            if offset.is_some() && *many {
                binds.push(format!("{v}_sql_offset"));
                sql.push_str(&format!(" OFFSET ${}", binds.len()));
            }
            sql
        }
    };

    // Nothing to read back: run it.
    if *op != SqlOp::Select && columns.is_empty() {
        c.line(format!("{}.execute(&mut *tx).await?;", query(&sql, &binds)));
        return Ok(());
    }
    if *op != SqlOp::Select {
        sql.push_str(&format!(" RETURNING {}", exprs.join(", ")));
    }
    let var = var.ok_or_else(|| {
        CodegenError::Internal("a SQL step that reads rows needs a variable".into())
    })?;
    // What the route answers when one row was expected and none came back.
    let missing_error = match missing {
        Some(m) => format!(
            "eda_runtime::http::HttpError::new({}, {:?})",
            m.status, m.message
        ),
        None => format!("eda_runtime::http::HttpError::not_found(\"{table}: no row matches\")"),
    };
    let fill = |target: &str, fields: Vec<&str>| {
        let mut lit = format!("{target} {{\n");
        for f in fields {
            lit.push_str(&format!("    {f}: row.try_get({f:?})?,\n"));
        }
        lit
    };
    // The number of rows that match, whatever the page.
    if let Some(total) = total_bind {
        let mut q = format!(
            "sqlx::query_scalar::<_, i64>({:?})",
            format!("SELECT count(*) FROM {from}{}", counted.1)
        );
        for b in &binds[..counted.0] {
            q.push_str(&format!(".bind({b})"));
        }
        c.line(format!(
            "let {total}: i64 = {q}.fetch_one(&mut *tx).await?;"
        ));
        scope.bind(total, TypeRef::scalar(sb_model::FieldType::Int64));
    }
    match (into, many) {
        (Some(schema), true) => {
            let ty = format!("pb::{schema}");
            let msg = project
                .message(schema)
                .ok_or_else(|| CodegenError::Internal(format!("unknown message `{schema}`")))?;
            let lit = fill(&ty, msg.fields.iter().map(|f| f.name.as_str()).collect());
            if let Some(more) = more_bind {
                // One row more than the page was read: its presence is the answer, and it is not part of the page.
                c.line(format!(
                    "let mut {var}_sql_raw = {}.fetch_all(&mut *tx).await?;",
                    query(&sql, &binds)
                ));
                c.line(format!(
                    "let {more}: bool = {var}_sql_raw.len() > {var}_sql_limit as usize;"
                ));
                c.line(format!("{var}_sql_raw.truncate({var}_sql_limit as usize);"));
                c.line(format!("let {var}: Vec<{ty}> = {var}_sql_raw"));
                scope.bind(more, TypeRef::scalar(sb_model::FieldType::Bool));
            } else {
                c.line(format!("let {var}: Vec<{ty}> = {}", query(&sql, &binds)));
                c.line("    .fetch_all(&mut *tx)");
                c.line("    .await?");
            }
            c.line("    .iter()");
            c.line(format!("    .map(|row| -> anyhow::Result<{ty}> {{"));
            c.line(format!(
                "        Ok({lit}        ..Default::default()\n    }})"
            ));
            c.line("    })");
            c.line("    .collect::<anyhow::Result<Vec<_>>>()?;");
            scope.bind(
                var,
                TypeRef {
                    repeated: true,
                    ..TypeRef::message(schema)
                },
            );
            if let Some(last) = last_bind {
                c.line(format!(
                    "let {last}: {ty} = {var}.last().cloned().unwrap_or_default();"
                ));
                scope.bind(last, TypeRef::message(schema));
            }
        }
        (_, true) => {
            return Err(CodegenError::Internal(
                "a list of rows needs a schema to convert them into".into(),
            ));
        }
        (found, false) => {
            let (ty, lit, bound) = match found {
                Some(schema) => {
                    let msg = project.message(schema).ok_or_else(|| {
                        CodegenError::Internal(format!("unknown message `{schema}`"))
                    })?;
                    let ty = format!("pb::{schema}");
                    let lit = fill(&ty, msg.fields.iter().map(|f| f.name.as_str()).collect());
                    (
                        ty,
                        format!("{lit}    ..Default::default()\n}}"),
                        TypeRef::message(schema),
                    )
                }
                None => {
                    let name = sql_row_name(table, id);
                    let lit = fill(&name, outs.iter().map(|o| o.field.as_str()).collect());
                    (
                        name,
                        format!("{lit}}}"),
                        TypeRef::message(sql_row_name(table, id)),
                    )
                }
            };
            c.open(format!("let {var} = "));
            if into.is_none() {
                // The row is a struct of its own, local to the step.
                c.line(format!("struct {ty} {{"));
                for o in &outs {
                    let mut shown = o.column.clone();
                    shown.nullable = o.optional;
                    c.line(format!("    {}: {},", o.field, column_rust(&shown)));
                }
                c.line("}");
            }
            c.line(format!("let row = {}", query(&sql, &binds)));
            c.line("    .fetch_optional(&mut *tx)");
            c.line("    .await?");
            c.line(format!("    .ok_or_else(|| {missing_error})?;"));
            c.line(lit);
            c.close_with(";");
            scope.bind(var, bound);
        }
    }
    Ok(())
}

fn describe(step: &Step) -> String {
    match step {
        Step::Log { .. } => "log".into(),
        Step::Let { name, .. } => format!("let {name}"),
        Step::Publish { topic, .. } => format!("publish to {topic}"),
        Step::PublishLive { event, .. } => format!("push `{event}` to the browsers"),
        Step::CallRpc {
            service, method, ..
        } => format!("call {service}.{method}"),
        Step::Branch { .. } => "branch".into(),
        Step::ForEach { item, .. } => format!("for each {item}"),
        Step::Respond { .. } => "respond".into(),
        Step::Fail { status, .. } => format!("fail {status}"),
        Step::VerifyHmac { header, .. } => format!("verify the signature in {header}"),
        Step::RateLimit {
            max,
            window_secs,
            shared,
            ..
        } => format!(
            "rate limit {max} per {window_secs}s{}",
            if *shared { " (shared)" } else { "" }
        ),
        Step::VerifyChallenge { .. } => "verify the challenge".into(),
        Step::Meter { key, .. } => format!("meter {key}"),
        Step::CheckQuota { key, .. } => format!("check the quota of {key}"),
        Step::HashPassword { bind, .. } => format!("hash password into {bind}"),
        Step::VerifyPassword { bind, .. } => format!("verify password into {bind}"),
        Step::RandomToken { bind, .. } => format!("random token into {bind}"),
        Step::Sha256 { bind, .. } => format!("sha256 into {bind}"),
        Step::Encrypt { bind, .. } => format!("encrypt into {bind}"),
        Step::SignJwt { bind, .. } => format!("sign a token into {bind}"),
        Step::VerifyJwt { bind, .. } => format!("verify a token into {bind}"),
        Step::Jwks { bind, .. } => format!("publish the public keys into {bind}"),
        Step::TotpGenerate { bind, .. } => format!("enrol an authenticator app into {bind}"),
        Step::PasskeyRegisterStart { bind, .. } => {
            format!("start a passkey registration into {bind}")
        }
        Step::PasskeyRegisterFinish { .. } => "finish a passkey registration".into(),
        Step::PasskeyLoginStart { bind, .. } => format!("start a passkey login into {bind}"),
        Step::PasskeyLoginFinish { bind, .. } => format!("finish a passkey login into {bind}"),
        Step::ImageSniff { bind, .. } => format!("recognise the image into {bind}"),
        Step::ObjectPut { .. } => "store an object".into(),
        Step::ObjectGet { bind, .. } => format!("read an object into {bind}"),
        Step::ObjectDelete { .. } => "delete an object".into(),
        Step::ObjectPresignGet { bind, .. } => format!("sign a download URL into {bind}"),
        Step::ObjectPresignPut { bind, .. } => format!("sign an upload URL into {bind}"),
        Step::TotpVerify { .. } => "verify a TOTP code".into(),
        Step::RecoveryCodes { bind, .. } => format!("issue recovery codes into {bind}"),
        Step::RecoveryCodeUse { .. } => "spend a recovery code".into(),
        Step::Decrypt { bind, .. } => format!("decrypt into {bind}"),
        Step::Sql { op, table, .. } => format!(
            "sql {} {table}",
            match op {
                SqlOp::Select => "select from",
                SqlOp::Insert => "insert into",
                SqlOp::Update => "update",
                SqlOp::Delete => "delete from",
            }
        ),
        Step::HttpCall {
            method,
            bind,
            status_bind,
            ..
        } => match (bind, status_bind) {
            (Some(var), _) | (None, Some(var)) => {
                format!("{} an external API into {var}", method.as_str())
            }
            _ => format!("{} an external API", method.as_str()),
        },
        Step::Code { .. } => "custom code".into(),
    }
}
