//! The GraphQL schema (SDL) of a service that asks for it (`Service::graphql`): one type per table, a read query by key and a
//! paginated connection per table, and the relations the foreign keys draw (a child points to its parent, a parent lists its
//! children). The columns that hold the tenant are left out: the tenant is never a client's to read or choose.
//!
//! Only the schema is generated: it is what a frontend reads to know what a single call will be able to fetch.

use sb_model::names::pascal;
use sb_model::names::shouty;
use sb_model::{
    BodyFormat, Column, ColumnType, GraphqlSourceField, HttpMethod, Route, Service, ServiceKind,
    Table,
};

use crate::writer::Code;

fn scalar(ty: ColumnType) -> &'static str {
    match ty {
        ColumnType::String => "String",
        ColumnType::Bool => "Boolean",
        ColumnType::Int32 => "Int",
        ColumnType::Int64 => "Long",
        ColumnType::Float | ColumnType::Double => "Float",
        ColumnType::Timestamp => "DateTime",
        ColumnType::Uuid => "ID",
        ColumnType::Jsonb => "JSON",
    }
}

fn camel(s: &str) -> String {
    let p = pascal(s);
    let mut chars = p.chars();
    chars
        .next()
        .map(|f| f.to_lowercase().chain(chars).collect())
        .unwrap_or_default()
}

fn exposed(table: &Table) -> impl Iterator<Item = &Column> {
    table
        .columns
        .iter()
        .filter(move |c| table.tenant_column.as_deref() != Some(c.name.as_str()))
}

fn column_type(c: &Column) -> String {
    let t = scalar(c.ty);
    if c.nullable {
        t.into()
    } else {
        format!("{t}!")
    }
}

/// The name of the field a foreign key adds to the child: `author_id` gives `author`, and a name already taken by a column
/// gets `Ref` appended.
fn parent_field(table: &Table, column: &str) -> String {
    let base = camel(column.strip_suffix("_id").unwrap_or(column));
    if table.columns.iter().any(|c| camel(&c.name) == base) {
        format!("{base}Ref")
    } else {
        base
    }
}

/// The name of the list a parent gets for the rows pointing at it.
fn children_field(parent: &Table, child: &Table) -> String {
    let base = camel(&child.name);
    if parent.columns.iter().any(|c| camel(&c.name) == base) {
        format!("{base}Rows")
    } else {
        base
    }
}

/// Whether the service is a gateway: it asked for GraphQL, owns no table and declares sources to read.
pub fn is_gateway(service: &Service) -> bool {
    service.graphql
        && service.kind == ServiceKind::Standard
        && service.tables.is_empty()
        && !service.graphql_sources.is_empty()
}

fn source_prop(f: &GraphqlSourceField) -> String {
    format!(
        "Prop {{ name: {:?}, field: {:?}, scalar: {:?}, nullable: {} }}",
        f.name,
        camel(&f.name),
        scalar(f.ty),
        f.nullable
    )
}

fn gateway_sdl(service: &Service) -> String {
    let mut c = Code::new();
    c.line("# @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line(format!(
        "# GraphQL schema of the `{}` gateway: it reads the services behind it.",
        service.name
    ));
    c.blank();
    for s in ["DateTime", "JSON", "Long"] {
        c.line(format!("scalar {s}"));
    }
    let mut query = Vec::new();
    for src in &service.graphql_sources {
        c.blank();
        c.line(format!("type {} {{", src.name));
        for f in &src.fields {
            let bang = if f.nullable { "" } else { "!" };
            c.line(format!("  {}: {}{bang}", camel(&f.name), scalar(f.ty)));
        }
        for r in &src.relations {
            if r.many {
                c.line(format!("  {}: [{}!]!", camel(&r.field), r.target));
            } else {
                c.line(format!("  {}: {}", camel(&r.field), r.target));
            }
        }
        c.line("}");
        let q = camel(&src.name);
        if let Some(key) = src
            .key
            .as_ref()
            .and_then(|k| src.fields.iter().find(|f| &f.name == k))
        {
            query.push(format!(
                "  {q}({}: {}!): {}",
                camel(&key.name),
                scalar(key.ty),
                src.name
            ));
        }
        query.push(format!("  {q}List(first: Int): [{}!]!", src.name));
    }
    c.blank();
    c.line("type Query {");
    for q in query {
        c.line(q);
    }
    c.line("}");
    c.finish()
}

/// The routes a client can call as mutations: the `POST`/`PUT`/`PATCH`/`DELETE` routes of a service that serves its tables (a
/// CSV body is a file, not a GraphQL value). The mutation plays the route itself, so its validation, its tenant and its errors
/// are the route's.
fn mutation_routes(service: &Service) -> Vec<&Route> {
    if is_gateway(service) || !service.graphql || service.tables.is_empty() {
        return Vec::new();
    }
    service
        .routes
        .iter()
        .filter(|r| r.method != HttpMethod::Get && r.body_format != BodyFormat::Csv)
        .collect()
}

/// Whether the endpoint of the service has mutations (the runtime then needs the HTTP client to call the routes).
pub fn serves_mutations(service: &Service) -> bool {
    serves_endpoint(service) && !mutation_routes(service).is_empty()
}

/// The `{params}` of a route path.
fn path_params(path: &str) -> Vec<&str> {
    path.split('{')
        .skip(1)
        .filter_map(|rest| rest.split_once('}').map(|(name, _)| name))
        .collect()
}

/// The SDL of the service, or `None` when it has not asked for it or has nothing to describe.
pub fn sdl(service: &Service) -> Option<String> {
    if is_gateway(service) {
        return Some(gateway_sdl(service));
    }
    if !service.graphql || service.kind != ServiceKind::Standard || service.tables.is_empty() {
        return None;
    }
    let mut c = Code::new();
    c.line("# @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line(format!(
        "# GraphQL schema of the `{}` service.",
        service.name
    ));
    c.blank();
    for s in ["DateTime", "JSON", "Long"] {
        c.line(format!("scalar {s}"));
    }
    c.blank();
    c.line("type PageInfo {");
    c.line("  hasNextPage: Boolean!");
    c.line("  endCursor: String");
    c.line("}");

    let mut query = Vec::new();
    for t in &service.tables {
        let ty = pascal(&t.name);
        let name = camel(&t.name);
        c.blank();
        c.line(format!("type {ty} {{"));
        for col in exposed(t) {
            c.line(format!("  {}: {}", camel(&col.name), column_type(col)));
        }
        for fk in t.foreign_keys.iter().filter(|f| f.columns.len() == 1) {
            let nullable = t
                .columns
                .iter()
                .find(|col| col.name == fk.columns[0])
                .is_some_and(|col| col.nullable);
            let bang = if nullable { "" } else { "!" };
            c.line(format!(
                "  {}: {}{bang}",
                parent_field(t, &fk.columns[0]),
                pascal(&fk.ref_table)
            ));
        }
        for child in &service.tables {
            let points_here = child
                .foreign_keys
                .iter()
                .any(|f| f.columns.len() == 1 && f.ref_table == t.name);
            if points_here {
                c.line(format!(
                    "  {}(first: Int, after: String): {}Connection!",
                    children_field(t, child),
                    pascal(&child.name)
                ));
            }
        }
        c.line("}");
        c.blank();
        c.line(format!("type {ty}Edge {{"));
        c.line(format!("  node: {ty}!"));
        c.line("  cursor: String!");
        c.line("}");
        c.blank();
        c.line(format!("type {ty}Connection {{"));
        c.line(format!("  edges: [{ty}Edge!]!"));
        c.line("  pageInfo: PageInfo!");
        c.line("}");

        let keys: Vec<String> = exposed(t)
            .filter(|col| col.primary_key)
            .map(|col| format!("{}: {}!", camel(&col.name), scalar(col.ty)))
            .collect();
        if !keys.is_empty() {
            query.push(format!("  {name}({}): {ty}", keys.join(", ")));
        }
        query.push(format!(
            "  {name}Connection(first: Int, after: String): {ty}Connection!"
        ));
    }
    c.blank();
    c.line("type Query {");
    for q in query {
        c.line(q);
    }
    c.line("}");
    let mutations = mutation_routes(service);
    if !mutations.is_empty() {
        c.blank();
        c.line("# One mutation per route: `input` holds the fields of the body and the {params} of the path;");
        c.line("# the answer is the body of the route.");
        c.line("type Mutation {");
        for r in mutations {
            c.line(format!("  # {:?} {}", r.method, r.path));
            c.line(format!("  {}(input: JSON): JSON", camel(&r.name)));
        }
        c.line("}");
    }
    Some(c.finish())
}

/// How the endpoint tells who is asking: the keys and the issuer of the first `verifyJwt` step of the service, the same
/// verification its routes make. A service with no such step has no endpoint: it would answer anyone.
fn token_check(service: &Service) -> Option<(String, String)> {
    let mut found = None;
    for step in service.handler_steps() {
        step.walk(&mut |s| {
            if let sb_model::Step::VerifyJwt { source, issuer, .. } = s
                && found.is_none()
            {
                let source = match source {
                    sb_model::JwksSource::Keys { key_envs } => {
                        let list: Vec<String> = key_envs.iter().map(|k| format!("{k:?}")).collect();
                        format!("eda_runtime::jwt::Source::Keys(&[{}])", list.join(", "))
                    }
                    sb_model::JwksSource::Url { url_env } => {
                        format!("eda_runtime::jwt::Source::Url({url_env:?})")
                    }
                };
                found = Some((source, format!("{issuer:?}")));
            }
        });
    }
    found
}

/// Whether the service serves `POST /graphql`: it asked for GraphQL, has tables, an HTTP server (routes) and a token to check.
pub fn serves_endpoint(service: &Service) -> bool {
    sdl(service).is_some() && !service.routes.is_empty() && token_check(service).is_some()
}

fn opt(v: Option<&str>) -> String {
    v.map_or("None".to_string(), |v| format!("Some({v:?})"))
}

fn column_meta(col: &Column) -> String {
    format!(
        "Column {{ name: {:?}, field: {:?}, scalar: {:?}, nullable: {} }}",
        col.name,
        camel(&col.name),
        scalar(col.ty),
        col.nullable
    )
}

/// `transport/graphql.rs` of a gateway: the description of its sources, and the route that checks the cookie `access_token`,
/// then runs the query, the services behind receiving the same token.
fn gateway_transport_rs(service: &Service, source: &str, issuer: &str) -> String {
    let mut c = Code::new();
    c.line("// @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line("//! `POST /graphql`: reads the services behind this gateway as one graph, for the holder of a valid `access_token` cookie.");
    c.blank();
    c.line("use std::sync::OnceLock;");
    c.blank();
    c.line("use axum::{");
    c.line("    Json, Router,");
    c.line("    http::{HeaderMap, StatusCode},");
    c.line("    response::{IntoResponse, Response},");
    c.line("    routing::post,");
    c.line("};");
    c.line("use eda_runtime::graphql::error_body;");
    c.line("use eda_runtime::graphql_gateway::{Gateway, Prop, Relation, Source};");
    c.blank();
    c.line("use crate::app::ctx::Ctx;");
    c.blank();
    c.line("static SOURCES: &[Source] = &[");
    c.indent();
    for s in &service.graphql_sources {
        c.open("Source");
        c.line(format!("name: {:?},", s.name));
        c.line(format!("base_url_env: {:?},", s.base_url_env));
        c.line(format!("path: {:?},", s.path));
        c.line(format!("query: {:?},", camel(&s.name)));
        c.line("props: &[");
        for f in &s.fields {
            c.line(format!("    {},", source_prop(f)));
        }
        c.line("],");
        let key = s
            .key
            .as_ref()
            .and_then(|k| s.fields.iter().find(|f| &f.name == k))
            .map_or("None".to_string(), |f| format!("Some({})", source_prop(f)));
        c.line(format!("key: {key},"));
        c.line("relations: &[");
        for r in &s.relations {
            c.line(format!(
                "    Relation {{ field: {:?}, target: {:?}, via: {:?}, target_field: {:?}, many: {}, batch_param: {} }},",
                camel(&r.field),
                r.target,
                r.via,
                r.target_field,
                r.many,
                opt(r.batch_param.as_deref())
            ));
        }
        c.line("],");
        c.close_with(",");
    }
    c.dedent();
    c.line("];");
    c.blank();
    c.open("pub fn router() -> Router<Ctx>");
    c.line("Router::new().route(\"/graphql\", post(handle))");
    c.close();
    c.blank();
    c.open("fn gateway() -> Result<&'static Gateway, &'static str>");
    c.line("static GATEWAY: OnceLock<Result<Gateway, String>> = OnceLock::new();");
    c.line("GATEWAY");
    c.line("    .get_or_init(|| Gateway::from_env(SOURCES).map_err(|e| e.to_string()))");
    c.line("    .as_ref()");
    c.line("    .map_err(|_| \"the GraphQL schema cannot be built\")");
    c.close();
    c.blank();
    c.open("fn refused(status: StatusCode, code: &str, message: &str) -> Response");
    c.line("(status, Json(error_body(code, message))).into_response()");
    c.close();
    c.blank();
    c.open(
        "async fn handle(headers: HeaderMap, Json(request): Json<serde_json::Value>) -> Response",
    );
    c.line("let cookies = headers.get_all(axum::http::header::COOKIE).iter().filter_map(|v| v.to_str().ok());");
    c.open("let Some(token) = eda_runtime::http::cookie(cookies, \"access_token\") else");
    c.line("return refused(StatusCode::UNAUTHORIZED, \"NON_AUTHENTIFIE\", \"not signed in\");");
    c.close_with(";");
    c.line(format!(
        "if eda_runtime::jwt::verify({source}, {issuer}, &token).await.is_err() {{"
    ));
    c.line("    return refused(StatusCode::UNAUTHORIZED, \"NON_AUTHENTIFIE\", \"invalid token\");");
    c.line("}");
    c.open("let gateway = match gateway()");
    c.line("Ok(g) => g,");
    c.line("Err(message) => return refused(StatusCode::INTERNAL_SERVER_ERROR, \"ERREUR_INTERNE\", message),");
    c.close_with(";");
    c.line("Json(gateway.execute(Some(token), request).await).into_response()");
    c.close();
    c.finish()
}

/// `transport/graphql.rs`: the description of the tables, and the route that checks the cookie `access_token` and runs the query.
pub fn transport_rs(service: &Service) -> Option<String> {
    let (source, issuer) = token_check(service).filter(|_| serves_endpoint(service))?;
    if is_gateway(service) {
        return Some(gateway_transport_rs(service, &source, &issuer));
    }
    let mut c = Code::new();
    c.line("// @generated by service-builder. Do not edit: changes are overwritten on export.");
    c.line("//! `POST /graphql`: reads the tables of the service for the holder of a valid `access_token` cookie.");
    c.blank();
    c.line("use std::sync::OnceLock;");
    c.blank();
    c.line("use axum::{");
    c.line("    Json, Router,");
    c.line("    extract::State,");
    c.line("    http::{HeaderMap, StatusCode},");
    c.line("    response::{IntoResponse, Response},");
    c.line("    routing::post,");
    c.line("};");
    let mutations = mutation_routes(service);
    if mutations.is_empty() {
        c.line("use eda_runtime::graphql::{Child, Column, Endpoint, Parent, Table, error_body};");
    } else {
        c.line("use eda_runtime::graphql::{");
        c.line("    Child, Column, Endpoint, Loopback, Mutation, Parent, Table, error_body,");
        c.line("};");
    }
    c.blank();
    c.line("use crate::app::ctx::Ctx;");
    c.blank();
    c.line("static TABLES: &[Table] = &[");
    c.indent();
    for t in &service.tables {
        c.open("Table");
        c.line(format!("name: {:?},", t.name));
        c.line(format!("ty: {:?},", pascal(&t.name)));
        c.line(format!("query: {:?},", camel(&t.name)));
        c.line("columns: &[");
        for col in exposed(t) {
            c.line(format!("    {},", column_meta(col)));
        }
        c.line("],");
        c.line("keys: &[");
        for col in exposed(t).filter(|c| c.primary_key) {
            c.line(format!("    {},", column_meta(col)));
        }
        c.line("],");
        c.line(format!("tenant: {},", opt(t.tenant_column.as_deref())));
        c.line("parents: &[");
        for fk in t.foreign_keys.iter().filter(|f| f.columns.len() == 1) {
            let nullable = t
                .columns
                .iter()
                .find(|col| col.name == fk.columns[0])
                .is_some_and(|col| col.nullable);
            c.line(format!(
                "    Parent {{ field: {:?}, column: {:?}, table: {:?}, ref_column: {:?}, nullable: {nullable} }},",
                parent_field(t, &fk.columns[0]),
                fk.columns[0],
                fk.ref_table,
                fk.ref_columns.first().map(String::as_str).unwrap_or("id")
            ));
        }
        c.line("],");
        c.line("children: &[");
        for child in &service.tables {
            for fk in child
                .foreign_keys
                .iter()
                .filter(|f| f.columns.len() == 1 && f.ref_table == t.name)
            {
                c.line(format!(
                    "    Child {{ field: {:?}, table: {:?}, column: {:?}, ref_column: {:?} }},",
                    children_field(t, child),
                    child.name,
                    fk.columns[0],
                    fk.ref_columns.first().map(String::as_str).unwrap_or("id")
                ));
            }
        }
        c.line("],");
        c.close_with(",");
    }
    c.dedent();
    c.line("];");
    c.blank();
    if !mutations.is_empty() {
        c.line("static MUTATIONS: &[Mutation] = &[");
        for r in &mutations {
            let params: Vec<String> = path_params(&r.path)
                .iter()
                .map(|p| format!("{p:?}"))
                .collect();
            c.line(format!(
                "    Mutation {{ field: {:?}, method: {:?}, path: {:?}, params: &[{}], body: {} }},",
                camel(&r.name),
                format!("{:?}", r.method).to_uppercase(),
                r.path,
                params.join(", "),
                r.method.has_body()
            ));
        }
        c.line("];");
        c.blank();
    }
    c.open("pub fn router() -> Router<Ctx>");
    c.line("Router::new().route(\"/graphql\", post(handle))");
    c.close();
    c.blank();
    c.open("fn endpoint() -> Result<&'static Endpoint, &'static str>");
    c.line("static ENDPOINT: OnceLock<Result<Endpoint, String>> = OnceLock::new();");
    c.line("ENDPOINT");
    c.line(format!(
        "    .get_or_init(|| Endpoint::from_env(TABLES, {}).map_err(|e| e.to_string()))",
        if mutations.is_empty() {
            "&[]"
        } else {
            "MUTATIONS"
        }
    ));
    c.line("    .as_ref()");
    c.line("    .map_err(|_| \"the GraphQL schema cannot be built\")");
    c.close();
    c.blank();
    c.open("fn refused(status: StatusCode, code: &str, message: &str) -> Response");
    c.line("(status, Json(error_body(code, message))).into_response()");
    c.close();
    c.blank();
    c.open(
        "async fn handle(State(ctx): State<Ctx>, headers: HeaderMap, Json(request): Json<serde_json::Value>) -> Response",
    );
    c.line("let cookies = headers.get_all(axum::http::header::COOKIE).iter().filter_map(|v| v.to_str().ok());");
    c.open("let Some(token) = eda_runtime::http::cookie(cookies, \"access_token\") else");
    c.line("return refused(StatusCode::UNAUTHORIZED, \"NON_AUTHENTIFIE\", \"not signed in\");");
    c.close_with(";");
    c.line(format!(
        "let claims = match eda_runtime::jwt::verify({source}, {issuer}, &token).await {{"
    ));
    c.line("    Ok(claims) => claims,");
    c.line("    Err(_) => return refused(StatusCode::UNAUTHORIZED, \"NON_AUTHENTIFIE\", \"invalid token\"),");
    c.line("};");
    c.line("// The tenant is a claim of the token: `tenantId`, or `tenant_id`.");
    c.line("let tenant = [\"tenantId\", \"tenant_id\"]");
    c.line("    .iter()");
    c.line("    .find_map(|k| claims.get(*k).and_then(|v| v.as_str()))");
    c.line("    .map(str::to_owned);");
    c.open("let endpoint = match endpoint()");
    c.line("Ok(e) => e,");
    c.line("Err(message) => return refused(StatusCode::INTERNAL_SERVER_ERROR, \"ERREUR_INTERNE\", message),");
    c.close_with(";");
    if mutations.is_empty() {
        c.line("Json(endpoint.execute(ctx.db.clone(), tenant, request).await).into_response()");
    } else {
        // The mutations play the routes of this very service over the loopback, with the caller's cookie.
        c.line(format!(
            "let loopback = Loopback {{ base: format!(\"http://127.0.0.1:{{}}\", eda_runtime::env_or({:?}, \"{}\")), token }};",
            format!("{}_HTTP_PORT", shouty(&service.name)),
            service.http_port.unwrap_or(sb_model::DEFAULT_HTTP_PORT)
        ));
        c.line("Json(endpoint.execute_with(ctx.db.clone(), tenant, Some(loopback), request).await).into_response()");
    }
    c.close();
    Some(c.finish())
}
