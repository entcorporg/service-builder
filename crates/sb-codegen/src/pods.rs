//! The files the Pods page runs the project with: a Dockerfile that builds every service into one image, a compose
//! file (infrastructure, admin interfaces, the services with their limits) and the configuration of Traefik.
//!
//! They are written next to the workspace, never into an export: an export stays what `cargo run` needs.

use std::collections::{BTreeMap, BTreeSet};

use sb_model::names::{shouty, snake};
use sb_model::{Frontend, Project, Service, ServiceKind, TraefikConfig};

use crate::GeneratedFile;
use crate::service::crate_name;

pub const COMPOSE_FILE: &str = "compose.pods.yml";
pub const DOCKERFILE: &str = "Dockerfile";
/// The script that compiles the services, inside the builder image.
pub const BUILD_SCRIPT: &str = "build.sh";
/// Printed by the build script for each binary it replaced: `SB_CHANGED orders`.
pub const CHANGED_MARK: &str = "SB_CHANGED";
/// Where the services find their binaries.
const BIN_DIR: &str = "/opt/services";

const HEADER: &str = "# @generated by service-builder (Pods page). Do not edit: it is written again on every start.\n";

/// The name of the compose project, and of the image that holds the services: `sb-<project>`.
pub fn stack_name(project: &Project) -> String {
    format!("sb-{}", snake(&project.name).replace('_', "-"))
}

/// The image every service of the stack runs in.
pub fn image(project: &Project) -> String {
    format!("{}:latest", stack_name(project))
}

/// The image the services are compiled in.
pub fn builder_image(project: &Project) -> String {
    format!("{}-builder:latest", stack_name(project))
}

/// The volumes of the build: the registry of cargo, the build directory, and the binaries the services run.
pub fn build_volumes(project: &Project) -> [(String, &'static str); 3] {
    let stack = stack_name(project);
    [
        (format!("{stack}-cargo"), "/usr/local/cargo/registry"),
        (format!("{stack}-build"), "/build"),
        (bin_volume(project), "/out"),
    ]
}

/// What the Pods page runs, for someone who wants to do it by hand from the folder of the stack.
pub fn manual_commands(project: &Project, engine: &str) -> Vec<String> {
    let volumes: Vec<String> = build_volumes(project)
        .iter()
        .map(|(name, at)| format!("-v {name}:{at}"))
        .collect();
    vec![
        format!(
            "{engine} build --target builder -t {} -f {DOCKERFILE} .",
            builder_image(project)
        ),
        format!(
            "{engine} build --target runtime -t {} -f {DOCKERFILE} .",
            image(project)
        ),
        format!(
            "{engine} run --rm -v \"$PWD\":/src:ro {} {} sh /src/{BUILD_SCRIPT}",
            volumes.join(" "),
            builder_image(project)
        ),
        format!("{engine} compose -f {COMPOSE_FILE} up -d"),
    ]
}

/// The volume that holds the binaries of the services.
pub fn bin_volume(project: &Project) -> String {
    format!("{}-bin", stack_name(project))
}

/// The name of a service in the compose file, which is also the name of its binary.
pub fn service_name(service: &Service) -> String {
    crate_name(service)
}

/// Something of the running stack a browser can open.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Link {
    pub label: String,
    pub url: String,
}

pub fn files(project: &Project) -> Vec<GeneratedFile> {
    files_with(project, &[])
}

/// The files of the stack, `mounts` being the files of the host the services read (a key the environment file names
/// by its path): each one is mounted read-only in every service, at the path it has on the host.
pub fn files_with(project: &Project, mounts: &[String]) -> Vec<GeneratedFile> {
    let mut files = vec![
        GeneratedFile::new(DOCKERFILE, dockerfile()),
        GeneratedFile::new(BUILD_SCRIPT, build_script(project)),
        GeneratedFile::new(".dockerignore", "target\n.git\n"),
        GeneratedFile::new(COMPOSE_FILE, compose(project, mounts)),
    ];
    if project.pods.traefik.enabled {
        files.push(GeneratedFile::new(
            "traefik/traefik.yml",
            traefik_static(project),
        ));
        files.push(GeneratedFile::new(
            "traefik/dynamic/services.yaml",
            traefik_services(project),
        ));
        files.push(GeneratedFile::new(
            "traefik/dynamic/routers.yaml",
            traefik_routers(project),
        ));
        files.push(GeneratedFile::new(
            "traefik/dynamic/middlewares.yaml",
            traefik_middlewares(project),
        ));
    }
    files
}

// ---- what the project holds ------------------------------------------------------------

fn has(project: &Project, kind: ServiceKind) -> bool {
    project.services.iter().any(|s| s.kind == kind)
}

/// The port a service answers HTTP on, if it does.
fn http_port(service: &Service) -> Option<u16> {
    match service.kind {
        ServiceKind::Standard => service.http_port.filter(|_| !service.routes.is_empty()),
        ServiceKind::Mta | ServiceKind::Realtime => service.http_port,
    }
}

fn grpc_port(service: &Service) -> Option<u16> {
    (service.kind == ServiceKind::Standard && !service.rpcs.is_empty()).then_some(service.port)
}

/// The paths of a service the proxy sends to it: its routes, or the stream of a real-time service. A mail service has
/// nothing for a browser.
fn public_paths(service: &Service) -> Vec<String> {
    match service.kind {
        ServiceKind::Standard => service.routes.iter().map(|r| r.path.clone()).collect(),
        ServiceKind::Realtime => service.realtime.iter().map(|r| r.path.clone()).collect(),
        ServiceKind::Mta => vec![],
    }
}

/// The header a service reads to know which frontend is calling. The proxy sets it, and only for the services that
/// have a route reading it: for the others, telling the frontends apart would serve nothing.
pub const FRONTEND_HEADER: &str = "X-Frontend-ID";

/// Whether a route of the service fills a field from [`FRONTEND_HEADER`].
fn reads_frontend(project: &Project, service: &Service) -> bool {
    service.routes.iter().any(|r| {
        project.message(&r.request).is_some_and(|m| {
            m.fields.iter().any(|f| {
                matches!(&f.source, Some(sb_model::RequestSource::Header { name })
                    if name.eq_ignore_ascii_case(FRONTEND_HEADER))
            })
        })
    })
}

/// Host ports of the admin interfaces when there is no proxy: the first free ones from 8081, in a fixed order.
fn admin_ports(project: &Project) -> BTreeMap<&'static str, u16> {
    let taken: BTreeSet<u16> = project
        .services
        .iter()
        .flat_map(|s| [Some(s.port), s.http_port])
        .flatten()
        .collect();
    let mut next = 8081;
    let mut ports = BTreeMap::new();
    for name in ["adminer", "kafka-ui", "mailpit"] {
        while taken.contains(&next) {
            next += 1;
        }
        ports.insert(name, next);
        next += 1;
    }
    ports
}

/// The admin interfaces of the stack: (container, port inside, sub-domain behind the proxy).
fn admin_uis(project: &Project) -> Vec<(&'static str, u16, &str)> {
    let pods = &project.pods;
    let hosts = &pods.traefik.hosts;
    let mut uis = vec![];
    if pods.adminer {
        uis.push(("adminer", 8080, hosts.adminer.as_str()));
    }
    if pods.kafka_ui {
        uis.push(("kafka-ui", 8080, hosts.kafka_ui.as_str()));
    }
    if has(project, ServiceKind::Mta) {
        uis.push(("mailpit", 8025, hosts.mailpit.as_str()));
    }
    uis
}

/// What can be opened in a browser once the stack runs: the admin interfaces, the frontends, the API.
pub fn links(project: &Project) -> Vec<Link> {
    let pods = &project.pods;
    let t = &pods.traefik;
    let label = |name: &str| match name {
        "adminer" => "Adminer (PostgreSQL)",
        "kafka-ui" => "Kafka UI",
        _ => "Mailpit (mails)",
    };
    let link = |label: &str, url: String| Link {
        label: label.to_string(),
        url,
    };
    let mut links = vec![];
    if t.enabled {
        for (name, _, sub) in admin_uis(project) {
            links.push(link(label(name), t.url(sub)));
        }
        if t.dashboard {
            links.push(link("Traefik", t.url(&t.hosts.dashboard)));
        }
        for f in &t.frontends {
            links.push(link(&format!("Frontend {}", f.name), t.url(&f.host)));
        }
        links.push(link("API", t.url(&t.hosts.api)));
    } else if pods.publish_ports {
        let ports = admin_ports(project);
        for (name, _, _) in admin_uis(project) {
            links.push(link(
                label(name),
                format!("http://localhost:{}", ports[name]),
            ));
        }
    }
    if pods.publish_ports {
        for s in &project.services {
            if let Some(port) = http_port(s) {
                links.push(link(&s.name, format!("http://localhost:{port}")));
            }
        }
    }
    links
}

