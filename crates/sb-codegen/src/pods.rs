/// Two images. The classic builder of Docker is enough for them: nothing of BuildKit is used, and Podman builds
/// them as well.
fn dockerfile() -> String {
    format!(
        "{HEADER}\
         # `builder` compiles the workspace: {BUILD_SCRIPT} runs in it, with its caches in volumes.\n\
         FROM docker.io/library/rust:1-bookworm AS builder\n\
         # librdkafka is built from its sources.\n\
         RUN apt-get update \\\n\
         \x20&& apt-get install -y --no-install-recommends cmake \\\n\
         \x20&& rm -rf /var/lib/apt/lists/*\n\
         \n\
         # `runtime` is what every service runs in: its binary comes from the volume the build filled.\n\
         FROM docker.io/library/debian:bookworm-slim AS runtime\n\
         RUN apt-get update \\\n\
         \x20&& apt-get install -y --no-install-recommends ca-certificates libssl3 libcurl4 \\\n\
         \x20&& rm -rf /var/lib/apt/lists/*\n"
    )
}

/// The build, run in a container of the `builder` image: the sources are mounted read-only on /src, and three
/// volumes keep the registry of cargo, the build directory and the binaries. Nothing is written on the host.
fn build_script(project: &Project) -> String {
    let bins: Vec<String> = project.services.iter().map(crate_name).collect();
    format!(
        "#!/bin/sh\n{HEADER}\
         # Run by the Pods page in the builder image:\n\
         #   /src (read-only): this folder    /build: the build directory, kept between builds\n\
         #   /out: the binaries, mounted by the services on {BIN_DIR}\n\
         set -eu\n\
         mkdir -p /build/src\n\
         cd /build/src\n\
         # The sources are copied with their dates (cargo compiles again only what changed); Cargo.lock and the\n\
         # build directory stay.\n\
         find . -mindepth 1 -maxdepth 1 ! -name Cargo.lock ! -name target -exec rm -rf {{}} +\n\
         cp -a /src/. .\n\
         cargo build --release --bins\n\
         for bin in {}; do\n\
         \x20 # Only a binary that changed is replaced, and its service restarted ({CHANGED_MARK} is read by the page).\n\
         \x20 if ! cmp -s \"target/release/$bin\" \"/out/$bin\"; then\n\
         \x20   cp --remove-destination \"target/release/$bin\" \"/out/$bin\"\n\
         \x20   echo \"{CHANGED_MARK} $bin\"\n\
         \x20 fi\n\
         done\n",
        bins.join(" ")
    )
}

