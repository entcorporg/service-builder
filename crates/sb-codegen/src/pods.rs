/// A small YAML writer: lines at a depth, two spaces per level.
#[derive(Default)]
struct Yaml {
    out: String,
}

impl Yaml {
    fn line(&mut self, depth: usize, text: impl AsRef<str>) -> &mut Self {
        for _ in 0..depth {
            self.out.push_str("  ");
        }
        self.out.push_str(text.as_ref());
        self.out.push('\n');
        self
    }

    fn blank(&mut self) -> &mut Self {
        self.out.push('\n');
        self
    }

    fn comment(&mut self, depth: usize, text: &str) -> &mut Self {
        self.line(depth, format!("# {text}"))
    }

    /// `mem_limit` with the swap capped to the same amount: the container never swaps.
    fn memory(&mut self, depth: usize, amount: &str) -> &mut Self {
        self.line(depth, format!("mem_limit: {amount}"));
        self.line(depth, format!("memswap_limit: {amount}"))
    }
}

/// A double-quoted YAML string. The values that reach it are validated: no quote and no backslash.
fn quoted(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

/// A memory amount in MiB (`768m` -> 768), to size the heap of a JVM inside it.
fn mebibytes(amount: &str) -> u64 {
    let digits = amount.trim_end_matches(['b', 'k', 'm', 'g']);
    let n: u64 = digits.parse().unwrap_or(0);
    match amount.as_bytes().last() {
        Some(b'g') => n * 1024,
        Some(b'm') => n,
        Some(b'k') => n / 1024,
        _ => n / (1024 * 1024),
    }
}

fn compose(project: &Project, mounts: &[String]) -> String {
    let pods = &project.pods;
    let t = &pods.traefik;
    let name = stack_name(project);
    let mta = has(project, ServiceKind::Mta);
    let realtime = has(project, ServiceKind::Realtime);
    // Published on the loopback only: the stack is not meant to be reached from the network without the proxy.
    let admin_port = |container: &str| {
        (!t.enabled && pods.publish_ports).then(|| admin_ports(project)[container])
    };

    let mut y = Yaml::default();
    y.out.push_str(HEADER);
    y.comment(0, "The stack of the Pods page. By hand, from this folder:");
    for command in manual_commands(project, "docker") {
        y.comment(0, &format!("  {command}"));
    }
    y.line(0, format!("name: {name}"));
    y.blank();
    y.line(0, "x-limits: &limits");
    if !pods.cpuset.is_empty() {
        y.line(1, format!("cpuset: {}", quoted(&pods.cpuset)));
    }
    y.line(1, format!("restart: {}", quoted(&pods.restart)));
    y.blank();
    y.line(0, "x-service: &service");
    y.line(1, "<<: *limits");
    y.line(1, format!("image: {}", image(project)));
    y.memory(1, &pods.service_memory);
    // The services stop on Ctrl+C. As the first process of a container they would not even get the signal: an
    // init process hands it over, and a stop takes milliseconds instead of the ten seconds before a kill.
    y.line(1, "init: true");
    y.line(1, "stop_signal: SIGINT");
    y.line(1, "volumes:");
    y.line(2, format!("- bin:{BIN_DIR}:ro"));
    if !mounts.is_empty() {
        y.comment(
            2,
            "The files the environment file names, where the services look for them.",
        );
    }
    for path in mounts {
        y.line(2, format!("- {}", quoted(&format!("{path}:{path}:ro"))));
    }
    if !pods.env_file.trim().is_empty() {
        y.line(1, "env_file:");
        y.line(2, format!("- {}", quoted(pods.env_file.trim())));
    }
    y.blank();
    y.line(0, "services:");

    // Kafka in KRaft mode, reached as kafka:19092 by the containers of the stack.
    y.line(1, "kafka:");
    y.line(2, "<<: *limits");
    y.line(2, "image: apache/kafka:3.9.0");
    y.memory(2, &pods.kafka_memory);
    y.line(2, "environment:");
    for (key, value) in [
        ("KAFKA_NODE_ID", "1".to_string()),
        ("KAFKA_PROCESS_ROLES", "broker,controller".into()),
        (
            "KAFKA_LISTENERS",
            "INTERNAL://:19092,CONTROLLER://:9093".into(),
        ),
        (
            "KAFKA_ADVERTISED_LISTENERS",
            "INTERNAL://kafka:19092".into(),
        ),
        (
            "KAFKA_LISTENER_SECURITY_PROTOCOL_MAP",
            "INTERNAL:PLAINTEXT,CONTROLLER:PLAINTEXT".into(),
        ),
        ("KAFKA_INTER_BROKER_LISTENER_NAME", "INTERNAL".into()),
        ("KAFKA_CONTROLLER_LISTENER_NAMES", "CONTROLLER".into()),
        ("KAFKA_CONTROLLER_QUORUM_VOTERS", "1@kafka:9093".into()),
        ("KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR", "1".into()),
        ("KAFKA_TRANSACTION_STATE_LOG_REPLICATION_FACTOR", "1".into()),
        ("KAFKA_TRANSACTION_STATE_LOG_MIN_ISR", "1".into()),
        ("KAFKA_GROUP_INITIAL_REBALANCE_DELAY_MS", "0".into()),
        // Half of the container for the heap: the rest is for the page cache and the JVM itself.
        (
            "KAFKA_HEAP_OPTS",
            format!("-Xmx{}m", (mebibytes(&pods.kafka_memory) / 2).max(64)),
        ),
    ] {
        y.line(3, format!("{key}: {}", quoted(&value)));
    }
    y.line(2, "healthcheck:");
    y.line(3, "test: [\"CMD-SHELL\", \"nc -z localhost 19092\"]");
    y.line(3, "interval: 5s");
    y.line(3, "timeout: 3s");
    y.line(3, "retries: 30");

    y.line(1, "postgres:");
    y.line(2, "<<: *limits");
    y.line(2, "image: postgres:16");
    y.memory(2, &pods.postgres_memory);
    y.line(2, "environment:");
    y.line(3, "POSTGRES_PASSWORD: postgres");
    y.line(2, "volumes:");
    y.line(3, "- postgres-data:/var/lib/postgresql/data");
    y.line(2, "healthcheck:");
    y.line(3, "test: [\"CMD-SHELL\", \"pg_isready -U postgres\"]");
    y.line(3, "interval: 5s");
    y.line(3, "timeout: 3s");
    y.line(3, "retries: 30");

    if pods.adminer {
        y.line(1, "adminer:");
        y.line(2, "<<: *limits");
        y.line(2, "image: adminer:5");
        y.memory(2, "64m");
        y.line(2, "depends_on:");
        y.line(3, "postgres: { condition: service_healthy }");
        y.line(2, "environment:");
        y.line(3, "ADMINER_DEFAULT_SERVER: postgres");
        if let Some(port) = admin_port("adminer") {
            y.line(2, "ports:");
            y.line(3, format!("- \"127.0.0.1:{port}:8080\""));
        }
    }
    if pods.kafka_ui {
        y.line(1, "kafka-ui:");
        y.line(2, "<<: *limits");
        y.line(2, "image: ghcr.io/kafbat/kafka-ui:v1.4.2");
        y.memory(2, "512m");
        y.line(2, "depends_on:");
        y.line(3, "kafka: { condition: service_healthy }");
        y.line(2, "environment:");
        y.line(3, format!("KAFKA_CLUSTERS_0_NAME: {}", quoted(&name)));
        y.line(3, "KAFKA_CLUSTERS_0_BOOTSTRAPSERVERS: kafka:19092");
        y.line(3, "DYNAMIC_CONFIG_ENABLED: \"false\"");
        y.line(3, "JAVA_OPTS: -Xmx320m");
        if let Some(port) = admin_port("kafka-ui") {
            y.line(2, "ports:");
            y.line(3, format!("- \"127.0.0.1:{port}:8080\""));
        }
    }
    if mta {
        y.comment(
            1,
            "Catches what the mail service sends: nothing leaves the stack.",
        );
        y.line(1, "mailpit:");
        y.line(2, "<<: *limits");
        y.line(2, "image: axllent/mailpit");
        y.memory(2, "64m");
        if let Some(port) = admin_port("mailpit") {
            y.line(2, "ports:");
            y.line(3, format!("- \"127.0.0.1:{port}:8025\""));
        }
    }
    if realtime {
        y.line(1, "dragonfly:");
        y.line(2, "<<: *limits");
        y.line(2, "image: docker.dragonflydb.io/dragonflydb/dragonfly");
        y.memory(2, "512m");
        y.line(
            2,
            "command: [\"--proactor_threads=1\", \"--maxmemory=256mb\"]",
        );
        y.line(2, "ulimits:");
        y.line(3, "memlock: -1");
    }
    if t.enabled {
        y.line(1, "traefik:");
        y.line(2, "<<: *limits");
        y.line(2, "image: traefik:v3");
        y.memory(2, "128m");
        if !t.frontends.is_empty() {
            y.comment(2, "The frontends are dev servers on the host.");
            y.line(2, "extra_hosts:");
            y.line(3, "- \"host.docker.internal:host-gateway\"");
        }
        y.line(2, "ports:");
        y.line(3, format!("- \"{}:80\"", t.http_port));
        if t.tls() {
            y.line(3, format!("- \"{}:443\"", t.https_port));
        }
        y.line(2, "volumes:");
        if t.tls() {
            y.line(3, "- letsencrypt:/letsencrypt");
        }
        y.line(3, "- ./traefik/traefik.yml:/etc/traefik/traefik.yml:ro");
        y.line(3, "- ./traefik/dynamic:/etc/traefik/dynamic:ro");
        y.line(2, "healthcheck:");
        y.line(
            3,
            "test: [\"CMD\", \"traefik\", \"healthcheck\", \"--ping\"]",
        );
        y.line(3, "interval: 10s");
        y.line(3, "timeout: 3s");
        y.line(3, "retries: 5");
    }

    for service in &project.services {
        y.blank();
        y.line(1, format!("{}:", crate_name(service)));
        y.line(2, "<<: *service");
        y.line(
            2,
            format!("command: [\"{BIN_DIR}/{}\"]", crate_name(service)),
        );
        let needs: Vec<&str> = match service.kind {
            ServiceKind::Realtime => vec!["dragonfly"],
            ServiceKind::Standard if realtime => vec!["kafka", "postgres", "dragonfly"],
            _ => vec!["kafka", "postgres"],
        };
        y.line(2, "depends_on:");
        for need in needs {
            let condition = if need == "dragonfly" {
                "service_started"
            } else {
                "service_healthy"
            };
            y.line(3, format!("{need}: {{ condition: {condition} }}"));
        }
        y.line(2, "environment:");
        for (key, value) in environment(project, service) {
            y.line(3, format!("{key}: {}", quoted(&value)));
        }
        let ports: Vec<u16> = [grpc_port(service), http_port(service)]
            .into_iter()
            .flatten()
            .collect();
        if pods.publish_ports && !ports.is_empty() {
            y.line(2, "ports:");
            for port in ports {
                y.line(3, format!("- \"127.0.0.1:{port}:{port}\""));
            }
        }
    }

    y.blank();
    y.line(0, "volumes:");
    y.line(1, "postgres-data:");
    if t.enabled && t.tls() {
        y.line(1, "letsencrypt:");
    }
    y.comment(
        1,
        "The binaries of the services: filled by the build, before the stack starts.",
    );
    y.line(1, "bin:");
    y.line(2, format!("name: {}", bin_volume(project)));
    y.line(2, "external: true");
    y.out
}

/// The origins of the frontends, as a browser names them.
fn origins(t: &TraefikConfig) -> Vec<String> {
    t.frontends.iter().map(|f| t.url(&f.host)).collect()
}

/// What a service reads from its environment to find the rest of the stack. The environment file of the project comes
/// on top of it for everything else (keys, secrets).
fn environment(project: &Project, service: &Service) -> Vec<(String, String)> {
    let t = &project.pods.traefik;
    let proxied = t.enabled && !t.frontends.is_empty();
    let database = || {
        (
            format!("{}_DATABASE_URL", shouty(&service.name)),
            format!(
                "postgres://postgres:postgres@postgres:5432/{}",
                snake(&service.name)
            ),
        )
    };
    let dragonfly = (
        "DRAGONFLY_URL".to_string(),
        "redis://dragonfly:6379".to_string(),
    );
    let mut env: Vec<(String, String)> = vec![];
    match service.kind {
        ServiceKind::Standard => {
            env.push(("KAFKA_BROKERS".into(), "kafka:19092".into()));
            env.push(database());
            // Where the other services answer gRPC.
            for other in &project.services {
                if other.name != service.name
                    && let Some(port) = grpc_port(other)
                {
                    env.push((
                        format!("{}_URL", shouty(&other.name)),
                        format!("http://{}:{port}", crate_name(other)),
                    ));
                }
            }
            if has(project, ServiceKind::Realtime) {
                env.push(dragonfly);
            }
            // The proxy answers CORS for the frontends: a second answer from the service would make the browser
            // refuse the response.
            if proxied && http_port(service).is_some() {
                env.push(("CORS_ORIGINS".into(), String::new()));
            }
        }
        ServiceKind::Mta => {
            env.push(("KAFKA_BROKERS".into(), "kafka:19092".into()));
            env.push(database());
            env.push(("SMTP_HOST".into(), "mailpit".into()));
            env.push(("SMTP_PORT".into(), "1025".into()));
        }
        ServiceKind::Realtime => {
            env.push(dragonfly);
            if proxied {
                env.push(("CORS_ALLOWED_ORIGINS".into(), origins(t).join(",")));
            }
            // The keys of the access tokens: the service of the project that publishes a JWKS, if there is one.
            let jwks = project.services.iter().find_map(|s| {
                let port = http_port(s).filter(|_| s.kind == ServiceKind::Standard)?;
                let route = s.routes.iter().find(|r| r.path.ends_with("/jwks.json"))?;
                Some(format!("http://{}:{port}{}", crate_name(s), route.path))
            });
            if let Some(url) = jwks {
                env.push(("JWKS_URL".into(), url));
            }
        }
    }
    env
}

