    #[test]
    fn services_that_share_a_start_keep_their_own_paths() {
        assert_eq!(static_prefix("/orders/{id}/items"), "/orders");
        assert_eq!(static_prefix("/auth/me"), "/auth/me");
        assert_eq!(static_prefix("/{id}"), "/");
        assert!(covers("/auth", "/auth/me") && !covers("/auth", "/authors"));

        let mut p = sample::orders();
        // Two services under /auth: the generic one, and the profile deeper.
        let mut route = p
            .services
            .iter()
            .flat_map(|s| &s.routes)
            .next()
            .expect("the sample has a route")
            .clone();
        for s in &mut p.services {
            s.routes.clear();
        }
        let mut add = |service: usize, name: &str, path: &str| {
            route.name = name.into();
            route.path = path.into();
            p.services[service].routes.push(route.clone());
            p.services[service]
                .http_port
                .get_or_insert(8090 + service as u16);
        };
        add(0, "login", "/auth/login");
        add(0, "session", "/auth/sessions/{id}");
        add(0, "keys", "/.well-known/jwks.json");
        add(1, "me", "/auth/me");
        add(1, "avatar", "/auth/me/avatar");
        add(1, "files", "/files/{id}");
        let routes = routed(&p);
        assert_eq!(routes[0].groups[&2], vec!["/auth/login", "/auth/sessions"]);
        assert_eq!(routes[0].well_known, vec!["/.well-known/jwks.json"]);
        // `/auth/me/avatar` is under `/auth/me`; `/files` belongs to this service alone.
        assert_eq!(routes[1].groups[&1], vec!["/files"]);
        assert_eq!(routes[1].groups[&2], vec!["/auth/me"]);

        p.pods.traefik.enabled = true;
        let routers = file(&files(&p), "traefik/dynamic/routers.yaml");
        let (first, second) = (crate_name(&p.services[0]), crate_name(&p.services[1]));
        assert!(
            routers.contains(&format!("api-{first}-well-known:")),
            "{routers}"
        );
        assert!(
            routers.contains("Path(`/.well-known/jwks.json`)"),
            "{routers}"
        );
        assert!(routers.contains(&format!("api-{second}-2:")), "{routers}");
        assert!(
            routers.contains("(PathPrefix(`/auth/login`) || PathPrefix(`/auth/sessions`))"),
            "{routers}"
        );
    }

