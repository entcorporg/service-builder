/// The literal start of a route path, up to its first parameter: `/orders/{id}/items` gives `/orders`.
fn static_prefix(path: &str) -> String {
    let kept: Vec<&str> = path
        .split('/')
        .skip(1)
        .take_while(|segment| !segment.starts_with('{'))
        .collect();
    format!("/{}", kept.join("/"))
}

fn first_segment(path: &str) -> &str {
    path.split('/').nth(1).unwrap_or_default()
}

/// Number of segments of a prefix: the longer one wins when two services share a start.
fn depth(prefix: &str) -> usize {
    prefix.split('/').filter(|s| !s.is_empty()).count()
}

fn covers(short: &str, long: &str) -> bool {
    short == "/" || long == short || long.starts_with(&format!("{short}/"))
}

/// What the proxy sends to one service.
struct Routed {
    service: String,
    /// The service reads [`FRONTEND_HEADER`]: it is served once per frontend, under `/<frontend>`.
    by_frontend: bool,
    /// Path prefixes, grouped by depth: one router per group, the deeper the higher its priority.
    groups: BTreeMap<usize, Vec<String>>,
    /// `/.well-known/...` paths: the same for every frontend, so they are served without a prefix.
    well_known: Vec<String>,
}

/// The path prefixes of each service. A service alone under a first segment gets the whole segment (`/orders`);
/// services that share one (`/auth/login` here, `/auth/me` there) each keep their own paths.
fn routed(project: &Project) -> Vec<Routed> {
    let paths: Vec<(&Service, Vec<String>)> = project
        .services
        .iter()
        .filter(|s| http_port(s).is_some())
        .map(|s| (s, public_paths(s)))
        .filter(|(_, paths)| !paths.is_empty())
        .collect();
    // How many services have a path under each first segment.
    let mut owners: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    for (service, paths) in &paths {
        for path in paths {
            owners
                .entry(first_segment(path))
                .or_default()
                .insert(&service.name);
        }
    }
    let mut out = vec![];
    for (service, paths) in &paths {
        let mut well_known = BTreeSet::new();
        let mut prefixes = BTreeSet::new();
        for path in paths {
            let first = first_segment(path);
            if first == ".well-known" {
                well_known.insert(path.clone());
            } else if owners[first].len() == 1 && !first.is_empty() && !first.starts_with('{') {
                prefixes.insert(format!("/{first}"));
            } else {
                prefixes.insert(static_prefix(path));
            }
        }
        // A prefix already covered by a shorter one of the same service says nothing more.
        let all: Vec<String> = prefixes.iter().cloned().collect();
        let mut groups: BTreeMap<usize, Vec<String>> = BTreeMap::new();
        for prefix in &all {
            if !all
                .iter()
                .any(|other| other != prefix && covers(other, prefix))
            {
                groups
                    .entry(depth(prefix))
                    .or_default()
                    .push(prefix.clone());
            }
        }
        out.push(Routed {
            service: crate_name(service),
            by_frontend: reads_frontend(project, service),
            groups,
            well_known: well_known.into_iter().collect(),
        });
    }
    out
}

/// `A || B` in parentheses, or `A` alone.
fn any_of(matchers: Vec<String>) -> String {
    if matchers.len() == 1 {
        matchers.into_iter().next().unwrap_or_default()
    } else {
        format!("({})", matchers.join(" || "))
    }
}

struct Router<'a> {
    name: String,
    rule: String,
    priority: Option<usize>,
    service: &'a str,
    middlewares: Vec<String>,
}

fn router(y: &mut Yaml, t: &TraefikConfig, r: Router) {
    y.line(2, format!("{}:", r.name));
    y.line(3, format!("rule: {}", quoted(&r.rule)));
    if let Some(priority) = r.priority {
        y.line(3, format!("priority: {priority}"));
    }
    y.line(3, "entryPoints:");
    y.line(4, if t.tls() { "- websecure" } else { "- web" });
    y.line(3, format!("service: {}", r.service));
    if t.tls() {
        y.line(3, "tls:");
        y.line(4, "certResolver: letsencrypt");
    }
    y.line(3, "middlewares:");
    for m in r.middlewares {
        y.line(4, format!("- {m}"));
    }
    y.blank();
}

fn host_rule(t: &TraefikConfig, sub: &str) -> String {
    format!("Host(`{}`)", t.fqdn(sub))
}

fn traefik_routers(project: &Project) -> String {
    let t = &project.pods.traefik;
    let mut y = Yaml::default();
    y.out.push_str(HEADER);
    y.comment(0, "Each admin interface and each frontend has its own host. The API of the services is on one host:");
    y.comment(0, "a service that reads X-Frontend-ID is served once per frontend under `/<frontend>`, which the proxy");
    y.comment(
        0,
        "removes before it sets the header; the other services are served once, as they are.",
    );
    y.line(0, "http:");
    y.line(1, "routers:");

    let admin = |extra: &[&str]| {
        let mut m = vec!["secure-headers".to_string()];
        if !t.admin_auth.is_empty() {
            m.push("admin-auth".into());
        }
        m.extend(extra.iter().map(|s| s.to_string()));
        m
    };
    let mut any = false;
    if t.dashboard {
        y.comment(2, "── Admin interfaces ──");
        router(
            &mut y,
            t,
            Router {
                name: "dashboard".into(),
                rule: host_rule(t, &t.hosts.dashboard),
                priority: None,
                service: "api@internal",
                middlewares: admin(&[]),
            },
        );
        any = true;
    }
    for (name, _, sub) in admin_uis(project) {
        router(
            &mut y,
            t,
            Router {
                name: name.into(),
                rule: host_rule(t, sub),
                priority: None,
                service: name,
                middlewares: admin(&[]),
            },
        );
        any = true;
    }
    for f in &t.frontends {
        y.comment(2, &format!("── Frontend {} ──", f.name));
        let service = format!("frontend-{}", f.name);
        router(
            &mut y,
            t,
            Router {
                name: service.clone(),
                rule: host_rule(t, &f.host),
                priority: None,
                service: &service,
                middlewares: vec!["secure-headers".into()],
            },
        );
        any = true;
    }

    let api = host_rule(t, &t.hosts.api);
    let routes = routed(project);
    let base = |cors: bool| {
        let mut m = vec!["secure-headers".to_string(), "ratelimit-api".to_string()];
        if cors {
            m.push("cors-api".into());
        }
        m
    };
    let cors = !t.frontends.is_empty();
    if !routes.is_empty() {
        y.comment(2, "── API ──");
    }
    for r in &routes {
        // Only a service that reads which frontend calls is served once per frontend.
        let callers: Vec<Option<&Frontend>> = if r.by_frontend && cors {
            t.frontends.iter().map(Some).collect()
        } else {
            vec![None]
        };
        for caller in &callers {
            let prefix = caller.map_or(String::new(), |f| format!("/{}", f.name));
            let mut middlewares = base(cors);
            if let Some(f) = caller {
                middlewares.push(format!("api-{}-prefix", f.name));
                middlewares.push(format!("frontend-{}-identity", f.name));
            }
            for (i, (depth, prefixes)) in r.groups.iter().enumerate() {
                let matchers = prefixes
                    .iter()
                    .map(|p| {
                        let path = if p == "/" { String::new() } else { p.clone() };
                        format!(
                            "PathPrefix(`{prefix}{}`)",
                            if path.is_empty() && prefix.is_empty() {
                                "/"
                            } else {
                                &path
                            }
                        )
                    })
                    .collect();
                let mut name = match caller {
                    Some(f) => format!("api-{}-{}", f.name, r.service),
                    None => format!("api-{}", r.service),
                };
                if i > 0 {
                    name.push_str(&format!("-{depth}"));
                }
                router(
                    &mut y,
                    t,
                    Router {
                        name,
                        rule: format!("{api} && {}", any_of(matchers)),
                        // Above the hosts alone, and a deeper prefix above a shorter one (the prefix of a
                        // frontend counts: `/admin/orders` wins over a service that owns `/admin`).
                        priority: Some(90 + 10 * (depth + usize::from(caller.is_some()))),
                        service: &r.service,
                        middlewares: middlewares.clone(),
                    },
                );
                any = true;
            }
        }
        if !r.well_known.is_empty() {
            let matchers = r
                .well_known
                .iter()
                .map(|p| format!("Path(`{p}`)"))
                .collect();
            router(
                &mut y,
                t,
                Router {
                    name: format!("api-{}-well-known", r.service),
                    rule: format!("{api} && {}", any_of(matchers)),
                    priority: Some(200),
                    service: &r.service,
                    middlewares: base(false),
                },
            );
            any = true;
        }
    }
    if !any {
        return format!("{HEADER}# Nothing to serve yet.\n");
    }
    y.out.truncate(y.out.trim_end().len());
    y.out.push('\n');
    y.out
}

