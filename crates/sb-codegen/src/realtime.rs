pub fn generate(_project: &Project, service: &Service) -> Result<Vec<GeneratedFile>, CodegenError> {
    let dir = crate::service::dir(service);
    let http_port = service
        .http_port
        .ok_or_else(|| CodegenError::Internal("a real-time service needs an HTTP port".into()))?;
    let config = service
        .realtime
        .as_ref()
        .ok_or_else(|| CodegenError::Internal("a real-time service needs its settings".into()))?;

    let mut files = vec![GeneratedFile::new(
        format!("{dir}/Cargo.toml"),
        cargo_toml(service),
    )];
    for (path, content) in FIXED {
        let content = match *path {
            "src/config.rs" => content.replace("::SERVER_PORT::", &http_port.to_string()),
            // `{:?}` of a string is a Rust string literal.
            "src/contract.rs" => content
                .replace("::CHANNEL::", &format!("{:?}", config.channel))
                .replace("::PATH::", &format!("{:?}", config.path))
                .replace("::ACCESS_COOKIE::", &format!("{:?}", config.access_cookie))
                .replace("::ISSUER::", &format!("{:?}", config.issuer))
                .replace(
                    "::SESSION_PREFIX::",
                    &format!("{:?}", config.session_key_prefix),
                ),
            _ => (*content).to_string(),
        };
        files.push(GeneratedFile::new(format!("{dir}/{path}"), content));
    }
    Ok(files)
}

